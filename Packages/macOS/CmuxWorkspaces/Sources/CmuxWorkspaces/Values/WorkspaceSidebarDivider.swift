public import Foundation

/// A persistent, unlabeled separator between two top-level sidebar rows.
///
/// Dividers are anchored to the row immediately above them rather than to a
/// fragile array index. The anchor is either an ungrouped workspace id or a
/// workspace-group anchor id. A divider without a valid, non-final anchor is
/// discarded by ``WorkspacesModel/normalizeSidebarDividers()`` so leading,
/// trailing, and adjacent separators cannot accumulate.
public struct WorkspaceSidebarDivider: Codable, Equatable, Hashable, Identifiable, Sendable {
    /// The divider's stable identity, used by rendering and drag payloads.
    public let id: UUID

    /// The top-level workspace row immediately above this divider.
    public var afterWorkspaceId: UUID

    /// Creates a divider anchored after a top-level sidebar row.
    ///
    /// - Parameters:
    ///   - id: Stable identity. A fresh UUID is generated by default.
    ///   - afterWorkspaceId: The row immediately above the divider.
    public init(id: UUID = UUID(), afterWorkspaceId: UUID) {
        self.id = id
        self.afterWorkspaceId = afterWorkspaceId
    }
}
