    private static let path = "$HOME/.cmux/cmux-display"

    public static func command(action: String, requestID: UUID? = nil) -> String {
        let argument = requestID.map { " --request-id \($0.uuidString.lowercased())" } ?? ""
        let body = """
        set -eu
        path=\"\(path)\"
        mkdir -p \"$HOME/.cmux\"
        helper_updated=0
        candidate=\"$(mktemp \"$HOME/.cmux/cmux-display.XXXXXX\")\"
        printf %s \"\(encodedSource)\" | base64 -d > \"$candidate\"
        chmod 700 \"$candidate\"
        if [ ! -x \"$path\" ] || ! cmp -s \"$candidate\" \"$path\"; then
          mv -f \"$candidate\" \"$path\"
          helper_updated=1
        else
          rm -f \"$candidate\"
        fi
        if [ \"$helper_updated\" = 1 ] && pgrep -u \"$(id -u)\" -f \"$path serve\" >/dev/null 2>&1; then
          pkill -TERM -u \"$(id -u)\" -f \"$path serve\" >/dev/null 2>&1 || true
          for attempt in $(seq 1 100); do
            pgrep -u \"$(id -u)\" -f \"$path serve\" >/dev/null 2>&1 || break
            sleep 0.1
          done
          pgrep -u \"$(id -u)\" -f \"$path serve\" >/dev/null 2>&1 && exit 1
        fi
        if ! pgrep -u \"$(id -u)\" -f \"$path serve\" >/dev/null 2>&1; then
          # Only the long-lived service needs the login environment: new
          # desktops inherit it (agent routing, BROWSER, CA certificates).
          nohup /bin/bash -lc \"exec \\\"$path\\\" serve\" > \"$HOME/.cmux/display-service.log\" 2>&1 &
        fi
        service_ready=0
        for attempt in $(seq 1 100); do
          if \"$path\" list > /dev/null 2>&1; then
            service_ready=1
            break
          fi
          sleep 0.1
        done
        [ \"$service_ready\" = 1 ] || exit 1
        \"$path\" \(action)\(argument)
        """
        // A plain shell: a login shell costs about 0.7s per request, and only
        // the service launch above needs that environment.
        return "runuser -u cmux -- env HOME=/home/cmux USER=cmux /bin/bash -c '\(body)'"
    }
