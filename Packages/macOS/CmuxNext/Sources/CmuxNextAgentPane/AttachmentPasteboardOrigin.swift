public import AppKit

/// What a pasteboard says about who wrote it (``AttachmentSource``). macOS does not name a
/// pasteboard's writer. An app can say it wrote the contents with nspasteboard.org's
/// `org.nspasteboard.source`, and only that statement is taken. The app in front when the contents
/// changed is not taken: a background tool, a clipboard manager or a script can write the pasteboard
/// while any app is in front, and a source is never a guess.
///
/// Contents from another device (Universal Clipboard), and contents a tool says it made
/// (nspasteboard.org's transient and auto-generated types), have no source even when they claim one.
/// cmux claims what it copies (Screenshot Tab) with ``write(_:to:bundleId:)``.
nonisolated extension AttachmentSource {
    static let pasteboardSourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    /// Contents another device sent (Universal Clipboard), or contents a tool says it made.
    static let unattributedPasteboardTypes: Set<String> = [
        "com.apple.is-remote-clipboard", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    /// Writes `objects` to `pasteboard` in place of what it held, each as one item that also says
    /// cmux wrote it (`org.nspasteboard.source`). The source is written with the contents, on the same
    /// item, never added to the pasteboard after them. Each item keeps every type its object writes, so an
    /// image still pastes as an image. Returns whether the pasteboard took the items.
    @MainActor @discardableResult
    public static func write(
        _ objects: [any NSPasteboardWriting], to pasteboard: NSPasteboard,
        bundleId: String? = Bundle.main.bundleIdentifier
    ) -> Bool {
        let source = bundleId.flatMap { isBundleId($0) ? $0 : nil }
        let items = objects.map { item(for: $0, on: pasteboard, source: source) }
        pasteboard.clearContents()
        return pasteboard.writeObjects(items)
    }

    /// One item with every type `object` writes for `pasteboard`, and `source` as its writer.
    @MainActor static func item(for object: any NSPasteboardWriting, on pasteboard: NSPasteboard, source: String?) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        for type in object.writableTypes(for: pasteboard) where type != pasteboardSourceType {
            guard let list = object.pasteboardPropertyList(forType: type) else { continue }
            switch list {
            case let data as Data: item.setData(data, forType: type)
            case let string as String: item.setString(string, forType: type)
            default: item.setPropertyList(list, forType: type)
            }
        }
        if let source { item.setString(source, forType: pasteboardSourceType) }
        return item
    }

    /// The bundle identifier `pasteboard` says wrote its contents, or nil when it says none.
    @MainActor static func claimed(on pasteboard: NSPasteboard) -> String? {
        claimed(types: Set((pasteboard.types ?? []).map(\.rawValue)), said: pasteboard.string(forType: pasteboardSourceType))
    }

    /// The writer a pasteboard with `types` names when it says `said` (`org.nspasteboard.source`).
    static func claimed(types: Set<String>, said: String?) -> String? {
        guard types.isDisjoint(with: unattributedPasteboardTypes), let said, isBundleId(said) else { return nil }
        return said
    }

    /// The source `bundleId` names: cmux, or an installed app; nil when no such app is installed.
    static func source(bundleId: String, apps: AttachmentSourceApps) -> AttachmentSource? {
        if bundleId == apps.ownBundleId() { return .cmux }
        guard isBundleId(bundleId), let name = apps.app(bundleId) else { return nil }
        return AttachmentSource(name: name, bundleId: bundleId)
    }
}
