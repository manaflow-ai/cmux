public import AppKit

/// Which app put what is on the general pasteboard there (``AttachmentSource``). macOS names no
/// pasteboard's writer, so this keeps a timeline from the moment the app starts: the pasteboard's
/// change count each time another app comes to the front, and each time macOS's screen capture
/// starts or ends (it puts Control-Shift-Command-3 and -4 captures on the pasteboard while some
/// other app is in front). The last stretch of the timeline in which the count moved names the
/// writer: the app that was in front then, or Screenshot when a capture was running.
///
/// It answers nothing when that is unknown: the pasteboard changed before the app started, its
/// contents came from another device (Universal Clipboard) or say a tool made them
/// (nspasteboard.org's transient and auto-generated types). An app that says it wrote them
/// (`org.nspasteboard.source`) is taken at its word.
///
/// The timeline is driven by NSWorkspace's own notifications: no timer and no polling. It keeps the
/// last ``limit`` marks and runs for the app's life; ``stop()`` removes its observers.
@MainActor public final class AttachmentPasteboardOrigin {
    public static let shared = AttachmentPasteboardOrigin()

    /// One point of the timeline: the pasteboard's change count when the front app changed or a
    /// screen capture started or ended, with who was in front and whether a capture was running.
    nonisolated struct Mark: Equatable, Sendable {
        var count: Int
        var front: String?
        var capturing: Bool
    }

    nonisolated static let limit = 64
    nonisolated static let screenCaptureBundleId = "com.apple.screencaptureui"
    nonisolated static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    /// Contents another device sent (Universal Clipboard), or contents a tool says it made.
    nonisolated static let unattributedTypes: Set<String> = [
        "com.apple.is-remote-clipboard", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    private(set) var marks: [Mark] = []
    private var observers: [NSObjectProtocol] = []
    private var running: NSKeyValueObservation?
    private let pasteboard: NSPasteboard
    private let workspace: NSWorkspace

    init(pasteboard: NSPasteboard = .general, workspace: NSWorkspace = .shared) {
        (self.pasteboard, self.workspace) = (pasteboard, workspace)
    }

    /// Starts the timeline (again a no-op): the app calls it as it launches.
    public func start() {
        guard observers.isEmpty else { return }
        mark()
        observers.append(workspace.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] _ in MainActor.assumeIsolated { self?.mark() } })
        running = workspace.observe(\.runningApplications, options: [.old, .new]) { [weak self] _, change in
            let ids = (change.newValue ?? []) + (change.oldValue ?? [])
            guard ids.contains(where: { $0.bundleIdentifier == Self.screenCaptureBundleId }) else { return }
            // NSWorkspace changes the list on the main thread; the count is read as it is told.
            if Thread.isMainThread { MainActor.assumeIsolated { self?.mark() } } else { Task { @MainActor in self?.mark() } }
        }
    }

    /// Says on `pasteboard`, which cmux just wrote, that cmux wrote it (`org.nspasteboard.source`).
    public static func claim(_ pasteboard: NSPasteboard, bundleId: String? = Bundle.main.bundleIdentifier) {
        guard let bundleId, AttachmentSource.isBundleId(bundleId) else { return }
        pasteboard.setString(bundleId, forType: sourceType)
    }

    /// Ends the timeline.
    public func stop() {
        for observer in observers { workspace.notificationCenter.removeObserver(observer) }
        observers = []
        running?.invalidate()
        running = nil
        marks = []
    }

    private func mark() {
        let capturing = workspace.runningApplications.contains { $0.bundleIdentifier == Self.screenCaptureBundleId }
        marks.append(Mark(count: pasteboard.changeCount, front: workspace.frontmostApplication?.bundleIdentifier,
                          capturing: capturing))
        if marks.count > Self.limit { marks.removeFirst(marks.count - Self.limit) }
    }

    /// Who put the pasteboard's contents there, or nil when that is not known.
    public func source(apps: AttachmentSourceApps = .live) -> AttachmentSource? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let said = pasteboard.string(forType: Self.sourceType)
        guard let writer = Self.writer(marks: marks, count: pasteboard.changeCount, types: types, said: said) else { return nil }
        return Self.source(bundleId: writer, apps: apps)
    }

    /// The bundle identifier of whoever put the pasteboard's contents there, from `marks` and the
    /// pasteboard's `count`, `types` and `said` (`org.nspasteboard.source`); nil when unknown.
    nonisolated static func writer(marks: [Mark], count: Int, types: Set<String>, said: String?) -> String? {
        guard types.isDisjoint(with: unattributedTypes) else { return nil }
        if let said, AttachmentSource.isBundleId(said) { return said }
        // The last stretch whose count moved: the count at its start differs from the next mark's
        // (or, for the last stretch, from the count now).
        for index in marks.indices.reversed() {
            let end = index == marks.index(before: marks.endIndex) ? count : marks[index + 1].count
            guard marks[index].count != end else { continue }
            return marks[index].capturing ? AttachmentSource.screenshotBundleId : marks[index].front
        }
        return nil
    }

    /// The source `bundleId` names: cmux, Screenshot, or an installed app; nil for none installed.
    nonisolated static func source(bundleId: String, apps: AttachmentSourceApps) -> AttachmentSource? {
        if bundleId == apps.ownBundleId() { return .cmux }
        guard AttachmentSource.isBundleId(bundleId), let name = apps.app(bundleId) else { return nil }
        return AttachmentSource(name: name, bundleId: bundleId)
    }
}
