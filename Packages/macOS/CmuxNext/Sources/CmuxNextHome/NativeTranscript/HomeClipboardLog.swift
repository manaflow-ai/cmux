import AppKit

/// One thing copied: a text, or a picture with its type (the bytes the + menu attaches, as a paste would).
nonisolated enum HomeClipboardContent: Hashable, Sendable {
    case text(String)
    case image(Data, typeIdentifier: String)

    /// Bytes it holds (the log's memory cap counts them).
    var byteCount: Int {
        switch self {
        case .text(let text): text.utf8.count
        case .image(let data, _): data.count
        }
    }
}

/// One row of the clipboard history: what was copied and the pasteboard's change count when it was read.
nonisolated struct HomeClipboardEntry: Hashable, Sendable, Identifiable {
    /// The general pasteboard's `changeCount` when this was read (unique per copy).
    let id: Int
    let content: HomeClipboardContent
}

/// The Chief's clipboard history (the + menu's Clipboard rows), as a value: newest first, in
/// memory only. Pure, so its rules are property-tested without a pasteboard server:
///
/// - Read once per copy: the same `changeCount` is never read twice (``needsRead(changeCount:)``).
/// - Never kept: anything a password manager or a clipboard-aware app marks concealed, transient
///   or generated (nspasteboard.org's types and the older markers they list), copied files
///   (Finder's copies: the menu offers files through the picker), blank text, text over
///   ``maxTextBytes`` and pictures over ``maxImageBytes``.
/// - A copy already in the log moves to the front instead of showing twice.
/// - At most ``capacity`` entries and ``maxTotalBytes`` in all: the oldest go first.
nonisolated struct HomeClipboardLog: Sendable, Equatable {
    /// Newest first.
    private(set) var entries: [HomeClipboardEntry] = []
    /// The last `changeCount` read (kept or skipped).
    private(set) var lastChangeCount: Int?
    let capacity: Int
    let maxTotalBytes: Int

    /// About 20 copies.
    static let defaultCapacity = 20
    /// A picture's bytes are kept up to 10 MB (a Retina screenshot is 2-8 MB).
    static let maxImageBytes = 10 * 1024 * 1024
    /// Text over 256 KB (a log dump) is not a clipboard row.
    static let maxTextBytes = 256 * 1024
    /// Everything the log holds stays under 40 MB.
    static let defaultMaxTotalBytes = 40 * 1024 * 1024

    init(capacity: Int = HomeClipboardLog.defaultCapacity, maxTotalBytes: Int = HomeClipboardLog.defaultMaxTotalBytes) {
        self.capacity = max(1, capacity)
        self.maxTotalBytes = max(1, maxTotalBytes)
    }

    /// Markers that keep a copy out of every clipboard history (nspasteboard.org): concealed
    /// (passwords; cmux's own `ConcealedPasteboard` writes it), transient, generated, plus the
    /// older per-app markers that page lists (1Password, KeeWeb, TypeIt4Me, Peter Maurer's apps).
    static let skippedTypes: [NSPasteboard.PasteboardType] = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "net.antelle.keeweb", "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ].map { NSPasteboard.PasteboardType($0) }

    /// Whether `changeCount` is a copy this log has not read yet.
    func needsRead(changeCount: Int) -> Bool { changeCount != lastChangeCount }

    /// What a pasteboard holds that the history keeps, or nil (marked, files, blank, too large).
    /// Pictures follow the paste rule (`HomeAttachmentIntake`): a picture beside real text is
    /// that text's own image, so the text is kept.
    @MainActor static func content(of board: any HomePasteboardContents) -> HomeClipboardContent? {
        if board.hasType(skippedTypes) || board.hasType([.fileURL]) { return nil }
        if !HomeAttachmentIntake.hasText(board), let picture = HomeAttachmentIntake.inputs(from: board).first,
           case let .data(data, type) = picture {
            return data.count <= maxImageBytes ? .image(data, typeIdentifier: type) : nil
        }
        guard let text = board.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= maxTextBytes else { return nil }
        return .text(text)
    }

    /// Reads one copy: `content` (nil when skipped) at `changeCount`. A change count already
    /// read changes nothing. Returns true when the entries changed.
    @discardableResult
    mutating func record(_ content: HomeClipboardContent?, changeCount: Int) -> Bool {
        guard needsRead(changeCount: changeCount) else { return false }
        lastChangeCount = changeCount
        guard let content else { return false }
        entries.removeAll { $0.content == content }
        entries.insert(HomeClipboardEntry(id: changeCount, content: content), at: 0)
        trim()
        return true
    }

    /// The newest `limit` entries (the + menu's rows).
    func newest(_ limit: Int) -> [HomeClipboardEntry] { Array(entries.prefix(max(0, limit))) }

    /// Forgets everything (the setting turned off).
    mutating func clear() {
        entries.removeAll()
        lastChangeCount = nil
    }

    private mutating func trim() {
        if entries.count > capacity { entries.removeLast(entries.count - capacity) }
        var total = entries.reduce(0) { $0 + $1.content.byteCount }
        // The newest entry always stays (each is under the per-item caps, which fit the total).
        while total > maxTotalBytes, entries.count > 1 {
            total -= entries.removeLast().content.byteCount
        }
    }
}
