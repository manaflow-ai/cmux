import Foundation

/// Writes the Swift source of the hot-message codec for CmuxNextIPC (p05-ipc-183) from
/// cmux-tui/spec/sdk-schema.json, at build time: CmuxNextWireGen's main writes `source()` to
/// `HotCodec+Schema.swift` in the plugin work directory. Nothing it writes is committed.
///
/// The output is, for every type a binary layout reaches (``HotSchema``), a `Hot<Name>` struct or
/// enum that is ``HotValue`` (its binary layout, in CmuxNextIPC's HotLayout.swift) and `Codable`
/// (its JSON form, the same members, so one value serves the JSON line and the frame), then one
/// `HotLayout<Body>` static per message and `HotLayoutInfo.schema`, every layout. The Rust twin is
/// cmux-tui/crates/cmux-ipc/build-support/hot_codec.rs; `Hot<Name>` is its `<Name>`. Two runs over
/// the same schema write the same bytes.
struct HotEmitter {
    /// The file name main writes `source()` to.
    static let outputFileName = "HotCodec+Schema.swift"

    let schema: HotSchema

    init(schema: HotSchema) {
        self.schema = schema
    }

    init(sdkSchema: Data) throws(HotSchemaError) {
        self.init(schema: try HotSchema(sdkSchema: sdkSchema))
    }

    func source() -> String {
        var out = """
        // Generated by CmuxNextWireGen (HotEmitter) from cmux-tui/spec/sdk-schema.json at build time.
        // Do not edit; never committed.

        import Foundation

        """
        for name in schema.enums.keys.sorted(by: HotSchema.byteOrder) {
            if let entry = schema.enums[name] { out += Self.enumeration(entry) }
        }
        for name in schema.structs.keys.sorted(by: HotSchema.byteOrder) {
            if let entry = schema.structs[name] { out += Self.structure(entry) }
        }
        for message in schema.messages {
            out += """

            extension HotLayout where Body == \(Self.typeName(message.type)) {
                /// The `\(message.name)` \(message.part.rawValue) layout.
                public static var \(Self.layoutName(message)): Self { Self(\(Self.info(message))) }
            }

            """
        }
        out += "\nextension HotLayoutInfo {\n"
        out += "    /// Every binary layout of the schema: commands, then events, by name.\n"
        out += "    public static let schema: [HotLayoutInfo] = [\n"
        for message in schema.messages {
            out += "        \(Self.info(message)),\n"
        }
        out += "    ]\n}\n"
        return out
    }

    // Names -----------------------------------------------------------------

    static func typeName(_ rust: String) -> String { "Hot" + rust }

    /// `resize-attached-view` request -> `resizeAttachedViewRequest`.
    static func layoutName(_ message: HotSchema.Message) -> String {
        SwiftNaming.identifier(SwiftNaming.propertyName(message.name + "_" + message.part.rawValue))
    }

    private static func property(_ wire: String) -> String {
        SwiftNaming.identifier(SwiftNaming.propertyName(wire))
    }

    private static func info(_ m: HotSchema.Message) -> String {
        "HotLayoutInfo(name: \(TableEmitter.literal(m.name)), part: .\(m.part.rawValue), "
            + "wireID: \(TableEmitter.hex(m.wireID, width: 4)), layoutVersion: \(m.layoutVersion), "
            + "typeName: \(TableEmitter.literal(m.type)))"
    }

    private static func swiftType(_ type: HotSchema.WireType) -> String {
        switch type {
        case .bool: "Bool"
        case .u16: "UInt16"
        case .u32: "UInt32"
        case .u64: "UInt64"
        case .i32: "Int32"
        case .i64: "Int64"
        case .f32: "Float"
        case .f64: "Double"
        case .string: "String"
        case .enumeration(let name), .object(let name): typeName(name)
        case .array(let items, _): "[\(swiftType(items))]"
        }
    }

    private static func fieldType(_ field: HotSchema.Field) -> String {
        swiftType(field.type) + (field.tagged ? "?" : "")
    }

    // Enums -----------------------------------------------------------------

    private static func enumeration(_ entry: HotSchema.Enumeration) -> String {
        let name = typeName(entry.name)
        var out = "\n/// `\(entry.name)`: a u8 index on the wire, its value in JSON.\n"
        out += "public enum \(name): String, Hashable, Sendable, CaseIterable {\n"
        for value in entry.values {
            out += "    case \(property(value)) = \(TableEmitter.literal(value))\n"
        }
        out += "}\n\nextension \(name) {\n"
        out += "    /// The wire index.\n    public var hotIndex: UInt8 {\n        switch self {\n"
        for (index, value) in entry.values.enumerated() {
            out += "        case .\(property(value)): \(index)\n"
        }
        out += "        }\n    }\n\n"
        out += "    /// The value with wire index `index`.\n"
        out += "    public init(hotIndex index: UInt8) throws(HotDecodeError) {\n        switch index {\n"
        for (index, value) in entry.values.enumerated() {
            out += "        case \(index): self = .\(property(value))\n"
        }
        out += "        default: throw .badEnum(type: \(TableEmitter.literal(entry.name)), index: index)\n"
        out += "        }\n    }\n}\n"
        if let fallback = entry.fallback {
            out += """

            extension \(name): Codable {
                /// An unknown value reads as `\(fallback)`.
                public init(from decoder: any Decoder) throws {
                    let raw = try decoder.singleValueContainer().decode(String.self)
                    self = Self(rawValue: raw) ?? .\(property(fallback))
                }
            }

            """
        } else {
            out += "\nextension \(name): Codable {}\n"
        }
        return out
    }

    // Structs ---------------------------------------------------------------

    private static func structure(_ entry: HotSchema.Struct) -> String {
        let name = typeName(entry.name)
        var out = "\n/// `\(entry.name)`, fields in layout order.\n"
        out += "public struct \(name): Hashable, Sendable {\n"
        for field in entry.fields {
            out += "    /// `\(field.wire)`.\n    public var \(property(field.wire)): \(fieldType(field))\n"
        }
        let parameters = entry.fields.map { field in
            "\(property(field.wire)): \(fieldType(field))" + (field.tagged ? " = nil" : "")
        }
        out += "\n    public init(\(parameters.joined(separator: ", "))) {\n"
        for field in entry.fields {
            out += "        self.\(property(field.wire)) = \(property(field.wire))\n"
        }
        out += "    }\n}\n"
        out += binary(entry, name: name)
        out += json(entry, name: name)
        return out
    }

    private static func binary(_ entry: HotSchema.Struct, name: String) -> String {
        var counter = 0
        var out = "\nextension \(name): HotValue {\n"
        out += "    public func hotWrite(to writer: inout HotWriter) throws(HotEncodeError) {\n"
        for field in entry.fields {
            out += write(field, value: property(field.wire), indent: "        ", counter: &counter)
        }
        out += "    }\n\n"
        out += "    public init(hotReader reader: inout HotReader) throws(HotDecodeError) {\n"
        for field in entry.fields {
            out += read(field, into: property(field.wire), indent: "        ", counter: &counter)
        }
        let arguments = entry.fields.map { "\(property($0.wire)): \(property($0.wire))" }
        out += "        self.init(\(arguments.joined(separator: ", ")))\n"
        out += "    }\n}\n"
        return out
    }

    private static func write(_ field: HotSchema.Field, value: String, indent: String, counter: inout Int) -> String {
        guard field.tagged else { return write(field.type, value: value, indent: indent, counter: &counter) }
        counter += 1
        let present = "value\(counter)"
        return "\(indent)if let \(present) = \(value) {\n"
            + "\(indent)    writer.tag(true)\n"
            + write(field.type, value: present, indent: indent + "    ", counter: &counter)
            + "\(indent)} else {\n\(indent)    writer.tag(false)\n\(indent)}\n"
    }

    /// Statements that write `value`, an expression of `type`.
    private static func write(_ type: HotSchema.WireType, value: String, indent: String, counter: inout Int) -> String {
        switch type {
        case .bool: return "\(indent)writer.bool(\(value))\n"
        case .u16: return "\(indent)writer.u16(\(value))\n"
        case .u32: return "\(indent)writer.u32(\(value))\n"
        case .u64: return "\(indent)writer.u64(\(value))\n"
        case .i32: return "\(indent)writer.i32(\(value))\n"
        case .i64: return "\(indent)writer.i64(\(value))\n"
        case .f32: return "\(indent)writer.f32(\(value))\n"
        case .f64: return "\(indent)writer.f64(\(value))\n"
        case .string(let maxBytes): return "\(indent)try writer.string(\(value), max: \(maxBytes))\n"
        case .enumeration: return "\(indent)writer.enumeration(\(value).hotIndex)\n"
        case .object: return "\(indent)try \(value).hotWrite(to: &writer)\n"
        case .array(let items, let maxItems):
            counter += 1
            let item = "item\(counter)"
            return "\(indent)try writer.count(\(value).count, max: \(maxItems))\n"
                + "\(indent)for \(item) in \(value) {\n"
                + write(items, value: item, indent: indent + "    ", counter: &counter)
                + "\(indent)}\n"
        }
    }

    private static func read(_ field: HotSchema.Field, into name: String, indent: String, counter: inout Int) -> String {
        guard field.tagged else { return read(field.type, into: name, indent: indent, counter: &counter) }
        counter += 1
        let present = "value\(counter)"
        return "\(indent)let \(name): \(fieldType(field))\n"
            + "\(indent)if try reader.tag() {\n"
            + read(field.type, into: present, indent: indent + "    ", counter: &counter)
            + "\(indent)    \(name) = \(present)\n"
            + "\(indent)} else {\n\(indent)    \(name) = nil\n\(indent)}\n"
    }

    /// Statements that declare `name` and read a `type` into it.
    private static func read(_ type: HotSchema.WireType, into name: String, indent: String, counter: inout Int) -> String {
        switch type {
        case .bool: return "\(indent)let \(name) = try reader.bool()\n"
        case .u16: return "\(indent)let \(name) = try reader.u16()\n"
        case .u32: return "\(indent)let \(name) = try reader.u32()\n"
        case .u64: return "\(indent)let \(name) = try reader.u64()\n"
        case .i32: return "\(indent)let \(name) = try reader.i32()\n"
        case .i64: return "\(indent)let \(name) = try reader.i64()\n"
        case .f32: return "\(indent)let \(name) = try reader.f32()\n"
        case .f64: return "\(indent)let \(name) = try reader.f64()\n"
        case .string(let maxBytes): return "\(indent)let \(name) = try reader.string(max: \(maxBytes))\n"
        case .enumeration(let type):
            return "\(indent)let \(name) = try \(typeName(type))(hotIndex: try reader.enumeration())\n"
        case .object(let type):
            return "\(indent)let \(name) = try \(typeName(type))(hotReader: &reader)\n"
        case .array(let items, let maxItems):
            counter += 1
            let count = "count\(counter)"
            let item = "item\(counter)"
            return "\(indent)let \(count) = try reader.count(max: \(maxItems))\n"
                + "\(indent)var \(name): \(swiftType(type)) = []\n"
                + "\(indent)\(name).reserveCapacity(\(count))\n"
                + "\(indent)for _ in 0..<\(count) {\n"
                + read(items, into: item, indent: indent + "    ", counter: &counter)
                + "\(indent)    \(name).append(\(item))\n"
                + "\(indent)}\n"
        }
    }

    // JSON ------------------------------------------------------------------

    private static func json(_ entry: HotSchema.Struct, name: String) -> String {
        guard !entry.fields.isEmpty || !entry.literals.isEmpty else {
            return """

            extension \(name): Codable {
                /// The members of an empty body are never read.
                public init(from decoder: any Decoder) throws {
                    self.init()
                }

                public func encode(to encoder: any Encoder) throws {
                    var container = encoder.singleValueContainer()
                    try container.encode([String: Bool]())
                }
            }

            """
        }
        var out = "\nextension \(name): Codable {\n    private enum CodingKeys: String, CodingKey {\n"
        for wire in (entry.fields.map(\.wire) + entry.literals.map(\.wire)).sorted(by: HotSchema.byteOrder) {
            out += "        case \(property(wire)) = \(TableEmitter.literal(wire))\n"
        }
        out += "    }\n\n    public init(from decoder: any Decoder) throws {\n"
        out += "        let container = try decoder.container(keyedBy: CodingKeys.self)\n"
        let arguments = entry.fields.map { field in
            let decode = field.tagged ? "decodeIfPresent" : "decode"
            return "            \(property(field.wire)): try container.\(decode)(\(swiftType(field.type)).self, "
                + "forKey: .\(property(field.wire)))"
        }
        if arguments.isEmpty {
            out += "        _ = container\n        self.init()\n"
        } else {
            out += "        self.init(\n\(arguments.joined(separator: ",\n"))\n        )\n"
        }
        out += "    }\n\n    public func encode(to encoder: any Encoder) throws {\n"
        out += "        var container = encoder.container(keyedBy: CodingKeys.self)\n"
        for literal in entry.literals {
            out += "        try container.encode(\(TableEmitter.literal(literal.value)), forKey: .\(property(literal.wire)))\n"
        }
        for field in entry.fields {
            // A required nullable member is written as null; an optional one is left out.
            let encode = field.tagged && !field.writesNull ? "encodeIfPresent" : "encode"
            out += "        try container.\(encode)(\(property(field.wire)), forKey: .\(property(field.wire)))\n"
        }
        out += "    }\n}\n"
        return out
    }
}
