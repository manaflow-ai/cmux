// Writes `public struct <Name>Request: DaemonRequest` for every command the macOS app
// calls (p05-ipc.md section 3.3, task 021), one file per family. A request type carries
// its command name and its Response only: method id, priority and capability live in
// CmuxNextIPC's MethodTable (task 023), as a Mojo method's generated params struct holds
// only its parameters while the ordinal and flags travel in the message header
// (mojo/public/cpp/bindings/lib/message_internal.h, `MessageHeader`).
//
// Every member has an explicit CodingKey with its wire name: the generated encoder needs
// no key strategy (WireKeyInventory lists the keys the old snake-case one sent otherwise).
// Nothing it writes is committed; main writes the files once the requests' target
// carries DaemonRequest and FieldUpdate (task 025) and the named schema types (task 020),
// which must be Hashable to be a FieldUpdate's value.

/// Emits the request and response types of a ``RequestSchema``.
struct RequestEmitter {
    /// One generated file.
    struct File: Equatable {
        let name: String
        let source: String
    }

    let schema: RequestSchema

    /// One file per family, in family-name order, each with its commands in wire-name order.
    func files() -> [File] {
        var families: [String: [RequestCommand]] = [:]
        for command in schema.commands { families[command.family, default: []].append(command) }
        return families.keys.sorted().map { family in
            let commands = families[family] ?? []
            let foundation = commands.contains { command in
                command.response.usesFoundation || command.fields.contains { $0.type.usesFoundation }
            }
            var source = """
            // Generated by CmuxNextWireGen (RequestEmitter) from cmux-tui/spec/sdk-schema.json at build
            // time: the `\(family)` commands the macOS app calls. Do not edit; never committed.

            """
            if foundation { source += "\npublic import Foundation\n" }
            for command in commands { source += "\n" + self.source(for: command) }
            return File(name: "Requests+\(SwiftNaming.typeName(family)).swift", source: source)
        }
    }

    /// The Swift source of `command`'s request type.
    func source(for command: RequestCommand) -> String {
        var writer = SwiftWriter()
        let id = command.methodID.map { "method \(MethodTableSchemaReader.hex($0, width: 4)), " } ?? ""
        writer.line("/// `\(command.wire)` (\(id)family `\(command.family)`).")
        let conformance = command.spawnsTerminal ? "TerminalSpawningRequest" : "DaemonRequest"
        writer.open("public struct \(command.typeName): \(conformance), Equatable")
        if command.response.swift != "Response" {
            writer.line("public typealias Response = \(command.response.swift)")
        }
        writer.line("public static let commandName: DaemonCommandName = \(TableEmitter.literal(command.wire))")
        if let declared = command.response.declared { declare(declared, role: .decodable, into: &writer) }
        for field in command.fields {
            if let declared = field.type.declared { declare(declared, role: .encodable, into: &writer) }
        }
        members(command.fields, role: .encodable, into: &writer)
        writer.close()
        return writer.text
    }

    // Declarations ----------------------------------------------------------

    /// Which way a generated object crosses the wire.
    enum Role {
        case encodable
        case decodable
    }

    private func declare(_ type: WireType, role: Role, into writer: inout SwiftWriter) {
        switch type {
        case .object(let object):
            writer.blank()
            // An encodable object can be a `FieldUpdate` value, which needs Hashable.
            let conformance = role == .encodable ? "Encodable, Sendable, Hashable" : "Decodable, Sendable, Equatable"
            writer.open("public struct \(object.name): \(conformance)")
            for field in object.fields {
                if let declared = field.type.declared { declare(declared, role: role, into: &writer) }
            }
            members(object.fields, role: role, into: &writer)
            writer.close()
        case .enumeration(let enumeration):
            writer.blank()
            writer.open("public enum \(enumeration.name): String, Codable, Sendable, Equatable, CaseIterable")
            for item in enumeration.cases {
                let name = SwiftNaming.identifier(item.swift)
                let wire = TableEmitter.literal(item.wire)
                writer.line(item.swift == item.wire ? "case \(name)" : "case \(name) = \(wire)")
            }
            if let fallback = enumeration.fallback {
                writer.blank()
                writer.line("/// A value this build does not know decodes as `.\(fallback)`.")
                writer.open("public init(from decoder: any Decoder) throws")
                writer.line("let raw = try decoder.singleValueContainer().decode(String.self)")
                writer.line("self = Self(rawValue: raw) ?? .\(SwiftNaming.identifier(fallback))")
                writer.close()
            }
            writer.close()
        case .named, .json, .array, .map, .literal:
            break
        }
    }

    /// Stored properties, the memberwise init, CodingKeys and the coder of `fields`.
    private func members(_ fields: [WireType.Field], role: Role, into writer: inout SwiftWriter) {
        let coded = fields.map { RequestMember(field: $0, role: role) }
        for member in coded where member.isStored {
            writer.blank()
            for line in member.field.description?.split(separator: "\n", omittingEmptySubsequences: false) ?? [] {
                writer.line(line.isEmpty ? "///" : "/// \(line)")
            }
            writer.line("public var \(member.name): \(member.propertyType)")
        }
        writer.blank()
        let parameters = coded.filter(\.isStored).map { member in
            "\(member.name): \(member.propertyType)\(member.parameterDefault.map { " = \($0)" } ?? "")"
        }
        writer.open("public init(\(parameters.joined(separator: ", ")))")
        for member in coded where member.isStored {
            writer.line("self.\(member.name) = \(member.name)")
        }
        writer.close()
        writer.blank()
        // An object with no members codes nothing: a request adds no key to the envelope's,
        // a nested value is `{}` and a decoded one accepts any object (as EmptyResponse does).
        if coded.isEmpty {
            switch role {
            case .encodable: writer.line("public func encode(to encoder: any Encoder) throws {}")
            case .decodable: writer.line("public init(from decoder: any Decoder) throws {}")
            }
            return
        }
        writer.open("enum CodingKeys: String, CodingKey")
        for member in coded {
            let swift = SwiftNaming.identifier(member.field.swift)
            let wire = TableEmitter.literal(member.field.wire)
            writer.line(member.field.swift == member.field.wire ? "case \(swift)" : "case \(swift) = \(wire)")
        }
        writer.close()
        writer.blank()
        switch role {
        case .encodable:
            writer.open("public func encode(to encoder: any Encoder) throws")
            writer.line("var container = encoder.container(keyedBy: CodingKeys.self)")
            for member in coded { member.encodeStatements.forEach { writer.line($0) } }
        case .decodable:
            writer.open("public init(from decoder: any Decoder) throws")
            writer.line("let container = try decoder.container(keyedBy: CodingKeys.self)")
            for member in coded { member.decodeStatements.forEach { writer.line($0) } }
        }
        writer.close()
    }
}

/// Lines of Swift with nesting.
struct SwiftWriter {
    private(set) var text = ""
    private var depth = 0

    mutating func line(_ content: some StringProtocol) {
        text += String(repeating: "    ", count: depth) + String(content) + "\n"
    }

    mutating func blank() {
        if !text.hasSuffix("{\n") && !text.hasSuffix("\n\n") { text += "\n" }
    }

    mutating func open(_ header: String) {
        line(header + " {")
        depth += 1
    }

    mutating func close() {
        depth -= 1
        line("}")
    }
}
