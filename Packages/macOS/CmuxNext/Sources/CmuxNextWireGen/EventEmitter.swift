import Foundation

/// Writes the Swift source of `DaemonWireEvent` for CmuxNextIPC (p05-ipc.md task 022): a case per
/// framed event of cmux-tui/spec/sdk-schema.json plus `unknown(name:raw:)`, and its
/// `WireEventSet` conformance, a switch on the event id that decodes the payload once into the
/// event's type. The decode logic (name scan, table lookup, fallback) is hand-written in
/// CmuxNextIPC's WireEventSet.swift; this writes only what the schema decides.
///
/// Each event's payload type is `<UpperCamel name>Event` (`size-state` is `SizeStateEvent`),
/// declared by TypeEmitter (task 020) next to the types it reaches. An event without an
/// `event_id` is not framed (MethodTableSchema) and decodes as `unknown`.
struct EventEmitter {
    /// The file name main writes `source()` to.
    static let outputFileName = "DaemonWireEvent+Schema.swift"

    /// One case of `DaemonWireEvent`.
    struct Case: Equatable {
        let id: UInt16
        /// The schema's kebab-case event name.
        let name: String
        /// The Swift case name, backquoted when it is a keyword.
        let caseName: String
        let payloadType: String
    }

    /// The cases in event-id order.
    let cases: [Case]

    init(schema: MethodTableSchema) throws(MethodTableSchemaError) {
        let events = schema.events.flatMap { family in family.slots.compactMap { $0 } }.sorted { $0.id < $1.id }
        var cases: [Case] = []
        var owners: [String: String] = ["unknown": "the unknown case"]
        for event in events {
            let path = "$.events.\(event.name)"
            let words = try Self.words(of: event.name, path: path)
            let identifier = words[0] + words.dropFirst().map(Self.capitalized).joined()
            if let owner = owners.updateValue(event.name, forKey: identifier) {
                throw MethodTableSchemaError(file: MethodTableSchema.sdkFile, path: path,
                                             message: "its Swift case `\(identifier)` is also \(owner)")
            }
            cases.append(Case(
                id: event.id,
                name: event.name,
                caseName: Self.keywords.contains(identifier) ? "`\(identifier)`" : identifier,
                payloadType: words.map(Self.capitalized).joined() + "Event"
            ))
        }
        self.cases = cases
    }

    init(sdkSchema: Data, resourceOperations: Data) throws(MethodTableSchemaError) {
        try self.init(schema: MethodTableSchema(sdkSchema: sdkSchema, resourceOperations: resourceOperations))
    }

    /// The Swift source of `DaemonWireEvent`. Two runs over the same schema write the same bytes.
    func source() -> String {
        var out = """
        // Generated by CmuxNextWireGen (EventEmitter) from cmux-tui/spec/sdk-schema.json at build
        // time. Do not edit; never committed.

        public import Foundation

        /// Every framed daemon event of the schema this build was generated from, and `unknown` for
        /// the rest.
        public enum DaemonWireEvent: Sendable, Equatable {

        """
        for event in cases {
            out += "    /// `\(event.name)` (\(TableEmitter.hex(event.id, width: 4))).\n"
            out += "    case \(event.caseName)(\(event.payloadType))\n"
        }
        out += """
            /// An event this build has no case for: its wire name and its undecoded bytes.
            case unknown(name: String, raw: Data)

            /// The event's wire name.
            public var name: String {
                switch self {

        """
        for event in cases {
            out += "        case .\(event.caseName): \(TableEmitter.literal(event.name))\n"
        }
        out += """
                case .unknown(let name, _): name
                }
            }
        }

        extension DaemonWireEvent: WireEventSet {
            public static func decodeKnown(
                id: EventID,
                payload: Data,
                using decoder: some WireEventDecoding
            ) throws -> DaemonWireEvent? {
                switch id.rawValue {

        """
        for event in cases {
            out += "        case \(TableEmitter.hex(event.id, width: 4)): "
                + "return .\(event.caseName)(try decoder.decode(\(event.payloadType).self, from: payload))\n"
        }
        out += """
                default: return nil
                }
            }

            /// Decodes one event line with one decode of it (WireEventSet.decode(line:table:using:)).
            public static func decode(
                line: Data,
                using decoder: some WireEventDecoding
            ) throws(WireEventDecodeError) -> DaemonWireEvent {
                try decode(line: line, table: .schema, using: decoder)
            }

            /// Decodes a TYPED_EVENT payload by its id (WireEventSet.decode(eventID:payload:table:using:)).
            public static func decode(
                eventID: EventID,
                payload: Data,
                using decoder: some WireEventDecoding
            ) throws(WireEventDecodeError) -> DaemonWireEvent {
                try decode(eventID: eventID, payload: payload, table: .schema, using: decoder)
            }
        }

        """
        return out
    }

    // Names -----------------------------------------------------------------

    /// The lowercase ASCII words of an event name (`size-state` is `size`, `state`); refuses a
    /// name that cannot become a Swift identifier.
    private static func words(of name: String, path: String) throws(MethodTableSchemaError) -> [String] {
        let words = name.split { !($0.isASCII && ($0.isLetter || $0.isNumber)) }.map { $0.lowercased() }
        guard name.allSatisfy({ $0.isASCII && ($0.isLetter || $0.isNumber || $0 == "-" || $0 == "_" || $0 == ".") }),
              let first = words.first?.first, first.isLetter
        else {
            throw MethodTableSchemaError(file: MethodTableSchema.sdkFile, path: path,
                                         message: "the name has no Swift case: use ASCII letters, digits and - _ ., starting with a letter")
        }
        return words
    }

    private static func capitalized(_ word: String) -> String {
        word.prefix(1).uppercased() + word.dropFirst()
    }

    /// Swift keywords a lower-camel case name could equal; such a case is backquoted.
    static let keywords: Set<String> = [
        "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init",
        "inout", "internal", "let", "open", "operator", "private", "precedencegroup", "protocol", "public",
        "rethrows", "static", "struct", "subscript", "typealias", "var", "break", "case", "catch", "continue",
        "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return",
        "throw", "switch", "where", "while", "as", "false", "is", "nil", "self", "super", "throws", "true",
        "try", "await", "async", "consume", "copy", "discard", "each", "borrowing", "consuming", "any", "some",
        "package", "sending",
    ]
}
