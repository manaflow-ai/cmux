import Foundation

/// Writes the Swift source of `MethodTable.schema` for CmuxNextIPC
/// (Sources/CmuxNextIPC/MethodTable.swift) from the two schema files, at build
/// time: CmuxNextWireGen's main writes `source()` to `MethodTable+Schema.swift`
/// in the plugin work directory. Nothing it writes is committed.
///
/// The output is one dense family array per id space (indexed by
/// `family - range.lowerBound`), each family a dense array of ordinals, the
/// same shape as the Rust tables of cmux-tui/crates/cmux-ipc/build.rs, but
/// holding only the commands and operations whose `clients` include `macos`.
/// Each family is its own declaration so the type checker never sees one huge
/// literal. It is one file, not one per family (p05-ipc.md, "Build time"): the
/// tool rewrites every output on any schema edit, so split files would all
/// recompile anyway. Two runs over the same schema write the same bytes.
struct TableEmitter {
    /// The file name main writes `source()` to.
    static let outputFileName = "MethodTable+Schema.swift"

    let schema: MethodTableSchema

    init(schema: MethodTableSchema) {
        self.schema = schema
    }

    init(sdkSchema: Data, resourceOperations: Data) throws(MethodTableSchemaError) {
        self.init(schema: try MethodTableSchema(sdkSchema: sdkSchema, resourceOperations: resourceOperations))
    }

    /// The Swift source of `extension MethodTable { public static let schema }`.
    func source() -> String {
        var out = """
        // Generated by CmuxNextWireGen (TableEmitter) from cmux-tui/spec/sdk-schema.json
        // and cmux-tui/spec/resource-operations-v2.json at build time. Do not edit;
        // never committed.

        extension MethodTable {
            /// The tables of the schema this build was generated from.
            public static let schema = MethodTable(v12: schemaV12, v2: schemaV2, events: schemaEvents)
        }

        """
        out += space("schemaV12", entry: "MethodAttributes", range: MethodTableSchema.Space.v12.range,
                     families: schema.v12, row: method)
        out += space("schemaV2", entry: "MethodAttributes", range: MethodTableSchema.Space.v2.range,
                     families: schema.v2, row: method)
        out += space("schemaEvents", entry: "EventAttributes", range: MethodTableSchema.Space.events.range,
                     families: schema.events, row: event)
        return out
    }

    // Spaces and families ---------------------------------------------------

    private func space<Row>(
        _ name: String,
        entry: String,
        range: ClosedRange<UInt8>,
        families: [MethodTableSchema.Family<Row>],
        row: (Row) -> String
    ) -> String {
        var out = "\nprivate let \(name): [MethodTableFamily<\(entry)>?] = [\n"
        for id in range {
            if families.contains(where: { $0.id == id }) {
                out += "    \(name)Family\(Self.hex(UInt16(id), width: 2)),\n"
            } else {
                out += "    nil,\n"
            }
        }
        out += "]\n"
        for family in families {
            out += "\nprivate let \(name)Family\(Self.hex(UInt16(family.id), width: 2)) = MethodTableFamily<\(entry)>(\n"
            out += "    id: \(Self.hex(UInt16(family.id), width: 2)),\n"
            out += "    name: \(Self.literal(family.name)),\n"
            out += "    entries: [\n"
            for slot in family.slots {
                out += "        \(slot.map(row) ?? "nil"),\n"
            }
            out += "    ]\n)\n"
        }
        return out
    }

    // Rows ------------------------------------------------------------------

    private func method(_ m: MethodTableSchema.Method) -> String {
        let payload = m.binaryLayout.map { ".binary(layoutVersion: \($0))" } ?? ".json"
        return "MethodAttributes(id: MethodID(rawValue: \(Self.hex(m.id, width: 4))), name: \(Self.literal(m.name)), "
            + "priority: .\(m.priority), ordering: .\(m.ordering), durability: .\(m.durability), "
            + "payload: \(payload), streamScoped: \(m.streamScoped), "
            + "crossesStreamOK: \(m.crossesStreamOK.map(Self.literal) ?? "nil"), "
            + "maxBytes: \(m.maxBytes.map { String($0) } ?? "nil"), "
            + "coalesce: \(Self.coalesce(m.coalesce)), urgent: \(m.urgent))"
    }

    private func event(_ e: MethodTableSchema.Event) -> String {
        "EventAttributes(id: EventID(rawValue: \(Self.hex(e.id, width: 4))), name: \(Self.literal(e.name)), "
            + "priority: .\(e.priority), coalesce: \(Self.coalesce(e.coalesce)))"
    }

    private static func coalesce(_ coalesce: MethodTableSchema.Coalesce?) -> String {
        guard let coalesce else { return "nil" }
        let key = coalesce.key.map(literal).joined(separator: ", ")
        let additive = coalesce.additive.map(literal).joined(separator: ", ")
        return "MethodCoalesce(key: [\(key)], additive: [\(additive)])"
    }

    /// A Swift string literal of `text`: escapes quotes, backslashes and every
    /// scalar outside printable ASCII, so schema text can never end the literal
    /// or start an interpolation.
    static func literal(_ text: String) -> String {
        var out = "\""
        for scalar in text.unicodeScalars {
            switch scalar {
            case "\"": out += "\\\""
            case "\\": out += "\\\\"
            case " "..."~": out.unicodeScalars.append(scalar)
            default: out += "\\u{\(String(scalar.value, radix: 16, uppercase: true))}"
            }
        }
        return out + "\""
    }

    static func hex(_ value: UInt16, width: Int) -> String {
        MethodTableSchemaReader.hex(value, width: width)
    }
}
