import Foundation

/// macOS virtual key codes (`NSEvent.keyCode`, Carbon `kVK_*`) to USB HID
/// usages on the keyboard page (0x07). Key codes name physical positions,
/// so the table is layout independent: a key sends the usage of the US
/// key at the same place, and the host applies its own layout (section 7).
public struct RemoteHIDKeyMap {
    public init() {}
    /// HID keyboard/keypad usage page.
    public let keyboardPage: UInt32 = 0x07

    /// The full usage (`page << 16 | id`) of a key code, nil for keys with no
    /// HID usage (fn) or unknown codes.
    public func usage(forKeyCode keyCode: UInt16) -> UInt32? {
        guard Int(keyCode) < table.count else { return nil }
        let id = table[Int(keyCode)]
        return id == 0 ? nil : keyboardPage << 16 | UInt32(id)
    }

    /// The key code of a HID usage id on the keyboard page (reverse lookup;
    /// tests and the mock host use it).
    public func keyCode(forUsage usage: UInt32) -> UInt16? {
        guard usage >> 16 == keyboardPage else { return nil }
        let id = UInt16(usage & 0xFFFF)
        return table.firstIndex(of: id).map(UInt16.init)
    }

    /// Modifier keys (HID 0xE0...0xE7) and Caps Lock.
    public func isModifier(keyCode: UInt16) -> Bool {
        modifierKeyCodes.contains(keyCode)
    }

    /// Left/right Control, Shift, Option, Command, and Caps Lock.
    public let modifierKeyCodes: Set<UInt16> = [0x36, 0x37, 0x38, 0x39, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E]

    /// Index = key code, value = HID usage id (0 = none). 0x80 entries.
    static let table: [UInt16] = {
        var t = [UInt16](repeating: 0, count: 0x80)
        for (code, id) in pairs { t[Int(code)] = id }
        return t
    }()

    private static let pairs: [(UInt16, UInt16)] = letters + digits + punctuation + editing + modifiers
        + functionKeys + keypad + international + media

    private static let letters: [(UInt16, UInt16)] = [
        (0x00, 0x04), (0x0B, 0x05), (0x08, 0x06), (0x02, 0x07), (0x0E, 0x08), (0x03, 0x09), // a b c d e f
        (0x05, 0x0A), (0x04, 0x0B), (0x22, 0x0C), (0x26, 0x0D), (0x28, 0x0E), (0x25, 0x0F), // g h i j k l
        (0x2E, 0x10), (0x2D, 0x11), (0x1F, 0x12), (0x23, 0x13), (0x0C, 0x14), (0x0F, 0x15), // m n o p q r
        (0x01, 0x16), (0x11, 0x17), (0x20, 0x18), (0x09, 0x19), (0x0D, 0x1A), (0x07, 0x1B), // s t u v w x
        (0x10, 0x1C), (0x06, 0x1D), // y z
    ]

    private static let digits: [(UInt16, UInt16)] = [
        (0x12, 0x1E), (0x13, 0x1F), (0x14, 0x20), (0x15, 0x21), (0x17, 0x22), // 1 2 3 4 5
        (0x16, 0x23), (0x1A, 0x24), (0x1C, 0x25), (0x19, 0x26), (0x1D, 0x27), // 6 7 8 9 0
    ]

    private static let punctuation: [(UInt16, UInt16)] = [
        (0x1B, 0x2D), (0x18, 0x2E), (0x21, 0x2F), (0x1E, 0x30), (0x2A, 0x31), // - = [ ] backslash
        (0x29, 0x33), (0x27, 0x34), (0x32, 0x35), (0x2B, 0x36), (0x2F, 0x37), // ; ' ` , .
        (0x2C, 0x38), // /
    ]

    private static let editing: [(UInt16, UInt16)] = [
        (0x24, 0x28), (0x35, 0x29), (0x33, 0x2A), (0x30, 0x2B), (0x31, 0x2C), // return escape delete tab space
        (0x72, 0x49), (0x73, 0x4A), (0x74, 0x4B), (0x75, 0x4C), (0x77, 0x4D), // help/insert home pgup fwd-delete end
        (0x79, 0x4E), (0x7C, 0x4F), (0x7B, 0x50), (0x7D, 0x51), (0x7E, 0x52), // pgdn right left down up
        (0x6E, 0x65), // context menu (Application)
    ]

    private static let modifiers: [(UInt16, UInt16)] = [
        (0x39, 0x39), // caps lock
        (0x3B, 0xE0), (0x38, 0xE1), (0x3A, 0xE2), (0x37, 0xE3), // left control shift option command
        (0x3E, 0xE4), (0x3C, 0xE5), (0x3D, 0xE6), (0x36, 0xE7), // right control shift option command
    ]

    private static let functionKeys: [(UInt16, UInt16)] = [
        (0x7A, 0x3A), (0x78, 0x3B), (0x63, 0x3C), (0x76, 0x3D), (0x60, 0x3E), // F1-F5
        (0x61, 0x3F), (0x62, 0x40), (0x64, 0x41), (0x65, 0x42), (0x6D, 0x43), // F6-F10
        (0x67, 0x44), (0x6F, 0x45), (0x69, 0x68), (0x6B, 0x69), (0x71, 0x6A), // F11-F15
        (0x6A, 0x6B), (0x40, 0x6C), (0x4F, 0x6D), (0x50, 0x6E), (0x5A, 0x6F), // F16-F20
    ]

    private static let keypad: [(UInt16, UInt16)] = [
        (0x47, 0x53), (0x4B, 0x54), (0x43, 0x55), (0x4E, 0x56), (0x45, 0x57), // clear / * - +
        (0x4C, 0x58), (0x53, 0x59), (0x54, 0x5A), (0x55, 0x5B), (0x56, 0x5C), // enter 1 2 3 4
        (0x57, 0x5D), (0x58, 0x5E), (0x59, 0x5F), (0x5B, 0x60), (0x5C, 0x61), // 5 6 7 8 9
        (0x52, 0x62), (0x41, 0x63), (0x51, 0x67), // 0 . =
    ]

    private static let international: [(UInt16, UInt16)] = [
        (0x0A, 0x64), // ISO section (non-US backslash)
        (0x5F, 0x85), (0x5E, 0x87), (0x5D, 0x89), // JIS keypad comma, underscore (Ro), yen
        (0x68, 0x90), (0x66, 0x91), // JIS kana (LANG1), eisu (LANG2)
    ]

    private static let media: [(UInt16, UInt16)] = [
        (0x4A, 0x7F), (0x48, 0x80), (0x49, 0x81), // mute, volume up, volume down
    ]
}
