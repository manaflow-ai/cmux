// swift-tools-version: 6.0

import Foundation
import PackageDescription

// cmux-mobile-ffi (cmux-tui/crates/cmux-mobile-ffi) for the iOS apps: the
// published CmuxMobileFFIFFI xcframework and the uniffi Swift bindings
// generated from the same build. cmux-mobile-ffi.yml publishes each
// feat-cmux-next build as the release cmux-mobile-ffi-<sha> and re-pins this
// package (scripts/cmux-next/publish-mobile-ffi-repin.sh): mobile-ffi-pin.json
// and Sources/CmuxMobileFFI/CmuxMobileFFI.swift move in one commit, and
// scripts/cmux-next/check-mobile-ffi-pin.sh checks they match the release and
// the Rust sources. Never hand-edit either; run scripts/cmux-next/repin-mobile-ffi.sh.
//
// Before the first release the pin is empty: the package declares no targets
// and ios/CmuxiOS does not link it.

struct MobileFFIPin: Decodable {
    let url: String
    let checksum: String
}

let mobileFFIPin: MobileFFIPin = {
    let file = Foundation.URL(fileURLWithPath: #filePath).deletingLastPathComponent()
        .appendingPathComponent("mobile-ffi-pin.json")
    do {
        return try Foundation.JSONDecoder().decode(MobileFFIPin.self, from: Foundation.Data(contentsOf: file))
    } catch {
        fatalError("Packages/Shared/CmuxMobileFFI/mobile-ffi-pin.json: cannot read the CmuxMobileFFIFFI pin (\(file.path)): \(error)")
    }
}()

let pinned = !mobileFFIPin.url.isEmpty

let package = Package(
    name: "CmuxMobileFFI",
    platforms: [
        .iOS(.v17),
        .macOS(.v14),
    ],
    products: pinned ? [.library(name: "CmuxMobileFFI", targets: ["CmuxMobileFFI"])] : [],
    targets: pinned ? [
        .binaryTarget(name: "CmuxMobileFFIFFI", url: mobileFFIPin.url, checksum: mobileFFIPin.checksum),
        .target(
            name: "CmuxMobileFFI",
            dependencies: ["CmuxMobileFFIFFI"],
            path: "Sources/CmuxMobileFFI",
            // Generated by uniffi-bindgen; not ours to make Swift 6 clean.
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
    ] : []
)
