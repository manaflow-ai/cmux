/// HID keyboard usages to macOS virtual key codes (the `kVK_*` values a
/// CGEvent takes), by US key position.
public struct HidMacKeyCodeMap: Sendable {
    public init() {}

    public func keyCode(for usage: HidUsage) -> UInt16? {
        guard usage.isKeyboard else { return nil }
        return Self.table[usage.id]
    }

    private static let table: [UInt32: UInt16] = [
        // a to z
        0x04: 0x00, 0x05: 0x0B, 0x06: 0x08, 0x07: 0x02, 0x08: 0x0E, 0x09: 0x03, 0x0A: 0x05, 0x0B: 0x04, 0x0C: 0x22,
