/// HID keyboard usages and text to X11 keysyms, for RFB `KeyEvent`
/// (RFC 6143 7.5.4). Keys map by their US position; text maps per Unicode
/// scalar (Latin-1 directly, everything else as `0x01000000 + scalar`).
public struct HidKeysymMap: Sendable {
    public init() {}

    /// The keysym of a keyboard usage, or nil for usages with no X11 key.
    public func keysym(for usage: HidUsage) -> UInt32? {
        guard usage.isKeyboard else { return nil }
        let id = usage.id
        switch id {
        case 0x04...0x1D: return 0x61 + id - 0x04
        case 0x1E...0x26: return 0x31 + id - 0x1E
        case 0x27: return 0x30
        case 0x3A...0x45: return 0xFFBE + id - 0x3A
        case 0x68...0x73: return 0xFFCA + id - 0x68
        case 0x59...0x61: return 0xFFB1 + id - 0x59
        default: return Self.table[id]
        }
    }

    /// Keysyms that type `text`, one per Unicode scalar.
    public func keysyms(for text: String) -> [UInt32] {
        text.unicodeScalars.map { scalar in
            switch scalar.value {
            case 0x0A, 0x0D: 0xFF0D
            case 0x09: 0xFF09
            case 0x08: 0xFF08
            case 0x20...0x7E, 0xA0...0xFF: scalar.value
            default: 0x0100_0000 + scalar.value
            }
        }
    }

    private static let table: [UInt32: UInt32] = [
        0x28: 0xFF0D, 0x29: 0xFF1B, 0x2A: 0xFF08, 0x2B: 0xFF09, 0x2C: 0x20,
        0x2D: 0x2D, 0x2E: 0x3D, 0x2F: 0x5B, 0x30: 0x5D, 0x31: 0x5C, 0x32: 0x5C, 0x33: 0x3B, 0x34: 0x27,
        0x35: 0x60, 0x36: 0x2C, 0x37: 0x2E, 0x38: 0x2F, 0x39: 0xFFE5,
        0x46: 0xFF61, 0x47: 0xFF14, 0x48: 0xFF13, 0x49: 0xFF63, 0x4A: 0xFF50, 0x4B: 0xFF55, 0x4C: 0xFFFF,
        0x4D: 0xFF57, 0x4E: 0xFF56, 0x4F: 0xFF53, 0x50: 0xFF51, 0x51: 0xFF54, 0x52: 0xFF52,
        0x53: 0xFF7F, 0x54: 0xFFAF, 0x55: 0xFFAA, 0x56: 0xFFAD, 0x57: 0xFFAB, 0x58: 0xFF8D, 0x62: 0xFFB0,
        0x63: 0xFFAE, 0x64: 0x5C, 0x65: 0xFF67,
        0xE0: 0xFFE3, 0xE1: 0xFFE1, 0xE2: 0xFFE9, 0xE3: 0xFFEB, 0xE4: 0xFFE4, 0xE5: 0xFFE2, 0xE6: 0xFFEA, 0xE7: 0xFFEC,
    ]
}
