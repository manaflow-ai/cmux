#!/usr/bin/env bash
# Regenerate pilot BUILD files, the root BUILD and MODULE.bazel.
# Usage: bazel/pilot_setup.sh METADATA_JSON ROOT_CRATE...
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
meta="$1"; shift
python3 "$here/bazel/gen_rust_build.py" "$meta" "$here" "$@"
python3 - "$meta" "$here" <<'PY'
import json, os, sys
meta, root = sys.argv[1], sys.argv[2]
m = json.load(open(meta))
ws = set(m["workspace_members"])
manifests = []
for p in m["packages"]:
    if p["source"] is not None:
        continue
    rel = os.path.relpath(p["manifest_path"], root)
    d = os.path.dirname(rel)
    # crate_universe takes each manifest's directory from its label package,
    # so every Cargo.toml needs its own (possibly stub) Bazel package.
    stub = os.path.join(root, d, "BUILD.bazel")
    if not os.path.exists(stub):
        open(stub, "w").write("# Bazel pilot stub: crate_universe needs a package per Cargo.toml.\n")
    pkg = d
    manifests.append("//%s:%s" % (pkg, os.path.relpath(rel, pkg) if pkg else rel))
exports = json.load(open(os.path.join(root, "bazel/root_exports.json")))
# Root package also owns Cargo.toml/Cargo.lock labels for dirs without BUILD.
root_files = sorted(set(exports + [x.split(":",1)[1] for x in manifests if x.startswith("//:")]))
with open(os.path.join(root, "BUILD.bazel"), "w") as f:
    f.write("""# Bazel pilot root package (generated by bazel/pilot_setup.sh).
exports_files(%s)

filegroup(
    name = "ghostty_next_srcs",
    srcs = glob(
        ["ghostty-next/**"],
        exclude = ["ghostty-next/.git/**", "ghostty-next/.zig-cache/**", "ghostty-next/zig-out/**", "ghostty-next/zig-pkg/**"],
    ),
    visibility = ["//visibility:public"],
)
""" % json.dumps(root_files, indent=4))
lock = "//cmux-tui:Cargo.lock" if os.path.exists(os.path.join(root, "cmux-tui/BUILD.bazel")) else "//:cmux-tui/Cargo.lock"
tpl = open(os.path.join(root, "bazel/MODULE.bazel.in")).read()
tpl = tpl.replace("@LOCKFILE@", json.dumps(lock)).replace("@MANIFESTS@", json.dumps(sorted(manifests), indent=8))
open(os.path.join(root, "MODULE.bazel"), "w").write(tpl)
print("manifests:", len(manifests), "lock:", lock)
PY
