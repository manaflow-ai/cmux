#!/bin/sh
# Postgres per server, user mode (server.md 8): runs as the non-root server
# user. Creates the cluster, the user unit, two apps, then proves isolation.
#   pg-user-mode.sh setup|prove
set -eu
here=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=pg-common.sh
. "$here/pg-common.sh"
[ -n "${HOME:-}" ] || HOME=$(getent passwd "$(id -u)" | cut -d: -f6)
export HOME
XDG_RUNTIME_DIR="/run/user/$(id -u)"
export XDG_RUNTIME_DIR
STATE="$HOME/.local/state/cmux/server"
PGSTATE="$STATE/postgres"
DATA="$PGSTATE/17/data"
RUN="$PGSTATE/run"
WAL="$STATE/backups/wal"
UNIT="$HOME/.config/systemd/user/cmux-postgres.service"
ms() { date +%s%3N; }

setup() {
  umask 077
  mkdir -p "$STATE" "$PGSTATE/17" "$RUN" "$WAL" "$STATE/backups/base" "$STATE/bin"
  chmod 700 "$STATE" "$RUN" "$WAL"
  [ -f "$STATE/install_id" ] || new_install_id >"$STATE/install_id"
  install_id=$(cat "$STATE/install_id")
  port=$(pg_port_for "$install_id")
  printf '%s\n' "$port" >"$PGSTATE/port"
  cp "$here/../cmux-archive-wal" "$STATE/bin/cmux-archive-wal"
  chmod 700 "$STATE/bin/cmux-archive-wal"
  echo "install_id=$install_id port=$port (15432 + fnv1a64 mod 10000)"
  t0=$(ms)
  "$PGBIN/initdb" -D "$DATA" --data-checksums --encoding=UTF8 --locale=C.UTF-8 \
    --auth-local=peer --auth-host=reject --username=cmux_admin >"$PGSTATE/initdb.log" 2>&1
  echo "initdb_ms=$(($(ms) - t0))"
  render_conf "$port" "$RUN" "$STATE/bin/cmux-archive-wal $WAL" >"$DATA/cmux.conf"
  printf "include = 'cmux.conf'\n" >>"$DATA/postgresql.conf"
  me=$(id -un)
  cat >"$DATA/pg_ident.conf" <<IDENT
# Generated by the cmux server postgres role.
cmuxadmin $me cmux_admin
IDENT
  cat >"$DATA/pg_hba.conf" <<HBA
# Generated by the cmux server postgres role. Changes are overwritten.
local all         cmux_admin peer map=cmuxadmin
local replication cmux_admin peer map=cmuxadmin
local sameuser    app_notes  scram-sha-256
local sameuser    app_crm    scram-sha-256
local all         all        reject
host  all         all        all reject
HBA
  mkdir -p "$(dirname "$UNIT")"
  cat >"$UNIT" <<UNITF
[Unit]
Description=cmux server Postgres 17 (prototype, user mode)
PartOf=cmux-server.service

[Service]
Type=notify
ExecStart=$PGBIN/postgres -D $DATA
ExecReload=/bin/kill -HUP \$MAINPID
KillMode=mixed
KillSignal=SIGINT
TimeoutStopSec=60

[Install]
WantedBy=cmux-server.service
UNITF
  systemctl --user daemon-reload
  t0=$(ms)
  systemctl --user enable --now cmux-postgres.service
  echo "cluster_start_ms=$(($(ms) - t0)) (Type=notify: start returns when postgres is ready)"
  for app in notes crm; do
    valid_app_id "$app" || { echo "bad app id $app"; exit 1; }
    mkdir -p "$STATE/apps/$app"
    chmod 700 "$STATE/apps/$app"
    secret=$(random_secret)
    printf '*:%s:app_%s:app_%s:%s\n' "$port" "$app" "$app" "$secret" >"$STATE/apps/$app/pgpass"
    chmod 600 "$STATE/apps/$app/pgpass"
    app_sql "$app" "PASSWORD '$(scram_verifier "$secret")'" |
      "$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -v ON_ERROR_STOP=1 -q
    unset secret
  done
  "$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -qc 'REVOKE CONNECT ON DATABASE postgres FROM PUBLIC; REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;'
  find "$STATE/apps/notes" "$RUN" -exec stat -c '  %A %U %n' {} +
}

# psql as app $1 to database $2 as role $3; prints the first error line or OK.
as_app() {
  if out=$(PGPASSFILE="$STATE/apps/$1/pgpass" "$PGBIN/psql" -h "$RUN" -p "$port" -U "$3" -d "$2" -w -Atc 'select current_user' 2>&1); then
    echo "OK($out)"
  else
    printf '%s\n' "$out" | head -n 1
  fi
}

check() { # label expected-pattern actual
  if printf '%s' "$3" | grep -Eq "$2"; then r=PASS; else r=FAIL; fi
  printf 'RESULT pg-user %s %s: %s\n' "$r" "$1" "$3"
}

prove() {
  port=$(cat "$PGSTATE/port")
  echo "--- TCP listeners (ss -ltnp):"
  ss -ltnp | sed 's/^/  /'
  if ss -ltnp | grep -q ":$port\b\|postgres"; then tcp="postgres listens on TCP"; else tcp="no postgres TCP listener"; fi
  check no-tcp '^no postgres' "$tcp"
  echo "--- Unix sockets:"
  ss -lxp | grep -i "$RUN" | sed 's/^/  /' || true
  check notes-own-db '^OK\(app_notes\)' "$(as_app notes app_notes app_notes)"
  check notes-cannot-open-crm-db 'no pg_hba.conf entry|rejects connection' "$(as_app notes app_crm app_notes)"
  check notes-cannot-login-as-crm 'password authentication failed|no password supplied|fe_sendauth' "$(as_app notes app_crm app_crm)"
  check notes-cannot-login-as-admin 'Peer authentication failed|password|rejects|no pg_hba' "$(PGPASSFILE="$STATE/apps/notes/pgpass" PGUSER=app_notes as_app notes postgres cmux_admin 2>&1 || true)"
  check crm-own-db '^OK\(app_crm\)' "$(as_app crm app_crm app_crm)"
  admin=$("$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -Atc 'select current_user' 2>&1)
  check admin-peer-service-user '^cmux_admin$' "$admin"
  pwroles=$("$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -Atc "select string_agg(rolname, ',' order by rolname) from pg_authid where rolpassword is not null" 2>&1)
  check only-app-roles-have-passwords '^app_crm,app_notes$' "$pwroles"
  public=$("$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -Atc "select datname || '=' || coalesce(datacl::text,'default') from pg_database where datname like 'app_%' order by 1" 2>&1 | tr '\n' ' ')
  check revoke-public 'app_crm=\{[^}]*\} app_notes=\{' "$public"
  limits=$("$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -Atc "select r.rolname||' conn='||r.rolconnlimit||' '||array_to_string(s.setconfig,' ') from pg_roles r join pg_db_role_setting s on s.setrole=r.oid where r.rolname='app_notes'" 2>&1)
  check role-limits 'conn=20 .*statement_timeout=30s.*temp_file_limit=1GB' "$limits"
  perms=$(stat -c '%a' "$RUN" "$STATE/apps/notes/pgpass" "$DATA" | tr '\n' ' ')
  check file-modes '^700 600 700 $' "$perms"
  echo "port=$port"
}

# User mode runs every app as the service user, so peer auth for cmux_admin
# lets any app process act as superuser. Fix under test: cmux_admin uses SCRAM
# with a secret only the postgres role can read, and each app runs in a mount
# namespace (bubblewrap) that shows it only its own pgpass and the socket.
sandbox() {
  port=$(cat "$PGSTATE/port")
  same_uid=$(PGPASSFILE="$STATE/apps/notes/pgpass" "$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -w -Atc 'select current_user' 2>&1 | head -n 1)
  check gap-same-uid-app-reaches-admin-via-peer '^cmux_admin$' "$same_uid"
  umask 077
  admin_secret=$(random_secret)
  printf '*:%s:*:cmux_admin:%s\n' "$port" "$admin_secret" >"$PGSTATE/admin.pgpass"
  chmod 600 "$PGSTATE/admin.pgpass"
  printf "ALTER ROLE cmux_admin PASSWORD '%s';\n" "$(scram_verifier "$admin_secret")" |
    "$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -q -v ON_ERROR_STOP=1
  unset admin_secret
  sed -i 's/^local all         cmux_admin peer map=cmuxadmin/local all         cmux_admin scram-sha-256/; s/^local replication cmux_admin peer map=cmuxadmin/local replication cmux_admin scram-sha-256/' "$DATA/pg_hba.conf"
  systemctl --user reload cmux-postgres.service
  admin=$(PGPASSFILE="$PGSTATE/admin.pgpass" "$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -w -Atc 'select current_user' 2>&1)
  check sandbox-admin-with-secret '^cmux_admin$' "$admin"
  jail() { # app, then the command
    a=$1
    shift
    bwrap --ro-bind / / --dev /dev --proc /proc --tmpfs /tmp --tmpfs "$STATE" \
      --ro-bind "$STATE/apps/$a" "$STATE/apps/$a" --bind "$RUN" "$RUN" --unshare-all --die-with-parent \
      env PGPASSFILE="$STATE/apps/$a/pgpass" "$@"
  }
  check sandbox-notes-own-db '^app_notes$' "$(jail notes "$PGBIN/psql" -h "$RUN" -p "$port" -U app_notes -d app_notes -w -Atc 'select current_user' 2>&1)"
  check sandbox-notes-cannot-admin 'password authentication failed|no password supplied|fe_sendauth' "$(jail notes "$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -w -Atc 'select 1' 2>&1 | head -n 1)"
  check sandbox-notes-cannot-read-admin-secret 'No such file' "$(jail notes cat "$PGSTATE/admin.pgpass" 2>&1)"
  check sandbox-notes-cannot-read-crm-pgpass 'No such file' "$(jail notes cat "$STATE/apps/crm/pgpass" 2>&1)"
}

case "${1:?setup|prove|sandbox}" in
  setup) setup ;;
  prove) prove ;;
  sandbox) sandbox ;;
esac
