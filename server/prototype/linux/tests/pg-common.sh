# fnv1a64 of $1, then 15432 + (hash mod 10000) (server.md 8.2). The Rust role
# also skips ports in use; this prototype only checks the first candidate.
pg_port_for() {
  python3 - "$1" <<'PY'
import sys
h = 0xcbf29ce484222325
for b in sys.argv[1].encode():
    h ^= b
    h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
print(15432 + h % 10000)
PY
}

new_install_id() { printf 'inst_%s\n' "$(od -An -N10 -tx1 /dev/urandom | tr -d ' \n')"; }

# A random 32-byte secret, base64url without padding.
random_secret() { head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n'; }

# SCRAM-SHA-256 verifier for the password on stdin, so the server, its logs
# and psql history never see the clear password (PASSWORD takes the
# verifier). The password never appears in argv (visible in ps):
#   printf '%s' "$secret" | scram_verifier
scram_verifier() {
  # The Python program is single-quoted on purpose: nothing in it expands.
  # shellcheck disable=SC2016
  python3 -c '
import base64, hashlib, hmac, os, sys
pw = sys.stdin.buffer.read()
salt = os.urandom(16)
it = 4096
salted = hashlib.pbkdf2_hmac("sha256", pw, salt, it)
ck = hmac.new(salted, b"Client Key", "sha256").digest()
sk = hmac.new(salted, b"Server Key", "sha256").digest()
stored = hashlib.sha256(ck).digest()
b = lambda x: base64.b64encode(x).decode()
print(f"SCRAM-SHA-256${it}:{b(salt)}${b(stored)}:{b(sk)}")
'
}

# Validates an app id before it becomes an identifier (server.md 8.3).
valid_app_id() {
  case "$1" in
    [a-z]*) ;;
    *) return 1 ;;
  esac
  case "$1" in *[!a-z0-9_]*) return 1 ;; esac
  [ "${#1}" -le 41 ]
}

# SQL for one app: role, limits, database, revokes. $2 = PASSWORD clause or ''.
app_sql() {
  app=$1
  pw_clause=$2
  cat <<SQL
CREATE ROLE "app_$app" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION CONNECTION LIMIT 20 $pw_clause;
ALTER ROLE "app_$app" SET statement_timeout = '30s';
ALTER ROLE "app_$app" SET idle_in_transaction_session_timeout = '60s';
ALTER ROLE "app_$app" SET temp_file_limit = '1GB';
CREATE DATABASE "app_$app" OWNER "app_$app";
REVOKE ALL ON DATABASE "app_$app" FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE "app_$app" TO "app_$app";
\\connect "app_$app"
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
ALTER SCHEMA public OWNER TO "app_$app";
\\connect postgres
SQL
}

# Common postgresql.conf settings ($1 port, $2 socket dir, $3 archive command).
render_conf() {
  cat <<CONF
# Generated by the cmux server postgres role. Changes are overwritten.
listen_addresses = ''
port = $1
unix_socket_directories = '$2'
unix_socket_permissions = ${UNIX_SOCKET_PERMISSIONS:-0700}
password_encryption = 'scram-sha-256'
wal_level = replica
archive_mode = on
archive_timeout = 60
archive_command = '$3 %p %f'
max_wal_senders = 3
log_destination = 'stderr'
logging_collector = off
log_line_prefix = '%m [%p] %q%u@%d '
CONF
}
