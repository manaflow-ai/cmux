#!/bin/sh
# Postgres per server, system mode (server.md 8.3): run as root once. Service
# user `cmux` owns the cluster; each app runs as OS user app-<app> and logs
# in by peer auth through a pg_ident map. No role has a password.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=pg-common.sh
. "$here/pg-common.sh"
[ "$(id -u)" = 0 ] || { echo 'run as root'; exit 1; }
ROOT=/var/lib/cmux
DATA=$ROOT/postgres/17/data
RUN=/run/cmux/postgres
WAL=$ROOT/backups/wal
ms() { date +%s%3N; }
check() {
  if printf '%s' "$3" | grep -Eq "$2"; then r=PASS; else r=FAIL; fi
  printf 'RESULT pg-system %s %s: %s\n' "$r" "$1" "$3"
}

getent group cmux-db >/dev/null || groupadd --system cmux-db
id cmux >/dev/null 2>&1 || useradd --system --home-dir "$ROOT" --shell /usr/sbin/nologin --gid cmux-db cmux
for app in notes crm; do
  valid_app_id "$app"
  id "app-$app" >/dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin --groups cmux-db "app-$app"
done
install -d -o cmux -g cmux-db -m 0700 "$ROOT" "$ROOT/postgres" "$ROOT/postgres/17" "$ROOT/backups" "$WAL" "$ROOT/bin"
install -o cmux -g cmux-db -m 0700 "$here/../cmux-archive-wal" "$ROOT/bin/cmux-archive-wal"
[ -f "$ROOT/install_id" ] || new_install_id >"$ROOT/install_id"
install_id=$(cat "$ROOT/install_id")
port=$(pg_port_for "$install_id")
echo "install_id=$install_id port=$port"
t0=$(ms)
runuser -u cmux -- "$PGBIN/initdb" -D "$DATA" --data-checksums --encoding=UTF8 --locale=C.UTF-8 \
  --auth-local=peer --auth-host=reject --username=cmux_admin >/dev/null
echo "initdb_ms=$(($(ms) - t0))"
UNIX_SOCKET_PERMISSIONS=0770 render_conf "$port" "$RUN" "$ROOT/bin/cmux-archive-wal $WAL" >"$DATA/cmux.conf"
printf "unix_socket_group = 'cmux-db'\n" >>"$DATA/cmux.conf"
printf "include = 'cmux.conf'\n" >>"$DATA/postgresql.conf"
cat >"$DATA/pg_ident.conf" <<'IDENT'
# Generated by the cmux server postgres role.
cmuxadmin cmux     cmux_admin
cmuxapps  app-notes app_notes
cmuxapps  app-crm   app_crm
IDENT
cat >"$DATA/pg_hba.conf" <<'HBA'
# Generated by the cmux server postgres role. Changes are overwritten.
local all         cmux_admin peer map=cmuxadmin
local replication cmux_admin peer map=cmuxadmin
local sameuser    app_notes  peer map=cmuxapps
local sameuser    app_crm    peer map=cmuxapps
local all         all        reject
host  all         all        all reject
HBA
chown cmux:cmux-db "$DATA/cmux.conf" "$DATA/pg_ident.conf" "$DATA/pg_hba.conf"
cat >/etc/systemd/system/cmux-postgres.service <<UNIT
[Unit]
Description=cmux server Postgres 17 (prototype, system mode)

[Service]
Type=notify
User=cmux
Group=cmux-db
RuntimeDirectory=cmux/postgres
RuntimeDirectoryMode=0750
ExecStart=$PGBIN/postgres -D $DATA
ExecReload=/bin/kill -HUP \$MAINPID
KillMode=mixed
KillSignal=SIGINT
NoNewPrivileges=yes
ProtectSystem=strict
ReadWritePaths=$ROOT
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
t0=$(ms)
systemctl enable --now cmux-postgres.service
echo "cluster_start_ms=$(($(ms) - t0))"
adm() { runuser -u cmux -- "$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -v ON_ERROR_STOP=1 -Atq "$@"; }
for app in notes crm; do app_sql "$app" '' | adm -d postgres; done
adm -d postgres -c 'REVOKE CONNECT ON DATABASE postgres FROM PUBLIC; REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;'
stat -c '  %A %U:%G %n' /run/cmux/postgres /run/cmux/postgres/.s.PGSQL."$port" "$DATA"

as() { # os-user db role
  if out=$(runuser -u "$1" -- "$PGBIN/psql" -h "$RUN" -p "$port" -U "$3" -d "$2" -w -Atc 'select current_user' 2>&1); then
    echo "OK($out)"
  else
    printf '%s\n' "$out" | head -n 1
  fi
}
if ss -ltnp | grep -q "postgres"; then tcp="postgres listens on TCP"; else tcp="no postgres TCP listener"; fi
check no-tcp '^no postgres' "$tcp"
check notes-own-db '^OK\(app_notes\)' "$(as app-notes app_notes app_notes)"
check notes-cannot-open-crm-db 'rejects connection|no pg_hba' "$(as app-notes app_crm app_notes)"
check notes-cannot-login-as-crm 'Peer authentication failed' "$(as app-notes app_crm app_crm)"
check notes-cannot-login-as-admin 'Peer authentication failed' "$(as app-notes postgres cmux_admin)"
check crm-own-db '^OK\(app_crm\)' "$(as app-crm app_crm app_crm)"
check admin-peer-service-user '^OK\(cmux_admin\)' "$(as cmux postgres cmux_admin)"
rootadm=$("$PGBIN/psql" -h "$RUN" -p "$port" -U cmux_admin -d postgres -w -Atc 'select 1' 2>&1 | head -n 1)
check root-is-not-admin 'Peer authentication failed' "$rootadm"
check non-member-cannot-reach-socket 'Permission denied' "$(as srvtest app_notes app_notes)"
check no-role-has-a-password '^0$' "$(adm -d postgres -c 'select count(*) from pg_authid where rolpassword is not null')"
