import Foundation
import Testing

#if canImport(cmux_DEV)
@testable import cmux_DEV
#elseif canImport(cmux)
@testable import cmux
#endif

@MainActor
struct SidebarAgentSurfaceNameTests {
    @Test
    func testRowCarriesUserSetSurfaceNameAndClearsItWithoutFallbackText() throws {
        let workspace = Workspace()
        let panelId = try #require(workspace.focusedPanelId)
        workspace.recordAgentPID(key: "claude_code.only", pid: 111, panelId: panelId, refreshPorts: false)

        #expect(try #require(workspace.sidebarAgentStatusRows().first).surfaceName == nil)

        #expect(workspace.setPanelCustomTitle(panelId: panelId, title: "  fix-pr93  "))
        #expect(try #require(workspace.sidebarAgentStatusRows().first).surfaceName == "fix-pr93")

        #expect(workspace.setPanelCustomTitle(panelId: panelId, title: nil))
        #expect(try #require(workspace.sidebarAgentStatusRows().first).surfaceName == nil)
    }

    @Test
    func testRowExcludesAutoGeneratedSurfaceTitleUntilUserClaimsIt() throws {
        let workspace = Workspace()
        let panelId = try #require(workspace.focusedPanelId)
        workspace.recordAgentPID(key: "claude_code.only", pid: 111, panelId: panelId, refreshPorts: false)

        #expect(workspace.setPanelCustomTitle(panelId: panelId, title: "Generated topic", source: .auto))
        #expect(try #require(workspace.sidebarAgentStatusRows().first).surfaceName == nil)

        #expect(workspace.setPanelCustomTitle(panelId: panelId, title: "Generated topic", source: .user))
        #expect(try #require(workspace.sidebarAgentStatusRows().first).surfaceName == "Generated topic")
    }

    @Test
    func testPresentationAppendsAndBoundsSurfaceNameWithoutChangingUnnamedRows() {
        let unnamed = SidebarAgentRowPresentation(
            paneLabel: "workers",
            agentDisplayName: "Claude Code",
            surfaceName: nil
        )
        #expect(unnamed.primaryText == "workers")
        #expect(unnamed.fullPrimaryText == "workers")

        let longName = String(repeating: "a", count: 24) + String(repeating: "z", count: 40)
        let named = SidebarAgentRowPresentation(
            paneLabel: "workers",
            agentDisplayName: "Claude Code",
            surfaceName: longName
        )
        #expect(
            named.primaryText
                == "workers · " + String(repeating: "a", count: 24) + "…" + String(repeating: "z", count: 23)
        )
        #expect(named.fullPrimaryText == "workers · \(longName)")

        let deduplicated = SidebarAgentRowPresentation(
            paneLabel: "fix-pr93",
            agentDisplayName: "Claude Code",
            surfaceName: "fix-pr93"
        )
        #expect(deduplicated.primaryText == "fix-pr93")
    }
}
