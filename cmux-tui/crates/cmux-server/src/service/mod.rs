/// What an install or start did.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ServiceReport {
    /// The main unit or plist path.
    pub unit: PathBuf,
    /// Some unit file was written (its content changed).
    pub changed: bool,
    pub restarted: bool,
    /// Linux user mode: linger is on (`None` elsewhere).
    pub linger: Option<bool>,
    /// Steps that need the user (for example the one `sudo` command).
    pub warnings: Vec<String>,
}

/// Loaded and running state, as far as the service manager reports it.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ServiceState {
    pub installed: bool,
    pub active: Option<bool>,
    pub enabled: Option<bool>,
}

/// The service manager for one layout.
pub struct Services<'a> {
    pub layout: &'a Layout,
    pub runner: &'a dyn Runner,
    /// The installing user (`loginctl`, `launchctl gui/<uid>`).
    pub uid: u32,
    pub user: String,
    /// `Some`: the units run this session daemon (the session service)
    /// instead of the store's `host run`. Paths and names are the same, so
    /// `up`, `down`, `status` and `uninstall` need no `Some` here.
    pub session: Option<SessionHost>,
    /// Linux user mode: turn linger on so the server runs from boot and
    /// after logout. `false` (`install --user`): leave linger as it is.
    pub linger: bool,
    /// Print each file before it is written (to stderr; human output only).
    pub announce: bool,
}

/// A runner that prints each command to stderr before it runs it, so a
/// person sees every change `cmux server install` makes, as it makes it.
pub struct Announce<'a>(pub &'a dyn Runner);

impl Runner for Announce<'_> {
    fn run(&self, cmd: &Cmd) -> std::io::Result<Output> {
        eprintln!("  $ {}", cmd.display());
        self.0.run(cmd)
    }
}

/// The ownership record in the layout's state folder: each unit or plist
/// file cmux wrote, by path, with the SHA-256 of what it wrote. A file is
/// cmux's when it is exactly what cmux writes now or what this record says
/// cmux wrote; one that only looks like cmux's (a "Generated by cmux"
/// header, a cmux ExecStart) is not, and neither is one edited after cmux
/// wrote it.
const RECORD: &str = "service-units.json";

thread_local! {
    /// The service locks this thread holds, by path: a command that holds
    /// one may call the `Services` steps that take it again.
    static HELD: std::cell::RefCell<Vec<PathBuf>> = const { std::cell::RefCell::new(Vec::new()) };
}

/// The lock file of the service commands, in the folder of the unit files
/// ([`Services::lock`]); the service managers load no file of this name.
const LOCK: &str = ".cmux-server.lock";

/// The service lock ([`Services::lock`]), held until this drops.
#[derive(Debug)]
pub struct ServiceLock {
    path: PathBuf,
    /// The unit files of the layout: when none is left as the outer hold
    /// ends (an uninstall), the lock file goes too.
    units: Vec<PathBuf>,
    /// None: this thread already held it; the outer hold releases it.
    lock: Option<crate::fsx::FileLock>,
}

impl Drop for ServiceLock {
    fn drop(&mut self) {
        let Some(lock) = self.lock.take() else { return };
        HELD.with(|held| held.borrow_mut().retain(|p| p != &self.path));
        // Removed while still held, then released: a command that opened
        // the old file meanwhile finds it is no longer the one at the name
        // (`Services::lock`) and refuses.
        if !self.units.iter().any(|unit| crate::fsx::exists_no_follow(unit)) {
            let _ = std::fs::remove_file(&self.path);
        }
        drop(lock);
    }
}

fn sha256_hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes).iter().map(|b| format!("{b:02x}")).collect()
}

/// Refuses a unit or plist directory another account could write to:
/// whoever can replace a file there runs code as this user at the next
/// login or boot.
#[cfg(unix)]
pub fn check_private_dir(dir: &Path, what: &str) -> Result<()> {
    let meta = match std::fs::metadata(dir) {
        Ok(meta) => meta,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(e) => return Err(Error::io(dir.display(), e)),
    };
    let owner = crate::sys::owner_uid(&meta);
    let euid = crate::sys::euid();
    if owner != euid {
        return Err(Error::rejected(format!(
            "{} ({what}) is owned by uid {owner}, not by you (uid {euid}); another account could replace what cmux puts there. Fix its owner, then run `cmux server install` again",
            dir.display()
        )));
    }
    let mode = crate::fsx::mode_of(&meta);
    if mode & 0o022 != 0 {
        return Err(Error::rejected(format!(
            "{} ({what}) has mode {mode:o}: other accounts can write to it and could replace what cmux puts there. Fix: chmod go-w {}",
            dir.display(),
            dir.display()
        )));
    }
    // The ACL of the folder itself, through a symlink to it if `dir` is one
    // (a stowed `~/.config`): reading the symlink's own ACL would miss it.
    let folder = std::fs::File::open(dir).map_err(|e| Error::io(dir.display(), e))?;
    if crate::acl::fd_write_grants(&folder).map_err(|e| Error::io(dir.display(), e))? {
        return Err(acl_refusal(dir, what));
    }
    Ok(())
}

/// A folder above the LaunchAgent log: owned by this account or root, and
/// writable by no other account (mode or ACL), so no one else can rename
/// or replace a folder of the log's path. A sticky folder of root's
/// (`/tmp`) passes: there only an entry's owner can rename it.
#[cfg(unix)]
fn check_folder_above(dir: &Path) -> Result<()> {
    let what = "a folder above the service log";
    let meta = match std::fs::symlink_metadata(dir) {
        Ok(meta) => meta,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(e) => return Err(Error::io(dir.display(), e)),
    };
    let owner = crate::sys::owner_uid(&meta);
    let euid = crate::sys::euid();
    let mode = crate::fsx::mode_of(&meta);
    let sticky_root = owner == 0 && mode & 0o1000 != 0;
    if (owner != euid && owner != 0) || (mode & 0o022 != 0 && !sticky_root && !meta.is_symlink()) {
        return Err(Error::rejected(format!(
            "{} ({what}) is owned by uid {owner} with mode {mode:o}: another account could replace a folder of the service log's path. Fix its owner or mode (chmod go-w), then run the command again",
            dir.display()
        )));
    }
    check_no_acl_grants(dir, what)
}

/// launchd opens the log by its path, so every folder that path goes
/// through must be safe from other accounts ([`check_folder_above`]).
/// The walk resolves the path one name at a time and follows each symlink
/// by hand, so it also checks the folders that only a symlink's target
/// names, through any chain of symlinks (`~/Library` -> a link in a
/// shared folder -> the real folder). A missing name is where install
/// will make a folder: refused when other accounts can write the folder
/// it goes in, since one of them could make it first and own it.
#[cfg(unix)]
fn check_log_path(logs: &Path) -> Result<()> {
    use std::ffi::OsString;
    use std::path::Component;

    /// About the kernels' own limits (40 on Linux, 32 on macOS).
    const MAX_LINKS: usize = 40;
    fn push(todo: &mut Vec<OsString>, path: &Path) {
        for part in path.components().rev() {
            match part {
                Component::Normal(name) => todo.push(name.to_owned()),
                Component::ParentDir => todo.push(OsString::from("..")),
                Component::RootDir | Component::CurDir | Component::Prefix(_) => {}
            }
        }
    }

    let logs = if logs.is_absolute() {
        logs.to_path_buf()
    } else {
        std::env::current_dir().map_err(|e| Error::io(logs.display(), e))?.join(logs)
    };
    // Names still to walk, the next one last.
    let mut todo = Vec::new();
    push(&mut todo, &logs);
    // The folder reached so far, with no symlink in it.
    let mut at = PathBuf::from("/");
    check_folder_above(&at)?;
    let mut links = 0;
    while let Some(name) = todo.pop() {
        if name == ".." {
            at.pop();
            continue;
        }
        let next = at.join(&name);
        let meta = match std::fs::symlink_metadata(&next) {
            Ok(meta) => meta,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                return check_creatable(&next, &at);
            }
            Err(e) => return Err(Error::io(next.display(), e)),
        };
        check_folder_above(&next)?;
        if meta.is_symlink() {
            links += 1;
            if links > MAX_LINKS {
                return Err(Error::rejected(format!(
                    "{} (on the service log's path) goes through more than {MAX_LINKS} symlinks (a loop?). Fix the symlinks, then run the command again",
                    logs.display()
                )));
            }
            let target = std::fs::read_link(&next).map_err(|e| Error::io(next.display(), e))?;
            if target.is_absolute() {
                at = PathBuf::from("/");
            }
            push(&mut todo, &target);
        } else {
            at = next;
        }
    }
    Ok(())
}

/// `missing` (on the log's path) does not exist and install will make it
/// in `parent`, a folder the walk already checked: refused when other
/// accounts can write `parent` (a sticky `/tmp` included), since one of
/// them could make `missing` first.
#[cfg(unix)]
fn check_creatable(missing: &Path, parent: &Path) -> Result<()> {
    let meta = std::fs::metadata(parent).map_err(|e| Error::io(parent.display(), e))?;
    if crate::fsx::mode_of(&meta) & 0o022 != 0 {
        return Err(Error::rejected(format!(
            "{} (on the service log's path) does not exist, and other accounts can write {}: one of them could make it first and own it. Make it yourself (mkdir -m 700 {}), then run the command again",
            missing.display(),
            parent.display(),
            missing.display()
        )));
    }
    Ok(())
}

#[cfg(not(unix))]
fn check_log_path(_logs: &Path) -> Result<()> {
    Ok(())
}

/// Refuses `path` when a macOS ACL entry allows writing it ([`crate::acl`]):
/// another account could replace what cmux puts there, whatever its mode
/// says. No-op where there are no such ACLs.
pub fn check_no_acl_grants(path: &Path, what: &str) -> Result<()> {
    if crate::acl::write_grants(path).map_err(|e| Error::io(path.display(), e))? {
        return Err(acl_refusal(path, what));
    }
    Ok(())
}

/// Refuses the file `path` (`what`) when another account could write it:
/// not owned by this account or root, a group or other write bit, or a
/// macOS ACL entry that allows writing. A missing file passes.
#[cfg(unix)]
pub(crate) fn check_not_shared(path: &Path, what: &str) -> Result<()> {
    use std::os::unix::fs::MetadataExt as _;
    let meta = match std::fs::symlink_metadata(path) {
        Ok(meta) => meta,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(e) => return Err(Error::io(path.display(), e)),
    };
    let owner = meta.uid();
    let mode = meta.mode() & 0o7777;
    if (owner != crate::sys::euid() && owner != 0) || mode & 0o022 != 0 {
        return Err(Error::rejected(format!(
            "{} ({what}) is owned by uid {owner} with mode {mode:o}: another account could change what the service manager runs or stops. Fix its owner or mode (chmod go-w {}), then run the command again",
            path.display(),
            path.display()
        )));
    }
    check_no_acl_grants(path, what)
}

#[cfg(not(unix))]
pub(crate) fn check_not_shared(_path: &Path, _what: &str) -> Result<()> {
    Ok(())
}

/// The variables that choose where a cmux daemon keeps its state, and so
/// its terminal host records (`cmux_tui_platform::workspace_state_dir`),
/// besides HOME.
pub(super) const STATE_ENV: [&str; 2] = ["CMUX_TUI_STATE_DIR", "XDG_STATE_HOME"];

/// What uninstall needs to end the terminals of the session service, read
/// before anything stops: a refusal here changes nothing.
#[derive(Debug)]
pub(super) struct Sweep {
    binary: PathBuf,
    session: String,
    /// The service's daemon, while it runs (it answered on the session's
    /// socket with this pid): it ends its own terminals before the manager
    /// stops it ([`end_running_daemon_terminals`]).
    running: Option<u32>,
    /// HOME and [`STATE_ENV`] as the manager gives them to the service
    /// (`None`: unset), for the daemon that ends what is left once the
    /// manager stopped the service ([`end_terminal_hosts`]).
    env: Vec<(String, Option<OsString>)>,
}

/// The sweep for the session service, or `None` for the store service.
/// - `daemon`: the pid of the service's daemon while it runs. It must answer
///   `daemon status` on the session's socket with that pid: then it ends its
///   own terminals, from its own state, and nothing of its process is read
///   here (cmux-next does not scan processes, plans/cmux-next/pty-holder.md
///   section 4).
/// - `manager_env`: each state variable as the service manager now gives a
///   service (`None`: unset); HOME is the user database's (what launchd and
///   systemd give a service). Once the manager stopped the service, a daemon
///   started with them ends the hosts a daemon that did not run left, and
///   those of a daemon the manager restarted meanwhile (launchd restarts
///   one that exits at once, `KeepAlive`), which got these same values.
///
/// Refuses when that cannot work: the running daemon does not answer as the
/// service's, the binary is gone or another account could replace it, the
/// HOME of the user database is unknown, or a state path is relative.
pub(super) fn sweep(
    s: &Services<'_>,
    daemon: Option<u32>,
    manager_env: &dyn Fn(&str) -> Result<Option<OsString>>,
) -> Result<Option<Sweep>> {
    let Some(host) = &s.session else { return Ok(None) };
    let binary = PathBuf::from(&host.binary);
    // The terminal hosts run on after the daemon (they may run this same
    // file, deleted). Without the file no daemon can adopt and end them.
    if !binary.is_file() {
        return Err(Error::rejected(format!(
            "{} (the cmux binary of the session service) is gone, so cmux cannot end the terminals of session {:?}. Run `cmux server install` to put it back, then run this command again",
            binary.display(),
            host.session
        )));
    }
    check_binary(&binary)?;
    let home = user_home(s, &host.session)?.into_os_string();
    let mut env = vec![("HOME".to_owned(), Some(home))];
    for key in STATE_ENV {
        env.push((key.to_owned(), manager_env(key)?));
    }
    // A relative path resolves against the working folder: the daemon's,
    // not this command's. None is ever relative as cmux sets them.
    if let Some((key, value)) = env
        .iter()
        .find_map(|(k, v)| v.as_ref().filter(|v| !Path::new(v).is_absolute()).map(|v| (k, v)))
    {
        return Err(Error::rejected(format!(
            "the service manager gives the daemon of session {:?} {key}={} (a relative path), which cmux cannot follow from here, so it ends no terminals",
            host.session,
            value.to_string_lossy()
        )));
    }
    if let Some(pid) = daemon {
        check_daemon_answers(s, &binary, &host.session, pid)?;
    }
    Ok(Some(Sweep { binary, session: host.session.clone(), running: daemon, env }))
}

/// `binary daemon ARGS` as a client of the session's own socket: never the
/// socket of a terminal this command may run in.
fn daemon_cmd(binary: &Path, args: &[&str]) -> Cmd {
    Cmd::new(binary)
        .arg("daemon")
        .args(args)
        .env_remove("CMUX_TUI_SOCKET")
        .env_remove("CMUX_MUX_SOCKET")
}

/// `status`, `session` and `pid` of a `daemon ... --json` answer.
fn daemon_answer(out: &Output) -> Option<(String, String, u64)> {
    let v: serde_json::Value = serde_json::from_slice(&out.stdout).ok()?;
    Some((v["status"].as_str()?.to_owned(), v["session"].as_str()?.to_owned(), v["pid"].as_u64()?))
}

fn shown_answer(out: &Output) -> String {
    match daemon_answer(out) {
        Some((status, session, pid)) => format!("{status}, session {session:?}, pid {pid}"),
        None => format!(
            "exit {}: {}",
            out.code.map_or_else(|| "by a signal".to_owned(), |c| c.to_string()),
            String::from_utf8_lossy(&out.stdout).trim()
        ),
    }
}

/// The daemon that answers on the session's socket, as this command finds
/// it, is the one the manager runs for the service (`pid`): another daemon
/// of the session (one the app started), the service's daemon behind a
/// socket of its own, or a socket folder this shell does not share with the
/// service would otherwise leave the service's terminals or end others.
fn check_daemon_answers(s: &Services<'_>, binary: &Path, session: &str, pid: u32) -> Result<()> {
    let cmd = daemon_cmd(binary, &["status", "--session", session, "--json"]);
    let out = s.runner.run(&cmd).map_err(|e| Error::io(cmd.display(), e))?;
    match daemon_answer(&out) {
        Some((status, theirs, p))
            if status == "running" && theirs == session && p == u64::from(pid) =>
        {
            Ok(())
        }
        _ => Err(Error::rejected(format!(
            "the service's daemon (pid {pid}) does not answer on the socket of session {session:?} from here (`{}`: {}), so cmux cannot have it end its terminals. Run this command in a login shell of this account, where that command answers with pid {pid}",
            cmd.display(),
            shown_answer(&out)
        ))),
    }
}

/// Which session a cmux terminal belongs to, from the `CMUX_TUI_SOCKET` its
/// daemon gave it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TerminalSession {
    /// A default socket of `session`.
    This,
    /// A default socket of another session.
    Other,
    /// Not a default socket path (a daemon run with `--socket` of its own),
    /// so its session cannot be told.
    Unknown,
}

/// The session of the terminal whose daemon listens on `socket`, against
/// `session`. Default sockets (cmux-tui-platform `platform.rs`, cmux-tui-core
/// `socket_path.rs`) are `cmux-tui-UID/<session>.sock`, or the SHA-256 of the
/// name in `cmux-tui-hashed-UID` or `cmux-tui-invalid-UID` when that path
/// would not fit or the name is not valid. Any other path is `Unknown`.
pub fn terminal_session(socket: &Path, session: &str) -> TerminalSession {
    let uid = crate::sys::uid();
    let (Some(stem), Some(dir)) = (
        socket.file_stem().and_then(|s| s.to_str()),
        socket.parent().and_then(|d| d.file_name()).and_then(|d| d.to_str()),
    ) else {
        return TerminalSession::Unknown;
    };
    if socket.extension().and_then(|e| e.to_str()) != Some("sock") {
        return TerminalSession::Unknown;
    }
    let named = |name: &str| {
        if name == session { TerminalSession::This } else { TerminalSession::Other }
    };
    if dir == format!("cmux-tui-{uid}") {
        return named(stem);
    }
    let hashed =
        dir == format!("cmux-tui-hashed-{uid}") || dir == format!("cmux-tui-invalid-{uid}");
    if hashed && stem.len() == 64 && stem.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')) {
        let digest = format!("{:x}", Sha256::digest(session.as_bytes()));
        return if stem == digest { TerminalSession::This } else { TerminalSession::Other };
    }
    TerminalSession::Unknown
}

fn user_home(s: &Services<'_>, session: &str) -> Result<PathBuf> {
    crate::sys::home_dir(s.uid).map_err(|e| {
        Error::rejected(format!(
            "cmux cannot read the home folder of uid {} from the user database ({e}), so it cannot reach the terminals of session {session:?}",
            s.uid
        ))
    })
}

/// The binary, a build staged beside it, and each folder install made for
/// it under HOME (`.local` and `.local/bin` of `SESSION_BINARY`), is this
/// account's (or root's) and writable by no other account: none can swap
/// the file uninstall runs.
fn check_binary(binary: &Path) -> Result<()> {
    check_not_shared(binary, "the cmux binary of the session service")?;
    // `daemon ensure` swaps in, and first runs, a build staged beside it
    // (`<binary>.staged`, cmux-tui staged_update.rs): it gets the same check.
    let mut staged = binary.as_os_str().to_owned();
    staged.push(".staged");
    check_not_shared(Path::new(&staged), "a cmux build staged beside the session binary")?;
    let folders = Path::new(cmux_server_core::units::SESSION_BINARY).components().count() - 1;
    for dir in binary.ancestors().skip(1).take(folders) {
        check_not_shared(dir, "a folder of the cmux binary of the session service")?;
    }
    Ok(())
}

/// While the service's daemon runs ([`Sweep::running`]), it ends its own
/// terminals, before the manager stops the service: a terminal host runs in
/// a session of its own (`setsid`) and ignores a SIGTERM that does not come
/// from PID 1 (cx-t2sqm.17), so launchd's bootout and `systemctl --user
/// kill` (the user manager is not PID 1) both left the shells, and a later
/// install's daemon adopted them. Its stop with `--end-terminals` refuses
/// new clients, ends every terminal (each shell gets SIGHUP, then SIGTERM,
/// then SIGKILL) and exits 0. The manager may start a new daemon then
/// (launchd at once, `KeepAlive`; systemd 3 s later, which the `disable
/// --now` that follows cancels): [`end_terminal_hosts`] ends what that one
/// started, once the manager stopped the service.
/// A failure leaves the service as it was, unit files included, so the
/// command can run again.
pub(super) fn end_running_daemon_terminals(s: &Services<'_>, sweep: &Sweep) -> Result<()> {
    let Sweep { binary, session, running: Some(pid), .. } = sweep else { return Ok(()) };
    let kept = "the service still runs and cmux removed nothing";
    // Checked again right before it runs.
    check_binary(binary).map_err(|e| outcome(e, kept))?;
    let cmd = daemon_cmd(binary, &["stop", "--session", session, "--end-terminals", "--json"]);
    let out = s.runner.run(&cmd).map_err(|e| Error::io(cmd.display(), e))?;
    match daemon_answer(&out) {
        Some((status, theirs, p))
            if out.ok() && status == "stopped" && &theirs == session && p == u64::from(*pid) =>
        {
            Ok(())
        }
        _ => Err(Error::rejected(format!(
            "the daemon of session {session:?} (pid {pid}) did not end its terminals (`{}`: {}), so their shells may still run; {kept}. Run the command again",
            cmd.display(),
            shown_answer(&out)
        ))),
    }
}

/// Once the manager stopped the service (so it cannot start a daemon beside
/// this one), ends the terminal hosts left: those of a daemon that did not
/// run (a crash, an earlier stop), and those a daemon the manager restarted
/// meanwhile started (launchd restarts a `KeepAlive` job that exits at once,
/// so the bootout may end a new daemon, not the one that ended its
/// terminals). A daemon started here adopts every host still running, and
/// its stop with `--end-terminals` ends them all; a host a client of it
/// started meanwhile ends too (the stop refuses new clients first). Both run
/// with HOME and the state variables as the manager gives them to the
/// service ([`sweep`]), not as this process has them.
///
/// Only a daemon this `ensure` started is stopped: one that already runs
/// (`running`: a daemon of the session the app started, outside the
/// service; `replaced`: a wedged one replaced) holds those terminals as its
/// own, and keeps them.
/// A failure leaves the unit files, so the command can run again.
/// `stopped`: what the caller did, for the message.
pub(super) fn end_terminal_hosts(s: &Services<'_>, sweep: &Sweep, stopped: &str) -> Result<()> {
    let Sweep { binary, session, env, .. } = sweep;
    // Checked again right before it runs.
    check_binary(binary).map_err(|e| outcome(e, &format!("{stopped}; cmux removed nothing")))?;
    let with_env = |mut cmd: Cmd| {
        for (key, value) in env {
            cmd = match value {
                Some(value) => cmd.env(key, value),
                None => cmd.env_remove(key),
            };
        }
        cmd
    };
    let failed = |cmd: &Cmd, why: String| {
        Error::rejected(format!(
            "cmux could not end the terminals of session {session:?} (`{}`: {why}), so their shells may still run; {stopped} and cmux removed nothing. Run the command again; or end them yourself (`{} daemon ensure --session {session}`, then `{} daemon stop --session {session} --end-terminals`) first",
            cmd.display(),
            binary.display(),
            binary.display()
        ))
    };
    let ensure = with_env(daemon_cmd(binary, &["ensure", "--session", session, "--json"]));
    let out = s.runner.run(&ensure).map_err(|e| Error::io(ensure.display(), e))?;
    let pid = match daemon_answer(&out) {
        Some((status, theirs, pid))
            if out.ok() && (status == "started" || status == "restarted") && &theirs == session =>
        {
            pid
        }
        Some((status, theirs, _))
            if out.ok() && (status == "running" || status == "replaced") && &theirs == session =>
        {
            return Ok(());
        }
        _ => return Err(failed(&ensure, shown_answer(&out))),
    };
    let stop =
        with_env(daemon_cmd(binary, &["stop", "--session", session, "--end-terminals", "--json"]));
    let out = s.runner.run(&stop).map_err(|e| Error::io(stop.display(), e))?;
    match daemon_answer(&out) {
        Some((status, theirs, p))
            if out.ok() && status == "stopped" && &theirs == session && p == pid =>
        {
            Ok(())
        }
        _ => Err(failed(&stop, shown_answer(&out))),
    }
}

/// `e` with what came of the command added (`nothing was changed`): the
/// checks say why, their callers say what was done before they refused.
pub(crate) fn outcome(mut e: Error, what: &str) -> Error {
    e.message = format!("{}; {what}", e.message);
    e
}

fn acl_refusal(path: &Path, what: &str) -> Error {
    Error::rejected(format!(
        "{} ({what}) has an ACL entry that allows writing (`ls -led {}` lists it): another account could replace what cmux puts there, whatever its mode says. Remove that entry (`chmod -N {}` removes them all), then run the command again",
        path.display(),
        path.display(),
        path.display()
    ))
}

#[cfg(not(unix))]
pub fn check_private_dir(_dir: &Path, _what: &str) -> Result<()> {
    Ok(())
}

/// The session service's binary and session name.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SessionHost {
    pub binary: String,
    pub session: String,
}

fn unsupported(kind: &ServiceKind) -> Error {
    Error::rejected(format!(
        "service kind {kind:?} is not supported by this build yet (server.md steps 7 and 8)"
    ))
}

impl Services<'_> {
    /// The main unit or plist path.
    pub fn unit_path(&self) -> Result<PathBuf> {
        match &self.layout.service {
            ServiceKind::SystemdUser { unit_path } | ServiceKind::SystemdSystem { unit_path } => {
                Ok(PathBuf::from(unit_path.as_str()))
            }
            ServiceKind::LaunchAgent { plist_path } => Ok(PathBuf::from(plist_path.as_str())),
            other => Err(unsupported(other)),
        }
    }

    /// Writes the units, enables them and starts the server. With
    /// `restart`, a running server is restarted (a new generation); its
    /// session host hands off and keeps terminal hosts (`KillMode=process`).
    pub fn install(&self, restart: bool) -> Result<ServiceReport> {
        let _lock = self.lock()?;
        self.preflight()?;
        for (path, text) in self.unit_files()? {
            if self.announce && std::fs::read_to_string(&path).ok().as_deref() != Some(&text) {
                eprintln!("  write {}", path.display());
            }
        }
        match &self.layout.service {
            ServiceKind::SystemdUser { .. } | ServiceKind::SystemdSystem { .. } => {
                systemd::install(self, restart)
            }
            ServiceKind::LaunchAgent { .. } => launchd::install(self, restart),
            other => Err(unsupported(other)),
        }
    }

    /// After the unit files are written, before the service manager reads
    /// them: from now on they are cmux's, even when a later build renders
    /// them differently.
    fn wrote(&self, files: &[(PathBuf, String)]) -> Result<()> {
        self.record_written(files)
    }

    /// Restarts a running server (rollback, upgrade); a stopped one starts.
    pub fn restart(&self) -> Result<()> {
        let _lock = self.lock()?;
        match &self.layout.service {
            ServiceKind::SystemdUser { .. } | ServiceKind::SystemdSystem { .. } => {
                systemd::restart(self)
            }
            ServiceKind::LaunchAgent { .. } => launchd::restart(self),
            other => Err(unsupported(other)),
        }
    }

    /// Starts the installed server and enables it, so it starts at each login or boot.
    pub fn start(&self) -> Result<()> {
        let _lock = self.lock()?;
        match &self.layout.service {
            ServiceKind::SystemdUser { .. } | ServiceKind::SystemdSystem { .. } => {
                systemd::start(self)
            }
            ServiceKind::LaunchAgent { .. } => launchd::start(self),
            other => Err(unsupported(other)),
        }
    }

    /// Stops the server and disables it, so it stays stopped across logins and boots.
    /// The units stay on disk.
    pub fn stop(&self) -> Result<()> {
        let _lock = self.lock()?;
        match &self.layout.service {
            ServiceKind::SystemdUser { .. } | ServiceKind::SystemdSystem { .. } => {
                systemd::stop(self)
            }
            ServiceKind::LaunchAgent { .. } => launchd::stop(self),
            other => Err(unsupported(other)),
        }
    }

    /// The unit or plist files at this layout's paths that cmux did not
    /// write (a hand-written `cmux-server.service`, a symlink to one), and
    /// a `cmux-server.service` systemd loads from another place (a package,
    /// `/etc/systemd/user`, a generator): install refuses them and
    /// uninstall stops, disables and removes nothing.
    /// An error (nothing changes) when systemd loads one of these units
    /// from another file, runs it as a transient or generated unit, or
    /// cannot say where it loads it from.
    pub fn foreign_units(&self) -> Result<Vec<PathBuf>> {
        let record = self.read_record()?;
        let mut foreign = Vec::new();
        for (path, rendered) in self.unit_files()? {
            let Ok(meta) = std::fs::symlink_metadata(&path) else { continue };
            let ours = meta.is_file()
                && std::fs::read(&path).is_ok_and(|bytes| {
                    bytes == rendered.as_bytes()
                        || record.get(&path.display().to_string()) == Some(&sha256_hex(&bytes))
                });
            if !ours {
                foreign.push(path);
            }
        }
        match self.layout.service {
            ServiceKind::SystemdUser { .. } | ServiceKind::SystemdSystem { .. } => {
                systemd::check_sources(self).map_err(|e| outcome(e, "nothing was changed"))?;
            }
            ServiceKind::LaunchAgent { .. } => {
                launchd::check_source(self).map_err(|e| outcome(e, "nothing was changed"))?;
            }
            _ => {}
        }
        Ok(foreign)
    }

    /// The folder of the ownership record: one only the account that runs
    /// install and uninstall can write. User mode: the state folder (yours).
    /// System mode: the store root (root's); the state folder there belongs
    /// to the service account `cmux`, which must not be able to forge it.
    fn record_dir(&self) -> PathBuf {
        match self.layout.mode {
            InstallMode::System => crate::fsx::local(&self.layout.root),
            InstallMode::User => crate::fsx::local(&self.layout.state),
        }
    }

    fn record_path(&self) -> PathBuf {
        self.record_dir().join(RECORD)
    }

    /// The ownership record; empty when there is none or it cannot be read
    /// as one (a lost record only makes cmux more careful). A record another
    /// account could have written is refused.
    ///
    /// Read through one descriptor opened without following a symlink, and
    /// checked after the open, so the file checked is the file read.
    fn read_record(&self) -> Result<BTreeMap<String, String>> {
        use std::io::Read as _;
        let path = self.record_path();
        check_private_dir(&self.record_dir(), "the folder of cmux's service unit record")?;
        let mut options = std::fs::OpenOptions::new();
        options.read(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt as _;
            options.custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK);
        }
        let mut file = match options.open(&path) {
            Ok(file) => file,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(BTreeMap::new()),
            Err(e) => {
                return Err(Error::rejected(format!(
                    "{} (the record of the service files cmux wrote) cannot be opened as a plain file ({e}); remove it, then run the command again",
                    path.display()
                )));
            }
        };
        let meta = file.metadata().map_err(|e| Error::io(path.display(), e))?;
        // An ACL entry can let another account write it whatever the mode
        // says (macOS; crate::acl): such a record is no record of cmux's.
        let private = meta.is_file()
            && crate::sys::owner_uid(&meta) == crate::sys::euid()
            && crate::fsx::mode_of(&meta) & 0o022 == 0
            && !crate::acl::fd_write_grants(&file).map_err(|e| Error::io(path.display(), e))?;
        if cfg!(unix) && !private {
            return Err(Error::rejected(format!(
                "{} (the record of the service files cmux wrote) is not a private file of yours (another account can write it by its mode or an ACL entry); remove it, then run the command again",
                path.display()
            )));
        }
        let mut text = Vec::new();
        file.read_to_end(&mut text).map_err(|e| Error::io(path.display(), e))?;
        Ok(serde_json::from_slice(&text).unwrap_or_default())
    }

    /// Records that cmux wrote `files` (path and content).
    fn record_written(&self, files: &[(PathBuf, String)]) -> Result<()> {
        let mut record = self.read_record()?;
        for (path, text) in files {
            record.insert(path.display().to_string(), sha256_hex(text.as_bytes()));
        }
        self.write_record(&record)
    }

    /// Drops `paths` from the record (the files are gone).
    fn forget_written(&self, paths: &[PathBuf]) -> Result<()> {
        let mut record = self.read_record()?;
        for path in paths {
            record.remove(&path.display().to_string());
        }
        self.write_record(&record)
    }

    fn write_record(&self, record: &BTreeMap<String, String>) -> Result<()> {
        let path = self.record_path();
        if record.is_empty() {
            if crate::fsx::exists_no_follow(&path) {
                std::fs::remove_file(&path).map_err(|e| Error::io(path.display(), e))?;
            }
            return Ok(());
        }
        if let Some(dir) = path.parent() {
            crate::fsx::ensure_dir(dir, 0o700)?;
        }
        let text = serde_json::to_vec_pretty(record)
            .map_err(|e| Error::rejected(format!("cannot write {}: {e}", path.display())))?;
        crate::fsx::atomic_write(&path, &text, 0o600)
    }

    /// Every check install makes before it changes anything: no foreign
    /// unit, and no directory it writes to (units, LaunchAgent log) that
    /// another account can write to or that is not this account's.
    pub fn preflight(&self) -> Result<()> {
        if let Some(path) = self.foreign_units()?.first() {
            return Err(Error::rejected(format!(
                "{} was not written by cmux, so cmux leaves it alone. Move it away (or remove it), then run `cmux server install` again",
                path.display()
            )));
        }
        self.check_unit_dirs()?;
        check_private_dir(&self.record_dir(), "the folder of cmux's service unit record")?;
        if self.layout.mode == InstallMode::User {
            check_private_dir(&crate::fsx::local(&self.layout.state), "the cmux state directory")?;
        }
        if matches!(self.layout.service, ServiceKind::LaunchAgent { .. }) {
            let logs = crate::fsx::local(&self.layout.logs());
            if std::fs::symlink_metadata(&logs).is_ok_and(|m| !m.is_dir()) {
                return Err(Error::rejected(format!(
                    "{} (the service log directory) is not a directory (a symlink?); launchd would write the service log wherever it points. Remove it, then run `cmux server install` again",
                    logs.display()
                )));
            }
            check_private_dir(&logs, "the service log directory")?;
            check_log_path(&logs)?;
            launchd::check_log(&logs.join("server.log"))?;
        }
        Ok(())
    }

    /// Stops, disables and removes every unit this crate writes. Returns
    /// the removed paths.
    pub fn uninstall(&self) -> Result<Vec<PathBuf>> {
        let _lock = self.lock()?;
        // The caller checked ownership before its own steps (a final backup
        // can take minutes). Check again right before anything stops: a unit
        // edited since, or one the service manager now loads from another
        // file, is left alone.
        if let Some(path) = self.foreign_units()?.first() {
            return Err(Error::rejected(format!(
                "{} changed since cmux checked it and is no longer the file cmux wrote, so cmux leaves it, and everything it may use, alone; nothing was changed",
                path.display()
            )));
        }
        // Uninstall removes the unit files by name: a folder another account
        // can write would let it swap one between the check and the removal.
        self.check_unit_dirs()?;
        // The manager reads a unit file again when uninstall stops it (an
        // implicit reload): one another account can write could make that
        // stop reach a unit that is not cmux's.
        for (path, _) in self.unit_files()? {
            check_not_shared(&path, "a service unit file cmux wrote")
                .map_err(|e| outcome(e, "nothing was changed"))?;
        }
        // What ending the session's terminals needs, read before anything
        // changes (the renewal included): a refusal changes nothing.
        let sweep = match &self.layout.service {
            ServiceKind::SystemdUser { .. } | ServiceKind::SystemdSystem { .. } => {
                systemd::sweep(self)
            }
            ServiceKind::LaunchAgent { .. } => launchd::sweep(self),
            _ => Ok(None),
        }
        .map_err(|e| outcome(e, "nothing was changed"))?;
        self.renew_unit_files()?;
        let removed = match &self.layout.service {
            ServiceKind::SystemdUser { .. } | ServiceKind::SystemdSystem { .. } => {
                systemd::uninstall(self, sweep.as_ref())
            }
            ServiceKind::LaunchAgent { .. } => launchd::uninstall(self, sweep.as_ref()),
            other => Err(unsupported(other)),
        }?;
        self.forget_written(&removed)?;
        Ok(removed)
    }

    /// Holds the service lock until the returned guard drops: one command
    /// that changes the service (install, uninstall, start, stop, restart)
    /// at a time, so none acts between another's checks and its steps (an
    /// install that starts the server while uninstall stops it, then sees
    /// it remove the units). The lock is an exclusive `flock` on a 0600 file
    /// of this account's in the folder of the unit files: that folder is
    /// writable by no other account (checked) and no step removes it (a
    /// `--purge` removes the state folder, never this one), and no other
    /// account can open the file to hold the lock itself. A lock taken on a
    /// file that is no longer the one at the name (removed by the uninstall
    /// that held it) does not count. A second command refuses at once and
    /// changes nothing. The CLI verbs take it for their whole run; the
    /// steps here take it again, which the same thread may.
    pub fn lock(&self) -> Result<ServiceLock> {
        let unit = self.unit_path()?;
        let Some(dir) = unit.parent() else {
            return Err(Error::rejected(format!("{} names no folder", unit.display())));
        };
        let path = dir.join(LOCK);
        let units = self.unit_files()?.into_iter().map(|(path, _)| path).collect();
        if HELD.with(|held| held.borrow().contains(&path)) {
            return Ok(ServiceLock { path, units, lock: None });
        }
        crate::fsx::ensure_dir(dir, 0o755)?;
        check_private_dir(dir, "the service directory")?;
        let mut options = std::fs::OpenOptions::new();
        options.create(true).truncate(false).write(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt as _;
            options.mode(0o600).custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK);
        }
        let file = options.open(&path).map_err(|e| Error::io(path.display(), e))?;
        let meta = file.metadata().map_err(|e| Error::io(path.display(), e))?;
        let private = meta.is_file()
            && crate::sys::owner_uid(&meta) == crate::sys::euid()
            && crate::fsx::mode_of(&meta) & 0o077 == 0;
        if cfg!(unix) && !private {
            return Err(Error::rejected(format!(
                "{} (the lock of cmux's service commands) is not a private file of yours; remove it, then run the command again",
                path.display()
            )));
        }
        let busy = || {
            Error::rejected(format!(
                "another cmux server command changes the service now (it holds {}); nothing was changed. Run this one again when it ends",
                path.display()
            ))
        };
        // The file at the name now is the one opened (`meta`): a lock on a
        // file that is no longer there holds nothing.
        let at_name = || {
            #[cfg(unix)]
            {
                use std::os::unix::fs::MetadataExt as _;
                std::fs::symlink_metadata(&path)
                    .is_ok_and(|now| now.dev() == meta.dev() && now.ino() == meta.ino())
            }
            #[cfg(not(unix))]
            true
        };
        // macOS: an allow entry (one the folder passes on, `allow
        // read,file_inherit`, or one added later) lets another account open
        // the file, whatever its mode, and hold a shared lock on it. Taking
        // the entry away would not close what it opened meanwhile, so the
        // command refuses, and the file goes when nothing holds it and it is
        // still the one at the name (never a new lock file another command
        // made meanwhile). A descriptor on a removed file holds nothing.
        if crate::acl::fd_any_grants(&file).map_err(|e| Error::io(path.display(), e))? {
            let removed = match crate::fsx::FileLock::try_acquire(file) {
                Ok(held) => {
                    let removed = at_name() && std::fs::remove_file(&path).is_ok();
                    drop(held);
                    removed
                }
                Err(_) => false,
            };
            return Err(Error::rejected(format!(
                "{} (the lock of cmux's service commands) has an ACL entry that lets another account open it; most likely {} passes ACL entries to new files (`ls -led {}` lists them). Remove them (`chmod -N {}`){}, then run the command again; nothing was changed",
                path.display(),
                dir.display(),
                dir.display(),
                dir.display(),
                if removed {
                    String::new()
                } else {
                    format!(" and the lock file (`rm {}`)", path.display())
                }
            )));
        }
        let lock = match crate::fsx::FileLock::try_acquire(file) {
            Ok(lock) => lock,
            Err(std::fs::TryLockError::WouldBlock) => return Err(busy()),
            Err(std::fs::TryLockError::Error(e)) => return Err(Error::io(path.display(), e)),
        };
        if !at_name() {
            return Err(busy());
        }
        HELD.with(|held| held.borrow_mut().push(path.clone()));
        Ok(ServiceLock { path, units, lock: Some(lock) })
    }

    /// Right before uninstall stops the service, puts the text cmux renders
    /// now into a new file at each unit or plist path that is still the file
    /// cmux wrote ([`crate::fsx::write_fresh`]; same bytes keep the
    /// modification time). The manager may read a unit again at the stop,
    /// and a write descriptor another account opened on the old file while
    /// it could still reaches only the old file. The new text is the one
    /// cmux renders, never the old bytes: with an old descriptor on the
    /// ownership record too, such an account could make any bytes match a
    /// recorded hash. Every file is checked first; one that is no longer
    /// cmux's stops uninstall before any file is written or anything stops.
    fn renew_unit_files(&self) -> Result<()> {
        use std::io::Read as _;
        let record = self.read_record()?;
        let units = self.unit_files()?;
        for (path, rendered) in &units {
            if !crate::fsx::exists_no_follow(path) {
                continue;
            }
            let mut options = std::fs::OpenOptions::new();
            options.read(true);
            #[cfg(unix)]
            {
                use std::os::unix::fs::OpenOptionsExt as _;
                options.custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK);
            }
            let bytes = options.open(path).ok().and_then(|mut file| {
                let meta = file.metadata().ok()?;
                if !meta.is_file() || crate::sys::owner_uid(&meta) != crate::sys::euid() {
                    return None;
                }
                let mut bytes = Vec::new();
                file.read_to_end(&mut bytes).ok()?;
                Some(bytes)
            });
            let key = path.display().to_string();
            let ours = bytes.is_some_and(|bytes| {
                bytes == rendered.as_bytes() || record.get(&key) == Some(&sha256_hex(&bytes))
            });
            if !ours {
                return Err(Error::rejected(format!(
                    "{} changed since cmux checked it and is no longer the file cmux wrote, so cmux leaves it, and everything it may use, alone; nothing was changed",
                    path.display()
                )));
            }
        }
        for (path, rendered) in &units {
            if crate::fsx::exists_no_follow(path) {
                crate::fsx::write_fresh(path, rendered.as_bytes(), 0o644)?;
            }
        }
        Ok(())
    }

    /// The folders the unit or plist files are in: not writable by another
    /// account (it could swap a file cmux writes or removes there).
    fn check_unit_dirs(&self) -> Result<()> {
        for (path, _) in self.unit_files()? {
            if let Some(dir) = path.parent() {
                check_private_dir(dir, "the service directory")?;
            }
        }
        Ok(())
    }

    /// Removes every unit or plist file of the layout that is, as it goes,
    /// still the file cmux wrote ([`crate::fsx::remove_if_unchanged`]): a
    /// file edited after the ownership check (while the service stopped) is
    /// left in place and uninstall fails. Returns the removed paths.
    pub(crate) fn remove_unit_files(&self) -> Result<Vec<PathBuf>> {
        let record = self.read_record()?;
        let mut removed = Vec::new();
        for (path, rendered) in self.unit_files()? {
            let key = path.display().to_string();
            let ours = |bytes: &[u8]| {
                bytes == rendered.as_bytes() || record.get(&key) == Some(&sha256_hex(bytes))
            };
            if crate::fsx::remove_if_unchanged(&path, ours)? {
                removed.push(path);
            }
        }
        Ok(removed)
    }

    /// Every unit or plist file of the layout with its core-rendered text.
    pub fn unit_files(&self) -> Result<Vec<(PathBuf, String)>> {
        match &self.layout.service {
            ServiceKind::SystemdUser { .. } | ServiceKind::SystemdSystem { .. } => {
                systemd::files(self)
            }
            ServiceKind::LaunchAgent { .. } => Ok(vec![(self.unit_path()?, launchd::plist(self)?)]),
            other => Err(unsupported(other)),
        }
    }

    pub fn state(&self) -> ServiceState {
        match &self.layout.service {
            ServiceKind::SystemdUser { .. } | ServiceKind::SystemdSystem { .. } => {
                systemd::state(self)
            }
            ServiceKind::LaunchAgent { .. } => launchd::state(self),
            _ => ServiceState::default(),
        }
    }
}
