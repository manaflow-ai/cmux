use super::*;

const BAKED: &str = "# generated by cmux; the same for every machine; managed, do not edit\n\
        export OPENAI_BASE_URL='https://coderouter.cmux.internal/v1'\n\
        export OPENAI_API_KEY='cmux-vm-edge-placeholder'\n\
        export CMUX_CODEROUTER_URL='https://coderouter.cmux.internal'\n\
        export ANTHROPIC_BASE_URL='https://coderouter.cmux.internal'\n\
        export ANTHROPIC_API_KEY='cmux-vm-edge-placeholder'\n";

#[test]
fn the_baked_file_is_the_route() {
    let vars = validate(parse(BAKED)).unwrap();
    assert_eq!(vars.len(), 5);
    assert_eq!(vars["ANTHROPIC_BASE_URL"], "https://coderouter.cmux.internal");
    assert_eq!(vars["ANTHROPIC_API_KEY"], PLACEHOLDER);
    assert_eq!(vars["OPENAI_BASE_URL"], "https://coderouter.cmux.internal/v1");
}

#[test]
fn other_names_and_shapes_are_skipped() {
    let text = format!(
        "{BAKED}export PATH='/evil'\nexport CLAUDE_CODE_OAUTH_TOKEN='x'\nOPENAI_MODEL=gpt\nexport OPENAI_API_KEY=unquoted\n"
    );
    let vars = parse(&text);
    assert!(!vars.contains_key("PATH"));
    assert!(!vars.contains_key("CLAUDE_CODE_OAUTH_TOKEN"));
    assert_eq!(vars["OPENAI_API_KEY"], PLACEHOLDER);
}

#[test]
fn a_token_or_a_plain_http_route_drops_the_file() {
    for bad in [
        BAKED.replace("cmux-vm-edge-placeholder'\nexport CMUX", "crt_abc.def'\nexport CMUX"),
        BAKED.replace("cmux-vm-edge-placeholder'\nexport CMUX", "eyJa.eyJb.sig'\nexport CMUX"),
        BAKED.replace(
            "'https://coderouter.cmux.internal'\nexport ANTHROPIC_API",
            "'http://coderouter.cmux.internal'\nexport ANTHROPIC_API",
        ),
    ] {
        assert_eq!(validate(parse(&bad)), Err(Problem::Invalid), "{bad}");
    }
    let no_claude: String =
        BAKED.lines().filter(|l| !l.contains("ANTHROPIC_BASE_URL")).collect::<Vec<_>>().join("\n");
    assert_eq!(validate(parse(&no_claude)), Err(Problem::Invalid));
}

#[test]
fn a_file_others_can_write_or_a_symlink_is_untrusted() {
    let dir = std::env::temp_dir().join(format!("acpmux-plane-{}", uuid::Uuid::now_v7()));
    std::fs::create_dir_all(&dir).unwrap();
    let file = dir.join("model-plane.env");
    assert_eq!(read_at(&file, false), Err(Problem::Missing));
    std::fs::write(&file, BAKED).unwrap();
    assert_eq!(read_at(&file, false).unwrap().len(), 5);
    // Not root's (tests do not run as root).
    #[cfg(unix)]
    if unsafe { libc::geteuid() } != 0 {
        assert_eq!(read_at(&file, true), Err(Problem::Untrusted));
    }
    #[cfg(unix)]
    {
        let link = dir.join("link.env");
        std::os::unix::fs::symlink(&file, &link).unwrap();
        assert_eq!(read_at(&link, false), Err(Problem::Untrusted));
    }
    let _ = std::fs::remove_dir_all(&dir);
}

/// Staging and production machines get no edge rule, so the baked host does not resolve
/// there and no spawn may get the route: the person's own sign-in stays in charge
/// (cmux-platform#1442). Where it resolves (development), the route is kept whole.
#[test]
fn a_machine_whose_plane_host_does_not_resolve_gets_no_route() {
    let plane = validate(parse(BAKED)).unwrap();
    assert!(where_resolves(plane.clone(), |_| false).is_empty(), "unresolved: no route");
    let asked = std::cell::RefCell::new(Vec::new());
    let kept = where_resolves(plane.clone(), |host| {
        asked.borrow_mut().push(host.to_owned());
        true
    });
    assert_eq!(kept, plane, "resolved: the whole route");
    assert_eq!(*asked.borrow(), ["coderouter.cmux.internal"], "one host, asked once");
    // A route naming a second host needs both to resolve.
    let mut split = plane.clone();
    split.insert("OPENAI_BASE_URL".into(), "https://other.example:8443/v1".into());
    assert!(where_resolves(split.clone(), |h| h == "coderouter.cmux.internal").is_empty());
    let asked = std::cell::RefCell::new(Vec::new());
    let kept = where_resolves(split.clone(), |host| {
        asked.borrow_mut().push(host.to_owned());
        true
    });
    assert_eq!(kept, split);
    assert_eq!(*asked.borrow(), ["coderouter.cmux.internal", "other.example:8443"]);
    assert!(where_resolves(BTreeMap::new(), |_| true).is_empty());
}

/// The reported bug: a daemon env with no route gets the machine's; a value anything else
/// already set (the daemon's, the login shell's, a profile's) is kept.
#[test]
fn a_spawn_gets_the_route_only_where_nothing_else_set_it() {
    let plane = validate(parse(BAKED)).unwrap();
    let mut cmd = std::process::Command::new("true");
    cmd.env_clear();
    cmd.env("OPENAI_BASE_URL", "https://mine.example/v1");
    cmd.env_remove("ANTHROPIC_API_KEY");
    let add: BTreeMap<_, _> = missing(&plane, |key| has(&cmd, false, key)).into_iter().collect();
    assert_eq!(add["ANTHROPIC_BASE_URL"], "https://coderouter.cmux.internal");
    assert_eq!(add["ANTHROPIC_API_KEY"], PLACEHOLDER);
    assert_eq!(add["OPENAI_API_KEY"], PLACEHOLDER);
    assert!(!add.contains_key("OPENAI_BASE_URL"), "a set value wins");
    let mut env = BTreeMap::from([("ANTHROPIC_BASE_URL".to_owned(), String::new())]);
    for (k, v) in missing(&plane, |key| env.get(key).is_some_and(|v| !v.is_empty())) {
        env.insert(k, v);
    }
    assert_eq!(
        env["ANTHROPIC_BASE_URL"], "https://coderouter.cmux.internal",
        "an empty value is none"
    );
}

#[test]
fn a_no_is_reused_for_a_burst_only_so_a_name_that_starts_resolving_routes_the_next_spawn() {
    let now = Instant::now();
    let no = Answer::new("coderouter.cmux.internal", now, Some(false));
    assert_eq!(no.reused("coderouter.cmux.internal", now), Some(false));
    // Production 2026-11-26 21:46 UTC: a "no" held for 60 s left every agent started after the
    // edge's name began resolving without a route.
    assert_eq!(no.reused("coderouter.cmux.internal", now + Duration::from_secs(3)), None);
    let yes = Answer::new("coderouter.cmux.internal", now, Some(true));
    assert_eq!(yes.reused("coderouter.cmux.internal", now + Duration::from_secs(59)), Some(true));
    assert_eq!(yes.reused("other.internal", now), None);
    let hung = Answer::new("coderouter.cmux.internal", now, None);
    assert_eq!(hung.reused("coderouter.cmux.internal", now + Duration::from_secs(9)), Some(false));
    assert_eq!(hung.reused("coderouter.cmux.internal", now + Duration::from_secs(11)), None);
}

#[test]
fn a_spawn_waits_for_a_name_that_starts_resolving_but_a_streak_pays_the_wait_once() {
    use std::cell::Cell;
    // Production 2026-11-26 23:49 UTC: agents started while the platform kicked the guest's
    // resolver kept no model route for their whole life.
    let start = SystemTime::UNIX_EPOCH + Duration::from_secs(1_800_000_000);
    let clock = Cell::new(start);
    let asked = Cell::new(0);
    let mut streak = None;
    let until = Streak::wait_until(&mut streak, start);
    assert_eq!(until, start + EDGE_WAIT);
    // The name starts resolving on the third lookup, 3 s in: this spawn gets the route.
    let routed = wait_for_name(
        || {
            asked.set(asked.get() + 1);
            asked.get() >= 3
        },
        || clock.get(),
        |d| clock.set(clock.get() + d),
        until,
    );
    assert!(routed);
    assert_eq!(clock.get(), start + Duration::from_secs(3));

    // A name that never resolves: the wait ends at its bound...
    let never = wait_for_name(|| false, || clock.get(), |d| clock.set(clock.get() + d), until);
    assert!(!never);
    assert_eq!(clock.get(), until);
    // ...and later spawns in the same streak do not wait again.
    let later = start + Duration::from_secs(120);
    assert_eq!(Streak::wait_until(&mut streak, later), until);
    let none =
        wait_for_name(|| panic!("no lookup after the streak's wait"), || later, |_| {}, until);
    assert!(!none);
    // A spare paused and claimed past the span waits again.
    let resumed = later + STREAK_SPAN;
    assert_eq!(Streak::wait_until(&mut streak, resumed), resumed + EDGE_WAIT);
}
