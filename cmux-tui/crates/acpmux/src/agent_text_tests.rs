#[test]
fn every_pattern_compiles() {
    for re in
        [&HEADER, &TRACE_ID, &GENERATED, &CO_AUTHOR, &SESSION_LINE, &RECEIPT, &BATCH_LINE, &HANDOFF]
    {
        assert!(re.is_some());
    }
}

#[test]
fn a_sent_by_trailer_reads_as_an_agents() {
    let text = "PR #1 is green.\n\nSent-by: devbox/lane-x harness=claude \
                    model=claude-opus-5-5";
    let found = detect(text);
    assert_eq!(found.from.as_deref(), Some("devbox/lane-x"));
    assert_eq!(found.signals, vec!["a Sent-by line"]);
}

#[test]
fn a_codex_handoff_reads_as_an_agents() {
    let text = "From Codex:\nHandoff for the lane.\n\nDo not merge or deploy until the probe is \
                    green.\n\nTrace-ID: ask-1234";
    let found = detect(text);
    assert_eq!(found.from.as_deref(), Some("Codex"));
    assert_eq!(found.signals, vec!["a \"From\" header", "a Trace-ID line"]);
}

#[test]
fn a_persons_words_read_as_theirs() {
    for text in [
        "Merge and deploy whenever you want.",
        "From now on: always rebase first.",
        "From the logs: it crashed at 3am",
        "from here, go left",
        "Can you check the trace id of that run?",
        "I generated this with a script",
        // Review of #37190 (F2): prose that says "generated with" is not a footer.
        "The docs were generated with Sphinx",
    ] {
        assert!(!detect(text).agent(), "{text:?} read as an agent's");
    }
}

#[test]
fn footers_and_receipts_name_their_signal() {
    let found = detect("Done.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)");
    assert_eq!(found.from.as_deref(), Some("Claude Code"));
    assert!(detect("Review (gpt-5.5): SHIP at abc123").agent());
    assert!(detect("Co-Authored-By: Claude <noreply@anthropic.com>").agent());
    assert!(detect("## Handoff\nnext steps").agent());
    let batch = detect("[message 1 of 2] from lane-a\nhello");
    assert_eq!(batch.from.as_deref(), Some("lane-a"));
}

/// Review of #37190 (F3): a footer line that starts exactly where the tail starts is read.
#[test]
fn a_tail_that_starts_on_a_line_reads_that_line() {
    let footer = "Trace-ID: ask-1";
    let body = "y".repeat(HEAD_BYTES + 10);
    let pad = "z".repeat(TAIL_BYTES - footer.len() - 1);
    let text = format!("{body}\n{footer}\n{pad}");
    assert_eq!(text.as_bytes()[text.len() - TAIL_BYTES - 1], b'\n');
    assert!(detect(&text).signals.contains(&"a Trace-ID line"));
}

/// The length bounds the patterns no longer carry hold on the match: one character more
/// is no signal. A footer starts its line (`GENERATED`), so a later "generated by" on the
/// line, past an overlong first one, is prose and no signal either.
#[test]
fn name_bounds_hold_at_their_edge() {
    let name = |n: usize| format!("A{}", "b".repeat(n.saturating_sub(1)));
    assert_eq!(detect(&format!("From {}:", name(48))).from, Some(name(48)));
    assert!(!detect(&format!("From {}:", name(49))).agent());
    let tool = |n: usize| format!("Generated with [{}](x)", name(n));
    assert_eq!(detect(&tool(32)).from, Some(name(32)));
    assert!(!detect(&tool(33)).agent());
    let later = format!("Generated with {} and generated by Codex(x)", name(40));
    assert!(!detect(&later).agent(), "{later:?}");
    assert!(!detect("Built the page, then generated by Codex(x)").agent());
    assert!(detect(&format!("Review ({}): SHIP", "r".repeat(80))).agent());
    assert!(!detect(&format!("Review ({}): SHIP", "r".repeat(81))).agent());
    assert!(detect("Verdict: BLOCK").agent());
    let batch = |n: usize| format!("[message 1 of 2] from {}", name(n));
    assert_eq!(detect(&batch(64)).from, Some(name(64)));
    assert!(!detect(&batch(65)).agent());
}

/// The cases the browser's mirror reads too (webviews agentText.ts, pasteMarks.test.tsx):
/// one list, so the composer and the daemon cannot drift on what reads as an agent's.
#[test]
fn the_shared_cases_read_as_the_browser_reads_them() {
    let cases: Vec<serde_json::Value> =
        serde_json::from_str(include_str!("agent_text_cases.json")).expect("the cases parse");
    for case in cases {
        let text = case["text"].as_str().expect("a case's text");
        let found = detect(text);
        assert_eq!(found.from.as_deref(), case["from"].as_str(), "{text:?}");
        assert_eq!(found.agent(), !case["from"].is_null(), "{text:?}");
    }
}

#[test]
fn a_huge_text_reads_its_head_and_tail_only() {
    let text = format!("From Hermes:\n{}\nTrace-ID: x", "y".repeat(10 * 1024 * 1024));
    let found = detect(&text);
    assert_eq!(found.from.as_deref(), Some("Hermes"));
    assert!(found.signals.contains(&"a Trace-ID line"));
}
