#!/usr/bin/env bun
// Refresh the vendored secret rules and the test corpus (hq#2509).
//
//   bun cmux-tui/crates/acpmux/rules/secrets/refresh.ts [gitleaks-tag] [noseyparker-tag]
//
// Writes, next to this file:
// - gitleaks.toml and LICENSE-gitleaks: gitleaks' default rules at the tag, unmodified (MIT).
// - labels.toml: each rule's mask label, the noun phrase of its description
//   ("Found a GitHub Personal Access Token, risking ..." -> "GitHub Personal Access Token"),
//   or an override below. Review the printed new labels before committing.
// - noseyparker-examples.json and LICENSE-noseyparker: Nosey Parker's rule examples and
//   negative examples (Apache-2.0), XORed and base64-encoded so no committed file holds a
//   string a secret scanner (or GitHub push protection, which decodes base64) would flag.
//
// Needs Bun 1.2.21 or newer (Bun.YAML). It only downloads rule files; it never runs or
// verifies a secret.

import { join } from "node:path";

const here = import.meta.dir;
const gitleaksTag = process.argv[2] ?? "v8.30.1";
const noseyTag = process.argv[3] ?? "v0.24.0";
/** Each example's bytes are XORed with this (`secret_scan_tests.rs` reads it back). */
const CORPUS_KEY = 0x5a;

/** Labels the description heuristic gets wrong. */
const overrides: Record<string, string> = {
  "aws-access-token": "AWS access key",
  "aws-amazon-bedrock-api-key-long-lived": "Amazon Bedrock API key",
  "aws-amazon-bedrock-api-key-short-lived": "Amazon Bedrock API key",
  "cisco-meraki-api-key": "Cisco Meraki API key",
  "codecov-access-token": "Codecov Access Token",
  "cohere-api-token": "Cohere API Token",
  "curl-auth-header": "auth token",
  "curl-auth-user": "credentials",
  "flutterwave-public-key": "Flutterwave Public Key",
  "generic-api-key": "secret",
  "hashicorp-tf-password": "HashiCorp Terraform password",
  "kubernetes-secret-yaml": "Kubernetes Secret",
  "nuget-config-password": "NuGet password",
  "sourcegraph-access-token": "Sourcegraph Access Token",
};

const lead =
  /^(?:Identified|Detected|Found|Discovered|Uncovered|Captured|Exposed)\s+(?:an?\s+|the\s+)?(?:(?:possible|potential|potentially exposed|exposed)\s+)?(?:pattern that (?:may indicate|resembles)\s+(?:an?\s+)?)?/i;
const stop =
  /(?:,|\s+(?:which|that|potentially|risking|posing|exposing|could|allowing|in|used|for|leading|enabling|compromising|threatening)\b|\.\s*$)/;

function label(id: string, description: string): string {
  if (overrides[id]) return overrides[id];
  const rest = description.replace(lead, "");
  const end = rest.search(stop);
  return (end < 0 ? rest : rest.slice(0, end)).trim().replace(/\.$/, "");
}

async function get(url: string): Promise<Response> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return response;
}

const gitleaksRaw = `https://raw.githubusercontent.com/gitleaks/gitleaks/${gitleaksTag}`;
const rules = await (await get(`${gitleaksRaw}/config/gitleaks.toml`)).text();
await Bun.write(join(here, "gitleaks.toml"), rules);
await Bun.write(join(here, "LICENSE-gitleaks"), await (await get(`${gitleaksRaw}/LICENSE`)).text());

const old = await Bun.file(join(here, "labels.toml"))
  .text()
  .then((text) => Bun.TOML.parse(text) as { labels?: Record<string, string> })
  .catch(() => ({ labels: {} }));
const config = Bun.TOML.parse(rules) as { rules: { id: string; description: string }[] };
const labels = config.rules.map((rule) => [rule.id, label(rule.id, rule.description)] as const);
const toml = [
  `# The mask label of each gitleaks rule, generated by refresh.ts from gitleaks ${gitleaksTag}.`,
  "# A secret the rule finds is replaced by [label].",
  "",
  "[labels]",
  ...labels.map(([id, text]) => `${JSON.stringify(id)} = ${JSON.stringify(text)}`),
  "",
].join("\n");
await Bun.write(join(here, "labels.toml"), toml);
for (const [id, text] of labels) {
  if (old.labels?.[id] !== text) console.log(`label ${id}: ${text}`);
}

// Nosey Parker's rules live as YAML files in its source tree.
const tree = (await (
  await get(`https://api.github.com/repos/praetorian-inc/noseyparker/git/trees/${noseyTag}?recursive=1`)
).json()) as { tree: { path: string }[]; truncated: boolean };
if (tree.truncated) throw new Error("the Nosey Parker tree listing is truncated");
const prefix = "crates/noseyparker/data/default/builtin/rules/";
const noseyRaw = `https://raw.githubusercontent.com/praetorian-inc/noseyparker/${noseyTag}`;
type NoseyRule = { id: string; name: string; examples?: string[]; negative_examples?: string[] };
const examples: { id: string; name: string; examples: string[]; negative: string[] }[] = [];
// XOR with a constant, then base64: GitHub push protection decodes plain base64 and blocks it.
const encode = (text: string) => Buffer.from(Buffer.from(text).map((b) => b ^ CORPUS_KEY)).toString("base64");
for (const { path } of tree.tree.filter((entry) => entry.path.startsWith(prefix) && entry.path.endsWith(".yml"))) {
  const file = Bun.YAML.parse(await (await get(`${noseyRaw}/${path}`)).text()) as { rules?: NoseyRule[] };
  for (const rule of file.rules ?? []) {
    examples.push({
      id: rule.id,
      name: rule.name,
      examples: (rule.examples ?? []).map(encode),
      negative: (rule.negative_examples ?? []).map(encode),
    });
  }
}
examples.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
await Bun.write(
  join(here, "noseyparker-examples.json"),
  `${JSON.stringify(
    { source: `praetorian-inc/noseyparker ${noseyTag}`, license: "Apache-2.0", xor: CORPUS_KEY, rules: examples },
    null,
    1,
  )}\n`,
);
await Bun.write(join(here, "LICENSE-noseyparker"), await (await get(`${noseyRaw}/LICENSE`)).text());
console.log(`${config.rules.length} gitleaks rules (${gitleaksTag}), ${examples.length} Nosey Parker rules (${noseyTag})`);
