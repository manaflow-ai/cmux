//! `agents_doctor` strings of the CLI catalog (English and Japanese): the
//! human readiness table of `cmux agents doctor` (cli/agents_doctor.rs).
//! `{…}` fields are replaced at the call site. The JSON report keeps its
//! stable ids, statuses and reasons in English; only these texts change.

#[derive(Debug, PartialEq, Eq)]
pub(crate) struct AgentsDoctorMessages {
    pub title: &'static str,
    pub header_check: &'static str,
    pub header_status: &'static str,
    pub header_detail: &'static str,
    pub fix_prefix: &'static str,
    pub status_ok: &'static str,
    pub status_missing: &'static str,
    pub status_unknown: &'static str,
    pub status_not_applicable: &'static str,
    pub status_cmux_only: &'static str,
    pub check_harness_claude: &'static str,
    pub check_harness_codex: &'static str,
    pub check_mcp_claude: &'static str,
    pub check_mcp_codex: &'static str,
    pub check_accessibility: &'static str,
    pub check_screen_recording: &'static str,
    pub check_capture_consent: &'static str,
    pub not_on_path: &'static str,
    /// `{harness}`: Claude Code or Codex.
    pub install_harness: &'static str,
    /// `{harness}`.
    pub harness_missing: &'static str,
    /// `{location}`: the config file that names the server.
    pub configured: &'static str,
    pub injected_in_cmux_chats: &'static str,
    pub start_from_cmux_chat: &'static str,
    /// `{location}`: the project's `.mcp.json`.
    pub pending_approval: &'static str,
    pub approve_in_claude: &'static str,
    /// `{location}`, `{error}`.
    pub config_unreadable: &'static str,
    /// `{location}`.
    pub fix_config: &'static str,
    pub granted: &'static str,
    pub not_granted: &'static str,
    /// `{url}`: the System Settings pane, opened by an exact `open` command.
    pub open_settings: &'static str,
    pub app_not_running: &'static str,
    pub open_cmux: &'static str,
    pub app_no_report: &'static str,
    /// Computer Use Setup is GUI-only (the CLI refuses its action), so the
    /// one exact command is rerunning the doctor after it.
    pub setup_command: &'static str,
    pub app_unresponsive: &'static str,
    pub computer_use_off: &'static str,
    pub disabled_by_policy: &'static str,
    pub helper_unavailable: &'static str,
    pub helper_starting: &'static str,
    pub helper_version_mismatch: &'static str,
    pub open_setup: &'static str,
    pub run_again: &'static str,
    pub capture_consent_not_reported: &'static str,
    pub allow_capture_prompt: &'static str,
    pub not_macos: &'static str,
}

