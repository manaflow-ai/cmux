#[test]
fn env_exports_parse_quoted_and_bare_values() {
    let contents = "# generated by cmux from machine boot env; managed, do not edit\n\
            export OPENAI_BASE_URL='https://coderouter.dev/v1'\n\
            export CMUX_CODEROUTER_URL='https://coderouter.dev'\n\
            export CMUX_VM_ID='it'\\''s-a-vm'\n\
            PLAIN=bare-value # trailing comment\n\
            DOUBLE=\"quoted \\\"value\\\"\"\n\
            \n\
            not a valid line\n\
            1BAD=nope\n\
            export BROKEN='unterminated\n";
    let values = parse_env_exports(contents);
    assert_eq!(values["OPENAI_BASE_URL"], "https://coderouter.dev/v1");
    assert_eq!(values["CMUX_CODEROUTER_URL"], "https://coderouter.dev");
    assert_eq!(values["CMUX_VM_ID"], "it's-a-vm");
    assert_eq!(values["PLAIN"], "bare-value");
    assert_eq!(values["DOUBLE"], "quoted \"value\"");
    assert!(!values.contains_key("1BAD"));
    assert!(!values.contains_key("BROKEN"));
    assert_eq!(values.len(), 5, "{values:?}");
}

#[test]
fn source_prefers_process_env_and_falls_back_per_key() {
    let file = "export CMUX_CODEROUTER_URL='https://file.example'\nexport CMUX_VM_ID='file-vm'\n";
    let env = |key: &str| (key == VM_ID_VAR).then(|| "env-vm".to_string());
    let source = resolve_source(env, Some(file)).expect("source resolves");
    assert_eq!(
        source,
        MachineIdentity { origin: "https://file.example".to_string(), vm_id: "env-vm".to_string() }
    );

    let trailing = resolve_source(
        |key| match key {
            CODEROUTER_URL_VAR => Some("https://coderouter.dev/".to_string()),
            VM_ID_VAR => Some("vm".to_string()),
            _ => None,
        },
        None,
    )
    .expect("env-only source resolves");
    assert_eq!(trailing.origin, "https://coderouter.dev/");
}

#[test]
fn source_is_absent_without_both_keys_or_with_a_bad_origin() {
    assert_eq!(resolve_source(|_| None, None), None);
    assert_eq!(resolve_source(|_| None, Some("export CMUX_VM_ID='vm'\n")), None);
    assert_eq!(resolve_source(|_| None, Some("export CMUX_CODEROUTER_URL='https://x'\n")), None);
    assert_eq!(
        resolve_source(
            |_| Some("   ".to_string()),
            Some("export CMUX_CODEROUTER_URL='https://x'\nexport CMUX_VM_ID='vm'\n")
        )
        .map(|source| source.vm_id),
        Some("vm".to_string()),
        "blank process values fall through to the file"
    );
    assert_eq!(
        resolve_source(
            |_| None,
            Some("export CMUX_CODEROUTER_URL='coderouter.dev'\nexport CMUX_VM_ID='vm'\n")
        ),
        None,
        "an origin without a scheme is not polled"
    );
}

/// A fresh devbox VM: no identity in the unit's env, no per-home file,
/// the image's baked env without `CMUX_VM_ID`, and the bound id.
#[test]
fn fresh_vm_resolves_from_the_image_env_and_the_bound_id() {
    let image = "# generated by cmux; the same for every machine; managed, do not edit\n\
            export OPENAI_BASE_URL='https://coderouter.cmux.internal/v1'\n\
            export OPENAI_API_KEY='cmux-vm-edge-placeholder'\n\
            export CMUX_CODEROUTER_URL='https://coderouter.cmux.internal'\n";
    assert_eq!(
        resolve_layered_source(|_| None, &[None, Some(image)], Some("vm-bound\n")),
        Some(MachineIdentity {
            origin: "https://coderouter.cmux.internal".to_string(),
            vm_id: "vm-bound".to_string()
        })
    );
    assert_eq!(
        resolve_layered_source(|_| None, &[None, Some(image)], None),
        None,
        "the image env alone has no machine id"
    );
    assert_eq!(
        resolve_layered_source(|_| None, &[None, None], Some("vm-bound")),
        None,
        "an id alone has no coderouter origin"
    );
}

#[test]
fn earlier_layers_win_per_key_and_bad_bound_ids_are_ignored() {
    let home = "export CMUX_VM_ID='home-vm'\n";
    let image =
        "export CMUX_CODEROUTER_URL='https://image.example'\nexport CMUX_VM_ID='image-vm'\n";
    let source =
        resolve_layered_source(|_| None, &[Some(home), Some(image)], Some("bound")).unwrap();
    assert_eq!(source.origin, "https://image.example");
    assert_eq!(source.vm_id, "home-vm", "a per-home value wins over the image's");
    let env = |key: &str| (key == VM_ID_VAR).then(|| "env-vm".to_string());
    assert_eq!(resolve_layered_source(env, &[Some(image)], Some("bound")).unwrap().vm_id, "env-vm");
    let url_only = "export CMUX_CODEROUTER_URL='https://x'\n";
    for bad in ["", "  \n", "two words", &"a".repeat(MAX_INSTANCE_ID_BYTES + 1)] {
        assert_eq!(resolve_layered_source(|_| None, &[Some(url_only)], Some(bad)), None, "{bad:?}");
    }
}
