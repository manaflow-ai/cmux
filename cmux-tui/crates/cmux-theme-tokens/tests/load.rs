#[test]
fn includes_load_after_the_file_and_nest() {
    let env = env_for("include-home");
    let loaded = load(&env, Appearance::Dark);
    // The include comes after the main file, so its background wins.
    assert_eq!(hex(loaded.input.background), "#222222");
    assert_eq!(hex(loaded.input.foreground), "#DDDDDD");
    assert!(loaded.diagnostics.is_empty(), "{:?}", loaded.diagnostics);
    let base = fixtures().join("include-home/.config/ghostty");
    let watch = loaded.watch_paths();
    for p in [
        base.join("config"),
        base.join("config.ghostty"),
        base.join("inc/colors.conf"),
        base.join("inc/nested.conf"),
        base.join("inc/missing.conf"),
    ] {
        assert!(watch.contains(&p), "{} not watched: {watch:?}", p.display());
    }
}

