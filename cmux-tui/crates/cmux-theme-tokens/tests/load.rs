#[test]
fn no_config_is_ghostty_default() {
    let loaded = load(&env_for("no-such-home"), Appearance::Dark);
    assert!(loaded.files.is_empty());
    assert_eq!(loaded.input, ThemeInput::GHOSTTY_DEFAULT);
    let t = ThemeTokens::derive(&loaded.input);
    assert!(t.is_dark);
    assert_tokens(&t, SWIFT_DEFAULT);
    assert_eq!(t, ThemeTokens::fallback());
}

#[test]
fn bundled_theme_by_name_matches_swift() {
    let loaded = load(&env_for("theme-home"), Appearance::Dark);
    assert_eq!(loaded.theme.as_deref(), Some("Monokai Fixture"));
    assert_eq!(loaded.theme_file, Some(fixtures().join("res/themes/Monokai Fixture")));
    assert_eq!(hex(loaded.input.background), "#272822");
    assert_eq!(loaded.input.selection_background.map(hex).as_deref(), Some("#57584F"));
    let t = ThemeTokens::derive(&loaded.input);
    assert_tokens(&t, SWIFT_MONOKAI);
    // Sidebar, titlebar and content are the terminal background exactly.
    assert_eq!(t.sidebar_background, loaded.input.background);
    assert_eq!(t.content_background, loaded.input.background);
}

#[test]
fn light_dark_pair_follows_appearance() {
    let dark = load(&env_for("pair-home"), Appearance::Dark);
    assert_eq!(dark.theme.as_deref(), Some("Monokai Fixture"));
    assert_tokens(&ThemeTokens::derive(&dark.input), SWIFT_MONOKAI);
    let light = load(&env_for("pair-home"), Appearance::Light);
    assert_eq!(light.theme.as_deref(), Some("Latte Fixture"));
    let t = ThemeTokens::derive(&light.input);
    assert!(!t.is_dark);
    assert_tokens(&t, SWIFT_LATTE);
}

#[test]
fn theme_value_forms() {
    assert_eq!(theme_for("Nord", Appearance::Light).as_deref(), Some("Nord"));
    assert_eq!(theme_for("dark:B,light:A", Appearance::Light).as_deref(), Some("A"));
    assert_eq!(theme_for("dark:B", Appearance::Light).as_deref(), Some("B"));
    assert_eq!(
        theme_for("light:iTerm2 Solarized Light,dark:Monokai Classic", Appearance::Dark).as_deref(),
        Some("Monokai Classic")
    );
    assert_eq!(theme_for("", Appearance::Dark), None);
}

