//! Fixture configs through the loader, and token values checked against the
//! Swift `ThemeTokens.derive` output for the same inputs.

use std::path::PathBuf;

use cmux_theme_tokens::*;

fn fixtures() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures")
}

fn env_for(home: &str) -> Env {
    Env {
        home: Some(fixtures().join(home)),
        ghostty_resources_dir: Some(fixtures().join("res")),
        xdg_data_dirs: Some(String::new()),
        ..Env::default()
    }
}

fn hex(c: Rgb) -> String {
    c.describe()
}

/// `name value` lines as the Swift dump prints them.
fn assert_tokens(t: &ThemeTokens, expected: &str) {
    for line in expected.lines().map(str::trim).filter(|l| !l.is_empty()) {
        let (name, value) = line.split_once(' ').unwrap();
        let got = match name {
            "window_background" => t.window_background,
            "chrome_background" => t.chrome_background,
            "elevated_background" => t.elevated_background,
            "strip_background" => t.strip_background,
            "text_primary" => t.text_primary,
            "text_secondary" => t.text_secondary,
            "text_tertiary" => t.text_tertiary,
            "hover_fill" => t.hover_fill,
            "selection_fill" => t.selection_fill,
            "pressed_fill" => t.pressed_fill,
            "separator" => t.separator,
            "pane_border" => t.pane_border,
            "focus_ring" => t.focus_ring,
            "text_selection" => t.text_selection,
            "attention" => t.attention,
            "danger" => t.danger,
            "success" => t.success,
            "highlight" => t.highlight,
            "highlight_text" => t.highlight_text,
            "shadow" => t.shadow,
            other => panic!("unknown token {other}"),
        };
        assert_eq!(hex(got), value, "{name}");
    }
}

