#[test]
fn borders_none_clears_lines_only() {
    let t = ThemeTokens::fallback();
    let none = t.with_borders(BorderMode::None);
    assert_eq!(none.separator.a, 0.0);
    assert_eq!(none.pane_border.a, 0.0);
    assert_eq!(none.focus_ring.a, 0.0);
    assert_eq!(none.selection_fill, t.selection_fill);
    assert_eq!(t.with_borders(BorderMode::Default), t);
    assert_eq!(BorderMode::parse("None"), Some(BorderMode::None));
    assert_eq!(BorderMode::None.width(1.0), 0.0);
}

