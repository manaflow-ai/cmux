// The docs reference, generated from the same tables as the d.ts: one row per op (scope, class,
// docs), per event stream and per signal source. `gen-cmux-global.ts --check` keeps it in step.

export interface RefOp { scope: string; class: string; docs?: string }
export interface RefEvent { docs: string; reads: string; scope: string }
export interface RefSignal { docs: string; scopes: string[]; push: string[]; pollFloorSeconds: number; staleAfterSeconds: number }

/** One table cell: a single line with `|` escaped. */
const cell = (s: string | undefined): string => (s ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|").trim()
const code = (s: string): string => `\`${s}\``

export function referenceMarkdown(input: {
  apiVersion: string
  ops: Record<string, RefOp>
  never: string[]
  events: Record<string, RefEvent>
  signals: Record<string, RefSignal>
}): string {
  const out: string[] = [
    "# cmux app API reference",
    "",
    `API version ${input.apiVersion}. Generated by tools/gen-cmux-global.ts from the same tables as cmux-app.d.ts and scopes.json; do not edit.`,
    "",
    "## Ops",
    "",
    "| Op | Class | Scope | Docs |",
    "| --- | --- | --- | --- |",
  ]
  for (const name of Object.keys(input.ops).sort()) {
    const op = input.ops[name]!
    out.push(`| ${code(name)} | ${op.class} | ${code(op.scope)} | ${cell(op.docs)} |`)
  }
  out.push("", "Ops no app may call:", "")
  for (const name of [...input.never].sort()) out.push(`- ${code(name)}`)
  out.push("", "## Event streams", "", "| Stream | Reads | Scope | Docs |", "| --- | --- | --- | --- |")
  for (const name of Object.keys(input.events).sort()) {
    const e = input.events[name]!
    out.push(`| ${code(name)} | ${code(e.reads)} | ${code(e.scope)} | ${cell(e.docs)} |`)
  }
  out.push("", "## Signal sources", "", "| Signal | Scopes | Pushed by | Poll floor (s) | Stale after (s) | Docs |", "| --- | --- | --- | --- | --- | --- |")
  for (const name of Object.keys(input.signals).sort()) {
    const s = input.signals[name]!
    out.push(`| ${code(name)} | ${s.scopes.map(code).join(", ")} | ${s.push.map(code).join(", ") || "nothing"} | ${s.pollFloorSeconds} | ${s.staleAfterSeconds} | ${cell(s.docs)} |`)
  }
  return out.join("\n") + "\n"
}
