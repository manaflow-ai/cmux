//! Writes `$OUT_DIR/dispatch.rs`: the `mod` line and the dispatch of every op module in `src/`.
//!
//! Every slice that added an op module used to add one `mod` line and one dispatch arm to
//! `src/lib.rs`, so each one that merged conflicted with every other open slice. Now adding a
//! module is adding its file. An op module is a file directly in `src/` (not `lib.rs`, and
//! not one another file includes with `#[path = ...]`) with a line that starts with
//! `pub(crate) fn handles(operation: &[u8]) -> bool`; it also has
//! `pub(crate) fn respond(operation: &[u8], request: &[u8]) -> Result<Vec<u8>, i32>`. Its
//! `mod` line is written here, so `src/lib.rs` does not declare it. Modules are asked in
//! name order, and no two may answer the same op (the `op_modules_are_disjoint` test), so
//! the order never decides which module answers.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const HANDLES: &str = "pub(crate) fn handles(operation: &[u8]) -> bool";

fn main() {
    let manifest =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let src = manifest.join("src");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src");

    let mut files: Vec<(String, PathBuf, String)> = Vec::new();
    for entry in std::fs::read_dir(&src).unwrap_or_else(|e| panic!("read {}: {e}", src.display())) {
        let path = entry.expect("src entry").path();
        if path.extension().and_then(|e| e.to_str()) != Some("rs") || !path.is_file() {
            continue;
        }
        let name = path.file_stem().and_then(|s| s.to_str()).expect("utf-8 file name").to_owned();
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
        files.push((name, path, text));
    }

    // Files another file includes as its own submodule (`#[path = "window_rules_desktop.rs"]`).
    let mut included: Vec<String> = Vec::new();
    for (_, _, text) in &files {
        for line in text.lines() {
            let line = line.trim();
            if let Some(rest) = line.strip_prefix("#[path = \"")
                && let Some(target) = rest.split('"').next()
            {
                included.push(target.trim_end_matches(".rs").to_owned());
            }
        }
    }

    let lib = files
        .iter()
        .find(|(name, _, _)| name == "lib")
        .map(|(_, _, text)| text.clone())
        .expect("src/lib.rs");
    let mut modules: Vec<(String, PathBuf)> = files
        .into_iter()
        .filter(|(name, _, text)| {
            name != "lib"
                && !included.contains(name)
                && text.lines().any(|line| line.starts_with(HANDLES))
        })
        .map(|(name, path, _)| (name, path))
        .collect();
    modules.sort();

    for (name, _) in &modules {
        for declared in [format!("mod {name};"), format!("pub mod {name};")] {
            if lib.lines().any(|line| line.trim() == declared) {
                panic!(
                    "src/lib.rs declares `{declared}`, but src/{name}.rs is an op module (it has \
                     `{HANDLES}`), whose `mod` line build.rs writes: drop the line from src/lib.rs"
                );
            }
        }
    }

    let mut out = String::new();
    out.push_str("// @generated by build.rs from the op modules in src/. Do not edit.\n\n");
    for (name, path) in &modules {
        let path = path.to_str().expect("utf-8 path");
        writeln!(out, "#[path = {path:?}]\nmod {name};").unwrap();
    }
    out.push_str(
        "\n/// An op module's `handles`.\n#[cfg(test)]\ntype OpHandles = fn(&[u8]) -> bool;\n",
    );
    out.push_str(
        "\n/// The op modules, in name order: each one's name and `handles`.\n\
         #[cfg(test)]\n\
         const OP_MODULES: &[(&str, OpHandles)] = &[\n",
    );
    for (name, _) in &modules {
        writeln!(out, "    ({name:?}, {name}::handles),").unwrap();
    }
    out.push_str(
        "];\n\n\
         /// The answer of the op module that handles `operation`, or None when none does.\n\
         fn respond_op_module(operation: &[u8], request: &[u8]) -> Option<Result<Vec<u8>, i32>> {\n",
    );
    for (name, _) in &modules {
        writeln!(
            out,
            "    if {name}::handles(operation) {{\n        return Some({name}::respond(operation, request));\n    }}"
        )
        .unwrap();
    }
    out.push_str("    None\n}\n");

    let dest = Path::new(&std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("dispatch.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("write {}: {e}", dest.display()));
}
