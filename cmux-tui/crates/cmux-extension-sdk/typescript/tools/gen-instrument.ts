// Writes src/generated/instrument.ts (gitignored, never committed), the Instrument kit's stylesheet and version for web panes
// (`cmux-extension-sdk/web/instrument`), from the kit's own sources: its version (webviews/src/kit/version.ts),
// its sheet (webviews/src/kit/kit.css, the `kit-*` classes) and the token blocks the app's pages
// read (webviews/src/pages/shared/desktop.css: design-scale, type-scale, motion-scale,
// layout-grid). A web pane loads only its extension's own files, so the package carries the sheet;
// nothing here is written by hand. A page's build runs it first.
//
//   bun tools/gen-instrument.ts           # write src/generated/instrument.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"

const repo = new URL("../../../../../", import.meta.url)
const read = (path: string) => readFileSync(new URL(path, repo), "utf8")
const OUT = new URL("../src/generated/instrument.ts", import.meta.url)
const BLOCKS = ["design-scale", "type-scale", "motion-scale", "layout-grid"]

const stripComments = (css: string) =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== "")
    .join("\n")

export function instrumentSource(): string {
  const version = /INSTRUMENT_VERSION = "([^"]+)"/.exec(read("webviews/src/kit/version.ts"))?.[1]
  if (!version) throw new Error("gen-instrument: no INSTRUMENT_VERSION in webviews/src/kit/version.ts")
  const desktop = read("webviews/src/pages/shared/desktop.css")
  const tokens = BLOCKS.map((name) => {
    const block = new RegExp(`/\\* ${name}:begin[^\\n]*\\n([\\s\\S]*?)/\\* ${name}:end \\*/`).exec(desktop)?.[1]
    if (block === undefined) throw new Error(`gen-instrument: no ${name} block in desktop.css`)
    return stripComments(block)
  })
  // Web panes carry the kit's rules inline and have no access to the app's base UI sheet.
  const kit = stripComments(
    read("webviews/src/kit/kit.css")
      .replace('@import "../ui/ui.css";', "")
      .replace('@import "./pill.css";', () => read("webviews/src/kit/pill.css")),
  )
  const css = [...tokens, kit].join("\n") + "\n"
  return `// GENERATED by tools/gen-instrument.ts from webviews/src/kit (version.ts, kit.css) and the token
// blocks of webviews/src/pages/shared/desktop.css; do not edit. \`bun tools/gen-instrument.ts\` rewrites it.

/** The Instrument kit version this sheet is (webviews/src/kit/version.ts; kit/CHANGELOG.md). */
export const INSTRUMENT_VERSION = ${JSON.stringify(version)}

/** The kit's design tokens (\`--ds-*\`, \`--text-*\`, \`--weight-*\`, \`--cmux-motion-*\`, read from the
 * \`--cmux-*\` theme variables cmux keeps current on the page) and its \`kit-*\` classes. */
export const INSTRUMENT_CSS = ${JSON.stringify(css)}
`
}

if (import.meta.main) {
  mkdirSync(new URL(".", OUT), { recursive: true })
  writeFileSync(OUT, instrumentSource())
  console.log("wrote src/generated/instrument.ts")
}
