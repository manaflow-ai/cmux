//! The settings schema as a JSON Schema (draft 2020-12) for editors and
//! agents (`cmux settings schema`). Built from the rows the owner validates
//! with, so it always matches the running build, and an editor and the
//! daemon agree on every portable kind. Domain kinds (themes, fonts,
//! sounds) are plain strings here: their values are facts of the Mac the
//! app runs on, which the owner checks on write. Not checked in: the export
//! it comes from changes with every settings pull request.

use serde_json::{Map, Value, json};

use super::{Choice, DomainKind, Kind, NumberRange, Row, Schema, Validation};

impl Schema {
    /// The JSON Schema document for the settings file. Keys outside the
    /// schema (actions, MCP, shortcuts and the like) stay allowed, so only
    /// schema keys are described.
    pub fn json_schema(&self) -> Value {
        let mut root = Map::new();
        root.insert(
            "$schema".into(),
            json!({
                "type": "string",
                "description": "This schema's location (a path such as ./cmux-next.schema.json), for editor completion and validation.",
            }),
        );
        for row in &self.rows {
            insert(&mut root, &row.path, leaf(row));
        }
        json!({
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "title": "cmux-next.json",
            "description": "cmux NEXT settings (~/.config/cmux/cmux-next.json). JSONC: comments and trailing commas are kept. Generated by `cmux settings schema` from the installed build's settings rows.",
            "x-cmux-schema-hash": self.schema_hash,
            "type": "object",
            "properties": Value::Object(root),
        })
    }
}

/// Puts `leaf` at `path`, creating an object schema per component.
fn insert(properties: &mut Map<String, Value>, path: &[String], leaf: Value) {
    let Some((head, rest)) = path.split_first() else { return };
    if rest.is_empty() {
        properties.insert(head.clone(), leaf);
        return;
    }
    let node = properties
        .entry(head.clone())
        .or_insert_with(|| json!({ "type": "object", "properties": {} }));
    if let Some(children) = node.get_mut("properties").and_then(Value::as_object_mut) {
        insert(children, rest, leaf);
    }
}

fn leaf(row: &Row) -> Value {
    let mut schema = match kind_schema(row) {
        Value::Object(members) => members,
        _ => Map::new(),
    };
    schema.insert("title".into(), json!(row.title.text));
    let description = row.help.as_ref().or(row.summary.as_ref()).map(|text| text.text.clone());
    if let Some(description) = description {
        schema.insert("description".into(), json!(description));
    }
    if let Some(default) = &row.default {
        schema.insert("default".into(), default.clone());
    }
    schema.insert("x-cmux-key".into(), json!(row.key));
    schema.insert("x-cmux-section".into(), json!(row.section));
    schema.insert("x-cmux-agent-settable".into(), json!(row.agent_settable));
    Value::Object(schema)
}

fn kind_schema(row: &Row) -> Value {
    match row.validation {
        Validation::Domain(DomainKind::BackdropSelection) => {
            let Kind::Choice(choices) = &row.kind else { return json!({ "type": "string" }) };
            // `system:<absolute path>` (a macOS wallpaper), `file:<absolute path>`
            // or `folder:<absolute path>` (not `/` alone).
            let path = json!({ "type": "string", "pattern": "^((system|file):/|folder:/.)" });
            return json!({ "anyOf": [choice(choices), path] });
        }
        Validation::Domain(DomainKind::ChatRoots) => {
            return json!({ "type": "array", "items": { "type": "string", "pattern": "^/" } });
        }
        Validation::Domain(DomainKind::CustomDensities) => {
            let density = json!({
                "type": "object",
                "required": ["id", "name"],
                "properties": {
                    "id": { "type": "string", "pattern": "^[a-z0-9][a-z0-9-]{0,63}$" },
                    "name": { "type": "string", "minLength": 1 },
                    "basedOn": { "type": "string" },
                    "level": { "type": "number" },
                    "spacing": { "type": "number" },
                    "fontSize": { "type": "number" },
                    "tokens": { "type": "object", "additionalProperties": { "type": "number", "minimum": 0 } },
                },
            });
            return json!({ "type": "array", "items": density });
        }
        _ => {}
    }
    match &row.kind {
        Kind::Toggle => json!({ "type": "boolean" }),
        Kind::Choice(choices) => choice(choices),
        Kind::ChoiceOrNumber(choices, range) => {
            json!({ "anyOf": [choice(choices), number(range)] })
        }
        Kind::ChoiceOrUrl(choices, url_key) => {
            let url = json!({
                "type": "object",
                "properties": { url_key.as_str(): { "type": "string", "pattern": "^[Hh][Tt][Tt][Pp][Ss]?://[^/?#@\\s]+/?$" } },
                "required": [url_key],
                "additionalProperties": false,
            });
            json!({ "anyOf": [choice(choices), url] })
        }
        Kind::Number(range) => number(range),
        Kind::Color => json!({
            "type": "string",
            "pattern": "^#?([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$",
            "examples": ["#3B82F6", "#3B82F680"],
        }),
        Kind::Theme => json!({
            "type": "string",
            "description": "A theme name, or light:<name>,dark:<name>.",
        }),
        Kind::FontFamily | Kind::Sound | Kind::Url | Kind::Text => json!({ "type": "string" }),
        Kind::HostList => json!({ "type": "array", "items": { "type": "string" } }),
        Kind::TimeRange => {
            // "HH:MM", hours 0-23 and minutes 0-59; the owner skips empty
            // parts and takes a leading "+" or zeros.
            let time = json!({
                "type": "string",
                "pattern": "^:*\\+?0*([0-9]|1[0-9]|2[0-3]):+\\+?0*([0-9]|[1-5][0-9]):*$",
            });
            json!({
                "type": "object",
                "properties": { "start": time, "end": time },
                "required": ["start", "end"],
            })
        }
        Kind::FolderList => {
            json!({ "type": "array", "items": { "type": "string", "pattern": "^(/|~/)" } })
        }
        Kind::StringList => {
            json!({ "type": "array", "items": { "type": "string", "minLength": 1 } })
        }
        Kind::OrderedChoices(choices) => json!({ "type": "array", "items": choice(choices) }),
        Kind::NumberList(range) => json!({ "type": "array", "items": number(range) }),
        Kind::StringMap => {
            json!({ "type": "object", "additionalProperties": { "type": "string" } })
        }
        Kind::SoundRules => {
            let events: Map<String, Value> = super::accepts::SOUND_RULE_EVENTS
                .iter()
                .map(|event| ((*event).to_owned(), json!({ "type": "string" })))
                .collect();
            json!({
                "type": "object",
                "additionalProperties": {
                    "anyOf": [
                        { "type": "string" },
                        {
                            "type": "object",
                            "properties": {
                                "sound": { "type": "string" },
                                "volume": { "type": "number", "minimum": 0, "maximum": 1 },
                                "events": {
                                    "type": "object",
                                    "properties": events,
                                    "additionalProperties": false,
                                },
                            },
                            "additionalProperties": false,
                        },
                    ],
                },
            })
        }
    }
}

fn choice(choices: &[Choice]) -> Value {
    json!({
        "type": "string",
        "enum": choices.iter().map(|choice| choice.value.clone()).collect::<Vec<_>>(),
        "enumDescriptions": choices.iter().map(|choice| choice.title.text.clone()).collect::<Vec<_>>(),
    })
}

fn number(range: &NumberRange) -> Value {
    json!({ "type": "number", "minimum": range.min, "maximum": range.max })
}
