//! The settings schema as a JSON Schema (draft 2020-12) for editors and
//! agents (`cmux settings schema`). Built from the rows the owner validates
//! with, so it always matches the running build, and an editor and the
//! daemon agree on every portable kind. Domain kinds (themes, fonts,
//! sounds) are plain strings here: their values are facts of the Mac the
//! app runs on, which the owner checks on write. Not checked in: the export
//! it comes from changes with every settings pull request.

use serde_json::{Map, Value, json};

use super::{Choice, DomainKind, Kind, NumberRange, Row, Schema, Validation};

impl Schema {
    /// The JSON Schema document for the settings file. Keys outside the
    /// schema (actions, MCP, shortcuts and the like) stay allowed, so only
    /// schema keys are described.
    pub fn json_schema(&self) -> Value {
        let mut root = Map::new();
        root.insert(
            "$schema".into(),
            json!({
                "type": "string",
                "description": "This schema's location (a path such as ./cmux-next.schema.json), for editor completion and validation.",
            }),
        );
        for row in &self.rows {
            insert(&mut root, &row.path, leaf(row));
        }
        json!({
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "title": "cmux-next.json",
            "description": "cmux NEXT settings (~/.config/cmux/cmux-next.json). JSONC: comments and trailing commas are kept. Generated by `cmux settings schema` from the installed build's settings rows.",
            "x-cmux-schema-hash": self.schema_hash,
            "type": "object",
            "properties": Value::Object(root),
        })
    }
}

impl Schema {
    /// The JSON Schema of a theme file (`themes/NAME.json`, `cmux theme
    /// schema`): the look rows `is_look` takes, dotted at the top or nested,
    /// and the file's own keys. Anything else is flagged, since the app
    /// refuses it.
    pub fn theme_file_json_schema(&self, is_look: impl Fn(&Row) -> bool) -> Value {
        let color = json!({ "type": "string", "pattern": "^#[0-9a-fA-F]{6}$" });
        let mut colors = Map::new();
        for token in ["background", "foreground", "cursor", "selection", "accent"] {
            colors.insert(token.into(), color.clone());
        }
        for index in 0..16 {
            colors.insert(index.to_string(), color.clone());
        }
        colors.insert("palette".into(), json!({ "type": "array", "maxItems": 16, "items": color }));
        let mut root = Map::new();
        root.insert("$schema".into(), json!({ "type": "string" }));
        root.insert(
            "name".into(),
            json!({ "type": "string", "description": "The look's name, as lists show it." }),
        );
        root.insert("description".into(), json!({ "type": "string" }));
        root.insert(
            "colors".into(),
            json!({
                "type": "object",
                "description": "The terminal theme's own colors (appearance.themeEdits of the theme appearance.theme names).",
                "properties": Value::Object(colors),
                "additionalProperties": false,
            }),
        );
        root.insert(
            "ghostty".into(),
            json!({
                "description": "A Ghostty theme block (background = #rrggbb, palette = 4=#rrggbb), as text or a list of lines.",
                "anyOf": [{ "type": "string" }, { "type": "array", "items": { "type": "string" } }],
            }),
        );
        root.insert(
            "density".into(),
            json!({
                "type": "object",
                "description": "The look's own density: the shape of every tab and sidebar row, the toolbar's buttons and the sidebar's width. A built-in (basedOn) with the Density Playground's tokens over it; it is the density in use while the file applies.",
                "properties": {
                    "basedOn": { "enum": ["ultraCompact", "compact", "cozy", "comfortable", "spacious"] },
                    "level": { "type": "number" },
                    "spacing": { "type": "number" },
                    "fontSize": { "type": "number" },
                    "tokens": {
                        "type": "object",
                        "description": "Density Playground tokens by name (tabCornerRadius, sidebarCornerRadius, sidebarWidth, browserRowHeight, toolbarGlyphSize, ...), in points.",
                        "additionalProperties": { "type": "number", "minimum": 0 },
                    },
                },
                "additionalProperties": false,
            }),
        );
        root.insert(
            "fonts".into(),
            json!({
                "type": "array",
                "description": "Font files the app registers for itself while the file applies (a theme pack's own faces), as absolute file: paths; the look names their families (terminal.fontFamily).",
                "items": { "type": "string", "pattern": "^file:/" },
                "maxItems": 32,
            }),
        );
        for row in self.rows.iter().filter(|row| is_look(row)) {
            root.insert(row.key.clone(), leaf(row));
            if row.path.len() > 1 {
                insert(&mut root, &row.path, leaf(row));
            }
        }
        json!({
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "title": "cmux theme file",
            "description": "A cmux look (~/.config/cmux/themes/NAME.json): look settings, dotted or nested, plus the terminal theme's own colors. JSONC. Generated by `cmux theme schema` from the installed build's settings rows.",
            "x-cmux-schema-hash": self.schema_hash,
            "type": "object",
            "properties": Value::Object(root),
            "additionalProperties": false,
        })
    }
}

/// Puts `leaf` at `path`, creating an object schema per component.
fn insert(properties: &mut Map<String, Value>, path: &[String], leaf: Value) {
    let Some((head, rest)) = path.split_first() else { return };
    if rest.is_empty() {
        properties.insert(head.clone(), leaf);
        return;
    }
    let node = properties
        .entry(head.clone())
        .or_insert_with(|| json!({ "type": "object", "properties": {} }));
    if let Some(children) = node.get_mut("properties").and_then(Value::as_object_mut) {
        insert(children, rest, leaf);
    }
}

fn leaf(row: &Row) -> Value {
    let mut schema = match kind_schema(row) {
        Value::Object(members) => members,
        _ => Map::new(),
    };
    schema.insert("title".into(), json!(row.title.text));
    let description = row.help.as_ref().or(row.summary.as_ref()).map(|text| text.text.clone());
    if let Some(description) = description {
        schema.insert("description".into(), json!(description));
    }
    if let Some(default) = &row.default {
        schema.insert("default".into(), default.clone());
    }
    schema.insert("x-cmux-key".into(), json!(row.key));
    schema.insert("x-cmux-section".into(), json!(row.section));
    schema.insert("x-cmux-agent-settable".into(), json!(row.agent_settable));
    Value::Object(schema)
}

fn kind_schema(row: &Row) -> Value {
    match row.validation {
        Validation::Domain(DomainKind::BackdropSelection) => {
            let Kind::Choice(choices) = &row.kind else { return json!({ "type": "string" }) };
            // `system:<absolute path>` (a macOS wallpaper), `file:<absolute path>`
            // or `folder:<absolute path>` (not `/` alone), or a `youtube:` video.
            let path = json!({ "type": "string", "pattern": "^((system|file):/|folder:/.)" });
            // `live:<id>` or `live:<extension>/<id>` (a live wallpaper).
            let live = json!({ "type": "string", "pattern": super::backdrop::LIVE_PATTERN });
            return json!({ "anyOf": [choice(choices), path, live, youtube(), shader()] });
        }
        Validation::Domain(DomainKind::BackdropPicture) => return picture(),
        Validation::Domain(DomainKind::BackdropSchedule) => {
            return json!({
                "type": "object",
                "propertyNames": { "pattern": super::backdrop::WHEN_PATTERN },
                "additionalProperties": picture(),
            });
        }
        Validation::Domain(DomainKind::BackdropLocation) => {
            return json!({ "type": "string", "pattern": super::backdrop::LOCATION_PATTERN });
        }
        Validation::Domain(DomainKind::BackdropMemory) => {
            let folder = json!({ "type": "string", "pattern": "^folder:/." });
            let rotate = json!({ "anyOf": [{ "const": "daily" }, folder] });
            let off = json!({ "anyOf": [{ "const": "none" }, picture()] });
            return json!({
                "type": "object",
                "properties": { "rotate": rotate, "folder": folder, "off": off },
                "additionalProperties": false,
            });
        }
        Validation::Domain(DomainKind::BackdropPlacement) => {
            return json!({
                "type": "object",
                "propertyNames": { "pattern": "\\S" },
                "additionalProperties": {
                    "type": "string",
                    "pattern": "^[ \\t]*(fill|fit|center|stretch)([ \\t]+[0-9.]+[ \\t]+[0-9.]+([ \\t]+[0-9.]+)?)?[ \\t]*$",
                },
            });
        }
        Validation::Domain(DomainKind::BackdropRecents) => {
            let listed = json!({ "type": "string", "enum": super::backdrop::selection_choices() });
            let path = json!({ "type": "string", "pattern": "^((system|file):/|folder:/.)" });
            return json!({
                "type": "array",
                "maxItems": super::backdrop::RECENTS_CAP,
                "uniqueItems": true,
                "items": { "anyOf": [listed, path, youtube()] },
            });
        }
        Validation::Domain(DomainKind::ChatRoots) => {
            return json!({ "type": "array", "items": { "type": "string", "pattern": "^/" } });
        }
        Validation::Domain(DomainKind::CustomDensities) => {
            let density = json!({
                "type": "object",
                "required": ["id", "name"],
                "properties": {
                    "id": { "type": "string", "pattern": "^[a-z0-9][a-z0-9-]{0,63}$" },
                    "name": { "type": "string", "minLength": 1 },
                    "basedOn": { "type": "string" },
                    "level": { "type": "number" },
                    "spacing": { "type": "number" },
                    "fontSize": { "type": "number" },
                    "tokens": { "type": "object", "additionalProperties": { "type": "number", "minimum": 0 } },
                },
            });
            return json!({ "type": "array", "items": density });
        }
        Validation::Domain(DomainKind::CommandLabels) => {
            let name = json!({ "type": "string", "minLength": 1 });
            let rule = json!({
                "type": "object",
                "required": ["label"],
                "anyOf": [{ "required": ["program"] }, { "required": ["match"] }],
                "properties": {
                    "label": name,
                    "program": { "anyOf": [name, { "type": "array", "minItems": 1, "items": name }] },
                    "match": name,
                    "link": { "type": "string" },
                    "icon": { "type": "string" },
                },
            });
            return json!({ "type": "array", "items": { "anyOf": [name, rule] } });
        }
        Validation::Domain(DomainKind::TranscriptTokens) => {
            // One property per token of schemas/transcript-look/transcript-look.json, so an editor
            // completes and checks a theme file's tokens.
            let mut properties = Map::new();
            for token in &crate::transcript_look::spec().tokens {
                let schema = match token.kind {
                    crate::transcript_look::TokenKind::Choice => {
                        json!({ "enum": token.choices, "description": token.description })
                    }
                    crate::transcript_look::TokenKind::Number => json!({
                        "type": "number", "minimum": token.min, "maximum": token.max,
                        "description": token.description,
                    }),
                };
                properties.insert(token.name.clone(), schema);
            }
            return json!({ "type": "object", "properties": properties, "additionalProperties": false });
        }
        Validation::Domain(DomainKind::AppId) => {
            // The manifest's own id pattern, read from its schema.
            return match super::app_id::app_id_pattern() {
                Some(pattern) => json!({ "type": "string", "pattern": pattern }),
                None => json!({ "type": "string" }),
            };
        }
        _ => {}
    }
    match &row.kind {
        Kind::Toggle => json!({ "type": "boolean" }),
        Kind::Choice(choices) => choice(choices),
        Kind::ChoiceOrNumber(choices, range) => {
            json!({ "anyOf": [choice(choices), number(range)] })
        }
        Kind::ChoiceOrUrl(choices, url_key) => {
            let url = json!({
                "type": "object",
                "properties": { url_key.as_str(): { "type": "string", "pattern": "^[Hh][Tt][Tt][Pp][Ss]?://[^/?#@\\s]+/?$" } },
                "required": [url_key],
                "additionalProperties": false,
            });
            json!({ "anyOf": [choice(choices), url] })
        }
        Kind::Number(range) => number(range),
        Kind::Color => json!({
            "type": "string",
            "pattern": "^#?([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$",
            "examples": ["#3B82F6", "#3B82F680"],
        }),
        Kind::Theme => json!({
            "type": "string",
            "description": "A theme name, or light:<name>,dark:<name>.",
        }),
        Kind::FontFamily | Kind::Sound | Kind::Url | Kind::Text => json!({ "type": "string" }),
        Kind::HostList => json!({ "type": "array", "items": { "type": "string" } }),
        Kind::TimeRange => {
            // "HH:MM", hours 0-23 and minutes 0-59; the owner skips empty
            // parts and takes a leading "+" or zeros.
            let time = json!({
                "type": "string",
                "pattern": "^:*\\+?0*([0-9]|1[0-9]|2[0-3]):+\\+?0*([0-9]|[1-5][0-9]):*$",
            });
            json!({
                "type": "object",
                "properties": { "start": time, "end": time },
                "required": ["start", "end"],
            })
        }
        Kind::FolderList => {
            json!({ "type": "array", "items": { "type": "string", "pattern": "^(/|~/)" } })
        }
        Kind::StringList => {
            json!({ "type": "array", "items": { "type": "string", "minLength": 1 } })
        }
        Kind::OrderedChoices(choices) => json!({ "type": "array", "items": choice(choices) }),
        Kind::NumberList(range) => json!({ "type": "array", "items": number(range) }),
        Kind::StringMap => {
            json!({ "type": "object", "additionalProperties": { "type": "string" } })
        }
        // The row's own shape, as the owner checks it (`shape::matches`).
        Kind::Json(shape) => shape.clone(),
        Kind::SoundRules => {
            let events: Map<String, Value> = super::accepts::SOUND_RULE_EVENTS
                .iter()
                .map(|event| ((*event).to_owned(), json!({ "type": "string" })))
                .collect();
            json!({
                "type": "object",
                "additionalProperties": {
                    "anyOf": [
                        { "type": "string" },
                        {
                            "type": "object",
                            "properties": {
                                "sound": { "type": "string" },
                                "volume": { "type": "number", "minimum": 0, "maximum": 1 },
                                "events": {
                                    "type": "object",
                                    "properties": events,
                                    "additionalProperties": false,
                                },
                            },
                            "additionalProperties": false,
                        },
                    ],
                },
            })
        }
    }
}

/// A fixed background: a listed one, a `system:` / `file:` absolute path or a
/// `youtube:` video.
fn picture() -> Value {
    let listed = json!({ "type": "string", "enum": super::backdrop::picture_choices() });
    let path = json!({ "type": "string", "pattern": super::backdrop::PATH_PATTERN });
    json!({ "anyOf": [listed, path, youtube(), shader()] })
}

/// A living wallpaper, `shader:NAME` (super::backdrop::SHADERS).
fn shader() -> Value {
    json!({ "type": "string", "enum": super::backdrop::shader_ids() })
}

/// A canonical `youtube:` video id (crate::youtube; a settings write turns a
/// pasted YouTube address into one).
fn youtube() -> Value {
    json!({ "type": "string", "pattern": crate::youtube::ID_PATTERN })
}

fn choice(choices: &[Choice]) -> Value {
    json!({
        "type": "string",
        "enum": choices.iter().map(|choice| choice.value.clone()).collect::<Vec<_>>(),
        "enumDescriptions": choices.iter().map(|choice| choice.title.text.clone()).collect::<Vec<_>>(),
    })
}

fn number(range: &NumberRange) -> Value {
    json!({ "type": "number", "minimum": range.min, "maximum": range.max })
}
