#!/usr/bin/env python3
"""Generates src/unicode_tables.rs: Ghostty's per-codepoint width and
grapheme-width properties, derived from the UCD the way Ghostty's build does
(uucode's `Wcwidth` component and Ghostty's `src/build/uucode_config.zig`).

Usage: gen_unicode.py UCD_DIR > src/unicode_tables.rs
UCD_DIR is uucode's `ucd/` (the uucode tarball Ghostty's build.zig.zon pins).
"""
import re
import sys

MAX = 0x110000


def ranges(path, want=None):
    """Yields (start, end, value) from a UCD `a..b ; value` file."""
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = [p.strip() for p in line.split(";")]
            cps, value = parts[0], parts[1]
            if want is not None and value != want:
                continue
            if ".." in cps:
                a, b = cps.split("..")
            else:
                a = b = cps
            yield int(a, 16), int(b, 16), value


def fill(table, path, want=None, value=None):
    for a, b, v in ranges(path, want):
        for cp in range(a, b + 1):
            table[cp] = v if value is None else value


def main(ucd):
    gc = ["Cn"] * MAX
    fill(gc, f"{ucd}/extracted/DerivedGeneralCategory.txt")
    eaw = ["N"] * MAX
    fill(eaw, f"{ucd}/extracted/DerivedEastAsianWidth.txt")
    ignorable = [False] * MAX
    fill(ignorable, f"{ucd}/DerivedCoreProperties.txt", "Default_Ignorable_Code_Point", True)
    gcb = [""] * MAX
    fill(gcb, f"{ucd}/auxiliary/GraphemeBreakProperty.txt")
    modifier = [False] * MAX
    fill(modifier, f"{ucd}/emoji/emoji-data.txt", "Emoji_Modifier", True)
    vs_base = set()
    with open(f"{ucd}/emoji/emoji-variation-sequences.txt", encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^([0-9A-F]+) FE0[EF]\s*;", line)
            if m:
                vs_base.add(int(m.group(1), 16))

    width = [1] * MAX
    wide_in_grapheme = [False] * MAX  # zero in a grapheme, yet width > 0
    for cp in range(MAX):
        g = gc[cp]
        if g in ("Cc", "Cs", "Zl", "Zp"):
            w = 0
        elif cp == 0x00AD:
            w = 1
        elif ignorable[cp]:
            w = 0
        elif cp == 0x2E3A:
            w = 2
        elif cp == 0x2E3B:
            w = 3
        elif eaw[cp] in ("W", "F"):
            w = 2
        elif gcb[cp] == "Regional_Indicator":
            w = 2
        else:
            w = 1
        standalone = 2 if cp == 0x20E3 else w
        zero_in = (
            w == 0
            or modifier[cp]
            or g in ("Mn", "Me")
            or gcb[cp] in ("V", "T", "Prepend")
        )
        if zero_in and not modifier[cp] and gcb[cp] != "Prepend":
            width[cp] = 0
        else:
            width[cp] = min(2, standalone)
            if zero_in:
                wide_in_grapheme[cp] = True

    def runs(values, start=0x100):
        out = []
        cp = start
        while cp < MAX:
            v = values[cp]
            end = cp
            while end + 1 < MAX and values[end + 1] == v:
                end += 1
            out.append((cp, end, v))
            cp = end + 1
        return out

    print("// @generated by tools/gen_unicode.py from the UCD that Ghostty's")
    print("// pinned uucode carries. Do not edit by hand.")
    print()
    print("/// Code point ranges (from U+0100) whose Ghostty width is not 1: (first, last, width).")
    print("pub(crate) const WIDTH: &[(u32, u32, u8)] = &[")
    for a, b, v in runs(width):
        if v != 1:
            print(f"    (0x{a:X}, 0x{b:X}, {v}),")
    print("];")
    print()
    print("/// Ranges that take no width inside a grapheme though they have one alone")
    print("/// (emoji modifiers, prepends).")
    print("pub(crate) const ZERO_IN_GRAPHEME: &[(u32, u32)] = &[")
    for a, b, v in runs(wide_in_grapheme):
        if v:
            print(f"    (0x{a:X}, 0x{b:X}),")
    print("];")
    print()
    print("/// Bases of an emoji variation sequence (VS15 / VS16 change their width).")
    print("pub(crate) const EMOJI_VS_BASE: &[(u32, u32)] = &[")
    bases = sorted(vs_base)
    i = 0
    while i < len(bases):
        j = i
        while j + 1 < len(bases) and bases[j + 1] == bases[j] + 1:
            j += 1
        print(f"    (0x{bases[i]:X}, 0x{bases[j]:X}),")
        i = j + 1
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
