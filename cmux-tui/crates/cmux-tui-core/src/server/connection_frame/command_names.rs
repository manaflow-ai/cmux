//! The wire name of every legacy command, as serde spells it (`Command` has
//! `rename_all = "kebab-case"`): the word a request's `cmd` field carries. The request
//! counters use it as a row name (`diagnostics/command_stats.rs`), so that a row never has
//! a byte of a request in it. A new `Command` variant does not compile until it has a line
//! here.

