    /// The kind a `set-client-info` request declares, as one of the request counters' own
    /// words (`diagnostics/command_stats.rs`); the client's word itself is not kept there.
    pub(super) fn declared_kind(&self) -> Option<ClientKind> {
        match self {
            Self::SetClientInfo { kind: Some(kind), .. } => Some(ClientKind::declared(kind)),
            _ => None,
        }
    }

