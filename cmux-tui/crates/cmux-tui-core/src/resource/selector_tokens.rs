            | "open"
            | "rename"
            | "delete"
            | "restore"
            | "purge"
            | "connect"
            | "snapshot"
            | "events"
            | "ping"
            | "shutdown"
            | "update"
            | "metadata"
            | "detach"
            | "set"
            | "clear"
            | "resolve"
            | "put"
