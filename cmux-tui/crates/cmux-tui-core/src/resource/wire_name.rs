//! The wire name of every resource operation, as the catalog spells it, and
//! the list of every operation.

use super::ResourceOperation;

macro_rules! operation_names {
    ($($variant:ident => $wire:literal,)*) => {
        impl ResourceOperation {
            pub const fn wire_name(self) -> &'static str {
                match self {
                    $(Self::$variant => $wire,)*
                }
            }

            /// Every operation, in this table's order.
            pub(crate) const ALL: &'static [Self] = &[$(Self::$variant,)*];
        }
    };
}

