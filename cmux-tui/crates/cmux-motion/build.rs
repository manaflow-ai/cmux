//! Reads the motion tokens from the spec's `design-tokens.json` (`motion`)
//! at build time and writes them as constants (`$OUT_DIR/tokens.rs`), so
//! the numbers live in one file that every port reads (cmux-next macOS,
//! this crate, the GPUI app) and the token functions stay `const`. A
//! missing key, a wrong type or a value out of range fails the build with
//! the json path; nothing falls back to a copy in code.

#[path = "build-support/json.rs"]
mod json;

use std::fmt::Write as _;
use std::path::PathBuf;

/// Repo root `plans/cmux-next/spec-proposals/visuals/design-tokens.json`,
/// the same file cmux-theme-tokens compiles in.
const TOKENS: &str = "../../../plans/cmux-next/spec-proposals/visuals/design-tokens.json";

/// `motion.springs` keys in `MotionSpring` declaration order.
const SPRINGS: [&str; 13] = [
    "move",
    "appear",
    "disappear",
    "settle",
    "scroll",
    "screen",
    "track",
    "selection",
    "panel",
    "pinDrag",
    "zoom",
    "exit",
    "tabOpen",
];
/// `motion.fades` keys in `MotionFade` declaration order.
const FADES: [&str; 12] = [
    "hover",
    "focus",
    "fadeIn",
    "fadeOut",
    "crossfade",
    "lift",
    "theme",
    "highlight",
    "launch",
    "pinLift",
    "pinSettle",
    "pinShrink",
];
/// `motion.tweens` keys in `MotionTween` declaration order.
const TWEENS: [&str; 3] = ["tabOpen", "tabClose", "tabMove"];
/// `motion.loops` keys in `MotionLoop` declaration order.
const LOOPS: [&str; 3] = ["spinner", "pulse", "flash"];

fn main() {
    let path = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"))
        .join(TOKENS);
    println!("cargo:rerun-if-changed={}", path.display());
    println!("cargo:rerun-if-changed=build-support/json.rs");
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let doc = json::parse(&text).unwrap_or_else(|e| panic!("design-tokens.json: {e}"));
    let motion = doc.get("motion").unwrap_or_else(|| panic!("design-tokens.json: no motion"));
    let code = generate(motion).unwrap_or_else(|e| panic!("design-tokens.json motion.{e}"));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("tokens.rs");
    std::fs::write(&out, code).unwrap_or_else(|e| panic!("{}: {e}", out.display()));
}

fn at<'a>(v: &'a json::Value, path: &[&str]) -> Result<&'a json::Value, String> {
    path.iter()
        .try_fold(v, |v, key| v.get(key))
        .ok_or_else(|| format!("{}: missing", path.join(".")))
}

fn number(
    v: &json::Value,
    path: &[&str],
    range: std::ops::RangeInclusive<f64>,
) -> Result<f64, String> {
    let n = at(v, path)?.as_f64().ok_or_else(|| format!("{}: not a number", path.join(".")))?;
    if !range.contains(&n) {
        return Err(format!("{}: {n} is outside {range:?}", path.join(".")));
    }
    Ok(n)
}

fn flag(v: &json::Value, path: &[&str]) -> Result<bool, String> {
    at(v, path)?.as_bool().ok_or_else(|| format!("{}: not a boolean", path.join(".")))
}

fn generate(m: &json::Value) -> Result<String, String> {
    let mut code =
        String::from("// Generated by cmux-motion/build.rs from design-tokens.json `motion`.\n");
    let speed = |key| number(m, &["speed", "value", key], 0.0..=10.0);
    let (fast, normal, off) = (speed("fast")?, speed("normal")?, speed("off")?);
    if fast != 1.0 || off != 0.0 {
        return Err(format!("speed.value: fast must be 1 and off 0 (got {fast}, {off})"));
    }
    writeln!(code, "pub(crate) const SPEED_NORMAL: f64 = {normal:?};").ok();

    writeln!(code, "pub(crate) const SPRINGS: [SpringParameters; {}] = [", SPRINGS.len()).ok();
    for key in SPRINGS {
        let response = number(m, &["springs", key, "value", "response"], 0.01..=2.0)?;
        let damping = number(m, &["springs", key, "value", "dampingFraction"], 0.05..=4.0)?;
        writeln!(code, "    SpringParameters::new({response:?}, {damping:?}), // {key}").ok();
    }
    code.push_str("];\n");

    let structural = at(m, &["structural", "value"])?
        .as_array()
        .ok_or("structural.value: not an array")?
        .iter()
        .map(|v| v.as_str().ok_or("structural.value: not a string").map(str::to_owned))
        .collect::<Result<Vec<_>, _>>()?;
    if let Some(unknown) = structural.iter().find(|k| !SPRINGS.contains(&k.as_str())) {
        return Err(format!("structural.value: unknown spring {unknown}"));
    }
    let flags: Vec<String> =
        SPRINGS.iter().map(|k| structural.iter().any(|s| s == k).to_string()).collect();
    writeln!(
        code,
        "pub(crate) const STRUCTURAL: [bool; {}] = [{}];",
        SPRINGS.len(),
        flags.join(", ")
    )
    .ok();

    let subtle = number(m, &["bounce", "value", "subtle"], 0.0..=0.9)?;
    if number(m, &["bounce", "value", "none"], 0.0..=0.0).is_err() {
        return Err("bounce.value.none: must be 0 (critically damped)".into());
    }
    let default_bounce = match at(m, &["bounce", "value", "default"])?.as_str() {
        Some("none") => "None",
        Some("subtle") => "Subtle",
        _ => return Err("bounce.value.default: not none or subtle".into()),
    };
    writeln!(code, "pub(crate) const SUBTLE_BOUNCE: f64 = {subtle:?};").ok();
    writeln!(
        code,
        "pub(crate) const DEFAULT_BOUNCE: MotionBounce = MotionBounce::{default_bounce};"
    )
    .ok();

    let kinds =
        ["paneAnimations", "newTab", "newWorkspace"].map(|k| flag(m, &["kinds", "value", k]));
    let [pane_animations, new_tab, new_workspace] = kinds;
    writeln!(
        code,
        "pub(crate) const DEFAULT_KINDS: [bool; 3] = [{}, {}, {}];",
        pane_animations?, new_tab?, new_workspace?
    )
    .ok();

    let geometry = number(m, &["settle", "value", "geometry"], 0.001..=4.0)?;
    let unit = number(m, &["settle", "value", "unit"], 0.000_001..=0.1)?;
    let factor = number(m, &["settle", "value", "velocityFactor"], 1.0..=100.0)?;
    writeln!(code, "pub(crate) const SETTLE_GEOMETRY: f32 = {:?};", geometry as f32).ok();
    writeln!(code, "pub(crate) const SETTLE_UNIT: f32 = {:?};", unit as f32).ok();
    writeln!(code, "pub(crate) const SETTLE_VELOCITY_FACTOR: f32 = {:?};", factor as f32).ok();

    code.push_str("pub(crate) const FADES: [f64; 12] = [\n");
    for key in FADES {
        let seconds = number(m, &["fades", key, "value"], 0.0..=5.0)?;
        writeln!(code, "    {seconds:?}, // {key}").ok();
    }
    code.push_str("];\n");
    writeln!(code, "pub(crate) const TWEENS: [TweenParameters; {}] = [", TWEENS.len()).ok();
    for key in TWEENS {
        let duration = number(m, &["tweens", key, "value", "duration"], 0.0..=2.0)?;
        let curve = match at(m, &["tweens", key, "value", "curve"])?.as_str() {
            Some("easeOutQuad") => "EaseOutQuad",
            _ => return Err(format!("tweens.{key}.value.curve: not easeOutQuad")),
        };
        writeln!(code, "    TweenParameters::new({duration:?}, TweenCurve::{curve}), // {key}")
            .ok();
    }
    code.push_str("];\n");
    for density in ["compact", "comfortable"] {
        let g = |key: &str| number(m, &["tabStrip", "value", density, key], 0.0..=1000.0);
        let c = |key: &str| {
            number(m, &["tabStrip", "value", density, "closingMode", key], 0.0..=1000.0)
        };
        writeln!(
            code,
            "pub(crate) const TAB_STRIP_{}: TabStripGeometry = TabStripGeometry {{ max_width: {:?}, open_start_width: {:?}, close_end_width: {:?}, min_active_width: {:?}, min_inactive_width: {:?}, pinned_width: {:?}, reorder_threshold: {:?}, closing_mode_below_pad: {:?}, closing_mode_trailing_pad: {:?}, closing_mode_exit_delay: {:?} }};",
            density.to_ascii_uppercase(),
            g("maxWidth")?,
            g("openStartWidth")?,
            g("closeEndWidth")?,
            g("minActiveWidth")?,
            g("minInactiveWidth")?,
            g("pinnedWidth")?,
            g("reorderThreshold")?,
            c("belowPad")?,
            c("trailingPad")?,
            c("exitDelay")?,
        )
        .ok();
    }
    code.push_str("pub(crate) const LOOPS: [f64; 3] = [\n");
    for key in LOOPS {
        let seconds = number(m, &["loops", key, "value"], 0.05..=10.0)?;
        writeln!(code, "    {seconds:?}, // {key}").ok();
    }
    code.push_str("];\n");
    Ok(code)
}
