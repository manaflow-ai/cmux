/* The app's conversation client rules (cmux-tui/crates/cmux-conversation,
 * src/app.rs and src/ffi.rs; Swift module CCmuxConversationFFI): the run
 * summary and run step pagers, the chunked attachment transfer, a run step's
 * tool and a part's plain text, the inbox op values, and one open
 * conversation's session: the confirmed mirror and the intent log of unconfirmed
 * sends (src/session.rs). Each call is an op name and a JSON request object in,
 * one JSON reply object out: cmux_conversation_call for the stateless rules,
 * cmux_conversation_session_call on a session handle. Any thread (a session is
 * under its own lock); no unwinding across the boundary.
 *
 * Ops (request -> reply; a rule that refuses its input answers
 * {"error": "<code>"} with return code 0):
 *   policy -> {attachment_chunk_bytes, attachment_chunk_timeout_ms,
 *              cloud_network_timeout_ms, max_page, runs_key_batch,
 *              runs_page_limit, cloud_runs_page_limit}
 *   clamp_page {limit} -> {limit}                    (1...max_page)
 *   runs_key_batches {turns, answers, answers_served} -> {batches: [{turns}|{answers}]}
 *   runs_next {owner: "local"|"cloud", has_more, started_at: [ms], turns, before?,
 *              oldest_started_at, unresolved?} -> {before: n|null, unresolved}
 *   run_steps_next {has_more, cursor, keys} -> {after: n|null}
 *   upload_plan {attachment, needs?, has_poster_file, has_preview_file}
 *       -> {pieces: [{variant, size, chunks: [{offset, length, progress}]}]}
 *       | {error: poster_needed|preview_needed|unknown_piece|invalid}
 *   read_next {offset, received, eof} -> {offset: n|null} | {error: no_progress}
 *   run_tool {tool} -> {name, input?: {id?, message?, tasks?, sender?,
 *              is_tell_envelope, is_spawn_envelope}, status?, output?, started_at?}
 *   plain_text {part} -> {text}
 *   inbox_op {kind: pin|mark_unread|mute, on, position?, until?} -> the op object
 *
 * Session ops (messages and heads stay the owner's JSON; an event is
 * {rev, change}; a pending send is the app's {client_msg_id, conversation,
 * parts, reply_to?, thread_root?, created_at} and comes back with
 * state {kind: sending|acknowledged|failed, rev?, reason?} and its op):
 *   load_started -> {}          load_failed -> {}   (drops the kept events)
 *   loaded {snapshot} -> {replaced, settled: [client ids]}
 *   apply {event} -> {outcome: applied|stale|gap|buffered, change?, settled}
 *   typing {participant, on} -> {changed, typing: [..]}
 *   add {send} -> {added}       acknowledge {client_msg_id, rev} -> {settled}
 *   reject {client_msg_id, reason} -> {}   discard {client_msg_id} -> {}
 *   retry {client_msg_id} -> {send|null}   resendable -> {sends: [..]}
 *   state {tail?} -> {mirror: {rev, summary, tail}|null, pending, typing,
 *                     loading, buffered}
 *
 * Return codes: 0 OK, -1 a null pointer, -2 the request is not a UTF-8 JSON
 * object, -3 an unknown op, -4 a panic inside (caught). On any code but 0
 * nothing is written to *out. cmux_conversation_abi_version() returns
 * ABI_VERSION (src/ffi.rs). */

