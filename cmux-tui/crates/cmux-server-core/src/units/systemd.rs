//! systemd units (server.md 4.3; hardening from 7.2 where it applies to the
//! supervisor itself).

use super::{SERVICE_USER, UnitError};
use crate::layout::Layout;
use crate::platform::{InstallMode, Platform};

/// systemd `ExecStart` quoting: the path in double quotes. Characters that
/// systemd would expand or that need escaping are refused.
fn exec_path(layout: &Layout) -> Result<String, UnitError> {
    let path = layout.current_cmux.as_str();
    if path.chars().any(|c| c.is_control() || matches!(c, '"' | '\\' | '$' | '%' | ';')) {
        return Err(UnitError::UnsafePath("current_cmux"));
    }
    Ok(format!("\"{path}\""))
}

/// `~/.config/systemd/user/cmux-server.service`. Needs linger to run
/// without a login session.
pub fn systemd_user_unit(layout: &Layout) -> Result<String, UnitError> {
    if layout.platform != Platform::Linux || layout.mode != InstallMode::User {
        return Err(UnitError::WrongLayout);
    }
    let exec = exec_path(layout)?;
    Ok(format!(
        "# Generated by cmux. Do not edit: `cmux server install` rewrites this file.
[Unit]
Description=cmux server
Documentation=https://cmux.com/docs/server
Wants=network-online.target
After=network-online.target

[Service]
Type=exec
ExecStart={exec} host run
Environment=CMUX_SERVER_MODE=user
Restart=always
RestartSec=2
# The session host keeps its terminal hosts across a restart: stop only the
# supervisor process (lane 1 handoff contract).
KillMode=process
TimeoutStopSec=30
NoNewPrivileges=yes

[Install]
WantedBy=default.target
"
    ))
}

/// `/etc/systemd/system/cmux-server.service`, running as user `cmux`.
///
/// `ProtectSystem=full` (not `strict`) keeps `/opt/cmux` writable for the
/// updater without a `ReadWritePaths` list that would have to follow the
/// layout; `/usr`, `/boot` and `/etc` are read-only.
pub fn systemd_system_unit(layout: &Layout) -> Result<String, UnitError> {
    if layout.platform != Platform::Linux || layout.mode != InstallMode::System {
        return Err(UnitError::WrongLayout);
    }
    let exec = exec_path(layout)?;
    Ok(format!(
        "# Generated by cmux. Do not edit: `cmux server install --system` rewrites this file.
[Unit]
Description=cmux server
Documentation=https://cmux.com/docs/server
Wants=network-online.target
After=network-online.target

[Service]
Type=exec
User={SERVICE_USER}
Group={SERVICE_USER}
ExecStart={exec} host run
Environment=CMUX_SERVER_MODE=system
Restart=always
RestartSec=2
KillMode=process
TimeoutStopSec=30
StateDirectory=cmux
StateDirectoryMode=0700
RuntimeDirectory=cmux
RuntimeDirectoryMode=0755
RuntimeDirectoryPreserve=yes
ConfigurationDirectory=cmux
UMask=0027
NoNewPrivileges=yes
PrivateTmp=yes
ProtectSystem=full
ProtectHome=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictSUIDSGID=yes
LockPersonality=yes

[Install]
WantedBy=multi-user.target
"
    ))
}
