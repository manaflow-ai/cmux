//! `initdb` argv and the generated config files (server.md 8.1 to 8.4).

use super::{
    ADMIN_MAP, ADMIN_ROLE, APPS_MAP, AppDb, ClusterSpec, DbMode, MAX_SOCKET_PATH, PgError, PgPlan,
    SHARED_DATABASE, SOCKET_GROUP, valid_os_user,
};
use crate::platform::{HostPath, InstallMode, Platform};
use crate::ports::POSTGRES_DEFAULT;

/// The file this crate owns inside the data directory.
pub const CONF_FILE: &str = "cmux.conf";
/// The one line the I/O crate appends to `postgresql.conf` after `initdb`.
pub const CONF_INCLUDE_LINE: &str = "include 'cmux.conf'";

const HEADER: &str = "# Generated by cmux (server.md 8). Do not edit: cmux rewrites this file.\n";

pub(super) fn validate(spec: &ClusterSpec) -> Result<(), PgError> {
    let paths = [
        (&spec.pg_bin_dir, "pg_bin_dir"),
        (&spec.data_dir, "data_dir"),
        (&spec.socket_dir, "socket_dir"),
        (&spec.cmux_bin, "cmux_bin"),
    ];
    for (path, name) in paths {
        if path.platform() != spec.platform || !safe_path(spec.platform, path.as_str()) {
            return Err(PgError::UnsafePath(name));
        }
    }
    if let Some(pwfile) = &spec.admin_pwfile
        && (pwfile.platform() != spec.platform || !safe_path(spec.platform, pwfile.as_str()))
    {
        return Err(PgError::UnsafePath("admin_pwfile"));
    }
    if (spec.platform == Platform::Windows) != spec.admin_pwfile.is_some() {
        return Err(PgError::PwfileMismatch);
    }
    if spec.port == 0 || spec.port == POSTGRES_DEFAULT {
        return Err(PgError::BadPort(spec.port));
    }
    if spec.platform != Platform::Windows {
        let len = socket_file(spec).len();
        if len > MAX_SOCKET_PATH {
            return Err(PgError::SocketPathTooLong(len));
        }
    }
    if !valid_os_user(&spec.service_user) {
        return Err(PgError::BadServiceUser);
    }
    Ok(())
}

/// Paths go into single-quoted config strings, a shell command line
/// (`archive_command`) and a comma-separated directory list, so quotes,
/// percent signs, commas and shell metacharacters are refused.
fn safe_path(platform: Platform, path: &str) -> bool {
    let refused: &[char] = match platform {
        Platform::Windows => &['"', '\'', '%', ',', '^', '&', '|', '<', '>', '!'],
        Platform::Linux | Platform::MacOs => &['"', '\'', '%', ',', '\\', '$', '`', '!'],
    };
    !path.chars().any(|c| c.is_control() || refused.contains(&c))
}

fn socket_file(spec: &ClusterSpec) -> String {
    format!("{}/.s.PGSQL.{}", spec.socket_dir.as_str(), spec.port)
}

/// A `postgresql.conf` string value: backslashes doubled, quotes doubled.
fn conf_string(value: &str) -> String {
    format!("'{}'", value.replace('\\', "\\\\").replace('\'', "''"))
}

fn bin(spec: &ClusterSpec, name: &str) -> HostPath {
    let exe =
        if spec.platform == Platform::Windows { format!("{name}.exe") } else { name.to_owned() };
    spec.pg_bin_dir.join(&exe)
}

impl PgPlan {
    /// `initdb` argv (server.md 8.1). The locale is PostgreSQL 17's builtin
    /// `C.UTF-8` provider with `--locale=C`, so the cluster does not depend on
    /// which OS locales exist (macOS and Windows lack `C.UTF-8`).
    pub fn initdb_argv(&self) -> Vec<String> {
        let s = &self.spec;
        let mut argv = vec![
            bin(s, "initdb").to_string(),
            format!("--pgdata={}", s.data_dir),
            "--data-checksums".to_owned(),
            "--encoding=UTF8".to_owned(),
            "--locale=C".to_owned(),
            "--locale-provider=builtin".to_owned(),
            "--builtin-locale=C.UTF-8".to_owned(),
        ];
        match &s.admin_pwfile {
            None => {
                argv.push("--auth-local=peer".to_owned());
                argv.push("--auth-host=reject".to_owned());
            }
            Some(pwfile) => {
                argv.push("--auth-local=scram-sha-256".to_owned());
                argv.push("--auth-host=scram-sha-256".to_owned());
                argv.push(format!("--pwfile={pwfile}"));
            }
        }
        argv.push(format!("--username={ADMIN_ROLE}"));
        argv
    }

    /// Contents of `<data>/cmux.conf` (server.md 8.2, 8.4). Data checksums
    /// are set by `initdb` and cannot be set here.
    pub fn postgresql_conf(&self, apps: &[AppDb]) -> String {
        let s = &self.spec;
        let mut out = String::from(HEADER);
        let listen = if self.listens_tcp(apps) { "127.0.0.1" } else { "" };
        out.push_str(&format!("listen_addresses = {}\n", conf_string(listen)));
        out.push_str(&format!("port = {}\n", s.port));
        if s.platform == Platform::Windows {
            out.push_str("unix_socket_directories = ''\n");
        } else {
            let dirs = format!("\"{}\"", s.socket_dir);
            out.push_str(&format!("unix_socket_directories = {}\n", conf_string(&dirs)));
            if s.mode == InstallMode::System {
                out.push_str(&format!("unix_socket_group = {}\n", conf_string(SOCKET_GROUP)));
                out.push_str("unix_socket_permissions = 0770\n");
            } else {
                out.push_str("unix_socket_permissions = 0700\n");
            }
        }
        out.push_str("password_encryption = 'scram-sha-256'\n");
        out.push_str("standard_conforming_strings = on\n");
        out.push_str("wal_level = replica\n");
        out.push_str("archive_mode = on\n");
        out.push_str("archive_timeout = 60\n");
        let command = format!("\"{}\" server db archive-wal \"%p\" \"%f\"", s.cmux_bin);
        out.push_str(&format!("archive_command = {}\n", conf_string(&command)));
        out
    }

    /// Full `pg_hba.conf` (server.md 8.3). First rule: the admin role for the
    /// service user only. Last rules: reject everything else.
    pub fn pg_hba_conf(&self, apps: &[AppDb]) -> String {
        let mut out = String::from(HEADER);
        out.push_str("# TYPE DATABASE USER ADDRESS METHOD\n");
        if self.uses_peer() {
            out.push_str(&format!("local all {ADMIN_ROLE} peer map={ADMIN_MAP}\n"));
        } else {
            out.push_str(&format!("host all {ADMIN_ROLE} 127.0.0.1/32 scram-sha-256\n"));
        }
        for app in apps {
            let db = hba_database(app);
            let role = app.id.role();
            if self.uses_peer() {
                let method = match self.spec.mode {
                    InstallMode::System => format!("peer map={APPS_MAP}"),
                    InstallMode::User => "scram-sha-256".to_owned(),
                };
                out.push_str(&format!("local {db} {role} {method}\n"));
            }
            if app.tcp || !self.uses_peer() {
                out.push_str(&format!("host {db} {role} 127.0.0.1/32 scram-sha-256\n"));
            }
        }
        out.push_str("local all all reject\n");
        out.push_str("host all all all reject\n");
        out
    }

    /// Full `pg_ident.conf`: the service user maps to the admin role; in
    /// system mode each app's OS user maps to its role.
    pub fn pg_ident_conf(&self, apps: &[AppDb]) -> String {
        let mut out = String::from(HEADER);
        out.push_str("# MAPNAME SYSTEM-USERNAME PG-USERNAME\n");
        if !self.uses_peer() {
            return out;
        }
        out.push_str(&format!("{ADMIN_MAP} {} {ADMIN_ROLE}\n", self.spec.service_user));
        if self.spec.mode == InstallMode::System {
            for app in apps {
                out.push_str(&format!("{APPS_MAP} {} {}\n", app.id.os_user(), app.id.role()));
            }
        }
        out
    }
}

fn hba_database(app: &AppDb) -> &'static str {
    match app.mode {
        DbMode::Database => "sameuser",
        DbMode::Schema => SHARED_DATABASE,
    }
}
