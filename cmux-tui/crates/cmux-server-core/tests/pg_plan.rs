//! Postgres plan goldens, injection refusal, schema vs database mode.

use cmux_server_core::pg::{
    AppDb, AppId, AppIdError, AppLimits, ClusterSpec, DbMode, PgError, PgPlan,
    password_from_random, pgpass_line, quote_ident, quote_literal, scram_verifier,
};
use cmux_server_core::{HostPath, InstallMode, Platform};
use proptest::prelude::*;

fn p(platform: Platform, s: &str) -> HostPath {
    HostPath::new(platform, s).unwrap()
}

fn linux_spec(mode: InstallMode) -> ClusterSpec {
    let (state, user) = match mode {
        InstallMode::User => ("/home/ana/.local/state/cmux/server", "ana"),
        InstallMode::System => ("/var/lib/cmux", "cmux"),
    };
    let socket = match mode {
        InstallMode::User => format!("{state}/postgres/run"),
        InstallMode::System => "/run/cmux/postgres".to_owned(),
    };
    ClusterSpec {
        mode,
        platform: Platform::Linux,
        pg_bin_dir: p(Platform::Linux, "/opt/cmux/current/lib/postgresql-17/bin"),
        data_dir: p(Platform::Linux, &format!("{state}/postgres/17/data")),
        socket_dir: p(Platform::Linux, &socket),
        port: 17274,
        cmux_bin: p(Platform::Linux, "/opt/cmux/current/bin/cmux"),
        service_user: user.to_owned(),
        admin_pwfile: None,
    }
}

fn windows_spec() -> ClusterSpec {
    let w = |s: &str| p(Platform::Windows, s);
    ClusterSpec {
        mode: InstallMode::User,
        platform: Platform::Windows,
        pg_bin_dir: w(r"C:\Users\ana\AppData\Local\cmux\current\pg\bin"),
        data_dir: w(r"C:\Users\ana\AppData\Local\cmux\server\postgres\17\data"),
        socket_dir: w(r"C:\Users\ana\AppData\Local\cmux\server\postgres\run"),
        port: 17274,
        cmux_bin: w(r"C:\Users\ana\AppData\Local\cmux\current\bin\cmux.exe"),
        service_user: "ana".to_owned(),
        admin_pwfile: Some(w(r"C:\Users\ana\AppData\Local\cmux\server\postgres\admin.pw")),
    }
}

fn app(id: &str, mode: DbMode, tcp: bool) -> AppDb {
    AppDb { id: AppId::parse(id).unwrap(), mode, tcp }
}

#[test]
fn initdb_argv_unix_and_windows() {
    let plan = PgPlan::new(linux_spec(InstallMode::System)).unwrap();
    assert_eq!(
        plan.initdb_argv(),
        [
            "/opt/cmux/current/lib/postgresql-17/bin/initdb",
            "--pgdata=/var/lib/cmux/postgres/17/data",
            "--data-checksums",
            "--encoding=UTF8",
            "--locale=C",
            "--locale-provider=builtin",
            "--builtin-locale=C.UTF-8",
            "--auth-local=peer",
            "--auth-host=reject",
            "--username=cmux_admin",
        ]
    );
    let win = PgPlan::new(windows_spec()).unwrap();
    let argv = win.initdb_argv();
    assert_eq!(argv[0], r"C:\Users\ana\AppData\Local\cmux\current\pg\bin\initdb.exe");
    assert!(argv.contains(&"--auth-local=scram-sha-256".to_owned()));
    assert!(argv.contains(&"--auth-host=scram-sha-256".to_owned()));
    assert!(argv.contains(
        &r"--pwfile=C:\Users\ana\AppData\Local\cmux\server\postgres\admin.pw".to_owned()
    ));
}

