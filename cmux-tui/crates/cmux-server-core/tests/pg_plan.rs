#[test]
fn hba_user_mode_and_windows() {
    let plan = PgPlan::new(linux_spec(InstallMode::User)).unwrap();
    let apps = [app("notes", DbMode::Database, false)];
    let hba = plan.pg_hba_conf(&apps);
    assert!(hba.contains("\nlocal all cmux_admin peer map=cmuxadmin\nlocal sameuser app_notes scram-sha-256\nlocal all all reject\nhost all all all reject\n"));
    assert!(plan.pg_ident_conf(&apps).ends_with("cmuxadmin ana cmux_admin\n"));
    let win = PgPlan::new(windows_spec()).unwrap();
    let hba = win.pg_hba_conf(&apps);
    assert!(hba.contains("\nhost all cmux_admin 127.0.0.1/32 scram-sha-256\nhost sameuser app_notes 127.0.0.1/32 scram-sha-256\n"));
    assert!(!hba.contains("peer"));
    assert!(hba.ends_with("host all all all reject\n"));
}

#[test]
fn app_sql_database_mode_system() {
    let plan = PgPlan::new(linux_spec(InstallMode::System)).unwrap();
    let a = app("notes", DbMode::Database, false);
    assert!(!plan.app_needs_password(&a));
    let sql = plan.app_sql(&a, &AppLimits::default(), None).unwrap();
    let rendered: Vec<(&str, &str)> =
        sql.iter().map(|s| (s.database.as_str(), s.sql.as_str())).collect();
    assert_eq!(
        rendered,
        [
            (
                "postgres",
                "CREATE ROLE \"app_notes\" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT CONNECTION LIMIT 20"
            ),
            ("postgres", "ALTER ROLE \"app_notes\" SET statement_timeout = '30000ms'"),
            (
                "postgres",
                "ALTER ROLE \"app_notes\" SET idle_in_transaction_session_timeout = '60000ms'"
            ),
            ("postgres", "ALTER ROLE \"app_notes\" SET temp_file_limit = '1048576kB'"),
            (
                "postgres",
                "CREATE DATABASE \"app_notes\" OWNER \"app_notes\" TEMPLATE \"template0\""
            ),
            ("postgres", "REVOKE ALL ON DATABASE \"app_notes\" FROM PUBLIC"),
            ("app_notes", "REVOKE CREATE ON SCHEMA \"public\" FROM PUBLIC"),
        ]
    );
    // A verifier where none is needed is refused (no silent password).
    assert_eq!(
        plan.app_sql(&a, &AppLimits::default(), Some("SCRAM-SHA-256$1:a$b:c")),
        Err(PgError::BadVerifier)
    );
}

#[test]
fn app_sql_schema_mode_user_with_password() {
    let plan = PgPlan::new(linux_spec(InstallMode::User)).unwrap();
    let a = app("crm", DbMode::Schema, false);
    assert!(plan.app_needs_password(&a));
    assert_eq!(plan.app_sql(&a, &AppLimits::default(), None), Err(PgError::BadVerifier));
    let v = scram_verifier(&password_from_random(&[7; 32]), &[1; 16], 4096).unwrap();
    let sql = plan.app_sql(&a, &AppLimits::default(), Some(&v)).unwrap();
    assert!(sql[0].sql.ends_with(&format!("CONNECTION LIMIT 20 PASSWORD '{v}'")));
    let tail: Vec<(&str, &str)> =
        sql[4..].iter().map(|s| (s.database.as_str(), s.sql.as_str())).collect();
    assert_eq!(
        tail,
        [
            ("postgres", "GRANT CONNECT ON DATABASE \"cmux_apps\" TO \"app_crm\""),
            ("cmux_apps", "CREATE SCHEMA \"app_crm\" AUTHORIZATION \"app_crm\""),
            ("cmux_apps", "REVOKE ALL ON SCHEMA \"app_crm\" FROM PUBLIC"),
            (
                "postgres",
                "ALTER ROLE \"app_crm\" IN DATABASE \"cmux_apps\" SET search_path = \"app_crm\""
            ),
        ]
    );
    let shared: Vec<String> = plan.shared_database_sql().into_iter().map(|s| s.sql).collect();
    assert_eq!(
        shared[0],
        "CREATE DATABASE \"cmux_apps\" OWNER \"cmux_admin\" TEMPLATE \"template0\""
    );
    assert_eq!(plan.cluster_sql().len(), 2);
    assert_eq!(
        plan.read_only_sql(&a, true).sql,
        "ALTER ROLE \"app_crm\" SET default_transaction_read_only = on"
    );
}

#[test]
fn verifier_injection_is_refused() {
    let plan = PgPlan::new(linux_spec(InstallMode::User)).unwrap();
    let a = app("crm", DbMode::Database, false);
    for bad in
        ["x", "SCRAM-SHA-256$4096:a$b:c'; DROP ROLE cmux_admin; --", "SCRAM-SHA-256$", "md5abc"]
    {
        assert_eq!(
            plan.app_sql(&a, &AppLimits::default(), Some(bad)),
            Err(PgError::BadVerifier),
            "{bad}"
        );
    }
}

#[test]
fn scram_verifier_golden() {
    let password = password_from_random(&std::array::from_fn(|i| i as u8));
    assert_eq!(password, "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f");
    let salt: [u8; 16] = std::array::from_fn(|i| i as u8);
    assert_eq!(
        scram_verifier(&password, &salt, 4096).unwrap(),
        "SCRAM-SHA-256$4096:AAECAwQFBgcICQoLDA0ODw==$poBvrHTZHMXdX1FqZ+R0BrW8cHgi6K4DshN9FcJHVCo=:M4BrcI1FUEX0G77OsfQBkLR75In22riA17sfy+TLnIY="
    );
    assert_eq!(scram_verifier("tab\there", &salt, 4096), None);
    assert_eq!(scram_verifier("x", &salt, 0), None);
    assert_eq!(
        pgpass_line(&app("crm", DbMode::Schema, false), "a:b\\c"),
        "*:*:cmux_apps:app_crm:a\\:b\\\\c\n"
    );
}

#[test]
fn app_ids_refuse_injection() {
    let cases: [(&str, AppIdError); 9] = [
        ("", AppIdError::Empty),
        ("Notes", AppIdError::BadStart),
        ("1notes", AppIdError::BadStart),
        ("_notes", AppIdError::BadStart),
        ("notes\"; DROP ROLE cmux_admin; --", AppIdError::BadChar(5)),
        ("no tes", AppIdError::BadChar(2)),
        ("notes-app", AppIdError::BadChar(5)),
        ("nötes", AppIdError::BadChar(1)),
        ("a23456789012345678901234567890123456789012", AppIdError::TooLong(42)),
    ];
    for (input, err) in cases {
        assert_eq!(AppId::parse(input), Err(err), "{input:?}");
    }
    let max = "a2345678901234567890123456789012345678901";
    assert_eq!(AppId::parse(max).unwrap().role().len(), 45);
    assert_eq!(quote_ident("a\"b").unwrap(), "\"a\"\"b\"");
    assert_eq!(quote_ident("a\0b"), None);
    assert_eq!(quote_literal("it's").unwrap(), "'it''s'");
}

#[test]
fn unsafe_specs_are_refused() {
    let mut s = linux_spec(InstallMode::User);
    s.cmux_bin = p(Platform::Linux, "/opt/cmux/$(reboot)/cmux");
    assert_eq!(PgPlan::new(s), Err(PgError::UnsafePath("cmux_bin")));
    let mut s = linux_spec(InstallMode::User);
    s.socket_dir = p(Platform::Linux, "/tmp/it's");
    assert_eq!(PgPlan::new(s), Err(PgError::UnsafePath("socket_dir")));
    let mut s = linux_spec(InstallMode::User);
    s.socket_dir = p(Platform::Linux, &format!("/{}", "d".repeat(90)));
    assert_eq!(PgPlan::new(s), Err(PgError::SocketPathTooLong(106)));
    let mut s = linux_spec(InstallMode::User);
    s.port = 5432;
    assert_eq!(PgPlan::new(s), Err(PgError::BadPort(5432)));
    let mut s = linux_spec(InstallMode::User);
    s.service_user = "ana; rm".to_owned();
    assert_eq!(PgPlan::new(s), Err(PgError::BadServiceUser));
    let mut s = windows_spec();
    s.admin_pwfile = None;
    assert_eq!(PgPlan::new(s), Err(PgError::PwfileMismatch));
    let mut s = linux_spec(InstallMode::User);
    s.data_dir = p(Platform::Windows, r"C:\data");
    assert_eq!(PgPlan::new(s), Err(PgError::UnsafePath("data_dir")));
}

proptest! {
    /// Any string either fails validation or yields identifiers made only of
    /// `[a-z0-9_]`, so nothing it renders can leave its quotes.
    #[test]
    fn app_id_parse_is_closed(id in "\\PC{0,48}") {
        if let Ok(app) = AppId::parse(&id) {
            prop_assert!(app.role().bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_'));
            let plan = PgPlan::new(linux_spec(InstallMode::System)).unwrap();
            let db = AppDb { id: app, mode: DbMode::Database, tcp: false };
            for s in plan.app_sql(&db, &AppLimits::default(), None).unwrap() {
                prop_assert!(!s.sql.contains(';'));
            }
        }
    }
}
