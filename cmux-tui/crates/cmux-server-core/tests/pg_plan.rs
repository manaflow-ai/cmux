#[test]
fn postgresql_conf_system_mode_and_tcp() {
    let plan = PgPlan::new(linux_spec(InstallMode::System)).unwrap();
    let conf = plan.postgresql_conf(&[app("notes", DbMode::Database, true)]);
    assert!(conf.contains("listen_addresses = '127.0.0.1'\n"));
    assert!(conf.contains("unix_socket_directories = '\"/run/cmux/postgres\"'\n"));
    assert!(conf.contains("unix_socket_group = 'cmux-db'\nunix_socket_permissions = 0770\n"));
    let win = PgPlan::new(windows_spec()).unwrap().postgresql_conf(&[]);
    assert!(win.contains("listen_addresses = '127.0.0.1'\n"));
    assert!(win.contains("unix_socket_directories = ''\n"));
    // Backslashes are doubled inside postgresql.conf strings.
    assert!(win.contains(
        r#"archive_command = '"C:\\Users\\ana\\AppData\\Local\\cmux\\current\\bin\\cmux.exe" server db archive-wal "%p" "%f"'"#
    ));
}

