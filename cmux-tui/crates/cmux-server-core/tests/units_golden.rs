#[test]
fn scheduled_task_xml_golden_parts() {
    let l = win(InstallMode::User);
    let xml = scheduled_task_xml(&l, r"DESKTOP-1\ana").unwrap();
    assert!(xml.starts_with("<?xml version=\"1.0\" encoding=\"UTF-16\"?>\n<Task version=\"1.4\""));
    assert!(xml.contains("    <LogonTrigger>\n      <Enabled>true</Enabled>\n      <UserId>DESKTOP-1\\ana</UserId>\n    </LogonTrigger>\n"));
    assert!(xml.contains("      <RunLevel>LeastPrivilege</RunLevel>\n"));
    assert!(xml.contains("    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>\n    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>\n"));
    assert!(xml.contains("    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>\n"));
    assert!(xml.contains(
        "      <Command>C:\\Users\\ana\\AppData\\Local\\cmux\\current\\bin\\cmux.exe</Command>\n      <Arguments>host run --mode user</Arguments>\n"
    ));
    assert_eq!(scheduled_task_xml(&l, "ana<x>"), Err(UnitError::BadUser));
    assert_eq!(scheduled_task_xml(&l, r"\ana"), Err(UnitError::BadUser));
    assert_eq!(scheduled_task_xml(&win(InstallMode::System), "ana"), Err(UnitError::WrongLayout));
}
