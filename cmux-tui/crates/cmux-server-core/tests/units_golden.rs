#[test]
fn launch_daemon_and_app_variants() {
    let l = unix(InstallMode::User, Platform::MacOs, "/Users/a&b");
    let daemon = launch_daemon_plist(&l, "ana").unwrap();
    assert!(daemon.contains("  <key>UserName</key>\n  <string>ana</string>\n"));
    assert!(daemon.contains("<string>/Users/a&amp;b/Library/Application Support/cmux/current/bin/cmux</string>"));
    assert_eq!(launch_daemon_plist(&l, "ana</string>"), Err(UnitError::BadUser));

    let mut env = LayoutEnv { home: Some("/Users/ana".to_owned()), ..LayoutEnv::default() };
    env.mac_app_bundle = Some("/Applications/cmux.app".to_owned());
    let app = layout(InstallMode::User, Platform::MacOs, &env).unwrap();
    let plist = launch_agent_plist(&app).unwrap();
    assert!(plist.contains("<key>BundleProgram</key>\n  <string>Contents/Resources/bin/cmux</string>"));
    assert!(plist.contains("<string>/Applications/cmux.app/Contents/Resources/bin/cmux</string>"));

    let system = unix(InstallMode::System, Platform::MacOs, "/var/root");
    assert_eq!(launch_agent_plist(&system), Err(UnitError::WrongLayout));
    assert!(launch_daemon_plist(&system, "_cmux").unwrap().contains("<string>/Library/Application Support/cmux/current/bin/cmux</string>"));
}

#[test]
fn windows_service_argv_golden() {
    let l = win(InstallMode::System);
    assert_eq!(
        windows_service_create_argv(&l).unwrap(),
        [
            "sc.exe",
            "create",
            "cmux-server",
            "binPath=",
            r#""C:\ProgramData\cmux\current\bin\cmux.exe" host run"#,
            "start=",
            "auto",
            "obj=",
            r"NT SERVICE\cmux-server",
            "DisplayName=",
            "cmux server",
        ]
    );
    assert_eq!(
        windows_service_failure_argv(),
        ["sc.exe", "failure", "cmux-server", "reset=", "86400", "actions=", "restart/2000/restart/2000/restart/60000"]
    );
    assert_eq!(windows_service_create_argv(&win(InstallMode::User)), Err(UnitError::WrongLayout));
}

#[test]
fn scheduled_task_xml_golden_parts() {
    let l = win(InstallMode::User);
    let xml = scheduled_task_xml(&l, r"DESKTOP-1\ana").unwrap();
    assert!(xml.starts_with("<?xml version=\"1.0\" encoding=\"UTF-16\"?>\n<Task version=\"1.4\""));
    assert!(xml.contains("    <LogonTrigger>\n      <Enabled>true</Enabled>\n      <UserId>DESKTOP-1\\ana</UserId>\n    </LogonTrigger>\n"));
    assert!(xml.contains("      <RunLevel>LeastPrivilege</RunLevel>\n"));
    assert!(xml.contains("    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>\n    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>\n"));
    assert!(xml.contains("    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>\n"));
    assert!(xml.contains(
        "      <Command>C:\\Users\\ana\\AppData\\Local\\cmux\\current\\bin\\cmux.exe</Command>\n      <Arguments>host run</Arguments>\n"
    ));
    assert_eq!(scheduled_task_xml(&l, "ana<x>"), Err(UnitError::BadUser));
    assert_eq!(scheduled_task_xml(&l, r"\ana"), Err(UnitError::BadUser));
    assert_eq!(scheduled_task_xml(&win(InstallMode::System), "ana"), Err(UnitError::WrongLayout));
}
