//! Service definition goldens: every variant runs `<current>/bin/cmux host run`.

use cmux_server_core::layout::{Layout, LayoutEnv, layout};
use cmux_server_core::units::{
    UnitError, app_service_agent_plist, host_run_argv, host_run_argv_with_mode, launch_agent_plist,
    launch_daemon_plist, scheduled_task_xml, systemd_app_server_template, systemd_system_unit,
    systemd_update_path_unit, systemd_update_service_unit, systemd_user_unit,
    windows_service_create_argv, windows_service_failure_argv,
};
use cmux_server_core::{InstallMode, Platform};

fn unix(mode: InstallMode, platform: Platform, home: &str) -> Layout {
    let env = LayoutEnv { home: Some(home.to_owned()), uid: Some(501), ..LayoutEnv::default() };
    layout(mode, platform, &env).unwrap()
}

fn win(mode: InstallMode) -> Layout {
    let env = LayoutEnv {
        local_app_data: Some(r"C:\Users\ana\AppData\Local".to_owned()),
        app_data: Some(r"C:\Users\ana\AppData\Roaming".to_owned()),
        program_data: Some(r"C:\ProgramData".to_owned()),
        program_files: Some(r"C:\Program Files".to_owned()),
        ..LayoutEnv::default()
    };
    layout(mode, Platform::Windows, &env).unwrap()
}

