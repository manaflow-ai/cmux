//! Service definition goldens: every variant runs `<current>/bin/cmux host run`.

use cmux_server_core::layout::{Layout, LayoutEnv, layout};
use cmux_server_core::units::{
    UnitError, host_run_argv, launch_agent_plist, launch_daemon_plist, scheduled_task_xml,
    systemd_system_unit, systemd_user_unit, windows_service_create_argv,
    windows_service_failure_argv,
};
use cmux_server_core::{InstallMode, Platform};

fn unix(mode: InstallMode, platform: Platform, home: &str) -> Layout {
    layout(mode, platform, &LayoutEnv { home: Some(home.to_owned()), ..LayoutEnv::default() }).unwrap()
}

fn win(mode: InstallMode) -> Layout {
    let env = LayoutEnv {
        local_app_data: Some(r"C:\Users\ana\AppData\Local".to_owned()),
        app_data: Some(r"C:\Users\ana\AppData\Roaming".to_owned()),
        program_data: Some(r"C:\ProgramData".to_owned()),
        program_files: Some(r"C:\Program Files".to_owned()),
        ..LayoutEnv::default()
    };
    layout(mode, Platform::Windows, &env).unwrap()
}

#[test]
fn systemd_user_unit_golden() {
    let l = unix(InstallMode::User, Platform::Linux, "/home/ana");
    assert_eq!(host_run_argv(&l), ["/home/ana/.local/share/cmux/current/bin/cmux", "host", "run"]);
    assert_eq!(
        systemd_user_unit(&l).unwrap(),
        "# Generated by cmux. Do not edit: `cmux server install` rewrites this file.
[Unit]
Description=cmux server
Documentation=https://cmux.com/docs/server
Wants=network-online.target
After=network-online.target

[Service]
Type=exec
ExecStart=\"/home/ana/.local/share/cmux/current/bin/cmux\" host run
Environment=CMUX_SERVER_MODE=user
Restart=always
RestartSec=2
# The session host keeps its terminal hosts across a restart: stop only the
# supervisor process (lane 1 handoff contract).
KillMode=process
TimeoutStopSec=30
NoNewPrivileges=yes

[Install]
WantedBy=default.target
"
    );
}

