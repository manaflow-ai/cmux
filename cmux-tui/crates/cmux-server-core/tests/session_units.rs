//! The session service: `cmux server install` keeps one session daemon
//! running when there is no published server channel (or with `--binary`).

use cmux_server_core::layout::{Layout, LayoutEnv, layout};
use cmux_server_core::units::{
    DEFAULT_SESSION, SessionUnit, UnitError, parse_session_unit, session_argv,
    session_launch_agent_plist, systemd_session_unit, systemd_user_unit, valid_session_name,
};
use cmux_server_core::{InstallMode, Platform};

fn unix(mode: InstallMode, platform: Platform, home: &str) -> Layout {
    let env = LayoutEnv { home: Some(home.to_owned()), uid: Some(501), ..LayoutEnv::default() };
    layout(mode, platform, &env).unwrap()
}

const BIN: &str = "/home/ana/.local/bin/cmux-tui";

#[test]
fn systemd_session_unit_golden() {
    let l = unix(InstallMode::User, Platform::Linux, "/home/ana");
    assert_eq!(
        systemd_session_unit(&l, BIN, DEFAULT_SESSION).unwrap(),
        "# Generated by cmux. Do not edit: `cmux server install` rewrites this file.
[Unit]
Description=cmux server (session main)
Documentation=https://cmux.com/docs/server
StartLimitIntervalSec=0

[Service]
Type=simple
ExecStart=\"/home/ana/.local/bin/cmux-tui\" daemon start --session main --terminal-reap-grace-seconds 30
Restart=always
RestartSec=3
RestartSteps=5
RestartMaxDelaySec=60
# A restart stops only the session daemon: terminals keep running in their
# terminal hosts and the next daemon takes them back.
KillMode=process
TimeoutStopSec=30

[Install]
WantedBy=default.target
"
    );
}

#[test]
fn session_launch_agent_golden() {
    let l = unix(InstallMode::User, Platform::MacOs, "/Users/ana");
    let plist = session_launch_agent_plist(&l, "/Users/ana/.local/bin/cmux-tui", "main").unwrap();
    assert!(plist.contains("\t<key>Label</key>\n\t<string>com.cmux.server</string>\n"), "{plist}");
    assert!(
        plist.contains(
            "\t<key>ProgramArguments</key>\n\t<array>\n\t\t<string>/Users/ana/.local/bin/cmux-tui</string>\n\t\t<string>daemon</string>\n\t\t<string>start</string>\n\t\t<string>--session</string>\n\t\t<string>main</string>\n\t\t<string>--terminal-reap-grace-seconds</string>\n\t\t<string>30</string>\n\t</array>\n"
        ),
        "{plist}"
    );
    assert!(plist.contains("\t<key>KeepAlive</key>\n\t<true/>\n"), "{plist}");
    assert!(plist.contains("\t<key>RunAtLoad</key>\n\t<true/>\n"), "{plist}");
}

#[test]
fn session_units_refuse_other_layouts_and_unsafe_values() {
    let linux_system = unix(InstallMode::System, Platform::Linux, "/home/ana");
    let mac = unix(InstallMode::User, Platform::MacOs, "/Users/ana");
    let linux = unix(InstallMode::User, Platform::Linux, "/home/ana");
    assert_eq!(systemd_session_unit(&linux_system, BIN, "main"), Err(UnitError::WrongLayout));
    assert_eq!(systemd_session_unit(&mac, BIN, "main"), Err(UnitError::WrongLayout));
    assert_eq!(session_launch_agent_plist(&linux, BIN, "main"), Err(UnitError::WrongLayout));
    for bad in ["", "-x", ".hidden", "a b", "a;b", "a/b", "x\n", &"s".repeat(65)] {
        assert_eq!(systemd_session_unit(&linux, BIN, bad), Err(UnitError::BadSession), "{bad:?}");
        assert_eq!(session_launch_agent_plist(&mac, BIN, bad), Err(UnitError::BadSession));
    }
    for bad in ["relative/cmux", "/a b\"c", "/x$HOME", "/x%h", "/x;y", "/x\ny"] {
        assert!(systemd_session_unit(&linux, bad, "main").is_err(), "{bad:?}");
    }
    assert!(valid_session_name("main") && valid_session_name("build-2.dev_x"));
}

#[test]
fn session_units_parse_back_and_store_units_do_not() {
    let linux = unix(InstallMode::User, Platform::Linux, "/home/ana");
    let mac = unix(InstallMode::User, Platform::MacOs, "/Users/ana");
    let want = SessionUnit { binary: BIN.to_owned(), session: "agents".to_owned() };
    assert_eq!(
        parse_session_unit(&systemd_session_unit(&linux, BIN, "agents").unwrap()),
        Some(want)
    );
    let mac_bin = "/Users/ana/.local/bin/cmux-tui";
    assert_eq!(
        parse_session_unit(&session_launch_agent_plist(&mac, mac_bin, "main").unwrap()),
        Some(SessionUnit { binary: mac_bin.to_owned(), session: "main".to_owned() })
    );
    assert_eq!(parse_session_unit(&systemd_user_unit(&linux).unwrap()), None);
    assert_eq!(parse_session_unit("not a unit"), None);
    assert_eq!(
        session_argv(BIN, "main"),
        [BIN, "daemon", "start", "--session", "main", "--terminal-reap-grace-seconds", "30"]
    );
}

/// A direct `daemon start` owner does not reap: without the grace, a
/// terminal whose last tab closed (a closed workspace) would run until the
/// service stops, holding its PTY and keeping `daemon stop --if-idle` from
/// ever stopping. The service's daemon reaps as every owner `daemon ensure`
/// starts does (30 s).
#[test]
fn the_session_daemon_reaps_closed_terminals() {
    let linux = unix(InstallMode::User, Platform::Linux, "/home/ana");
    let unit = systemd_session_unit(&linux, BIN, "main").unwrap();
    assert!(unit.contains(" --terminal-reap-grace-seconds 30\n"), "{unit}");
    let mac = unix(InstallMode::User, Platform::MacOs, "/Users/ana");
    let plist = session_launch_agent_plist(&mac, "/Users/ana/.local/bin/cmux-tui", "main").unwrap();
    assert!(plist.contains("<string>--terminal-reap-grace-seconds</string>"), "{plist}");
}

/// A unit or plist an earlier install wrote (no reap grace) still reads back
/// as the session service, so uninstall and status still know it.
#[test]
fn session_units_without_the_reap_grace_still_parse() {
    let old_unit =
        "[Service]\nExecStart=\"/home/ana/.local/bin/cmux-tui\" daemon start --session main\n";
    assert_eq!(
        parse_session_unit(old_unit),
        Some(SessionUnit { binary: BIN.to_owned(), session: "main".to_owned() })
    );
    let old_plist = "<array>\n\t\t<string>/Users/ana/.local/bin/cmux-tui</string>\n\t\t<string>daemon</string>\n\t\t<string>start</string>\n\t\t<string>--session</string>\n\t\t<string>main</string>\n\t</array>\n";
    assert_eq!(
        parse_session_unit(old_plist),
        Some(SessionUnit {
            binary: "/Users/ana/.local/bin/cmux-tui".to_owned(),
            session: "main".to_owned()
        })
    );
    // Anything else after the session is not a unit cmux wrote.
    let other =
        "ExecStart=\"/home/ana/.local/bin/cmux-tui\" daemon start --session main --other 1\n";
    assert_eq!(parse_session_unit(other), None);
}
