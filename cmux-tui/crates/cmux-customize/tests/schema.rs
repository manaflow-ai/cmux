//! `cmux customize schema`: every customizable thing, read from the tables
//! their owners validate with, so an agent never guesses a key.

use cmux_customize::schema::{Schema, Section, key_constants, rust, typescript};
use serde_json::json;

#[test]
fn every_setting_key_is_listed_with_its_type_range_and_default() {
    let schema = Schema::current();
    let settings = cmux_config::Schema::embedded();
    assert_eq!(schema.settings.len(), settings.rows.len());
    for row in &settings.rows {
        let listed = schema.setting(&row.key).unwrap_or_else(|| panic!("{} missing", row.key));
        assert_eq!(listed.kind, row.kind.name(), "{}", row.key);
        assert_eq!(listed.default, row.default, "{}", row.key);
        assert_eq!(listed.agent_settable, row.agent_settable, "{}", row.key);
        assert!(listed.schema.is_object(), "{} has no value schema", row.key);
    }
    let toggle = schema.setting("history.terminalCommands").expect("a toggle");
    assert_eq!(toggle.schema, json!({"type": "boolean"}));
    assert!(!toggle.agent_settable);
    let number = schema.settings.iter().find(|s| s.kind == "number").expect("a number");
    let range = number.range.as_ref().expect("a number has a range");
    assert!(range.min <= range.max);
    let choice = schema
        .settings
        .iter()
        .find(|s| s.kind == "choice" && s.schema.get("enum").is_some())
        .expect("a choice");
    assert!(!choice.choices.is_empty());
    assert_eq!(choice.schema["enum"], json!(choice.choices));
}

#[test]
fn theme_files_tokens_view_slots_and_extension_points_come_from_their_tables() {
    let schema = Schema::current();
    assert_eq!(schema.theme.file_setting, "appearance.themeFile");
    assert!(schema.theme.file_keys.iter().any(|key| key == "colors"));
    assert!(schema.theme.colors.iter().any(|color| color == "background"));
    assert!(schema.settings.iter().any(|s| s.key == "appearance.accent" && s.theme_file));
    assert!(
        schema.theme.tokens.iter().any(|t| t.name == "windowBackground" && !t.formula.is_empty())
    );

    let interfaces: Vec<&str> =
        schema.extension_points.iter().map(|point| point.interface.as_str()).collect();
    assert_eq!(interfaces, cmux_app_manifest::KNOWN_INTERFACES);
    let section = schema.views.iter().find(|slot| slot.interface == "cmux.section/1").unwrap();
    assert_eq!(section.place_option.as_deref(), Some("defaultRegion"));
    assert_eq!(section.places, ["top", "middle", "bottom"]);
    let status = schema.views.iter().find(|slot| slot.interface == "cmux.status/1").unwrap();
    assert!(status.places.iter().any(|place| place == "titlebar"));
    assert!(!schema.views.iter().any(|slot| slot.interface == "cmux.opener/1"));
    for slot in &schema.views {
        let point = schema.extension_points.iter().find(|p| p.interface == slot.interface);
        assert!(
            point.is_some_and(|point| point.view),
            "{} is a slot but not a view",
            slot.interface
        );
    }
}

#[test]
fn one_part_answers_alone() {
    let schema = Schema::current();
    let views = schema.to_json(Section::parse("views"));
    assert!(views.get("views").is_some_and(|v| v.is_array()));
    assert!(views.get("settings").is_none());
    assert_eq!(Section::parse("extensions"), Some(Section::ExtensionPoints));
    assert_eq!(Section::parse("nope"), None);
    let all = schema.to_json(None);
    for part in ["settings", "theme", "views", "extension_points"] {
        assert!(all.get(part).is_some(), "{part}");
    }
}

#[test]
fn the_typescript_types_name_every_key_and_slot() {
    let schema = Schema::current();
    let ts = typescript(&schema);
    assert!(ts.starts_with("// GENERATED by cmux_customize::schema"));
    for setting in &schema.settings {
        assert!(ts.contains(&format!("  {:?}: ", setting.key)), "{} not typed", setting.key);
    }
    assert!(ts.contains("  \"history.terminalCommands\": boolean\n"));
    assert!(ts.contains("\"cmux.section/1\": \"top\" | \"middle\" | \"bottom\""));
    assert!(ts.contains("export type SettingKey = keyof CmuxSettings"));
    assert!(ts.contains("export type ThemeToken = keyof CmuxThemeTokens"));
    assert_eq!(ts.matches('{').count(), ts.matches('}').count(), "unbalanced braces");
    assert!(!ts.contains("export const"), "types only: an import type adds nothing to a bundle");
}

#[test]
fn the_rust_tables_give_every_key_one_constant() {
    let schema = Schema::current();
    let constants = key_constants(&schema.settings);
    assert_eq!(constants.len(), schema.settings.len());
    let mut names: Vec<&str> = constants.iter().map(|(name, _)| name.as_str()).collect();
    names.sort_unstable();
    names.dedup();
    assert_eq!(names.len(), constants.len(), "two keys share a constant");
    assert!(
        constants.iter().any(|(n, k)| n == "APPEARANCE_THEME_FILE" && *k == "appearance.themeFile")
    );
    let source = rust(&schema);
    assert!(source.contains("pub const APPEARANCE_THEME_FILE: &str = \"appearance.themeFile\";"));
    assert!(
        source.contains(&format!("pub const SETTINGS_HASH: &str = {:?};", schema.settings_hash))
    );
}

#[test]
fn the_generated_types_change_only_with_their_tables() {
    let (a, b) = (Schema::current(), Schema::current());
    assert_eq!(typescript(&a), typescript(&b));
    assert_eq!(rust(&a), rust(&b));
}
