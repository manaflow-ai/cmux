#!/usr/bin/env python3
"""Generate the Swift wire types of the app's in-process FFI ops from the Rust rule crates, or check that they generate.

    python3 cmux-tui/bindings/codegen/swift_ffi/generate.py --out DIR [--bindings window_rules.json]
    python3 cmux-tui/bindings/codegen/swift_ffi/generate.py --check

Rust is the single source: the generator reads the serde types in the crate's source (rust_types.py) and renders
the ones a bindings file names (emit.py). Every `*.json` beside this file is one bindings file: the crate's
`rust_src`, the Swift target's `sources_root`, the `output` file name, and its `types`.

The files are build output, never committed (scripts/ci/generated_files_guard.py). A SwiftPM build tool plugin
(Packages/macOS/CmuxNext/Plugins/WindowRulesWireTypesPlugin) runs `--out <its work folder> --bindings FILE`
before every build of its target. `--out` refuses a folder SwiftPM would compile a second time.

--check  renders every bindings file (so a Rust change the emitter cannot express fails here, not in the build)
         and refuses a generated type that a hand-written file under sources_root still declares in the same
         namespace. Agents run it before a push; codegen/generate.py runs it with the SDKs.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
from pathlib import Path, PurePosixPath
from typing import Any

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from codegen.swift_ffi.emit import HEADER_MARK, BindingError, Emitter  # noqa: E402
from codegen.swift_ffi.rust_types import RustReadError, read_crate  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).resolve().parent
SUFFIX = ".generated.swift"
_DECLARATION = re.compile(
    r"^(\s*)(?:@\w+(?:\([^)]*\))?\s+)*(?:(?:public|package|internal|fileprivate|private|nonisolated|final|indirect)\s+)*"
    r"(?:struct|enum|class|actor|protocol|typealias)\s+(\w+)",
    re.M,
)
_EXTENSION = re.compile(r"^(\s*)(?:(?:public|nonisolated)\s+)*extension\s+([\w.]+)", re.M)


def bindings_files() -> list[Path]:
    return sorted(HERE.glob("*.json"))


def load_bindings(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise BindingError(f"cannot read {path}: {error}") from error
    for key in ("rust_src", "sources_root", "output", "types"):
        if key not in value:
            raise BindingError(f"{path}: needs {key!r}")
    if not str(value["output"]).endswith(SUFFIX) or "/" in str(value["output"]):
        raise BindingError(f"{path}: output must be a file name ending in {SUFFIX}")
    return value


def repo_path(repo_root: Path, raw: str) -> Path:
    relative = PurePosixPath(raw)
    if relative.is_absolute() or ".." in relative.parts:
        raise BindingError(f"{raw!r} must stay inside the repository")
    return repo_root.joinpath(*relative.parts)


def render(bindings: dict[str, Any], repo_root: Path) -> str:
    items = read_crate(repo_path(repo_root, bindings["rust_src"]))
    emitter = Emitter(items, bindings)
    return emitter.render(list(bindings["types"]))


def check_out_folder(out: Path, repo_root: Path) -> None:
    resolved = out.resolve()
    if resolved.is_relative_to(repo_root.resolve()) and "Sources" in resolved.relative_to(repo_root.resolve()).parts:
        raise BindingError(f"--out {out} is inside a package's Sources folder; SwiftPM would compile it twice")


def write(name: str, content: str, out: Path) -> None:
    target = out / name
    if target.exists():
        with target.open(encoding="utf-8") as handle:
            if handle.readline().rstrip("\n") != HEADER_MARK:
                raise BindingError(f"{target} exists and is not generated by this emitter; refusing to replace it")
        if target.read_text(encoding="utf-8") == content:
            return
    out.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")


def hand_written_declarations(root: Path) -> dict[str, str]:
    """{full Swift name: file} of the types hand-written Swift under ROOT declares, nested by braces and extensions."""
    found: dict[str, str] = {}
    for path in sorted(root.rglob("*.swift")):
        if path.name.endswith(SUFFIX):
            continue
        text = re.sub(r"//[^\n]*", "", path.read_text(encoding="utf-8"))
        events = [(m.start(), "decl", m.group(2)) for m in _DECLARATION.finditer(text)]
        events += [(m.start(), "ext", m.group(2)) for m in _EXTENSION.finditer(text)]
        events.sort()
        stack: list[tuple[int, str]] = []  # (brace depth it opened at, name)
        depth = 0
        cursor = 0
        for start, kind, name in events:
            for char in text[cursor:start]:
                if char == "{":
                    depth += 1
                elif char == "}":
                    depth -= 1
                    while stack and stack[-1][0] > depth:
                        stack.pop()
            cursor = start
            if depth != (stack[-1][0] if stack else 0):
                continue  # inside a function body
            full = ".".join([part for _, part in stack] + [name])
            if kind == "decl":
                found.setdefault(full, path.as_posix())
            if "typealias" not in text[start : text.find("\n", start + 1)]:
                stack.append((depth + 1, name))
    return found


def run(*, mode: str, repo_root: Path, files: list[Path], out: Path | None = None) -> list[str]:
    problems: list[str] = []
    for path in files:
        bindings = load_bindings(path)
        content = render(bindings, repo_root)
        if mode == "out":
            if out is None:
                raise ValueError("--out needs a folder")
            check_out_folder(out, repo_root)
            write(bindings["output"], content, out)
            continue
        with tempfile.TemporaryDirectory(prefix="cmux-swift-ffi-") as temporary:
            write(bindings["output"], content, Path(temporary))
        declared = hand_written_declarations(repo_path(repo_root, bindings["sources_root"]))
        for key, options in bindings["types"].items():
            if options["swift"] in declared:
                problems.append(f"{options['swift']} is generated from {key} and still declared by hand in {declared[options['swift']]}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--out", type=Path, metavar="DIR", help="write the generated Swift file under DIR")
    mode.add_argument("--check", action="store_true", help="check that every bindings file generates and is not hand-written")
    parser.add_argument("--bindings", type=Path, action="append", help="one bindings file (default: every *.json here)")
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT)
    arguments = parser.parse_args(argv)
    chosen = "check" if arguments.check else "out"
    try:
        problems = run(mode=chosen, repo_root=arguments.repo_root, files=arguments.bindings or bindings_files(),
                       out=arguments.out)
    except (BindingError, RustReadError, ValueError, OSError) as error:
        print(f"Swift FFI codegen failed: {error}", file=sys.stderr)
        return 1
    if problems:
        print("Swift FFI codegen check failed:\n" + "\n".join(f"- {problem}" for problem in problems), file=sys.stderr)
        return 1
    print(f"{'checked' if chosen == 'check' else 'wrote'} swift-ffi")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
