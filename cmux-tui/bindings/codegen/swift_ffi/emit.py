"""Render Swift Codable types from the serde wire types of a Rust rule crate (rust_types.py).

Rust owns the wire: field and variant names after serde's renames, which fields are optional, which may be
missing (`skip_serializing_if`), the enum tags and every doc comment. The bindings file (window_rules.json)
owns only what Rust cannot say about the Swift side: the Swift name and nesting, access, conformances, a
field's Swift type where the app reads it as another shape of the same JSON (a Rust enum the app keeps as a
`String`, `usize` the app keeps as `Int`), associated-value labels, and the Swift names of the crate's types
that stay hand-written.

The directions: a Rust `Serialize` type is one the app decodes, a Rust `Deserialize` type one it encodes.
Conformances default to that (`Decodable`, `Encodable`, `Codable`), `Equatable` for `PartialEq`, `Hashable` for
`Hash`, and `Sendable`. A shape the emitter cannot express (`flatten`, `untagged`, an externally tagged enum
with data, a tuple struct, a tuple variant other than one struct) raises BindingError, so a Rust change the
Swift could read differently fails `generate.py --check` and the build, never the wire.

Wire rules (the JSON the hand-written types sent and read):
- a property's name is the field's serde name; a Swift name the bindings give writes a CodingKeys case;
- an Optional is encoded only when set (Rust reads a missing Option as None);
- a field Rust may leave out (`skip_serializing_if`) decodes as its default when missing;
- a Rust field with a default (`#[serde(default)]` on it or on its type) gets that default in Swift too, as
  the property's initial value and the init's default argument, when it is a plain value (false, 0, "", [],
  [:], nil); a `default = "path"` field is a required argument;
- a unit-only enum is a `String` enum of its wire names; with `#[serde(other)]` an unknown name decodes as that
  case;
- an internally tagged enum (`tag = "kind"`) reads and writes its tag beside the variant's fields; a newtype
  variant's struct sits flat beside the tag; an unknown tag fails to decode, as the hand-written types did.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any

from .rust_types import Field, Item, Variant

HEADER_MARK = "// GENERATED by cmux-tui/bindings/codegen/swift_ffi/generate.py"

SWIFT_KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init", "inout",
    "internal", "let", "open", "operator", "private", "protocol", "public", "rethrows", "static", "struct",
    "subscript", "typealias", "var", "break", "case", "continue", "default", "defer", "do", "else",
    "fallthrough", "for", "guard", "if", "in", "repeat", "return", "switch", "where", "while", "as", "catch",
    "false", "is", "nil", "self", "Self", "super", "throw", "throws", "true", "try", "Type", "Any",
}

_SCALARS = {
    "bool": "Bool", "String": "String", "str": "String", "&str": "String", "&'static str": "String",
    "f64": "Double", "f32": "Double", "u64": "UInt64", "i64": "Int", "i32": "Int", "u32": "Int", "u16": "Int",
    "u8": "Int", "usize": "Int", "isize": "Int", "i8": "Int", "i16": "Int", "Uuid": "String", "PathBuf": "String",
}
_DEFAULTS = {"Bool": "false", "String": '""', "Double": "0", "Int": "0", "UInt64": "0", "Int32": "0", "UInt8": "0"}


class BindingError(ValueError):
    pass


def camel(name: str) -> str:
    """`new_tab_page` and `NewTabPage` as `newTabPage`."""
    if "_" in name:
        head, *rest = [part for part in name.split("_") if part]
        return head[:1].lower() + head[1:] + "".join(part[:1].upper() + part[1:] for part in rest)
    return name[:1].lower() + name[1:]


def rename(name: str, rule: str | bool | None, *, variant: bool) -> str:
    """serde's rename_all for a field (`snake_case` in Rust) or a variant (`PascalCase` in Rust)."""
    if not rule or rule is True:
        return name
    words = (
        [word.lower() for word in re.findall(r"[A-Z][a-z0-9]*|[0-9]+", name)] if variant
        else [word for word in name.split("_") if word]
    )
    if rule == "camelCase":
        return words[0] + "".join(word[:1].upper() + word[1:] for word in words[1:]) if words else name
    if rule == "snake_case":
        return "_".join(words)
    if rule == "kebab-case":
        return "-".join(words)
    if rule == "lowercase":
        return "".join(words)
    if rule == "SCREAMING_SNAKE_CASE":
        return "_".join(words).upper()
    if rule == "PascalCase":
        return "".join(word[:1].upper() + word[1:] for word in words)
    raise BindingError(f"rename_all {rule!r} is not supported")


def ident(name: str) -> str:
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def split_generic(text: str) -> tuple[str, list[str]]:
    """`Option<Vec<String>>` as (`Option`, [`Vec<String>`])."""
    if "<" not in text:
        return text, []
    head, _, rest = text.partition("<")
    inner = rest[: rest.rindex(">")]
    args: list[str] = []
    depth = 0
    current = ""
    for char in inner:
        if char == "<":
            depth += 1
        elif char == ">":
            depth -= 1
        if char == "," and depth == 0:
            args.append(current.strip())
            current = ""
        else:
            current += char
    if current.strip():
        args.append(current.strip())
    return head.strip().split("::")[-1], args


@dataclass(slots=True)
class Prop:
    """One stored property: a struct's field or an enum variant's associated value."""

    swift: str
    wire: str
    type: str  # the Swift type, `T?` for an Optional
    optional: bool
    default: str | None  # the Swift default expression; None: required
    may_be_missing: bool  # Rust may leave it out when it writes (skip_serializing_if)
    docs: list[str]
    label: str | None = None  # an associated value's label; "_" unlabeled


class Emitter:
    """Renders the types `types` names (bindings key `module::Name` to its options) from the crate's `items`."""

    def __init__(self, items: dict[str, Item], bindings: dict[str, Any]):
        self.items = items
        self.bindings = bindings
        self.namespace: str = bindings["namespace"]
        self.types: dict[str, dict[str, Any]] = bindings.get("types", {})
        self.names: dict[str, str] = dict(bindings.get("names", {}))
        for key, options in self.types.items():
            if key not in items:
                raise BindingError(f"{key}: no such struct or enum in the crate")
            self.names[items[key].name] = options.get("swift", items[key].name)

    # Types

    def swift_type(self, rust: str, context: str) -> str:
        rust = rust.strip()
        if rust.startswith("&") and rust not in _SCALARS:
            rust = rust.lstrip("&").strip()
            rust = re.sub(r"^'\w+\s+", "", rust)
        if rust in _SCALARS:
            return _SCALARS[rust]
        if rust.startswith("[") and rust.endswith("]"):
            return f"[{self.swift_type(rust[1:-1].split(';')[0], context)}]"
        head, args = split_generic(rust)
        if head == "Option" and len(args) == 1:
            inner = self.swift_type(args[0], context)
            return inner if inner.endswith("?") else f"{inner}?"
        if head in {"Vec", "VecDeque", "BTreeSet", "HashSet"} and len(args) == 1:
            return f"[{self.swift_type(args[0], context)}]"
        if head in {"BTreeMap", "HashMap", "IndexMap"} and len(args) == 2:
            return f"[{self.swift_type(args[0], context)}: {self.swift_type(args[1], context)}]"
        if head in {"Box", "Arc", "Rc", "Cow"} and args:
            return self.swift_type(args[-1], context)
        if args or not re.fullmatch(r"[A-Z]\w*", head):
            raise BindingError(f"{context}: the Rust type {rust!r} has no Swift type (bind it in `fields`)")
        if head not in self.names:
            raise BindingError(f"{context}: {head} is neither generated nor named in `names`")
        return self.names[head]

    def default_for(self, swift: str, rust: str) -> str | None:
        if swift.endswith("?"):
            return "nil"
        if swift.startswith("[") and ":" in swift:
            return "[:]"
        if swift.startswith("["):
            return "[]"
        if swift in _DEFAULTS:
            return _DEFAULTS[swift]
        return None

    def prop(self, owner: str, field: Field, rename_rule: str | bool | None, container_default: bool,
             options: dict[str, Any]) -> Prop:
        serde = field.attrs.serde
        if "flatten" in serde:
            raise BindingError(f"{owner}.{field.name}: #[serde(flatten)] is not supported")
        if serde.get("skip") is True or serde.get("skip_serializing") is True and serde.get("skip_deserializing") is True:
            raise BindingError(f"{owner}.{field.name}: a skipped field is not on the wire; omit it in Rust's wire type")
        wire = serde["rename"] if isinstance(serde.get("rename"), str) else rename(field.name, rename_rule, variant=False)
        bound = options.get("fields", {}).get(field.name, {})
        swift_name = bound.get("swift", camel(field.name) if wire != camel(field.name) else wire)
        swift = bound.get("type") or self.swift_type(field.type, f"{owner}.{field.name}")
        optional = swift.endswith("?")
        rust_default = container_default or serde.get("default") is True
        if isinstance(serde.get("default"), str):
            rust_default = False
        default = bound.get("default")
        if default is None and (rust_default or optional):
            default = self.default_for(swift, field.type)
        may_be_missing = "skip_serializing_if" in serde
        if may_be_missing and default is None:
            raise BindingError(f"{owner}.{field.name}: Rust may leave it out, so the binding needs a `default`")
        return Prop(swift_name, wire, swift, optional, default, may_be_missing, field.attrs.docs)

    # Rendering

    def render(self, keys: list[str]) -> str:
        groups: dict[str, list[str]] = {}
        for key in keys:
            options = self.types[key]
            swift = options.get("swift", self.items[key].name)
            parent = ".".join([self.namespace, *swift.split(".")[:-1]])
            groups.setdefault(parent, []).append(self.render_type(key))
        lines = [HEADER_MARK + ". Do not edit: the types are Rust's (window_rules.json says which)."]
        lines += [f"{line}" for line in self.bindings.get("imports", [])]
        for parent, bodies in groups.items():
            lines.append("")
            lines.append(f"extension {parent} {{")
            lines.append("\n\n".join(bodies))
            lines.append("}")
        return "\n".join(lines) + "\n"

    def header(self, key: str, item: Item, options: dict[str, Any], conformances: list[str], kind: str) -> list[str]:
        name = options.get("swift", item.name).split(".")[-1]
        access = options.get("access", "public")
        modifiers = " ".join(part for part in (access if access != "internal" else "", "nonisolated") if part)
        docs = [f"    /// {line}".rstrip() for line in item.attrs.docs]
        return [*docs, f"    {modifiers} {kind} {name}: {', '.join(conformances)} {{"]

    def conformances(self, item: Item, options: dict[str, Any], raw: str | None = None) -> list[str]:
        if "conforms" in options:
            return list(options["conforms"])
        decodes, encodes = "Serialize" in item.attrs.derives, "Deserialize" in item.attrs.derives
        found = [raw] if raw else []
        found.append("Codable" if decodes and encodes else "Decodable" if decodes else "Encodable" if encodes else "")
        if "Hash" in item.attrs.derives:
            found.append("Hashable")
        elif "PartialEq" in item.attrs.derives:
            found.append("Equatable")
        found.append("Sendable")
        return [part for part in found if part]

    def render_type(self, key: str) -> str:
        item = self.items[key]
        options = self.types[key]
        for attribute in ("untagged", "from", "into", "try_from", "transparent", "remote"):
            if attribute in item.attrs.serde:
                raise BindingError(f"{key}: #[serde({attribute})] is not supported")
        if item.kind == "struct":
            return self.render_struct(key, item, options)
        if all(variant.kind == "unit" for variant in item.variants) and "tag" not in item.attrs.serde:
            return self.render_string_enum(key, item, options)
        if "tag" in item.attrs.serde and "content" not in item.attrs.serde:
            return self.render_tagged_enum(key, item, options)
        raise BindingError(f"{key}: only unit-only and internally tagged (`tag`) enums are supported")

    def coding(self, conformances: list[str]) -> tuple[bool, bool]:
        decodes = any(c in {"Decodable", "Codable"} for c in conformances)
        encodes = any(c in {"Encodable", "Codable"} for c in conformances)
        return decodes, encodes

    def render_struct(self, key: str, item: Item, options: dict[str, Any]) -> str:
        if item.tuple:
            raise BindingError(f"{key}: a tuple or unit struct is not supported")
        container_default = item.attrs.serde.get("default") is True
        props = [
            self.prop(key, field, item.attrs.serde.get("rename_all"), container_default, options)
            for field in item.fields
            if field.name not in options.get("omit", [])
        ]
        conformances = self.conformances(item, options)
        decodes, _ = self.coding(conformances)
        lines = self.header(key, item, options, conformances, "struct")
        access = options.get("access", "public")
        member = "public " if access == "public" else ""
        for prop in props:
            lines += [f"        /// {line}".rstrip() for line in prop.docs]
            initial = f" = {prop.default}" if prop.default is not None and prop.default != "nil" else ""
            lines.append(f"        {member}var {ident(prop.swift)}: {prop.type}{initial}")
        if options.get("init", True):
            parameters = ", ".join(
                f"{ident(p.swift)}: {p.type}" + (f" = {p.default}" if p.default is not None else "") for p in props
            )
            lines += ["", f"        {member}init({parameters}) {{"]
            lines += [f"            self.{ident(p.swift)} = {ident(p.swift)}" for p in props]
            lines.append("        }")
        renamed = any(p.swift != p.wire for p in props)
        lenient = decodes and any(p.may_be_missing and not p.optional for p in props)
        if renamed or lenient:
            cases = ", ".join(ident(p.swift) if p.swift == p.wire else f'{ident(p.swift)} = "{p.wire}"' for p in props)
            lines += ["", f"        private enum CodingKeys: String, CodingKey {{ case {cases} }}"]
        if lenient:
            lines += ["", f"        {member}init(from decoder: any Decoder) throws {{",
                      "            let container = try decoder.container(keyedBy: CodingKeys.self)"]
            for p in props:
                lines.append(f"            {ident(p.swift)} = {self.read(p)}")
            lines.append("        }")
        lines.append("    }")
        return "\n".join(lines)

    def read(self, p: Prop) -> str:
        bare = p.type[:-1] if p.optional else p.type
        key = f".{ident(p.swift)}"
        if p.optional:
            return f"try container.decodeIfPresent({bare}.self, forKey: {key})"
        if p.may_be_missing:
            return f"try container.decodeIfPresent({bare}.self, forKey: {key}) ?? {p.default}"
        return f"try container.decode({bare}.self, forKey: {key})"

    def variant_wire(self, item: Item, variant: Variant) -> str:
        if isinstance(variant.attrs.serde.get("rename"), str):
            return variant.attrs.serde["rename"]
        return rename(variant.name, item.attrs.serde.get("rename_all"), variant=True)

    def render_string_enum(self, key: str, item: Item, options: dict[str, Any]) -> str:
        conformances = self.conformances(item, options, raw="String")
        decodes, _ = self.coding(conformances)
        lines = self.header(key, item, options, conformances, "enum")
        other = None
        cases_bound = options.get("cases", {})
        for variant in item.variants:
            if variant.name in options.get("omit", []):
                continue
            swift = cases_bound.get(variant.name, {}).get("swift", camel(variant.name))
            wire = self.variant_wire(item, variant)
            if variant.attrs.serde.get("other") is True:
                other = swift
            lines += [f"        /// {line}".rstrip() for line in variant.attrs.docs]
            lines.append(f"        case {ident(swift)}" + (f' = "{wire}"' if wire != swift else ""))
        if other and decodes:
            member = "public " if options.get("access", "public") == "public" else ""
            lines += ["", f"        {member}init(from decoder: any Decoder) throws {{",
                      f"            self = Self(rawValue: try decoder.singleValueContainer().decode(String.self)) ?? .{ident(other)}",
                      "        }"]
        lines.append("    }")
        return "\n".join(lines)

    def render_tagged_enum(self, key: str, item: Item, options: dict[str, Any]) -> str:
        tag = item.attrs.serde["tag"]
        assert isinstance(tag, str)
        conformances = self.conformances(item, options)
        decodes, encodes = self.coding(conformances)
        lines = self.header(key, item, options, conformances, "enum")
        member = "public " if options.get("access", "public") == "public" else ""
        cases: list[tuple[str, str, list[Prop], str | None]] = []  # swift case, wire tag, props, newtype payload
        keys: dict[str, str] = {camel(tag): tag}
        for variant in item.variants:
            if variant.name in options.get("omit", []):
                continue
            bound = options.get("cases", {}).get(variant.name, {})
            swift = bound.get("swift", camel(variant.name))
            wire = self.variant_wire(item, variant)
            if variant.attrs.serde.get("other") is True:
                raise BindingError(f"{key}::{variant.name}: #[serde(other)] on a tagged enum is not supported")
            payload = None
            props: list[Prop] = []
            if variant.kind == "tuple":
                if len(variant.fields) != 1:
                    raise BindingError(f"{key}::{variant.name}: a tuple variant must hold one struct")
                payload = self.swift_type(variant.fields[0].type, f"{key}::{variant.name}")
            elif variant.kind == "struct":
                rule = variant.attrs.serde.get("rename_all") or item.attrs.serde.get("rename_all_fields")
                labels = bound.get("labels")
                for index, field in enumerate(variant.fields):
                    prop = self.prop(f"{key}::{variant.name}", field, rule, False, bound)
                    prop.label = labels[index] if labels else prop.swift
                    props.append(prop)
                    if prop.swift in keys and keys[prop.swift] != prop.wire:
                        raise BindingError(f"{key}: {prop.swift} reads two wire keys")
                    keys[prop.swift] = prop.wire
            lines += [f"        /// {line}".rstrip() for line in variant.attrs.docs]
            if payload:
                lines.append(f"        case {ident(swift)}({payload})")
            elif props:
                values = ", ".join(p.type if p.label == "_" else f"{p.label}: {p.type}" for p in props)
                lines.append(f"        case {ident(swift)}({values})")
            else:
                lines.append(f"        case {ident(swift)}")
            cases.append((swift, wire, props, payload))
        coding_cases = ", ".join(ident(s) if s == w else f'{ident(s)} = "{w}"' for s, w in keys.items())
        tag_key = f".{ident(camel(tag))}"
        lines += ["", f"        private enum CodingKeys: String, CodingKey {{ case {coding_cases} }}"]
        if decodes:
            lines += ["", f"        {member}init(from decoder: any Decoder) throws {{",
                      "            let container = try decoder.container(keyedBy: CodingKeys.self)",
                      f"            switch try container.decode(String.self, forKey: {tag_key}) {{"]
            for swift, wire, props, payload in cases:
                if payload:
                    value = f"(try {payload}(from: decoder))"
                elif props:
                    value = "(" + ", ".join(
                        (self.read(p) if p.label == "_" else f"{p.label}: {self.read(p)}") for p in props
                    ) + ")"
                else:
                    value = ""
                lines.append(f'            case "{wire}": self = .{ident(swift)}{value}')
            lines += [f'            case let other: throw DecodingError.dataCorruptedError(forKey: {tag_key}, in: container, debugDescription: "{tag} \\(other)")',
                      "            }", "        }"]
        if encodes:
            lines += ["", f"        {member}func encode(to encoder: any Encoder) throws {{",
                      "            var container = encoder.container(keyedBy: CodingKeys.self)",
                      "            switch self {"]
            for swift, wire, props, payload in cases:
                if payload:
                    lines += [f"            case let .{ident(swift)}(value):",
                              "                try value.encode(to: encoder)",
                              f'                try container.encode("{wire}", forKey: {tag_key})']
                    continue
                names = [f"value{index}" for index in range(len(props))]
                binding = f"(let {', let '.join(names)})" if props else ""
                lines += [f"            case .{ident(swift)}{binding}:",
                          f'                try container.encode("{wire}", forKey: {tag_key})']
                for name, prop in zip(names, props):
                    verb = "encodeIfPresent" if prop.optional else "encode"
                    lines.append(f"                try container.{verb}({name}, forKey: .{ident(prop.swift)})")
            lines += ["            }", "        }"]
        lines.append("    }")
        return "\n".join(lines)
