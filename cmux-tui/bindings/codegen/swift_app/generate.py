#!/usr/bin/env python3
"""Generate or check the CmuxNextDaemon request types listed in swift_app/bindings.json.

    python3 cmux-tui/bindings/codegen/swift_app/generate.py --write
    python3 cmux-tui/bindings/codegen/swift_app/generate.py --check

codegen/generate.py runs this after the SDKs (with no --language), so its --check and --write cover it.
A file is owned when its first line is the generator's header (emit.HEADER_MARK): --check reports owned
files that differ, are missing or are no longer generated; --write updates them and deletes the stale
ones. Other `*.generated.swift` files belong to other generators and are left alone.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path, PurePosixPath
from typing import Any

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from codegen.ir import load_ir  # noqa: E402
from codegen.swift_app.emit import HEADER_MARK, BindingError, render  # noqa: E402
from codegen.validate import ValidationError  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[4]
DEFAULT_SCHEMA = REPO_ROOT / "cmux-tui" / "spec" / "sdk-schema.json"
DEFAULT_BINDINGS = Path(__file__).resolve().with_name("bindings.json")
SUFFIX = ".generated.swift"


def load_bindings(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise BindingError(f"cannot read {path}: {error}") from error
    if not isinstance(value, dict):
        raise BindingError(f"{path} must be an object")
    return value


def output_root(repo_root: Path, bindings: dict[str, Any]) -> Path:
    raw = bindings.get("output_root")
    if not isinstance(raw, str) or not raw:
        raise BindingError("bindings need output_root, a repository-relative folder")
    relative = PurePosixPath(raw)
    if relative.is_absolute() or ".." in relative.parts:
        raise BindingError(f"output_root {raw!r} must stay inside the repository")
    return repo_root.joinpath(*relative.parts)


def _owned(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8") as handle:
            return handle.readline().rstrip("\n") == HEADER_MARK
    except (OSError, UnicodeError):
        return False


def owned_files(root: Path) -> set[str]:
    if not root.is_dir():
        return set()
    return {
        path.relative_to(root).as_posix()
        for path in root.rglob("*" + SUFFIX)
        if path.is_file() and _owned(path)
    }


def run(*, mode: str, schema: Path, bindings: Path, repo_root: Path) -> list[str]:
    """Write or check; return the drift problems (always empty after a write)."""
    if mode not in {"write", "check"}:
        raise ValueError(f"unknown mode {mode!r}")
    loaded = load_bindings(bindings)
    files = render(load_ir(schema), loaded)
    root = output_root(Path(repo_root), loaded)
    owned = owned_files(root)
    problems: list[str] = []
    for relative, content in files.items():
        target = root / relative
        if target.exists() and relative not in owned:
            raise BindingError(f"{target} exists and is not generated by this emitter; refusing to replace it")
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == content:
            continue
        if mode == "write":
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
        else:
            problems.append(f"{'missing' if current is None else 'changed'} {relative}")
    for relative in sorted(owned - set(files)):
        if mode == "write":
            stale = root / relative
            stale.unlink()
            parent = stale.parent
            while parent != root and parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
                parent = parent.parent
        else:
            problems.append(f"stale {relative}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="update the generated Swift files")
    mode.add_argument("--check", action="store_true", help="fail when the generated Swift files differ")
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    parser.add_argument("--bindings", type=Path, default=DEFAULT_BINDINGS)
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT)
    arguments = parser.parse_args(argv)
    chosen = "write" if arguments.write else "check"
    try:
        problems = run(mode=chosen, schema=arguments.schema, bindings=arguments.bindings,
                       repo_root=arguments.repo_root)
    except (BindingError, ValidationError, ValueError) as error:
        print(f"Swift app codegen failed: {error}", file=sys.stderr)
        return 1
    if problems:
        print(
            "the generated Swift request types are stale: run python3 cmux-tui/bindings/codegen/generate.py --write\n"
            + "\n".join(f"- {problem}" for problem in problems),
            file=sys.stderr,
        )
        return 1
    print(f"{'wrote' if chosen == 'write' else 'checked'} swift-app")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
