#!/usr/bin/env python3
"""Generate or check the CmuxNextDaemon request types listed in swift_app/bindings.json.

    python3 cmux-tui/bindings/codegen/swift_app/generate.py --out DIR
    python3 cmux-tui/bindings/codegen/swift_app/generate.py --check

The files are not in git (Leo, 2026-10-21: don't commit generatable files): CmuxNextDaemon's
DaemonRequestsPlugin, a SwiftPM build-tool plugin, runs --out into its work directory on every build.
--out writes one flat folder (a prebuild output folder is read one level deep), rewrites only files
whose text changed, so an incremental build recompiles nothing it did not change, and deletes the
owned files it no longer generates. A file is owned when its first line is the generator's header
(emit.HEADER_MARK); other files in the folder are left alone and never replaced.
--check renders every binding against the schema and writes nothing; codegen/generate.py runs it
after the SDKs (with no --language), so a schema change that breaks a binding fails there too.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path, PurePosixPath
from typing import Any

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from codegen.ir import load_ir  # noqa: E402
from codegen.swift_app.emit import HEADER_MARK, BindingError, render  # noqa: E402
from codegen.validate import ValidationError  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[4]
DEFAULT_SCHEMA = REPO_ROOT / "cmux-tui" / "spec" / "sdk-schema.json"
DEFAULT_BINDINGS = Path(__file__).resolve().with_name("bindings.json")
SUFFIX = ".generated.swift"


def load_bindings(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise BindingError(f"cannot read {path}: {error}") from error
    if not isinstance(value, dict):
        raise BindingError(f"{path} must be an object")
    return value


def _owned(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8") as handle:
            return handle.readline().rstrip("\n") == HEADER_MARK
    except (OSError, UnicodeError):
        return False


def owned_files(root: Path) -> set[str]:
    if not root.is_dir():
        return set()
    return {path.name for path in root.glob("*" + SUFFIX) if path.is_file() and _owned(path)}


def flat(files: dict[str, str]) -> dict[str, str]:
    """Key each file by its name alone; two families generating one file name is refused."""
    out: dict[str, str] = {}
    for relative, content in files.items():
        name = PurePosixPath(relative).name
        if name in out:
            raise BindingError(f"two generated files are named {name}; a type name must be unique in the module")
        out[name] = content
    return out


def run(*, schema: Path, bindings: Path, out: Path | None) -> None:
    """Render every binding; with out, write the files there and delete the stale owned ones."""
    files = flat(render(load_ir(schema), load_bindings(bindings)))
    if out is None:
        return
    owned = owned_files(out)
    for name, content in files.items():
        target = out / name
        if target.exists() and name not in owned:
            raise BindingError(f"{target} exists and is not generated by this emitter; refusing to replace it")
        if target.exists() and target.read_text(encoding="utf-8") == content:
            continue
        out.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    for name in sorted(owned - set(files)):
        (out / name).unlink()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--out", type=Path, help="write the generated Swift files into this folder")
    mode.add_argument("--check", action="store_true", help="render every binding and write nothing")
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    parser.add_argument("--bindings", type=Path, default=DEFAULT_BINDINGS)
    arguments = parser.parse_args(argv)
    try:
        run(schema=arguments.schema, bindings=arguments.bindings, out=arguments.out)
    except (BindingError, ValidationError, ValueError) as error:
        print(f"Swift app codegen failed: {error}", file=sys.stderr)
        return 1
    if arguments.check:
        print("checked swift-app")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
