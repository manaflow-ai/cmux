#!/usr/bin/env python3
"""Generate or verify the page clients' copy of spec/page-router.json.

The daemon embeds spec/page-router.json; the React pages get the same table as
webviews/src/pages/shared/generated/pageRouter.ts, so a page knows which
operations it may call and which need the person's gesture (page-router.md).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

CODEGEN_DIR = Path(__file__).resolve().parent
CMUX_TUI = CODEGEN_DIR.parent.parent
SPEC = CMUX_TUI / "spec" / "page-router.json"
OUTPUT = CMUX_TUI.parent / "webviews" / "src" / "pages" / "shared" / "generated" / "pageRouter.ts"


def render(spec: dict) -> str:
    pages = {
        page: {
            "read": sorted(entry["read"]),
            "gesture": sorted(entry["gesture"]),
            "confirm": sorted(entry["confirm"]),
        }
        for page, entry in sorted(spec["pages"].items())
    }
    namespaces = {
        name: {
            "owner": entry["owner"],
            "read": sorted(entry["read"]),
            "mutation": sorted(entry["mutation"]),
        }
        for name, entry in sorted(spec["namespaces"].items())
    }
    lines = [
        "// Generated by cmux-tui/bindings/codegen/page_router.py from cmux-tui/spec/page-router.json.",
        "// Do not edit. The daemon enforces the same table (page-router.md).",
        "",
        f"export const PAGE_ROUTER_CAPABILITY = {json.dumps(spec['capability'])};",
        "",
        "export interface PageOperations {",
        "  readonly read: readonly string[];",
        "  readonly gesture: readonly string[];",
        "  readonly confirm: readonly string[];",
        "}",
        "",
        f"export const PAGE_OPERATIONS: Readonly<Record<string, PageOperations>> = {json.dumps(pages, indent=2)};",
        "",
        "export interface RoutedNamespace {",
        "  readonly owner: string;",
        "  readonly read: readonly string[];",
        "  readonly mutation: readonly string[];",
        "}",
        "",
        f"export const ROUTED_NAMESPACES: Readonly<Record<string, RoutedNamespace>> = {json.dumps(namespaces, indent=2)};",
        "",
        "/** What `page` may do with the v2 operation `operation`: `read`, `gesture`, `confirm`, or `none`. */",
        'export function pageGrant(page: string, operation: string): "read" | "gesture" | "confirm" | "none" {',
        "  const entry = PAGE_OPERATIONS[page];",
        '  if (!entry) return "none";',
        '  if (entry.read.includes(operation)) return "read";',
        '  if (entry.gesture.includes(operation)) return "gesture";',
        '  if (entry.confirm.includes(operation)) return "confirm";',
        '  return "none";',
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    text = render(json.loads(SPEC.read_text(encoding="utf-8")))
    if arguments.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(CMUX_TUI.parent)}")
        return 0
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if current != text:
        print(
            f"{OUTPUT.relative_to(CMUX_TUI.parent)} is stale: run "
            "python3 cmux-tui/bindings/codegen/page_router.py --write",
            file=sys.stderr,
        )
        return 1
    print(f"checked {OUTPUT.relative_to(CMUX_TUI.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
