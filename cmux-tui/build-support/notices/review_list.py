"""Write REVIEW.md, the license review list, from reviewed.json.

  review_list.py --cache DIR --lock A/Cargo.lock [--lock ...] [--check]

DIR is a fetch_crates.py cache (the crate sources give the sha256 of each
extra or skipped file). One row per choice: extra license files, skipped
license files, elections and stored upstream texts, each with the crate, the
file, the source URL, the sha256 and the reason.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys
import tomllib

HERE = Path(__file__).resolve().parent
REGISTRY = Path("registry/src/index.crates.io-notices")


def versions(locks: list[Path]) -> dict[str, list[str]]:
    found: dict[str, set[str]] = {}
    for lock in locks:
        for package in tomllib.loads(lock.read_text(encoding="utf-8")).get("package", []):
            found.setdefault(package["name"], set()).add(package["version"])
    return {name: sorted(values) for name, values in found.items()}


def file_rows(cache: Path, table: dict, reasons: dict, known: dict[str, list[str]]) -> list[str]:
    rows = []
    for name in sorted(table):
        entry = table[name]
        files = entry["files"] if isinstance(entry, dict) else entry
        reason = entry["reason"] if isinstance(entry, dict) else reasons.get(name, "")
        if not reason:
            raise SystemExit(f"review_list: {name}: no reason recorded")
        for version in known.get(name, []):
            for file in files:
                path = cache / REGISTRY / f"{name}-{version}" / file
                digest = hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else "(file not in this version)"
                rows.append(f"| {name} {version} | `{file}` | https://crates.io/api/v1/crates/{name}/{version}/download | `{digest}` | {reason} |")
    return rows


def render(cache: Path, locks: list[Path]) -> str:
    reviewed = json.loads((HERE / "reviewed.json").read_text(encoding="utf-8"))
    known = versions(locks)
    out = [
        "# License review list for rust_notices.py data",
        "",
        "Generated by review_list.py from reviewed.json; do not edit by hand. Owned by the license review:",
        "every row is a choice that the tool cannot make from crate metadata. No license text was edited.",
        "",
        "## Extra license files inside a crate (`extra_license_files`)",
        "",
        "| Crate | File in the .crate | Source | SHA-256 | Reason |",
        "| --- | --- | --- | --- | --- |",
        *file_rows(cache, reviewed.get("extra_license_files", {}), reviewed.get("extra_license_reasons", {}), known),
        "",
        "## License files deliberately not included (`skipped_license_files`)",
        "",
        "| Crate | File in the .crate | Source | SHA-256 | Reason |",
        "| --- | --- | --- | --- | --- |",
        *file_rows(cache, reviewed.get("skipped_license_files", {}), {}, known),
        "",
        "## Elections (`elections`)",
        "",
        "| Crate | Declared | Concluded | Reason |",
        "| --- | --- | --- | --- |",
        *[f"| {name} | {e['declared']} | {e['concluded']} | {e['reason']} |" for name, e in sorted(reviewed.get("elections", {}).items())],
        "",
        "## Stored upstream texts for crates that ship no license file (`license_texts`)",
        "",
        "Reason for every row: the .crate ships no license file; the text is the repository's file at the",
        "commit that the crate's `.cargo_vcs_info.json` records for the release (fetch_reviewed_text.py).",
        "",
        "| Crate | Stored file | Source | SHA-256 |",
        "| --- | --- | --- | --- |",
        *[f"| {key} | `{e['file']}` | {e['source']} | `{e['sha256']}` |" for key, t in sorted(reviewed.get("license_texts", {}).items()) for e in t["files"]],
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--lock", type=Path, action="append", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render(args.cache, args.lock)
    target = HERE / "REVIEW.md"
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            print(f"review_list: {target} is stale; run review_list.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
