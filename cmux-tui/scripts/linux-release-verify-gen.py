#!/usr/bin/env python3
"""Write the signed release file's verifier into the Linux installers, keys from web-update-keys.json.

cmux-tui/scripts/linux-release-verify.sh is the one source of the shell function set that
web/public/tui/install-static.sh and cmux-tui/scripts/machine-join.sh carry inline (a script fetched
by curl runs alone, so it cannot source a second file). This writes it between the scripts'
"BEGIN linux-release-verify" and "END linux-release-verify" lines, with a clr_keys function holding
the public keys of Packages/macOS/CmuxNext/Sources/CmuxNextUpdater/Resources/web-update-keys.json as
PEM bodies (cmuxterm-hq docs/design/linux-signed-packages.md, section 3).

  linux-release-verify-gen.py            rewrite both scripts
  linux-release-verify-gen.py --check    exit 1 when a script's copy, channel.rs KEYS, or the Cloud
                                         bake's LINUX_RELEASE_KEYS (web linuxRelease.ts) differs
  linux-release-verify-gen.py --render SCRIPT --keys KEYS.json
                                         print SCRIPT with KEYS.json's keys instead (the tests)
"""
import argparse
import base64
import hashlib
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SOURCE = "cmux-tui/scripts/linux-release-verify.sh"
KEYS = "Packages/macOS/CmuxNext/Sources/CmuxNextUpdater/Resources/web-update-keys.json"
CHANNEL_RS = "cmux-tui/crates/cmux-host/src/updater/channel.rs"
# The Cloud image bake's node:crypto verifier of the same release file.
WEB_TS = "web/services/vms/drivers/linuxRelease.ts"
SCRIPTS = ("web/public/tui/install-static.sh", "cmux-tui/scripts/machine-join.sh")
BEGIN = ("# BEGIN linux-release-verify: generated by cmux-tui/scripts/linux-release-verify-gen.py from "
         + SOURCE + " and web-update-keys.json; edit those, not this")
END = "# END linux-release-verify"
# The DER prefix of an Ed25519 SubjectPublicKeyInfo: the raw 32-byte key follows it.
ED25519_SPKI_PREFIX = bytes.fromhex("302a300506032b6570032100")


def load_keys(path):
    keys = []
    for entry in json.load(open(path))["keys"]:
        raw = base64.b64decode(entry["ed25519"], validate=True)
        if len(raw) != 32 or hashlib.sha256(raw).hexdigest()[:16] != entry["id"]:
            sys.exit(f"linux-release-verify-gen: {path}: key {entry.get('id')} is not a 32-byte key matching its id")
        keys.append((entry["id"], entry["ed25519"], raw))
    if not keys:
        sys.exit(f"linux-release-verify-gen: {path} holds no keys")
    return keys


def block(keys):
    source = open(os.path.join(ROOT, SOURCE)).read().rstrip("\n")
    lines = ["clr_keys() { # The trusted release keys: id, then the PEM body of the Ed25519 public key."]
    for key_id, _, raw in keys:
        lines.append(f"  printf '%s\\n' '{key_id} {base64.b64encode(ED25519_SPKI_PREFIX + raw).decode()}'")
    lines.append("}")
    return "\n".join([BEGIN, source, *lines, END])


def render(text, keys, name):
    pattern = re.compile(r"^# BEGIN linux-release-verify[^\n]*\n.*?^# END linux-release-verify$", re.S | re.M)
    if len(pattern.findall(text)) != 1:
        sys.exit(f"linux-release-verify-gen: {name} needs exactly one BEGIN/END linux-release-verify block")
    return pattern.sub(lambda _: block(keys), text)


def rust_keys():
    text = open(os.path.join(ROOT, CHANNEL_RS)).read()
    m = re.search(r"pub const KEYS: &\[\(&str, &str\)\] =\s*&\[(.*?)\];", text, re.S)
    if not m:
        sys.exit(f"linux-release-verify-gen: no KEYS in {CHANNEL_RS}")
    return re.findall(r'\(\s*"([0-9a-f]{16})"\s*,\s*"([A-Za-z0-9+/=]+)"\s*\)', m.group(1))


def web_keys():
    text = open(os.path.join(ROOT, WEB_TS)).read()
    m = re.search(r"export const LINUX_RELEASE_KEYS\b[^=]*=\s*\[(.*?)\];", text, re.S)
    if not m:
        sys.exit(f"linux-release-verify-gen: no LINUX_RELEASE_KEYS in {WEB_TS}")
    return re.findall(r'\[\s*"([0-9a-f]{16})"\s*,\s*"([A-Za-z0-9+/=]+)"\s*,?\s*\]', m.group(1))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--render")
    parser.add_argument("--keys")
    args = parser.parse_args()
    if args.render:
        if not args.keys:
            sys.exit("linux-release-verify-gen: --render needs --keys")
        sys.stdout.write(render(open(args.render).read(), load_keys(args.keys), args.render))
        return 0
    keys = load_keys(os.path.join(ROOT, KEYS))
    bad = []
    if sorted(rust_keys()) != sorted((key_id, b64) for key_id, b64, _ in keys):
        bad.append(f"{CHANNEL_RS} KEYS {rust_keys()} differ from {KEYS}")
    if sorted(web_keys()) != sorted((key_id, b64) for key_id, b64, _ in keys):
        bad.append(f"{WEB_TS} LINUX_RELEASE_KEYS {web_keys()} differ from {KEYS}")
    for rel in SCRIPTS:
        path = os.path.join(ROOT, rel)
        text = open(path).read()
        want = render(text, keys, rel)
        if want == text:
            continue
        if args.check:
            bad.append(f"{rel}'s linux-release-verify block differs from {SOURCE} and {KEYS}")
        else:
            open(path, "w").write(want)
            print(f"linux-release-verify-gen: wrote {rel}")
    for line in bad:
        print(f"linux-release-verify-gen: {line}", file=sys.stderr)
    if bad:
        print("next: run python3 cmux-tui/scripts/linux-release-verify-gen.py and commit what it writes", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
