// Reuse translations owned by the Apple app. Ambiguous English messages are
// omitted rather than selecting a translation from an unrelated context.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const locales = ['en','de','fr','ar','es','zh-Hant','zh-Hans','ko','ja'];
const candidates = new Map();
const sourceFiles = [
  ...fs.readdirSync(path.join(root,'windows/src')).filter(name=>name.endsWith('.cjs')).map(name=>path.join(root,'windows/src',name)),
  ...fs.readdirSync(path.join(root,'windows/renderer')).filter(name=>name.endsWith('.js') && name!=='catalog-messages.js').map(name=>path.join(root,'windows/renderer',name)),
  path.join(root,'windows/renderer/index.html')
];
const source = sourceFiles.map(file=>fs.readFileSync(file,'utf8')).join('\n');
const catalogs = [path.join(root,'Resources/Localizable.xcstrings')];
for (const file of fs.readdirSync(path.join(root,'Packages'), {recursive:true})) {
  if (file.endsWith('Localizable.xcstrings')) catalogs.push(path.join(root,'Packages',file));
}
for (const file of catalogs) {
  const catalog = JSON.parse(fs.readFileSync(file,'utf8'));
  for (const [key, entry] of Object.entries(catalog.strings)) {
    const english = entry.localizations?.en?.stringUnit?.value;
    if (!english) continue;
    if (!candidates.has(english)) candidates.set(english,[]);
    candidates.get(english).push(entry);
  }
}
const messages = Object.fromEntries(locales.map(locale=>[locale,{}]));
for (const [english, entries] of [...candidates].sort(([a],[b])=>a.localeCompare(b,'en'))) {
  if (!source.includes(JSON.stringify(english)) && !source.includes(`'${english.replaceAll("'","\\'")}'`)) continue;
  for (const locale of locales) {
    const values = new Set(entries.map(entry=>entry.localizations?.[locale]?.stringUnit?.value).filter(value=>value!==undefined));
    if (values.size===1) messages[locale][english]=[...values][0];
  }
}
const serialized = JSON.stringify(messages,null,2)+'\n';
fs.writeFileSync(path.join(root,'windows/renderer/catalog-messages.js'),'// Generated by npm run build:locales.\nexport default '+serialized.trimEnd()+';\n');
fs.writeFileSync(path.join(root,'windows/src/catalog-messages.json'),serialized);
console.log(`Exported ${Object.keys(messages.en).length} unambiguous messages from ${catalogs.length} catalogs into ${locales.length} locales.`);
