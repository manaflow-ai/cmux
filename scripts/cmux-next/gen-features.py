def rust_const(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).upper()


def _string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _float(value):
    return repr(float(value))


def _swift_param(param):
    kind = param["type"]
    if kind == "bool":
        value = ".bool(default: %s)" % ("true" if param["default"] else "false")
    else:
        number = (lambda item: str(int(item))) if kind == "int" else _float
        value = ".%s(default: %s, min: %s, max: %s)" % (
            kind, number(param["default"]), number(param["min"]), number(param["max"]))
    return """            FeatureParamSpec(
                name: %s,
                description: %s,
                value: %s
            ),""" % (_string(param["name"]), _string(param["description"]), value)


def swift_order(features):
    """The Swift slot order: shipped features, then benchOnly ones, so each build's registry indices are dense."""
    return [f for f in features if not f.get("benchOnly")] + [f for f in features if f.get("benchOnly")]


def _swift_registered(features):
    names = "[]" if not features else "[\n%s\n    ]" % "\n".join("        .%s," % feature["name"] for feature in features)
    return """    /// Every feature, by index: `registered[feature.index] == feature`.
    public static let registered: [Feature] = %s
""" % names


def swift(features):
    features = swift_order(features)
    shipped = [feature for feature in features if not feature.get("benchOnly")]
    blocks = []
    for index, feature in enumerate(features):
        defaults = feature["defaults"]
        params = "[]" if not feature["params"] else "[\n%s\n        ]" % "\n".join(
            _swift_param(param) for param in feature["params"])
        chromium = feature.get("chromium_feature")
        expires = feature.get("expires")
        blocks.append("""    /// {description}
    public static let {name} = Feature(
        index: {index},
        name: {name_literal},
        owner: {owner},
        description: {description_literal},
        kind: .{kind},
        process: .{process},
        chromiumFeature: {chromium},
        defaults: FeatureDefaults(dev: {dev}, nightly: {nightly}, release: {release}),
        expires: {expires},
        params: {params},
        stories: [{stories}],
        sticky: {sticky},
        runtimeMutable: {runtime_mutable}{replaces}
    )
""".format(
            description=feature["description"], name=feature["name"], index=index, name_literal=_string(feature["name"]),
            owner=_string(feature["owner"]), description_literal=_string(feature["description"]), kind=feature["kind"],
            process=feature["process"], chromium=_string(chromium) if chromium else "nil",
            dev=_bool(defaults["dev"]), nightly=_bool(defaults["nightly"]), release=_bool(defaults["release"]),
            expires=_string(expires) if expires else "nil", params=params,
            stories=", ".join(_string(story) for story in feature["stories"]),
            sticky=_bool(feature["sticky"]), runtime_mutable=_bool(feature["runtimeMutable"]),
            replaces=",\n        replaces: [%s]" % ", ".join(_string(key) for key in feature["replaces"])
            if feature.get("replaces") else ""))
    body = "\n".join(blocks[:len(shipped)]) + ("\n" if shipped else "")
    registered = _swift_registered(features)
    if len(shipped) < len(features):
        # benchOnly: compiled only where CMUX_BENCH_HOOKS code is (DEBUG and bench builds), never in a shipped app.
        body += "    #if %s\n%s    #endif\n\n" % (BENCH_ONLY_CONDITION, "\n".join(blocks[len(shipped):]))
        registered = "    #if %s\n%s    #else\n%s    #endif\n" % (
            BENCH_ONLY_CONDITION, registered, _swift_registered(shipped))
    comment = "\n".join("// " + line for line in HEADER.split("\n"))
    return """{comment}

nonisolated extension Feature {{
{body}{registered}}}
""".format(comment=comment, body=body, registered=registered)


def _bool(value):
    return "true" if value else "false"


def rust(features):
    """The daemon-side features in the shape cmux-features/src/lib.rs reads: `TABLE` and one handle per entry
    (`feature_handles!`, which fails the build on a name `TABLE` lacks). The daemon's `Snapshot` resolves only
    the defaults, the kind (a client hello applies a kill switch at once) and the process; the other fields
    stay in the JSON and the Swift registry."""
    daemon = [feature for feature in features if feature["process"] in ("daemon", "both")]
    entries = []
    handles = []
    for feature in daemon:
        defaults = feature["defaults"]
        entries.append("""    crate::FeatureDef {{
        name: {name},
        defaults: crate::Defaults {{ dev: {dev}, nightly: {nightly}, release: {release} }},
        kind: crate::Kind::{kind},
        process: crate::Process::{process},
    }},""".format(
            name=_string(feature["name"]), dev=_bool(defaults["dev"]), nightly=_bool(defaults["nightly"]),
            release=_bool(defaults["release"]), kind=feature["kind"][0].upper() + feature["kind"][1:],
            process=feature["process"].capitalize()))
        handles.append("        /// {description}\n        {const} = {name},".format(
            description=feature["description"], const=rust_const(feature["name"]), name=_string(feature["name"])))
    comment = "\n".join("// " + line for line in HEADER.split("\n"))
    table = "&[\n%s\n]" % "\n".join(entries) if entries else "&[]"
    handle_list = "\n" + "\n".join(handles) + "\n    " if handles else ""
    return """{comment}
//
// The daemon-side features (process "daemon" or "both"); the app's registry has every feature.

/// Every daemon-side feature in registry order; a handle is its index here.
pub(crate) const TABLE: &[crate::FeatureDef] = {table};

/// One handle per daemon feature, for `Snapshot::is_enabled`.
pub mod feature {{
    feature_handles!(super::TABLE;{handles});
}}
""".format(comment=comment, table=table, handles=handle_list)


def outputs(features):
    return {SWIFT_OUT: swift(features), RUST_OUT: rust(features)}


def missing_target(root, rel):
    """Why `rel` has no target to compile it yet (task p12-perf-process-091 adds the Swift target, 095 the
    crate), or None. A generated file is written and checked only once its target exists."""
    if rel == SWIFT_OUT:
        package = os.path.join(root, SWIFT_PACKAGE)
        declared = os.path.isfile(package) and re.search(
            r'\.target\(\s*name:\s*"%s"' % SWIFT_TARGET, _read(package))
        return None if declared else "%s declares no %s target" % (SWIFT_PACKAGE, SWIFT_TARGET)
    return None if os.path.isfile(os.path.join(root, RUST_MANIFEST)) else "no %s" % RUST_MANIFEST


def rustfmt(text, root):
    """`text` as the pre-commit hook would format it (rustfmt with cmux-tui's config), or as is without rustfmt."""
    binary = shutil.which("rustfmt")
    if not binary:
        return text
    crate_root = os.path.join(root, "cmux-tui")
    config = os.path.join(crate_root, "rustfmt.toml")
    command = [binary, "--edition", RUST_EDITION] + (["--config-path", config] if os.path.isfile(config) else [])
    done = subprocess.run(command, input=text, capture_output=True, text=True,
                          cwd=crate_root if os.path.isdir(crate_root) else root)
    if done.returncode != 0:
        raise RuntimeError("rustfmt rejected the generated Rust:\n" + done.stderr)
    return done.stdout


def rust_tokens(text):
    """Rust source without layout: whitespace and trailing commas dropped outside string literals."""
    parts = re.split(r'("(?:[^"\\]|\\.)*")', text)
    for number in range(0, len(parts), 2):
        parts[number] = re.sub(r",(?=[\]})])", "", re.sub(r"\s+", "", parts[number]))
    return "".join(parts)


def same_output(rel, old, new):
    # rustfmt owns the Rust layout (the pre-commit hook formats every staged .rs file).
    if rel.endswith(".rs"):
        return rust_tokens(old) == rust_tokens(new)
    return old == new


