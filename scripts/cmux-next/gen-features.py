def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 when a generated file drifted or a feature file is invalid")
    mode.add_argument("--unmigrated", action="store_true", help="MQ6: perf-path Bool tunables and env switches not yet a feature")
    mode.add_argument("--unmigrated-params", action="store_true", help="MQ16: numeric perf-owned tunables not yet a FeatureParam")
    parser.add_argument("--count", action="store_true", help="with a queue: print only the number")
    parser.add_argument("--root", default=ROOT, help=argparse.SUPPRESS)
    parser.add_argument("--today", type=datetime.date.fromisoformat, default=None, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    if args.count and not (args.unmigrated or args.unmigrated_params):
        parser.error("--count goes with --unmigrated or --unmigrated-params")
    today = args.today or datetime.date.today()
    features, errors, warnings = load_features(args.root, today)
    for warning in warnings:
        print("warning: " + warning, file=sys.stderr)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print("%d invalid feature file problem(s); see %s and schemas/features/README.md" % (len(errors), SCHEMA),
              file=sys.stderr)
        return 1

    if args.unmigrated or args.unmigrated_params:
        rows = unmigrated(args.root, features) if args.unmigrated else unmigrated_params(args.root, features)
        if args.count:
            print(len(rows))
        else:
            for key, where in rows:
                print("%s\t%s" % (key, where))
            print("%d unmigrated" % len(rows))
        return 0

    drifted = []
    for rel, text in outputs(features).items():
        full = os.path.join(args.root, rel)
        if os.path.exists(full) and same_output(rel, _read(full), text):
            continue
        if args.check:
            drifted.append(rel)
            continue
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w") as handle:
            handle.write(rustfmt(text, args.root) if rel.endswith(".rs") else text)
        print("wrote " + rel)
    if drifted:
        print("generated feature registries drifted from %s: %s\nrun python3 scripts/cmux-next/gen-features.py"
              % (FEATURES_DIR, ", ".join(drifted)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
