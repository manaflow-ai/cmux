def _finite(value):
    # json.load reads an overflowing literal such as 1e400 as inf without calling parse_constant.
    try:
        return math.isfinite(value)
    except OverflowError:  # an int too large for a float
        return False


def _is_type(value, name):
    if name == "boolean":
        return isinstance(value, bool)
    if name == "integer":
        return (isinstance(value, int) and not isinstance(value, bool) and _finite(value)) or (
            isinstance(value, float) and math.isfinite(value) and value.is_integer())
    if name == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool) and _finite(value)
    return isinstance(value, {"string": str, "array": list, "object": dict, "null": type(None)}[name])


def _same(a, b):
    if isinstance(a, bool) or isinstance(b, bool):
        return isinstance(a, bool) and isinstance(b, bool) and a == b
    return a == b


def _describe_forbidden(schema):
    names = [name for name in schema.get("required", [])]
    names += [name for sub in schema.get("anyOf", []) for name in sub.get("required", [])]
    return " or ".join(repr(name) for name in names) if names else json.dumps(schema)


@functools.lru_cache(maxsize=None)
def _ecma_pattern(pattern):
    """`pattern` compiled with ECMA-262's `$`, which matches only at the end of the string; Python's `$`
    also matches before a final newline, and a description ending in one would break the generated
    single-line string literals."""
    out, in_class, index = [], False, 0
    while index < len(pattern):
        char = pattern[index]
        if char == "\\":
            out.append(pattern[index:index + 2])
            index += 2
            continue
        if in_class:
            in_class = char != "]"
        elif char == "[":
            in_class = True
        elif char == "$":
            char = r"\Z"
        out.append(char)
        index += 1
    return re.compile("".join(out))


def schema_errors(value, schema, root, path=""):
    """Every way `value` fails `schema`, as "<json pointer>: <reason>" strings."""
    if "$ref" in schema:
        ref = schema["$ref"]
        assert ref.startswith("#/"), ref
        target = root
        for part in ref[2:].split("/"):
            target = target[part]
        return schema_errors(value, target, root, path)
    where = path or "/"
    if "type" in schema:
        types = schema["type"] if isinstance(schema["type"], list) else [schema["type"]]
        if not any(_is_type(value, name) for name in types):
            return ["%s: expected %s" % (where, " or ".join(types))]
    errors = []
    if "enum" in schema and not any(_same(value, option) for option in schema["enum"]):
        errors.append("%s: %s is not one of %s" % (where, json.dumps(value), ", ".join(map(json.dumps, schema["enum"]))))
    if "const" in schema and not _same(value, schema["const"]):
        errors.append("%s: expected %s" % (where, json.dumps(schema["const"])))
    if isinstance(value, str) and "pattern" in schema and not _ecma_pattern(schema["pattern"]).search(value):
        errors.append("%s: %s does not match %s" % (where, json.dumps(value), schema["pattern"]))
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            errors.append("%s: needs at least %d item(s)" % (where, schema["minItems"]))
        if schema.get("uniqueItems"):
            seen = [json.dumps(item, sort_keys=True) for item in value]
            if len(seen) != len(set(seen)):
                errors.append("%s: items repeat" % where)
        if "items" in schema:
            for number, item in enumerate(value):
                errors += schema_errors(item, schema["items"], root, "%s/%d" % (path, number))
    if isinstance(value, dict):
        for name in schema.get("required", []):
            if name not in value:
                errors.append("%s: missing %r" % (where, name))
        properties = schema.get("properties", {})
        for name, item in value.items():
            if name in properties:
                errors += schema_errors(item, properties[name], root, "%s/%s" % (path, name))
            elif schema.get("additionalProperties") is False:
                errors.append("%s: unknown property %r" % (where, name))
    for sub in schema.get("allOf", []):
        label = sub.get("description")
        errors += [label + ": " + error if label else error for error in schema_errors(value, sub, root, path)]
    if "anyOf" in schema and all(schema_errors(value, sub, root, path) for sub in schema["anyOf"]):
        errors.append("%s: matches none of anyOf" % where)
    if "not" in schema and not schema_errors(value, schema["not"], root, path):
        errors.append("%s: %s is not allowed here" % (where, _describe_forbidden(schema["not"])))
    if "if" in schema:
        branch = "else" if schema_errors(value, schema["if"], root, path) else "then"
        if branch in schema:
            errors += schema_errors(value, schema[branch], root, path)
    return errors


