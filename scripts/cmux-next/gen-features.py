# Registry

def load_schema(root):
    with open(os.path.join(root, SCHEMA)) as handle:
        return json.load(handle)


def _walk(root, top, suffix):
    base = os.path.join(root, top)
    for directory, subdirs, files in os.walk(base):
        subdirs[:] = sorted(name for name in subdirs if name not in SKIP_DIRS)
        for name in sorted(files):
            if name.endswith(suffix):
                full = os.path.join(directory, name)
                yield os.path.relpath(full, root), full


def _test_exists(root, name):
    """A teardownTest names a test function: `func <last>` in Swift tests or `fn <last>` in cmux-tui."""
    last = re.split(r"[./:]+", name)[-1]
    swift = re.compile(r"\bfunc\s+%s\s*\(" % re.escape(last))
    rust = re.compile(r"\bfn\s+%s\s*\(" % re.escape(last))
    for rel, full in _walk(root, SWIFT_ROOT, ".swift"):
        if "/Tests/" in "/" + rel and swift.search(_read(full)):
            return True
    for _, full in _walk(root, RUST_CRATES, ".rs"):
        if rust.search(_read(full)):
            return True
    return False


def _read(path):
    with open(path, encoding="utf-8", errors="replace") as handle:
        return handle.read()


def load_features(root, today):
    """(features sorted by name, errors, warnings). Errors are schema and registry violations."""
    schema = load_schema(root)
    directory = os.path.join(root, FEATURES_DIR)
    names = sorted(os.listdir(directory)) if os.path.isdir(directory) else []
    features, errors, warnings = [], [], []
    for file_name in names:
        rel = FEATURES_DIR + "/" + file_name
        if not file_name.endswith(".json"):
            errors.append("%s: features.d holds only <name>.json files" % rel)
            continue
        try:
            with open(os.path.join(directory, file_name)) as handle:
                data = json.load(handle, parse_constant=_reject_constant)
        except (ValueError, OSError) as error:
            errors.append("%s: %s" % (rel, error))
            continue
        found = schema_errors(data, schema, schema)
        if not found:
            found = _registry_errors(root, data, file_name, today, warnings, rel)
        if found:
            errors += ["%s: %s" % (rel, error) for error in found]
        else:
            features.append(data)
    errors += _cross_errors(features)
    return features, errors, warnings


def _reject_constant(token):
    raise ValueError("%s is not a JSON number" % token)


def _registry_errors(root, data, file_name, today, warnings, rel):
    """What the schema cannot say: file name, the 60-day perfPath expiry, param ranges, stories, tests."""
    errors = []
    name = data["name"]
    if file_name != name + ".json":
        errors.append("the file must be named %s.json" % name)
    if name in SWIFT_RESERVED:
        errors.append("%r is reserved in the generated Swift" % name)
    if "expires" in data:
        try:
            expires = datetime.date.fromisoformat(data["expires"])
        except ValueError:
            errors.append("/expires: %r is not a date" % data["expires"])
        else:
            limit = today + datetime.timedelta(days=PERF_PATH_MAX_DAYS)
            if data["kind"] == "perfPath" and expires > limit:
                errors.append("/expires: a perfPath feature expires within %d days (by %s), not %s"
                              % (PERF_PATH_MAX_DAYS, limit.isoformat(), expires.isoformat()))
            if expires < today:
                warnings.append("%s: expired on %s; make it permanent or remove it" % (rel, expires.isoformat()))
    params = data["params"]
    param_names = [param["name"] for param in params]
    if len(param_names) != len(set(param_names)):
        errors.append("/params: names repeat")
    for number, param in enumerate(params):
        if param["type"] != "bool":
            low, high, value = param["min"], param["max"], param["default"]
            if not (low <= value <= high):
                errors.append("/params/%d: default %s is outside [%s, %s]" % (number, value, low, high))
    stories_dir = os.path.join(root, STORIES_DIR)
    if os.path.isdir(stories_dir):
        for story in data["stories"]:
            if not os.path.isfile(os.path.join(stories_dir, story + ".json")):
                errors.append("/stories: no story %s/%s.json" % (STORIES_DIR, story))
    if data["runtimeMutable"] and not _test_exists(root, data["teardownTest"]):
        errors.append("/teardownTest: no test function named %r" % data["teardownTest"])
    return errors


def _cross_errors(features):
    errors = []
    for label, values in (
        ("Rust constant", [rust_const(feature["name"]) for feature in features]),
        ("chromium_feature", [feature.get("chromium_feature") for feature in features
                              if "chromium_feature" in feature]),
        ("replaces", [key for feature in features for key in feature.get("replaces", [])]
         + [param["replaces"] for feature in features for param in feature["params"] if "replaces" in param]),
    ):
        repeated = sorted({value for value in values if values.count(value) > 1})
        if repeated:
            errors.append("%s: %s is used by more than one feature" % (FEATURES_DIR, label + " " + ", ".join(repeated)))
    return errors


