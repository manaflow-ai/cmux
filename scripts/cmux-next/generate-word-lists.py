#!/usr/bin/env python3
"""Writes the word lists cmux compiles in instead of reading at run time.

Each list used to be a bundled text file read in a static initializer: a disk read on whichever thread asked first,
often the main thread, while every other first reader waited (once-blocking, p02-threads-122). They are compiled in
instead, as Chromium compiles its registry data into the binary (net/base/registry_controlled_domains/, generated from
effective_tld_names.dat by make_dafsa.py): no file is read at run time.

  tlds            CmuxNextBrowser's top-level domains (`TopLevelDomains.all`, the omnibar typo fix and the terminal's
                  link finder), from IANA's root zone file, which you download:
                    curl -o /tmp/tlds.txt https://data.iana.org/TLD/tlds-alpha-by-domain.txt
                    python3 scripts/cmux-next/generate-word-lists.py tlds /tmp/tlds.txt
  pairing-words   CmuxNextServer's BIP-39 English list (`PairingWords.list`, the pairing fingerprint words), from the
                  Rust crate's copy, so the app and `cmux_server_core::pairing` never disagree:
                    python3 scripts/cmux-next/generate-word-lists.py pairing-words

`--check` exits 1 when the Swift file differs from its source. Reads only its source and writes only its Swift file
(no network). Not a CI gate (Lawrence 2026-10-23); run it after a source changes.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCES = REPO / "Packages/macOS/CmuxNext/Sources"
TLDS_OUTPUT = SOURCES / "CmuxNextBrowser/Omnibox/TopLevelDomains+List.swift"
WORDS_SOURCE = REPO / "cmux-tui/crates/cmux-server-core/src/pairing/bip39-english.txt"
WORDS_OUTPUT = SOURCES / "CmuxNextServer/Model/PairingWords+List.swift"
PER_LINE = 10


def lines_of(text: str) -> tuple[str, list[str]]:
    """The file's first `#` comment and its other non-empty lines, lowercased, in file order."""
    version = next((line[1:].strip() for line in text.splitlines() if line.startswith("#")), "")
    found = [line.strip().lower() for line in text.splitlines() if line.strip() and not line.startswith("#")]
    bad = [word for word in found if not word.isascii() or not word.replace("-", "").isalnum()]
    if bad:
        raise SystemExit(f"not a plain ASCII label: {bad[:5]}")
    return version, found


def literal(words: list[str]) -> str:
    rows = [", ".join(f'"{word}"' for word in words[i:i + PER_LINE]) for i in range(0, len(words), PER_LINE)]
    return ",\n".join(f"        {row}" for row in rows) + ",\n"


def render_tlds(text: str) -> str:
    version, found = lines_of(text)
    return (
        "// Generated by scripts/cmux-next/generate-word-lists.py tlds from\n"
        "// https://data.iana.org/TLD/tlds-alpha-by-domain.txt; do not edit.\n"
        f"// {version}\n\n"
        "nonisolated extension TopLevelDomains {\n"
        f"    /// The IANA root zone's {len(found)} delegated top-level domains, lowercased (ASCII and punycode).\n"
        "    static let all: Set<String> = [\n"
        f"{literal(found)}"
        "    ]\n"
        "}\n"
    )


def render_words(text: str) -> str:
    _, found = lines_of(text)
    if len(found) != 2048:
        raise SystemExit(f"{WORDS_SOURCE} has {len(found)} words, not 2,048")
    return (
        "// Generated by scripts/cmux-next/generate-word-lists.py pairing-words from\n"
        "// cmux-tui/crates/cmux-server-core/src/pairing/bip39-english.txt; do not edit.\n\n"
        "nonisolated extension PairingWords {\n"
        "    /// The BIP-39 English list, 2,048 words in index order.\n"
        "    static let list: [String] = [\n"
        f"{literal(found)}"
        "    ]\n"
        "}\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("list", choices=("tlds", "pairing-words"))
    parser.add_argument("source", type=Path, nargs="?", help="tlds: IANA's tlds-alpha-by-domain.txt")
    parser.add_argument("--check", action="store_true", help="exit 1 when the Swift file differs from the source")
    parser.add_argument("--output", type=Path, help="write here instead of the Swift file in Sources")
    args = parser.parse_args(argv)
    if args.list == "tlds":
        if args.source is None:
            parser.error("tlds needs IANA's tlds-alpha-by-domain.txt")
        text, output = render_tlds(args.source.read_text(encoding="utf-8")), TLDS_OUTPUT
    else:
        text, output = render_words((args.source or WORDS_SOURCE).read_text(encoding="utf-8")), WORDS_OUTPUT
    output = args.output or output
    if args.check:
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if current != text:
            print(f"{output} is stale: run {Path(__file__).name} {args.list}", file=sys.stderr)
            return 1
        return 0
    output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
