#!/usr/bin/env python3
"""Measure acpmux session startup and time to the first agent message.

The bench uses a real acpmux daemon and a short prompt, then reads only the
session event timestamps. It never records the model response text. Every
session name is generated by this process and is purged in a finally block.

Example:
    acpmux-first-token-bench.py --acpmux acpmux --harness codex --runs 5

The JSON result is suitable for a CI artifact or a cloud-lane handoff. It
measures a warm VM/daemon unless the caller starts a fresh daemon separately;
it is intentionally explicit about that limit.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import subprocess
import sys
import time
import uuid
from pathlib import Path
from typing import Any, Sequence

SCHEMA = "cmux.acpmux.first-token.v1"


def percentile(values: Sequence[float], fraction: float) -> float | None:
    """Return a nearest-rank percentile, or None for an empty sample."""
    if not values:
        return None
    ordered = sorted(values)
    index = max(0, min(len(ordered) - 1, math.ceil(fraction * len(ordered)) - 1))
    return ordered[index]


def event_time(events: Sequence[dict[str, Any]], kind: str) -> int | None:
    """Read the first daemon wall-clock timestamp for an event kind."""
    for event in events:
        if event.get("kind") == kind and isinstance(event.get("at"), int | float):
            return int(event["at"])
    return None


def run_command(argv: Sequence[str], timeout: float) -> subprocess.CompletedProcess[str]:
    return subprocess.run(argv, capture_output=True, text=True, timeout=timeout, check=False)


def read_events(acpmux: str, name: str, timeout: float) -> list[dict[str, Any]]:
    result = run_command([acpmux, "session", "tail", name, "--last", "300", "--json"], timeout)
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or f"session tail exited {result.returncode}")
    events: list[dict[str, Any]] = []
    for line in result.stdout.splitlines():
        try:
            value = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(value, dict):
            events.append(value)
    return events


def one_run(acpmux: str, harness: str, cwd: Path, prompt: str, timeout: float) -> dict[str, Any]:
    name = f"cmux-first-token-{uuid.uuid4().hex[:12]}"
    started = time.monotonic()
    created = False
    try:
        command = [
            acpmux,
            "new",
            "--name",
            name,
            "--detach",
            "--cwd",
            str(cwd),
            "--model",
            harness,
            "--policy",
            "approve-all",
            "--timeout",
            str(max(1, math.ceil(timeout))),
            prompt,
        ]
        launch = run_command(command, timeout)
        created = launch.returncode == 0
        if not created:
            detail = (launch.stderr or launch.stdout).strip()
            raise RuntimeError(detail or f"session create exited {launch.returncode}")
        waited = run_command([acpmux, "wait", name, "--until", "done", "--timeout", str(math.ceil(timeout))], timeout + 5)
        if waited.returncode != 0:
            detail = (waited.stderr or waited.stdout).strip()
            raise RuntimeError(detail or f"session wait exited {waited.returncode}")
        events = read_events(acpmux, name, timeout)
        created_at = event_time(events, "created")
        turn_at = event_time(events, "turn_started")
        first_at = event_time(events, "agent_message_chunk")
        ended_at = event_time(events, "turn_end")
        if first_at is None or created_at is None or turn_at is None:
            raise RuntimeError("session completed without created, turn_started, and agent_message_chunk events")
        return {
            "name": name,
            "created_to_first_ms": first_at - created_at,
            "turn_to_first_ms": first_at - turn_at,
            "first_to_end_ms": None if ended_at is None else ended_at - first_at,
            "wall_ms": round((time.monotonic() - started) * 1000, 1),
        }
    except (OSError, subprocess.SubprocessError, RuntimeError) as error:
        return {"name": name, "error": str(error), "wall_ms": round((time.monotonic() - started) * 1000, 1)}
    finally:
        if created:
            # This name was generated above; never remove a caller-owned session.
            subprocess.run([acpmux, "session", "kill", "--purge", name], capture_output=True, text=True, check=False)


def result(runs: Sequence[dict[str, Any]]) -> dict[str, Any]:
    successful = [run for run in runs if isinstance(run.get("created_to_first_ms"), (int, float))]
    samples = [float(run["created_to_first_ms"]) for run in successful]
    turn_samples = [float(run["turn_to_first_ms"]) for run in successful if isinstance(run.get("turn_to_first_ms"), (int, float))]
    return {
        "schema": SCHEMA,
        "measurement": "warm_daemon_session_to_first_agent_message",
        "runs": list(runs),
        "summary": {
            "requested": len(runs),
            "successful": len(successful),
            "failed": len(runs) - len(successful),
            "created_to_first_ms": {
                "p50": percentile(samples, 0.50),
                "p95": percentile(samples, 0.95),
                "max": max(samples) if samples else None,
            },
            "turn_to_first_ms": {
                "p50": percentile(turn_samples, 0.50),
                "p95": percentile(turn_samples, 0.95),
                "max": max(turn_samples) if turn_samples else None,
            },
        },
    }


def self_test() -> None:
    assert percentile([], 0.5) is None
    assert percentile([4, 1, 3, 2], 0.5) == 2
    assert percentile([4, 1, 3, 2], 0.95) == 4
    events = [{"kind": "created", "at": 100}, {"kind": "created", "at": 200}]
    assert event_time(events, "created") == 100
    print("acpmux-first-token-bench self-test: ok")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--acpmux", default="acpmux", help="acpmux executable")
    parser.add_argument("--harness", default="codex", help="harness family/profile")
    parser.add_argument("--cwd", default=os.getcwd(), type=Path, help="session working directory")
    parser.add_argument("--prompt", default="Reply with exactly OK.")
    parser.add_argument("--runs", type=int, default=3)
    parser.add_argument("--timeout", type=float, default=90.0)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)
    if args.self_test:
        self_test()
        return 0
    if args.runs < 1:
        parser.error("--runs must be positive")
    if not args.cwd.is_dir():
        parser.error(f"--cwd is not a directory: {args.cwd}")
    runs = [one_run(args.acpmux, args.harness, args.cwd, args.prompt, args.timeout) for _ in range(args.runs)]
    print(json.dumps(result(runs), indent=2, sort_keys=True))
    return 0 if all("error" not in run for run in runs) else 1


if __name__ == "__main__":
    raise SystemExit(main())
