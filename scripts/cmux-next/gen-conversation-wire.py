#!/usr/bin/env python3
"""Write the Swift wire types of the daemon's conversation commands from the protocol schema.

The daemon's conversation commands (`conversation-*`, `cloud-conversation-*`, `cloud-inbox-*`,
`cloud-session-*`, `cloud-host-replica-*`) are described once, in cmux-tui/spec/sdk-schema.json,
which cmux-tui's tests emit from the Rust protocol types. This script writes the Swift request
and result structs of CmuxNextDaemon (Sources/CmuxNextDaemon/Conversations and
CloudConversations) from that schema, so the Swift is not a hand-kept mirror of the Rust.

scripts/cmux-next/conversation-wire.json says which Swift type is which command or schema
shape, and keeps the Swift-only facts the schema has no place for: the Swift names and integer
types, init defaults and clamps, decode fallbacks, doc comments and conformances. Every wire key
it names must exist in the schema shape it maps (or carry "extra": true), every key the schema
requires must be there, and a request may not leave a required key optional, so a protocol change
that breaks the Swift fails the build instead of the wire.

Types that do not map to a plain keyed struct (ops with custom encoders, enums with unknown
cases, event unions, requests that wrap another request's encoding) stay hand-written next to
the generated ones; computed properties and helpers live in hand-written extensions.

The Swift is not in git: the package's ConversationWireTypesPlugin build-tool plugin
(Packages/macOS/CmuxNext/Plugins/ConversationWireTypesPlugin) runs this script with --swift-out
into its work directory on every build. scripts/ci/generated-files.json lists it with status
"build".

  gen-conversation-wire.py --swift-out DIR   write the Swift files into DIR (flat)
  gen-conversation-wire.py --check           validate the spec against the schema; write nothing
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SCHEMA = REPO / "cmux-tui/spec/sdk-schema.json"
SPEC = REPO / "scripts/cmux-next/conversation-wire.json"
HEADER = (
    "// Generated by scripts/cmux-next/gen-conversation-wire.py from cmux-tui/spec/sdk-schema.json\n"
    "// and scripts/cmux-next/conversation-wire.json at build time. Do not edit; not in git.\n"
)

SWIFT_KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "func", "import", "init", "inout", "let",
    "operator", "protocol", "static", "struct", "subscript", "typealias", "var", "break", "case",
    "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat",
    "return", "switch", "where", "while", "as", "catch", "false", "is", "nil", "rethrows", "super",
    "self", "throw", "throws", "true", "try",
}
ACRONYMS = {"id": "ID", "ids": "IDs", "url": "URL", "urls": "URLs"}
INTEGERS = {"Int", "Int64", "Int32", "UInt", "UInt64", "UInt32", "UInt16"}
SCALARS = {
    "string": {"String"},
    "boolean": {"Bool"},
    "int32": INTEGERS, "int64": INTEGERS, "uint16": INTEGERS, "uint32": INTEGERS, "uint64": INTEGERS,
    "float32": {"Double", "Float"}, "float64": {"Double", "Float"},
}
STDLIB_SCALARS = INTEGERS | {"String", "Bool", "Double", "Float"}
DEFAULT_SCALAR = {
    "string": "String", "boolean": "Bool", "int32": "Int32", "int64": "Int64", "uint16": "UInt16",
    "uint32": "UInt32", "uint64": "UInt64", "float32": "Double", "float64": "Double",
}


class SpecError(Exception):
    pass


def swift_name(wire: str) -> str:
    parts = wire.split("_")
    out = [parts[0]] + [ACRONYMS.get(p, p[:1].upper() + p[1:]) for p in parts[1:]]
    return "".join(out)


def ident(name: str) -> str:
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def schema_shape(schema: dict, ref: str) -> dict:
    """`request:cmd`, `result:cmd`, `type:Name` or `event:name` to its object shape."""
    kind, _, name = ref.partition(":")
    try:
        if kind == "request":
            shape = schema["commands"][name]["request"]
        elif kind == "result":
            shape = schema["commands"][name]["result"]
        elif kind == "type":
            shape = schema["types"][name]
        elif kind == "event":
            shape = schema["events"][name]["payload"]
        else:
            raise SpecError(f"unknown schema reference {ref!r}")
    except KeyError:
        raise SpecError(f"{ref}: not in {SCHEMA.relative_to(REPO)}") from None
    if not isinstance(shape, dict) or shape.get("kind") != "object":
        raise SpecError(f"{ref}: not an object shape")
    return shape


def default_type(t: dict) -> str | None:
    kind = t.get("kind")
    if kind == "scalar":
        return DEFAULT_SCALAR.get(t["name"])
    if kind == "ref" and t["name"] != "JsonValue":
        return t["name"]
    if kind == "array":
        inner = default_type(t["items"])
        return f"[{inner}]" if inner else None
    return None


def base_matches(swift: str, t: dict) -> bool:
    """Loose check that a Swift type can carry the schema type (scalars and arrays of scalars)."""
    swift = swift.rstrip("?")
    kind = t.get("kind")
    if kind == "scalar":
        # A module type (ClientTransactionID) wraps a scalar with its own Codable; only the
        # standard library's scalars are checked.
        if swift not in STDLIB_SCALARS:
            return True
        return swift in SCALARS.get(t["name"], {swift})
    if kind == "array":
        return swift.startswith("[") and swift.endswith("]") and base_matches(swift[1:-1], t["items"])
    return True


class Field:
    def __init__(self, owner: str, wire: str, spec: dict, schema_field: dict | None, request: bool):
        self.wire = wire
        self.name = spec.get("name") or swift_name(wire)
        where = f"{owner}.{wire}"
        typ = spec.get("type")
        if typ is None:
            if schema_field is None:
                raise SpecError(f"{where}: an extra key needs a type")
            typ = default_type(schema_field["type"])
            if typ is None:
                raise SpecError(f"{where}: give its Swift type (schema type {schema_field['type']})")
            if schema_field["presence"] == "optional" or schema_field.get("nullable"):
                typ += "?"
        self.type = typ
        self.optional = typ.endswith("?")
        self.doc = spec.get("doc")
        self.default = spec.get("default")  # the init parameter's default
        self.fallback = spec.get("fallback")  # decode: decodeIfPresent(...) ?? fallback
        self.value = spec.get("value")  # stored initial value, not an init parameter
        self.set = spec.get("set")  # the init's assignment expression
        self.is_let = bool(spec.get("let"))
        if schema_field is not None:
            st = schema_field["type"]
            if not base_matches(typ, st):
                raise SpecError(f"{where}: Swift {typ} cannot carry schema {st}")
            required = schema_field["presence"] == "required"
            if request and required and self.optional:
                raise SpecError(f"{where}: the schema requires it; a request may not leave it optional")
            if not request and not required and not self.optional and self.fallback is None:
                raise SpecError(f"{where}: optional in the schema; make it optional or give a fallback")


def doc_lines(doc, indent: str) -> list[str]:
    if not doc:
        return []
    lines = doc if isinstance(doc, list) else [doc]
    return [f"{indent}/// {line}".rstrip() for line in lines]


def emit_type(schema: dict, entry: dict, capabilities: set[str]) -> list[str]:
    full = entry["name"]
    parent, _, name = full.rpartition(".")
    request = entry.get("request")
    ref = f"request:{request}" if request else entry.get("schema")
    shape = schema_shape(schema, ref) if ref else None
    schema_fields = shape["fields"] if shape else {}
    fields = []
    for wire, fspec in (entry.get("fields") or {}).items():
        fspec = fspec or {}
        sf = schema_fields.get(wire)
        if sf is None and not fspec.get("extra"):
            raise SpecError(f"{full}.{wire}: not a key of {ref}; mark it \"extra\": true if the schema lacks it")
        fields.append(Field(full, wire, fspec, sf, bool(request)))
    if shape is not None:
        named = {f.wire for f in fields}
        for wire, sf in schema_fields.items():
            if wire in named or wire in entry.get("skip", ()):
                continue
            if sf["type"].get("kind") == "literal":
                continue
            if request and sf["presence"] == "required":
                raise SpecError(f"{full}: the schema's required key {wire!r} is missing")
            if not request and sf["presence"] == "required" and not entry.get("partial"):
                raise SpecError(f"{full}: the schema's required key {wire!r} is not read "
                                "(add it, list it in \"skip\", or mark the type \"partial\")")

    conforms = list(entry.get("conforms") or (["DaemonRequest"] if request else ["Decodable", "Sendable"]))
    ind = "    " if parent else ""
    out: list[str] = []
    out += doc_lines(entry.get("doc"), ind)
    out.append(f"{ind}public struct {name}: {', '.join(conforms)} {{")
    i2 = ind + "    "
    if request:
        cap = entry.get("capability")
        out.append(f"{i2}public typealias Response = {entry['response']}")
        out.append(f'{i2}public static let command = "{request}"')
        if cap is not None:
            if cap.startswith("="):
                out.append(f'{i2}public static let requiredCapability: String? = "{cap[1:]}"')
            else:
                if capabilities and cap not in capabilities:
                    raise SpecError(f"{full}: DaemonCapability has no case {cap!r}")
                out.append(f"{i2}public static let requiredCapability: String? = DaemonCapability.{cap}.rawValue")
    for sname, sdef in (entry.get("statics") or {}).items():
        if isinstance(sdef, dict):
            out += doc_lines(sdef.get("doc"), i2)
            sdef = sdef["value"]
        out.append(f"{i2}public static let {sname} = {sdef}")
    for f in fields:
        out += doc_lines(f.doc, i2)
        kw = "let" if f.is_let else "var"
        init_value = f" = {f.value}" if f.value is not None else ""
        out.append(f"{i2}public {kw} {ident(f.name)}: {f.type}{init_value}")

    init = entry.get("init")
    if request and init is None:
        init = "public"
    if init:
        params = [f for f in fields if f.value is None]
        sig = ", ".join(
            f"{ident(f.name)}: {f.type}" + (f" = {f.default}" if f.default is not None else "") for f in params)
        out.append("")
        if not params:
            out.append(f"{i2}{init} init() {{}}")
        else:
            out.append(f"{i2}{init} init({sig}) {{")
            for f in params:
                out.append(f"{i2}    self.{f.name} = {f.set or ident(f.name)}")
            out.append(f"{i2}}}")
    if fields:
        out.append("")
        out.append(f"{i2}enum CodingKeys: String, CodingKey {{")
        for f in fields:
            out.append(f'{i2}    case {ident(f.name)} = "{f.wire}"')
        out.append(f"{i2}}}")
    if not request and any(f.fallback is not None for f in fields):
        out.append("")
        out.append(f"{i2}public init(from decoder: any Decoder) throws {{")
        out.append(f"{i2}    let c = try decoder.container(keyedBy: CodingKeys.self)")
        for f in fields:
            base = f.type.rstrip("?")
            if f.optional or f.fallback is not None:
                expr = f"try c.decodeIfPresent({base}.self, forKey: .{ident(f.name)})"
                if f.fallback is not None:
                    expr += f" ?? {f.fallback}"
            else:
                expr = f"try c.decode({base}.self, forKey: .{ident(f.name)})"
            out.append(f"{i2}    self.{f.name} = {expr}")
        out.append(f"{i2}}}")
    out.append(f"{ind}}}")
    if parent:
        out = [f"extension {parent} {{"] + out + ["}"]
    return out


def daemon_capabilities() -> set[str]:
    path = REPO / "Packages/macOS/CmuxNext/Sources/CmuxNextDaemon/Connection/DaemonEndpoint.swift"
    try:
        text = path.read_text()
    except OSError:
        return set()
    m = re.search(r"enum DaemonCapability[^{]*\{(.*?)\n\}", text, re.S)
    if not m:
        return set()
    return set(re.findall(r"^\s*case\s+(\w+)", m.group(1), re.M))


def render(schema: dict, spec: dict) -> dict[str, str]:
    capabilities = daemon_capabilities()
    files: dict[str, str] = {}
    seen: set[str] = set()
    for file_name, entries in spec["files"].items():
        if not re.fullmatch(r"[A-Za-z0-9+]+", file_name):
            raise SpecError(f"{file_name}: a file name is letters, digits and +")
        chunks = []
        for entry in entries:
            if entry["name"] in seen:
                raise SpecError(f"{entry['name']}: listed twice")
            seen.add(entry["name"])
            chunks.append("\n".join(emit_type(schema, entry, capabilities)))
        files[f"ConversationWire+{file_name}.generated.swift"] = HEADER + "\n" + "\n\n".join(chunks) + "\n"
    return files


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--swift-out", type=Path, help="write the Swift files into this directory")
    mode.add_argument("--check", action="store_true", help="validate the spec against the schema")
    args = parser.parse_args(argv)
    try:
        files = render(json.loads(SCHEMA.read_text()), json.loads(SPEC.read_text()))
    except SpecError as error:
        print(f"gen-conversation-wire.py: {error}", file=sys.stderr)
        return 1
    if args.check:
        print(f"gen-conversation-wire.py: {len(files)} files OK")
        return 0
    out: Path = args.swift_out
    out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        path = out / name
        if not path.exists() or path.read_text() != text:  # keep mtimes stable for incremental builds
            path.write_text(text)
    for stale in out.glob("ConversationWire+*.generated.swift"):
        if stale.name not in files:
            stale.unlink()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
