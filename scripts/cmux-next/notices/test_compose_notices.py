"""Tests for compose_notices.py (stdlib unittest)."""

from __future__ import annotations

from pathlib import Path
import sys
import unittest

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import compose_notices  # noqa: E402

HAND = "# Third-Party Licenses\n\n## Sparkle\n\nSparkle text\n"
MIT = "MIT License\n\nCopyright (c) someone\n"
APACHE = "Apache License\nVersion 2.0\n"
ODD = "a text with ``` inside\n"


def section(section_id: str, crates: list[tuple[str, str, str]], texts: dict[str, str]) -> str:
    out = [f"<!-- notices-section: {section_id} -->", f"## Rust crates: {section_id}", "", "Generated by test.", ""]
    out += [f"- **{name}**: {lic}. Files: `LICENSE` (text {sha})" for name, lic, sha in crates]
    out += ["", f"### License texts (Rust crates: {section_id})", ""]
    for sha, text in sorted(texts.items()):
        fence = "````" if "```" in text else "```"
        out += [f"#### Text {sha}", "", fence + "text", text.rstrip("\n"), fence, ""]
    return "\n".join(out) + "\n"


A = section("rust-a", [("a 1.0.0", "MIT", "aaaaaaaaaaaa")], {"aaaaaaaaaaaa": MIT, "cccccccccccc": ODD})
B = section("rust-b", [("b 2.0.0", "MIT OR Apache-2.0", "aaaaaaaaaaaa")], {"aaaaaaaaaaaa": MIT, "bbbbbbbbbbbb": APACHE})


class ComposeNoticesTest(unittest.TestCase):
    def test_hand_written_is_byte_for_byte_with_markers(self) -> None:
        text = compose_notices.compose(HAND, [])
        self.assertIn("<!-- notices-section: manual-sparkle -->\n## Sparkle\n\nSparkle text\n", text)
        self.assertEqual(text.replace("<!-- notices-section: manual-sparkle -->\n", "").split("-->\n", 1)[1], HAND)

    def test_identical_texts_across_sections_are_printed_once(self) -> None:
        text = compose_notices.compose(HAND, [A, B])
        self.assertEqual(text.count("MIT License\n\nCopyright (c) someone"), 1)
        self.assertEqual(text.count("Apache License\nVersion 2.0"), 1)
        self.assertEqual(text.count("a text with ``` inside"), 1)
        self.assertIn("<!-- notices-section: rust-a -->", text)
        self.assertIn("<!-- notices-section: rust-b -->", text)
        self.assertIn("- **b 2.0.0**: MIT OR Apache-2.0. Files: `LICENSE` (text aaaaaaaaaaaa)", text)
        shared = text.index("<!-- notices-section: rust-license-texts -->")
        self.assertGreater(shared, text.index("<!-- notices-section: rust-b -->"))
        self.assertLess(text.index("#### Text aaaaaaaaaaaa"), text.index("#### Text bbbbbbbbbbbb"))

    def test_output_is_byte_stable_and_order_independent_for_texts(self) -> None:
        self.assertEqual(compose_notices.compose(HAND, [A, B]), compose_notices.compose(HAND, [A, B]))
        tail_ab = compose_notices.compose(HAND, [A, B]).split("rust-license-texts -->", 1)[1]
        tail_ba = compose_notices.compose(HAND, [B, A]).split("rust-license-texts -->", 1)[1]
        self.assertEqual(tail_ab, tail_ba)

    def test_two_texts_with_one_id_fail(self) -> None:
        clash = section("rust-c", [("c 1.0.0", "MIT", "aaaaaaaaaaaa")], {"aaaaaaaaaaaa": "another text\n"})
        with self.assertRaises(SystemExit):
            compose_notices.compose(HAND, [A, clash])


if __name__ == "__main__":
    unittest.main()
