"""The generated notices section for the Ghostty themes the app bundles.

  ghostty_themes_notice.py [--root REPO] [--out FILE]

The app copies Resources/ghostty/themes (bundle-ghostty-resources.sh), a
snapshot of an iTerm2-Color-Schemes release. ghostty-themes.json records that
release, its commit and archive, and a digest of the theme files; the section
prints the release and the pinned license text (the shared Ghostty
pinned-licenses manifest entry it names, checked against its sha256). Changed
themes with an old record fail, so a theme update must also update the record.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
PINNED = Path("cmux-tui/build-support/notices/ghostty/pinned-licenses")


class ThemesError(RuntimeError):
    pass


def tree_digest(root: Path) -> tuple[int, str]:
    value = hashlib.sha256()
    count = 0
    for path in sorted(root.rglob("*")):
        if path.is_file():
            count += 1
            value.update(path.relative_to(root).as_posix().encode() + b"\0" + hashlib.sha256(path.read_bytes()).hexdigest().encode() + b"\n")
    return count, value.hexdigest()


def render(repo: Path) -> str:
    record = json.loads((repo / "scripts/cmux-next/notices/ghostty-themes.json").read_text(encoding="utf-8"))
    count, digest = tree_digest(repo / record["source"])
    if (count, digest) != (record["files"], record["tree_sha256"]):
        raise ThemesError(
            f"{record['source']} has {count} files (digest {digest}); ghostty-themes.json records "
            f"{record['files']} ({record['tree_sha256']}). Update the record to the iTerm2-Color-Schemes "
            "release the new themes come from."
        )
    manifest = json.loads((repo / PINNED / "MANIFEST.json").read_text(encoding="utf-8"))
    texts = []
    for item in manifest["packages"][record["license"]]["files"]:
        data = (repo / PINNED / item["path"]).read_bytes()
        if hashlib.sha256(data).hexdigest() != item["sha256"]:
            raise ThemesError(f"pinned text {item['path']} does not match its sha256")
        texts.append((item, data.decode("utf-8")))
    out = [
        "<!-- notices-section: ghostty-themes -->",
        "## Ghostty themes",
        "",
        f"Generated by scripts/cmux-next/notices/ghostty_themes_notice.py. The {record['files']} color themes in "
        f"`Contents/Resources/ghostty/themes` come from iTerm2-Color-Schemes {record['release']} "
        f"(https://github.com/mbadolato/iTerm2-Color-Schemes, commit {record['commit']}; archive {record['archive']}).",
        "",
    ]
    for item, text in texts:
        fence = "````" if "```" in text else "```"
        out += [f"Source of this text: {item['upstream']}", "", fence + "text", text.rstrip("\n"), fence, ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=HERE.parents[2])
    parser.add_argument("--out", type=Path)
    args = parser.parse_args(argv)
    try:
        text = render(args.root)
    except (ThemesError, OSError, KeyError) as error:
        print(f"ghostty_themes_notice: error: {error}", file=sys.stderr)
        return 1
    if args.out:
        args.out.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
