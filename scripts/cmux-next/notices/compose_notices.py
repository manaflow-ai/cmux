"""Compose THIRD_PARTY_LICENSES.md from the hand-written input and the
generated sections.

  compose_notices.py --hand-written hand-written.md --section FILE ... --out OUT [--check]

The hand-written input is copied byte for byte; the tool only adds a line
`<!-- notices-section: manual-<slug of the heading> -->` before each `## `
heading, so bundle-map.json can name it. Generated sections (rust_notices.py
markdown, which carries its own marker) follow in the order given.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

HEADER = (
    "<!-- Generated by scripts/cmux-next/generate-third-party-notices.sh; do not edit.\n"
    "     Hand-written sections: scripts/cmux-next/notices/hand-written.md (owned by the license review). -->\n"
)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def compose(hand_written: str, sections: list[str]) -> str:
    out = [HEADER]
    seen: set[str] = set()
    for line in hand_written.splitlines(keepends=True):
        if line.startswith("## "):
            marker = "manual-" + slug(line[3:])
            if marker in seen:
                raise SystemExit(f"compose_notices: two hand-written sections are named {marker}")
            seen.add(marker)
            out.append(f"<!-- notices-section: {marker} -->\n")
        out.append(line)
    if not hand_written.endswith("\n"):
        out.append("\n")
    for section in sections:
        out += ["\n---\n\n", section]
    return "".join(out)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--hand-written", type=Path, required=True)
    parser.add_argument("--section", type=Path, action="append", default=[])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = compose(args.hand_written.read_text(encoding="utf-8"), [s.read_text(encoding="utf-8") for s in args.section])
    if args.check:
        if not args.out.is_file() or args.out.read_text(encoding="utf-8") != text:
            print(f"compose_notices: {args.out} is stale; run scripts/cmux-next/generate-third-party-notices.sh", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
