#!/usr/bin/env python3
"""Generate and validate the cmux-next coordination ledger index."""

from __future__ import annotations

import argparse
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[2]
COORDINATION = ROOT / "plans" / "cmux-next"
LANES = COORDINATION / "coordination"
STUB = COORDINATION / "COORDINATION.md"
INDEX = LANES / "INDEX.md"
EXPECTED_STUB = "See plans/cmux-next/coordination/INDEX.md for the generated coordination ledger.\n"


def lane_files() -> list[Path]:
    return sorted(path for path in LANES.glob("*.md") if path.name != INDEX.name)


def render_index(paths: list[Path]) -> str:
    lines = [
        "# cmux-next coordination index",
        "",
        "Generated by `scripts/cmux-next/generate-coordination-index.py`; do not edit this file.",
        "",
        "The coordination ledger is split by lane so unrelated updates do not conflict.",
        "Read the lane file before changing a shared surface. Newest entries remain first within each lane.",
        "",
        "## Lane files",
        "",
    ]
    lines.extend(f"- [{path.stem}]({path.name})" for path in paths)
    return "\n".join(lines) + "\n"


def validate(paths: list[Path]) -> list[str]:
    errors: list[str] = []
    if STUB.read_text() != EXPECTED_STUB:
        errors.append(f"{STUB.relative_to(ROOT)} must contain exactly the one-line generated-index stub")
    if not paths:
        errors.append(f"{LANES.relative_to(ROOT)} must contain at least one lane file")
    seen: set[str] = set()
    for path in paths:
        if path.stem in seen:
            errors.append(f"duplicate lane name: {path.stem}")
        seen.add(path.stem)
        first_line = path.read_text().splitlines()[:1]
        expected = f"# Lane: {path.stem}"
        if first_line != [expected]:
            errors.append(f"{path.relative_to(ROOT)} must start with {expected!r}")
    if INDEX.read_text() != render_index(paths):
        errors.append(f"{INDEX.relative_to(ROOT)} is stale; run {Path(__file__).relative_to(ROOT)} --write")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()

    paths = lane_files()
    if args.write:
        INDEX.write_text(render_index(paths))
        return 0

    errors = validate(paths)
    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        return 1
    print(f"coordination index is current ({len(paths)} lanes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
