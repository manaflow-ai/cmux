#!/usr/bin/env python3
"""Linux tier progress report: targets built, tests executed and build times, from receipts only.

    tier-report.py [RECEIPT ...] [--json] [--write-doc FILE]

RECEIPT is a file written by `swift-tier.sh --receipt` or `swift-shared.sh --receipt`
(p15-oracle-004), or a directory of them (every `*.json` inside). With no RECEIPT the report
reads /tmp/oracle/linux-*.json, the paths of the plan's done checks.

Prints a Markdown report: one progress row per receipt (oldest first), then the done checks
1-3 of plans/cmux-next/chrome-parity/p15-oracle.md section 5 for the newest receipt of each
runner. `--write-doc FILE` also puts the report between the linux-tier-report markers of FILE
(plans/cmux-next/oracle-DESIGN.md). `--json` prints the same numbers as JSON instead.

This is a report, not a gate: an unmet done check never changes the exit status. Exit 0 when the
report was written, 2 when a receipt cannot be read or does not match the contract below.
Every number comes from a receipt field; nothing is counted from logs, source or the checkout.
The report names each receipt with its sha256, so a reader can check any number with jq.

Receipt contract (schema cmux-linux-swift-v1, written by p15-oracle-004):
    {"schema": "cmux-linux-swift-v1",
     "runner": "tier" | "shared",
     "sha": str, "toolchain": str, "startedAt": ISO 8601 str,
     "sanitize": null | "thread" | "address",
     "fallback": null | str            (tier only: why the waves 0-1 fallback is used),
     "clean": bool                     (the build started from an empty scratch path),
     "buildMs": int, "testMs": int,
     "units": [{"name": str,
                "kind": "source" | "test" | "package"   (package: swift-shared.sh),
                "status": "built" | "failed" | "skipped",
                "tests": {"executed", "passed", "failed", "skipped", "linuxExpected": int}
                         (optional; executed = passed + failed; linuxExpected counts the
                          failures that a [ linux ] Expectations line covers)}],
     "incremental": [{"target": str, "ms": int}],          (--measure-incremental)
     "errorsQueue": null | {"errors": int, "files": int}}  (--errors-queue)

Chrome reference (chromium/src): base/test/launcher/test_results_tracker.cc
(SaveSummaryAsJSON) writes the results summary that the bots read, and
testing/merge_scripts/standard_gtest_merge.py merges shard summaries; the numbers on the
dashboards come from those files, never from the console log. This report does the same with
the runner receipts.

Stdlib only, Python 3.9+, safe under `python3 -I`.
"""

from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

SCHEMA = "cmux-linux-swift-v1"
DEFAULT_GLOB = "/tmp/oracle/linux-*.json"
BEGIN_MARKER = (
    "<!-- linux-tier-report:begin (generated by scripts/cmux-next/linux/tier-report.py "
    "--write-doc; do not edit) -->"
)
END_MARKER = "<!-- linux-tier-report:end -->"

# Targets of p15-oracle.md section 5 (done checks 1-3).
TIER_SOURCE_TARGETS = 30
TIER_TEST_TARGETS = 15
TIER_TESTS = 1500
TIER_FALLBACK_TESTS = 1000
SHARED_PACKAGES = 26
SHARED_TESTS = 2900
LINUX_SHARE_MAX = 0.05
CLEAN_BUILD_MS = 600_000
INCREMENTAL_TARGET = "CmuxNextTerminalGeometry"
INCREMENTAL_MS = 30_000

RUNNERS = ("tier", "shared")
KINDS = ("source", "test", "package")
STATUSES = ("built", "failed", "skipped")
SANITIZERS = (None, "thread", "address")
TEST_FIELDS = ("executed", "passed", "failed", "skipped", "linuxExpected")


class ReportError(Exception):
    """A receipt or doc that cannot be read, or a receipt off the contract; names the file and field."""


@dataclass
class Summary:
    path: str
    sha256: str
    runner: str
    sha: str
    toolchain: str
    started_at: str
    sanitize: Optional[str]
    fallback: Optional[str]
    clean: bool
    build_ms: int
    test_ms: int
    built: Dict[str, int]
    failed_units: List[str]
    tests: Dict[str, int]
    max_linux_share: Optional[float]
    max_linux_unit: Optional[str]
    incremental: Dict[str, int]
    errors_queue: Optional[Dict[str, int]]
    per_unit_tests: Dict[str, int] = field(default_factory=dict)


def _need(obj: Dict[str, Any], key: str, kinds: tuple, where: str) -> Any:
    if key not in obj:
        raise ReportError(f"{where}: missing {key!r}")
    value = obj[key]
    # bool is an int subclass; a count field must not accept true/false.
    if isinstance(value, bool) and bool not in kinds:
        raise ReportError(f"{where}.{key}: expected {_names(kinds)}, got {value!r}")
    if not isinstance(value, kinds):
        raise ReportError(f"{where}.{key}: expected {_names(kinds)}, got {value!r}")
    if isinstance(value, int) and not isinstance(value, bool) and value < 0:
        raise ReportError(f"{where}.{key}: negative {value}")
    return value


def _names(kinds: tuple) -> str:
    return " or ".join("null" if k is type(None) else k.__name__ for k in kinds)


def _one_of(value: Any, allowed: tuple, where: str) -> Any:
    if value not in allowed:
        raise ReportError(f"{where}: {value!r} is not one of {list(allowed)}")
    return value


def summarize(path: str) -> Summary:
    try:
        raw = Path(path).read_bytes()
    except OSError as error:
        raise ReportError(f"{path}: {error.strerror}") from error
    try:
        data = json.loads(raw)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ReportError(f"{path}: not JSON ({error})") from error
    if not isinstance(data, dict):
        raise ReportError(f"{path}: the receipt is not a JSON object")
    where = path
    schema = _need(data, "schema", (str,), where)
    if schema != SCHEMA:
        raise ReportError(f"{where}.schema: {schema!r}, this report reads {SCHEMA!r}")
    runner = _one_of(_need(data, "runner", (str,), where), RUNNERS, f"{where}.runner")
    sanitize = _one_of(_need(data, "sanitize", (str, type(None)), where), SANITIZERS,
                       f"{where}.sanitize")
    fallback = _need(data, "fallback", (str, type(None)), where) if "fallback" in data else None

    built = {kind: 0 for kind in KINDS}
    failed_units: List[str] = []
    totals = {name: 0 for name in TEST_FIELDS}
    per_unit: Dict[str, int] = {}
    max_share: Optional[float] = None
    max_unit: Optional[str] = None
    seen = set()
    for index, unit in enumerate(_need(data, "units", (list,), where)):
        uwhere = f"{where}.units[{index}]"
        if not isinstance(unit, dict):
            raise ReportError(f"{uwhere}: not an object")
        name = _need(unit, "name", (str,), uwhere)
        kind = _one_of(_need(unit, "kind", (str,), uwhere), KINDS, f"{uwhere}.kind")
        if (kind, name) in seen:
            raise ReportError(f"{uwhere}: {kind} unit {name!r} appears twice")
        seen.add((kind, name))
        status = _one_of(_need(unit, "status", (str,), uwhere), STATUSES, f"{uwhere}.status")
        if status == "built":
            built[kind] += 1
        elif status == "failed":
            failed_units.append(name)
        if "tests" not in unit:
            continue
        tests = _need(unit, "tests", (dict,), uwhere)
        twhere = f"{uwhere}.tests"
        counts = {key: _need(tests, key, (int,), twhere) for key in TEST_FIELDS}
        if counts["passed"] + counts["failed"] != counts["executed"]:
            raise ReportError(f"{twhere}: passed {counts['passed']} + failed {counts['failed']}"
                               f" != executed {counts['executed']}")
        if counts["linuxExpected"] > counts["failed"]:
            raise ReportError(f"{twhere}: linuxExpected {counts['linuxExpected']}"
                               f" > failed {counts['failed']}")
        for key in TEST_FIELDS:
            totals[key] += counts[key]
        per_unit[name] = counts["executed"]
        if counts["executed"]:
            share = counts["linuxExpected"] / counts["executed"]
            if max_share is None or share > max_share:
                max_share, max_unit = share, name

    incremental: Dict[str, int] = {}
    for index, item in enumerate(data.get("incremental") or []):
        iwhere = f"{where}.incremental[{index}]"
        if not isinstance(item, dict):
            raise ReportError(f"{iwhere}: not an object")
        incremental[_need(item, "target", (str,), iwhere)] = _need(item, "ms", (int,), iwhere)

    queue = data.get("errorsQueue")
    errors_queue = None
    if queue is not None:
        if not isinstance(queue, dict):
            raise ReportError(f"{where}.errorsQueue: not an object")
        errors_queue = {key: _need(queue, key, (int,), f"{where}.errorsQueue")
                        for key in ("errors", "files")}

    return Summary(
        path=path,
        sha256=hashlib.sha256(raw).hexdigest(),
        runner=runner,
        sha=_need(data, "sha", (str,), where),
        toolchain=_need(data, "toolchain", (str,), where),
        started_at=_need(data, "startedAt", (str,), where),
        sanitize=sanitize,
        fallback=fallback,
        clean=_need(data, "clean", (bool,), where),
        build_ms=_need(data, "buildMs", (int,), where),
        test_ms=_need(data, "testMs", (int,), where),
        built=built,
        failed_units=sorted(failed_units),
        tests=totals,
        max_linux_share=max_share,
        max_linux_unit=max_unit,
        incremental=incremental,
        errors_queue=errors_queue,
        per_unit_tests=per_unit,
    )


def receipt_paths(args: List[str]) -> List[str]:
    if not args:
        return sorted(glob.glob(DEFAULT_GLOB))
    paths: List[str] = []
    for arg in args:
        if os.path.isdir(arg):
            paths.extend(sorted(glob.glob(os.path.join(arg, "*.json"))))
        else:
            paths.append(arg)
    return paths


@dataclass
class Check:
    name: str
    target: str
    value: str
    met: bool


def _seconds(ms: int) -> str:
    return f"{ms / 1000:.1f} s"


def _share(summary: Summary) -> str:
    if summary.max_linux_share is None:
        return "-"
    return f"{summary.max_linux_share * 100:.1f} % ({summary.max_linux_unit})"


def _share_ok(summary: Summary) -> bool:
    return summary.max_linux_share is None or summary.max_linux_share <= LINUX_SHARE_MAX


def done_checks(summary: Summary) -> List[Check]:
    tests = summary.tests["executed"]
    unexpected = summary.tests["failed"] - summary.tests["linuxExpected"]
    checks: List[Check] = []
    if summary.runner == "tier":
        need_tests = TIER_FALLBACK_TESTS if summary.fallback else TIER_TESTS
        checks += [
            Check("1 source targets built", f">= {TIER_SOURCE_TARGETS}",
                  str(summary.built["source"]), summary.built["source"] >= TIER_SOURCE_TARGETS),
            Check("1 test targets built", f">= {TIER_TEST_TARGETS}",
                  str(summary.built["test"]), summary.built["test"] >= TIER_TEST_TARGETS),
            Check("1 tests executed" + (" (fallback)" if summary.fallback else ""),
                  f">= {need_tests}", str(tests), tests >= need_tests),
        ]
    else:
        checks += [
            Check("2 packages built", f">= {SHARED_PACKAGES}", str(summary.built["package"]),
                  summary.built["package"] >= SHARED_PACKAGES),
            Check("2 tests executed", f">= {SHARED_TESTS}", str(tests), tests >= SHARED_TESTS),
        ]
    number = "1" if summary.runner == "tier" else "2"
    checks += [
        Check(f"{number} failures outside [ linux ]", "0", str(unexpected),
              unexpected == 0 and not summary.failed_units),
        Check(f"{number} largest [ linux ] share", f"<= {LINUX_SHARE_MAX * 100:.0f} %",
              _share(summary), _share_ok(summary)),
    ]
    if summary.runner == "tier":
        clean_ok = summary.clean and summary.sanitize is None
        checks.append(Check(
            "3 clean tier build", f"< {_seconds(CLEAN_BUILD_MS)}",
            _seconds(summary.build_ms) if clean_ok else "not a clean, unsanitized build",
            clean_ok and summary.build_ms < CLEAN_BUILD_MS))
        inc = summary.incremental.get(INCREMENTAL_TARGET)
        checks.append(Check(
            f"3 incremental {INCREMENTAL_TARGET}", f"< {_seconds(INCREMENTAL_MS)}",
            _seconds(inc) if inc is not None else "not measured",
            inc is not None and inc < INCREMENTAL_MS))
    return checks


def latest_by_runner(summaries: List[Summary]) -> Dict[str, Summary]:
    """Newest unsanitized receipt per runner; sanitizer runs are slower by design."""
    latest: Dict[str, Summary] = {}
    for summary in sorted(summaries, key=lambda s: s.started_at):
        if summary.sanitize is None:
            latest[summary.runner] = summary
    return latest


def render_markdown(summaries: List[Summary]) -> str:
    lines: List[str] = []
    if not summaries:
        lines += ["No receipt yet. Run `scripts/cmux-next/linux/swift-tier.sh --all --receipt "
                  "/tmp/oracle/linux-tier.json` (and `swift-shared.sh`), then "
                  "`python3 -I scripts/cmux-next/linux/tier-report.py --write-doc "
                  "plans/cmux-next/oracle-DESIGN.md`.", ""]
        return "\n".join(lines)
    ordered = sorted(summaries, key=lambda s: s.started_at)
    lines += [
        "Generated from runner receipts only (`python3 -I scripts/cmux-next/linux/tier-report.py`).",
        "A report, not a gate.",
        "",
        "| Started | Runner | SHA | Sanitizer | Source built | Test built | Packages built "
        "| Failed units | Tests executed | Passed | Failed | [ linux ] | Build | Tests | "
        "Incremental | Queue errors |",
        "| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: "
        "| ---: | ---: | --- | ---: |",
    ]
    for s in ordered:
        incremental = ", ".join(f"{t} {_seconds(ms)}" for t, ms in sorted(s.incremental.items()))
        queue = str(s.errors_queue["errors"]) if s.errors_queue else "-"
        lines.append(
            f"| {s.started_at} | {s.runner} | `{s.sha[:12]}` | {s.sanitize or '-'} "
            f"| {s.built['source']} | {s.built['test']} | {s.built['package']} "
            f"| {len(s.failed_units)} | {s.tests['executed']} | {s.tests['passed']} "
            f"| {s.tests['failed']} | {s.tests['linuxExpected']} "
            f"| {_seconds(s.build_ms)}{'' if s.clean else ' (warm)'} | {_seconds(s.test_ms)} "
            f"| {incremental or '-'} | {queue} |")
    for runner, s in sorted(latest_by_runner(ordered).items()):
        lines += ["", f"### Done checks, newest {runner} receipt (`{s.sha[:12]}`, {s.started_at})",
                  ""]
        if s.fallback:
            lines += [f"Fallback stated in the receipt: {s.fallback}", ""]
        lines += ["| Check | Target | Value | Met |", "| --- | --- | --- | --- |"]
        for check in done_checks(s):
            lines.append(f"| {check.name} | {check.target} | {check.value} "
                         f"| {'yes' if check.met else 'no'} |")
        if s.failed_units:
            lines += ["", "Failed units: " + ", ".join(f"`{u}`" for u in s.failed_units)]
    lines += ["", "Receipts:", ""]
    for s in ordered:
        lines.append(f"- `{s.path}` sha256 `{s.sha256}`, toolchain `{s.toolchain}`")
    lines.append("")
    return "\n".join(lines)


def render_json(summaries: List[Summary]) -> str:
    ordered = sorted(summaries, key=lambda s: s.started_at)
    latest = latest_by_runner(ordered)
    payload = {
        "receipts": [{
            "path": s.path, "sha256": s.sha256, "runner": s.runner, "sha": s.sha,
            "toolchain": s.toolchain, "startedAt": s.started_at, "sanitize": s.sanitize,
            "fallback": s.fallback, "clean": s.clean, "buildMs": s.build_ms,
            "testMs": s.test_ms, "built": s.built, "failedUnits": s.failed_units,
            "tests": s.tests, "maxLinuxShare": s.max_linux_share,
            "maxLinuxUnit": s.max_linux_unit, "incremental": s.incremental,
            "errorsQueue": s.errors_queue, "testsPerUnit": s.per_unit_tests,
        } for s in ordered],
        "doneChecks": {runner: [{"name": c.name, "target": c.target, "value": c.value,
                                 "met": c.met} for c in done_checks(s)]
                       for runner, s in sorted(latest.items())},
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def write_doc(doc: Path, report: str) -> None:
    try:
        text = doc.read_text(encoding="utf-8")
    except OSError as error:
        raise ReportError(f"{doc}: {error.strerror}") from error
    begin = text.find(BEGIN_MARKER)
    end = text.find(END_MARKER)
    if begin < 0 or end < begin:
        raise ReportError(f"{doc}: no linux-tier-report begin/end markers")
    body = report if report.endswith("\n") else report + "\n"
    new = text[:begin + len(BEGIN_MARKER)] + "\n" + body + text[end:]
    if new != text:
        doc.write_text(new, encoding="utf-8")


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Linux tier progress report from swift-tier.sh / swift-shared.sh receipts.")
    parser.add_argument("receipts", nargs="*", help=f"receipt files or directories "
                                                     f"(default {DEFAULT_GLOB})")
    parser.add_argument("--json", action="store_true", help="print JSON, not Markdown")
    parser.add_argument("--write-doc", type=Path, metavar="FILE",
                        help="replace the report between the markers of FILE")
    args = parser.parse_args(argv)
    try:
        summaries = [summarize(path) for path in receipt_paths(args.receipts)]
        report = render_markdown(summaries)
        if args.write_doc is not None:
            write_doc(args.write_doc, report)
    except ReportError as error:
        print(f"tier-report.py: {error}", file=sys.stderr)
        return 2
    sys.stdout.write(render_json(summaries) if args.json else report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
