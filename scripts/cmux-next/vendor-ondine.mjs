#!/usr/bin/env node
// Rebuilds Resources/markdown-viewer/ondine.min.js, the vendored Ondine Mermaid compiler
// (https://github.com/wevm/ondine, MIT) the markdown page loads as the host library `__lib/ondine.js`.
//
// The package is pinned to one exact version and tarball digest; the script refuses any other
// bytes. It never runs the package's code or install scripts: it extracts the tarball into an
// empty temporary directory and rewrites three ES modules (the WebAssembly glue, the renderer and
// the size-optimized `all` module as base64) into one classic script that sets `globalThis.ondine`.
//
//   curl -sSLo /tmp/ondine.tgz https://registry.npmjs.org/ondine/-/ondine-0.0.1.tgz
//   node scripts/cmux-next/vendor-ondine.mjs /tmp/ondine.tgz
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "0.0.1";
// npm `dist.integrity` of ondine@0.0.1 (SLSA provenance: wevm/ondine main@f662aa795b91).
const INTEGRITY =
  "sha512-Ur5h6bYx9lu0VNDszo6B/gNmMJ3POFuY3PqYqsHP9vAk9d5oIoLd0IqdsxhIV5dcDvpzk9nWZYzDX47EAZ2HTQ==";

const tarball = process.argv[2];
if (!tarball) throw new Error("usage: vendor-ondine.mjs <ondine-" + VERSION + ".tgz>");
const bytes = readFileSync(tarball);
const integrity = "sha512-" + createHash("sha512").update(bytes).digest("base64");
if (integrity !== INTEGRITY) throw new Error(`tarball integrity ${integrity} is not ondine@${VERSION}`);

const work = mkdtempSync(join(tmpdir(), "ondine-vendor-"));
try {
  execFileSync("tar", ["-xzf", resolve(tarball), "-C", work]);
  const dist = join(work, "package", "dist");
  const pkg = JSON.parse(readFileSync(join(work, "package", "package.json"), "utf8"));
  if (pkg.version !== VERSION) throw new Error(`package.json says ${pkg.version}`);
  const strip = (text) =>
    text
      .split("\n")
      .filter((line) => !line.startsWith("import ") && !line.startsWith("//# sourceMappingURL"))
      .map((line) => line.replace(/^export (function|class|const) /, "$1 "))
      .join("\n");
  const glue = strip(readFileSync(join(dist, "internal", "Wasm.js"), "utf8"));
  const render = strip(readFileSync(join(dist, "Render.js"), "utf8"));
  const all = strip(readFileSync(join(dist, "internal", "all.generated.js"), "utf8"));
  for (const [name, text] of [["Wasm.js", glue], ["Render.js", render], ["all.generated.js", all]]) {
    if (/\bimport\s*\(|\beval\s*\(|new Function|\bfetch\s*\(|innerHTML/.test(text)) throw new Error(`${name}: unexpected API`);
  }
  const out = [
    `/*! ondine ${VERSION} | MIT License | Copyright (c) 2025-present (see ondine.LICENSE) | https://github.com/wevm/ondine`,
    ` * Generated by scripts/cmux-next/vendor-ondine.mjs from the npm tarball ${INTEGRITY}. Do not edit. */`,
    `"use strict";`,
    `(() => {`,
    `const Wasm = (() => {`,
    glue,
    `return { instantiate };`,
    `})();`,
    render,
    all,
    `globalThis.ondine = Object.freeze({ version: ${JSON.stringify(VERSION)}, create, RenderError, wasm });`,
    `})();`,
    ``,
  ].join("\n");
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
  writeFileSync(join(root, "Resources", "markdown-viewer", "ondine.min.js"), out);
  writeFileSync(join(root, "Resources", "markdown-viewer", "ondine.LICENSE"), readFileSync(join(work, "package", "LICENSE"), "utf8"));
  console.log(`wrote ondine.min.js (${out.length} bytes)`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
