#!/usr/bin/env python3
"""Write the CSS and Swift copies of the one type scale (Leo 2026-10-13: unify the font sizes).

The one scale is schemas/type-scale/type-scale.json. This script writes the webviews' tokens (the
generated block of webviews/src/pages/shared/desktop.css: --font-ui, --text-<step>,
--text-<step>--line-height, --text-<step>--letter-spacing, --weight-<name>) and the app's
(CmuxNextDesign/TypeScale.generated.swift), so a size changes in one place for both. It also writes the
extension SDK's tables (the generated block of cmux-extension-sdk tokens.ts: TYPE_ROLES from scene-type.json,
SPACE, RADIUS and DURATION from scene-scale.json, whose steps name the app scale each comes from). The UI font is the
system font (Lawrence 2026-11-07), which carries its own size-specific tracking, so every step's
letter-spacing token is 0em.

    python3 scripts/cmux-next/gen-type-scale.py           # write the copies
    python3 scripts/cmux-next/gen-type-scale.py --check   # exit 1 when a copy drifted
"""
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SOURCE = "schemas/type-scale/type-scale.json"
# The scene DSL's type roles and Apple style names (RFD 0009): the web renderer and the design check read
# this file; the Swift copy is `SceneType` in SWIFT_FILE.
SCENE_SOURCE = "schemas/type-scale/scene-type.json"
CSS_FILE = "webviews/src/pages/shared/desktop.css"
SWIFT_FILE = "Packages/macOS/CmuxNext/Sources/CmuxNextDesign/TypeScale.generated.swift"
# The extension SDK's spacing, radius and motion steps, each tied to the app scale it comes from (RFD
# component-libraries, item 12); with SCENE_SOURCE's roles they are the SDK's tables in SDK_FILE.
SCENE_SCALE = "schemas/design-scale/scene-scale.json"
DESIGN_SCALE = "schemas/design-scale/design-scale.json"
LAYOUT_GRID = "schemas/layout-grid/layout-grid.json"
MOTION_SCALE = "schemas/motion-scale/motion-scale.json"
APP_SCALES = {"design-scale": DESIGN_SCALE, "layout-grid": LAYOUT_GRID, "motion-scale": MOTION_SCALE}
SDK_FILE = "cmux-tui/crates/cmux-extension-sdk/typescript/src/tokens.ts"
# Two generated blocks, where the tables have always been (a bundle keeps the order it reads them in).
SDK_BLOCKS = ("scene-type", "scene-scale")


def sdk_markers(block):
    source = SCENE_SOURCE if block == "scene-type" else SCENE_SCALE
    return ("// %s:begin. GENERATED by scripts/cmux-next/gen-type-scale.py from %s; do not edit." % (block, source),
            "// %s:end" % block)
# What this check reads. scripts/web_lint_prepush.py runs it alone when a push touches one (declared_inputs()).
INPUTS = (SOURCE, SCENE_SOURCE, CSS_FILE, SWIFT_FILE, SCENE_SCALE, SDK_FILE, DESIGN_SCALE, LAYOUT_GRID, MOTION_SCALE)
BEGIN = "/* type-scale:begin. GENERATED by scripts/cmux-next/gen-type-scale.py from " + SOURCE + "; do not edit. */"
END = "/* type-scale:end */"
SWIFT_WEIGHTS = {400: ".regular", 500: ".medium", 600: ".semibold", 700: ".bold"}
SCENE_WEIGHTS = ("regular", "medium", "semibold", "bold")


def load():
    with open(os.path.join(ROOT, SOURCE)) as handle:
        data = json.load(handle)
    sizes = [step["size"] for step in data["steps"]]
    assert sizes == sorted(set(sizes)), "steps run small to large, one size each"
    for step in data["steps"]:
        assert set(step) <= {"name", "size", "lineHeight", "for"}, step
    for weight in data["weights"]:
        assert set(weight) == {"name", "weight", "for"} and weight["weight"] in SWIFT_WEIGHTS, weight
    font = data["font"]
    assert set(font) == {"about", "stack"} and font["stack"], font
    return data


def load_scene():
    """scene-type.json: roles and Apple style names, each one size and weight; a style names the role at its size."""
    with open(os.path.join(ROOT, SCENE_SOURCE)) as handle:
        data = json.load(handle)
    roles = {role["name"]: role for role in data["roles"]}
    assert len(roles) == len(data["roles"]), "one row per role"
    for role in data["roles"]:
        assert set(role) == {"name", "helper", "size", "weight"} and role["weight"] in SCENE_WEIGHTS, role
    for style in data["styles"]:
        assert set(style) == {"name", "size", "weight", "role"} and style["weight"] in SCENE_WEIGHTS, style
        assert style["name"] not in roles, "a role name is the role: %s" % style["name"]
        assert roles.get(style["role"], {}).get("size") == style["size"], "a style names the role at its size: %s" % style
    return data


def scene_swift(scene):
    """`SceneType`: what a scene node's `font` name draws, the table the web renderer reads."""
    def row(item):
        return '        "%s": Style(size: %s, weight: .%s),' % (item["name"], item["size"], item["weight"])
    rows = "\n".join(row(item) for item in scene["roles"] + scene["styles"])
    return """
/// The scene DSL's type (RFD 0009): every name a scene node's `font` may take, a cmux type role or an
/// Apple text style, at one size and weight. The web scene renderer reads the same table
/// ({src}), so both draw a name alike.
public nonisolated struct SceneType {{
    public nonisolated init() {{}}
    /// One name's size in points at the default text size, and its weight.
    public struct Style: Sendable, Equatable {{
        public let size: CGFloat
        public let weight: NSFont.Weight
    }}

    /// Roles first (`numeral` ... `footnote`), then the Apple style names.
    public static let styles: [String: Style] = [
{rows}
    ]
}}
""".format(src=SCENE_SOURCE, rows=rows)


def font_stack(data):
    """`--font-ui`: the system font stack."""
    return ", ".join(data["font"]["stack"])


def source_json(data):
    """type-scale.json as written: one line per step and weight, each step with its tracking."""
    def row(item, keys):
        return "{ " + ", ".join("%s: %s" % (json.dumps(k), json.dumps(item[k])) for k in keys if k in item) + " }"
    head = {k: v for k, v in data.items() if k not in ("steps", "weights")}
    text = json.dumps(head, indent=2)[:-2] + ",\n"
    text += '  "steps": [\n' + ",\n".join(
        "    " + row(step, ("name", "size", "lineHeight", "for")) for step in data["steps"]) + "\n  ],\n"
    text += '  "weights": [\n' + ",\n".join(
        "    " + row(weight, ("name", "weight", "for")) for weight in data["weights"]) + "\n  ]\n}\n"
    return text


def css_block(data):
    lines = [BEGIN, ":root {", "  --cmux-interface-scale: 1;"]
    lines.append("  /* The UI font: the macOS system font (SF Pro), with its own tracking, so no letter-spacing. */")
    lines.append("  --font-ui: %s;" % font_stack(data))
    for step in data["steps"]:
        lines.append("  --text-%s: calc(%spx * var(--cmux-interface-scale, 1)); /* %s */" % (step["name"], step["size"], step["for"]))
        lines.append("  --text-%s--line-height: calc(%spx * var(--cmux-interface-scale, 1));" % (step["name"], step["lineHeight"]))
        lines.append("  --text-%s--letter-spacing: 0em;" % step["name"])
    lines.append("  /* Menu and picker rows: the body step (NSFont.menuFont is the system size). */")
    lines.append("  --text-control: var(--text-body);")
    lines.append("  --text-control--line-height: var(--text-body--line-height);")
    lines.append("  --text-control--letter-spacing: var(--text-body--letter-spacing);")
    lines.append("  /* Reading content (transcript, markdown, the prompt): the user's agent pane font size. */")
    lines.append("  --text-content: var(--cv-font-size, 14px);")
    lines.append("  --text-content--line-height: var(--cv-line-height, 22.75px);")
    for weight in data["weights"]:
        lines.append("  --weight-%s: %s; /* %s */" % (weight["name"], weight["weight"], weight["for"]))
    lines += ["}", END]
    return "\n".join(lines)


def app_value(ref, apps):
    """The app's value a scene-scale step's `from` names (scene-scale.json's `about` lists the forms)."""
    scale, _, path = ref.partition(":")
    data = apps[scale]
    if scale == "layout-grid":
        return next(metric["pt"] for metric in data["metrics"] if metric["name"] == path)
    if scale == "motion-scale":
        return next(step["ms"] for step in data["steps"] if step["name"] == path)
    head, _, name = path.partition(".")
    if head == "spacing":
        if name.startswith("layout."):
            return data["spacing"]["layout"][int(name[len("layout."):])]
        return next(step["px"] for step in data["spacing"]["steps"] if step["name"] == name)
    assert head in ("radii", "namedRadii"), ref
    row = next(row for row in data[head] if row["name"] == name)
    assert "px" in row, "a radius the SDK copies has a px value: %s" % ref
    return row["px"]


def load_scene_scale():
    """scene-scale.json with each step's value as its `from` names it today."""
    with open(os.path.join(ROOT, SCENE_SCALE)) as handle:
        data = json.load(handle)
    apps = {}
    for scale, path in APP_SCALES.items():
        with open(os.path.join(ROOT, path)) as handle:
            apps[scale] = json.load(handle)
    assert set(data) == {"about", "space", "radius", "duration", "differs"}, sorted(data)
    for table, unit in (("space", "px"), ("radius", "px"), ("duration", "ms")):
        names = [step["name"] for step in data[table]]
        assert len(names) == len(set(names)), "one row per %s step" % table
        for step in data[table]:
            assert set(step) <= {"name", unit, "from", "why"} and "from" in step, step
            if step["from"] is None:
                assert step.get("why"), "a scene-only step says why: %s" % step
            else:
                step[unit] = app_value(step["from"], apps)
    return data


def scene_scale_json(data):
    """scene-scale.json as written: one line per step, values from their `from`."""
    def row(item):
        return "{ " + ", ".join("%s: %s" % (json.dumps(k), json.dumps(v)) for k, v in item.items()) + " }"
    parts = ['  "about": %s' % json.dumps(data["about"])]
    for table in ("space", "radius", "duration", "differs"):
        parts.append('  "%s": [\n' % table + ",\n".join("    " + row(item) for item in data[table]) + "\n  ]")
    return "{\n" + ",\n".join(parts) + "\n}\n"


def sdk_blocks(scene, scale):
    """The SDK's tables, as an extension bundles them: the type roles, then spacing, radius and motion."""
    def ident(name):
        return name if name.isidentifier() else json.dumps(name)
    roles = "\n".join('  %s: { size: %s, weight: "%s" },' % (role["name"], role["size"], role["weight"]) for role in scene["roles"])
    def table(rows, unit):
        return "{ " + ", ".join("%s: %s" % (ident(row["name"]), row[unit]) for row in rows) + " }"
    return {
        "scene-type": """/**
 * The type roles: each a point size and weight (Apple's widget text styles), drawn by the helper
 * named for it. Text goes through a role, not a size: `cmux ext dev` warns on a size that is not
 * one of these, and on more than four roles in one widget.
 */
export const TYPE_ROLES = {{
{roles}
}} as const""".format(roles=roles),
        "scene-scale": """/**
 * The spacing scale, in points: every gap and padding is one of these (a 4 pt grid, with 2 and
 * 6 for tight rows). `cmux ext dev` warns on any other value and names the nearest step.
 */
export const SPACE = {space} as const
/** The corner radii, in points: the app's radius scale and its popup and card corners. */
export const RADIUS = {radius} as const
/** The motion scale's durations, in milliseconds (`.animation({{ duration }})` takes seconds). */
export const DURATION = {duration} as const""".format(space=table(scale["space"], "px"),
                radius=table(scale["radius"], "px"), duration=table(scale["duration"], "ms")),
    }


def sdk(current, scene, scale):
    for block, text in sdk_blocks(scene, scale).items():
        begin, end = sdk_markers(block)
        start, stop = current.index(begin), current.index(end) + len(end)
        current = current[:start] + begin + "\n" + text + "\n" + end + current[stop:]
    return current


def css(current, data):
    start, end = current.index(BEGIN), current.index(END) + len(END)
    return current[:start] + css_block(data) + current[end:]


def swift(data, scene):
    steps = "\n".join(
        "    /// %s.\n    @MainActor public static var %s: CGFloat { Base.%s * Typography.userScale }\n    @MainActor public static var %sLineHeight: CGFloat { Base.%sLineHeight * Typography.userScale }"
        % (step["for"][0].upper() + step["for"][1:], step["name"], step["name"], step["name"], step["name"])
        for step in data["steps"])
    base_steps = "\n".join(
        "        public static let %s: CGFloat = %s\n        public static let %sLineHeight: CGFloat = %s"
        % (step["name"], step["size"], step["name"], step["lineHeight"])
        for step in data["steps"])
    weights = "\n".join(
        "    /// %s.\n    public static let %s: NSFont.Weight = %s"
        % (weight["for"][0].upper() + weight["for"][1:], weight["name"], SWIFT_WEIGHTS[weight["weight"]])
        for weight in data["weights"])
    return """// GENERATED by scripts/cmux-next/gen-type-scale.py from
// {src}. Do not edit; edit the JSON and rerun.

public import AppKit

/// The one type scale of cmux NEXT, shared with the webviews' `--text-*` tokens: every chrome font
/// size is one of `sizes`, in one of the scale's weights. New fonts use these (scripts/cmux-next/check-swift-type-scale.py).
public nonisolated struct TypeScale: Sendable {{
    public init() {{}}

    /// `--font-ui`, the webviews' UI font: the macOS system font (pinned by schemas/type-scale/ui-font-pin.json).
    /// Natively the same face is `NSFont.systemFont` (`Typography.system`).
    public static let fontStack = "{stack}"

{steps}

    /// Reference sizes for off-main probes and surfaces that apply their own text scale.
    public nonisolated struct Base: Sendable {{
        public init() {{}}
{base_steps}
    }}

    /// Unscaled token values, small to large. The named steps follow Interface Size live.
    public static let sizes: [CGFloat] = [{sizes}]

{weights}
}}
{scene}""".format(src=SOURCE, scene=scene_swift(scene), steps=steps, base_steps=base_steps, weights=weights, sizes=", ".join(str(step["size"]) for step in data["steps"]),
           stack=font_stack(data).replace('"', '\\"'))


def main():
    check = "--check" in sys.argv[1:]
    data = load()
    scene = load_scene()
    with open(os.path.join(ROOT, CSS_FILE)) as handle:
        current_css = handle.read()
    scale = load_scene_scale()
    with open(os.path.join(ROOT, SDK_FILE)) as handle:
        current_sdk = handle.read()
    wanted = {CSS_FILE: css(current_css, data), SWIFT_FILE: swift(data, scene), SOURCE: source_json(data),
              SDK_FILE: sdk(current_sdk, scene, scale), SCENE_SCALE: scene_scale_json(scale)}
    drifted = []
    for path, text in wanted.items():
        full = os.path.join(ROOT, path)
        old = open(full).read() if os.path.exists(full) else None
        if old == text:
            continue
        if check:
            drifted.append(path)
        else:
            with open(full, "w") as handle:
                handle.write(text)
            print("wrote " + path)
    if drifted:
        print("type scale copies drifted from %s, %s or the app scales: %s\nrun python3 scripts/cmux-next/gen-type-scale.py" % (SOURCE, SCENE_SCALE, ", ".join(drifted)))
        sys.exit(1)


if __name__ == "__main__":
    main()
