#!/usr/bin/env python3
"""Build the CmuxNext CI target graph (build output, never committed; hq#2572 step 2).

The graph is what scripts/ci/cmux_next_route.py uses to pick the CmuxNext test
targets a pull request can affect. It comes from SwiftPM, not from reading
Package.swift by eye:

  targets   `swift package dump-package`: each target's kind, source
            directory, the targets it depends on in this package and the local
            packages whose products it uses
  packages  each local package dependency's repository directory
  reads     for each test target, the repository files and directories its
            sources name in string literals (schemas, fixtures, plans, cmux-tui
            vectors), which a test can read without depending on them in SwiftPM

Only `dump-package` needs Swift (the 6.2 tools), and its output depends on
Package.swift alone. So the dump is cached in DUMP_CACHE (ignored) with the
SHA-256 of the Package.swift it came from, and the graph is rebuilt from it in
a tenth of a second wherever it is used: the router builds it in memory on
every run (load()), so no stale copy can stand in for the tree. A missing dump,
or one from another Package.swift, fails with the command to run. CI restores
the dump from the Actions cache by that hash (.github/actions/cmux-next-target-graph).

The graph used to be committed (Packages/macOS/CmuxNext/ci-target-graph.json):
about 75 autofix commits, 19 hand fixes and a merge-driver line in two weeks.
That path is ignored now; this script still writes it for reading.

Usage: scripts/cmux-next/ci-target-graph.py [--dump FILE] [--docker] [--dump-only] [--out FILE|-]
  --dump FILE  use dump-package JSON from FILE (and cache it) instead of running swift
  --docker     run dump-package in the pinned Swift 6.2 Linux image (no local Swift)
  --dump-only  refresh the cached dump; write no graph
  --out FILE   write the graph there (- for standard output) instead of GRAPH
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "Packages/macOS/CmuxNext"
MANIFEST = PACKAGE / "Package.swift"
# Both ignored build output (.gitignore).
GRAPH = PACKAGE / "ci-target-graph.json"
DUMP_CACHE = PACKAGE / "ci-package-dump.json"
HEADER = "Generated by scripts/cmux-next/ci-target-graph.py from swift package dump-package; build output, never committed."
# The Swift 6.2 Linux image the autofix workflows dump the manifest with.
SWIFT_IMAGE = "docker.io/library/swift@sha256:eccc7a97f9b9881d9659e2e788081fd7675f86d39793b51200bfb178398b3784"
REFRESH = "scripts/cmux-next/ci-target-graph.py --dump-only (add --docker without a local Swift 6.2)"

STRING_LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
# Literals that name the machine, not the checkout.
SYSTEM_PREFIXES = ("/", "~")


def repo_relative(path: Path) -> str | None:
    try:
        return path.resolve().relative_to(ROOT.resolve()).as_posix()
    except ValueError:
        return None


def manifest_sha256(root: Path = ROOT) -> str:
    return hashlib.sha256((root / MANIFEST.relative_to(ROOT)).read_bytes()).hexdigest()


def run_dump_package(docker: bool) -> dict:
    if docker:
        # The whole checkout, read-only at its own path: local package paths resolve outside the package.
        command = ["docker", "run", "--rm", "-v", f"{ROOT}:{ROOT}:ro", "-w", str(PACKAGE),
                   SWIFT_IMAGE, "swift", "package", "dump-package"]
    else:
        command = ["swift", "package", "dump-package"]
    try:
        output = subprocess.run(command, cwd=PACKAGE, check=True, capture_output=True, text=True).stdout
    except FileNotFoundError:
        raise SystemExit(f"CI target graph: {command[0]} is not installed; "
                         + ("install Docker" if docker else "use --docker (the pinned Swift 6.2 image)")) from None
    except subprocess.CalledProcessError as error:
        raise SystemExit(f"CI target graph: {' '.join(command[:4])} failed:\n{error.stderr.strip()[-2000:]}") from None
    return json.loads(output)


def write_dump_cache(manifest: dict, sha: str) -> None:
    DUMP_CACHE.write_text(json.dumps({"manifest_sha256": sha, "dump": manifest}, sort_keys=True) + "\n",
                          encoding="utf-8")


def cached_dump(root: Path = ROOT) -> dict:
    """The cached dump-package output for root's Package.swift; exits with the fix when it is
    missing or from another Package.swift (never a stale graph)."""
    cache = root / DUMP_CACHE.relative_to(ROOT)
    relative = DUMP_CACHE.relative_to(ROOT)
    if not cache.is_file():
        raise SystemExit(f"CI target graph: {relative} is missing. The graph is build output (hq#2572); "
                         f"run {REFRESH}")
    data = json.loads(cache.read_text(encoding="utf-8"))
    if data.get("manifest_sha256") != manifest_sha256(root):
        raise SystemExit(f"CI target graph: {relative} is from another Package.swift "
                         f"({str(data.get('manifest_sha256'))[:12]}, now {manifest_sha256(root)[:12]}); run {REFRESH}")
    return data["dump"]


def dump_package(dump: Path | None, docker: bool = False) -> dict:
    """dump-package output for the current Package.swift: from FILE, the cache, or Swift."""
    sha = manifest_sha256()
    if dump is not None:
        manifest = json.loads(dump.read_text(encoding="utf-8"))
    else:
        try:
            return cached_dump()
        except SystemExit:
            manifest = run_dump_package(docker)
    write_dump_cache(manifest, sha)
    return manifest


def load(root: Path = ROOT) -> dict:
    """The graph of root's tree, built now from the cached dump: what the router reads."""
    if root.resolve() != ROOT.resolve():
        raise SystemExit(f"CI target graph: load {root} with its own scripts/cmux-next/ci-target-graph.py")
    return build_graph(cached_dump(root))


def local_packages(manifest: dict) -> dict[str, str]:
    """Local package name and identity (lowercased) -> repository directory."""
    found: dict[str, str] = {}
    for dependency in manifest.get("dependencies", []):
        for spec in dependency.get("fileSystem", []):
            path = Path(spec["path"])
            if not path.is_absolute():
                path = PACKAGE / path
            relative = repo_relative(path)
            if relative is None:
                continue
            found[path.name] = relative
    return found


def dependency_name(dependency: dict) -> tuple[str, str]:
    """('target', name) or ('product', package) for one dump-package dependency."""
    if "target" in dependency:
        return "target", dependency["target"][0]
    if "product" in dependency:
        product = dependency["product"]
        return "product", product[1] or product[0]
    if "byName" in dependency:
        return "byName", dependency["byName"][0]
    raise SystemExit(f"unknown dependency shape: {dependency}")


def literal_reads(source_dir: Path) -> list[str]:
    """Repository paths a test target's sources name in string literals."""
    reads: set[str] = set()
    for source in sorted(source_dir.rglob("*.swift")):
        text = source.read_text(encoding="utf-8")
        for literal in STRING_LITERAL.findall(text):
            # An interpolated path counts up to its first interpolation.
            literal = literal.split("\\(", 1)[0]
            # Two path segments at least: a lone "docs/" is a folder name in a
            # fixture far more often than a read of the repository's docs.
            if "/" not in literal.strip("/") or literal.startswith(SYSTEM_PREFIXES) or "://" in literal:
                continue
            if any(ch.isspace() for ch in literal):
                continue
            for base in (ROOT, PACKAGE, source_dir, source.parent):
                candidate = base / literal
                try:
                    if not candidate.exists():
                        continue
                except OSError:
                    # Not a path at all: a certificate or other blob too long
                    # for the filesystem (ENAMETOOLONG on macOS).
                    continue
                relative = repo_relative(candidate)
                if relative is None or relative in ("", "."):
                    continue
                # Reads inside the target itself are already its sources.
                if (relative + "/").startswith(repo_relative(source_dir) + "/"):
                    continue
                if candidate.is_dir():
                    relative += "/"
                reads.add(relative)
                break
    # A file under a directory that is itself read adds nothing.
    return sorted(
        read for read in reads
        if not any(other != read and other.endswith("/") and read.startswith(other) for other in reads)
    )


def build_graph(manifest: dict) -> dict:
    packages = local_packages(manifest)
    names = {target["name"] for target in manifest["targets"]}
    package_root = repo_relative(PACKAGE)
    targets: dict[str, dict] = {}
    for target in sorted(manifest["targets"], key=lambda t: t["name"]):
        kind = target["type"]
        default = ("Tests/" if kind == "test" else "Sources/") + target["name"]
        path = target.get("path") or (default if kind != "binary" else None)
        local_targets: set[str] = set()
        used_packages: set[str] = set()
        for dependency in target.get("dependencies", []):
            how, name = dependency_name(dependency)
            if how in ("target", "byName") and name in names:
                local_targets.add(name)
            elif name in packages:
                used_packages.add(name)
            elif how == "product":
                # A remote package (Sparkle): its pin is Package.resolved.
                continue
            else:
                raise SystemExit(f"{target['name']}: dependency {name} is neither a target nor a local package")
        entry: dict = {
            "kind": kind,
            "path": f"{package_root}/{path}" if path else None,
            "targets": sorted(local_targets),
            "packages": sorted(used_packages),
        }
        if kind == "test":
            entry["reads"] = literal_reads(PACKAGE / path)
        targets[target["name"]] = entry
    return {
        "_comment": HEADER,
        "packages": dict(sorted(packages.items())),
        "targets": targets,
    }


def render(graph: dict) -> str:
    return json.dumps(graph, indent=2, sort_keys=False) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dump", type=Path, help="dump-package JSON to use (and cache) instead of running swift")
    parser.add_argument("--docker", action="store_true", help="run dump-package in the pinned Swift 6.2 image")
    parser.add_argument("--dump-only", action="store_true", help="refresh the cached dump; write no graph")
    parser.add_argument("--out", help="where to write the graph (- for standard output)")
    args = parser.parse_args(argv)

    manifest = dump_package(args.dump, args.docker)
    if args.dump_only:
        print(f"{DUMP_CACHE.relative_to(ROOT)} is current for Package.swift {manifest_sha256()[:12]}")
        return 0
    text = render(build_graph(manifest))
    if args.out == "-":
        sys.stdout.write(text)
        return 0
    out = Path(args.out) if args.out else GRAPH
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} (build output; not committed)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
