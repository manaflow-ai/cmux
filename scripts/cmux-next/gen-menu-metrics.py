#!/usr/bin/env python3
"""Write the Swift and CSS copies of the one menu row grid (Leo 2026-10-21: "idk if we
generalized the left alignment across all stuff yet").

The one grid is schemas/menu-metrics/menu-metrics.json. This script writes the app's copy
(CmuxNextDesign/MenuMetrics.generated.swift) and the webviews' CSS (the generated block of
webviews/src/pages/shared/desktop.css: --cmux-menu-<name>, plus --cmux-menu-text-x for a menu
with an icon column), so every menu's highlight, separators, icon and text columns and shortcut
column change in one place.

    python3 scripts/cmux-next/gen-menu-metrics.py           # write the copies
    python3 scripts/cmux-next/gen-menu-metrics.py --check   # exit 1 when a copy drifted
"""
import json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SOURCE = "schemas/menu-metrics/menu-metrics.json"
CSS_FILE = "webviews/src/pages/shared/desktop.css"
SWIFT_FILE = "Packages/macOS/CmuxNext/Sources/CmuxNextDesign/MenuMetrics.generated.swift"
BEGIN = "/* menu-metrics:begin. GENERATED by scripts/cmux-next/gen-menu-metrics.py from " + SOURCE + "; do not edit. */"
END = "/* menu-metrics:end */"
# The motion scale's block comes before it in desktop.css; a missing menu block is written after it.
ANCHOR = "/* motion-scale:end */"
NAMES = {"highlightInset", "highlightRadius", "separatorInset", "stateX", "stateIconX", "iconX", "iconSize", "iconGap", "trailing", "shortcutGap"}


def load():
    with open(os.path.join(ROOT, SOURCE)) as handle:
        data = json.load(handle)
    for metric in data["metrics"]:
        assert set(metric) == {"name", "pt", "for"} and metric["name"].isidentifier(), metric
        assert isinstance(metric["pt"], (int, float)) and metric["pt"] >= 0, metric
    names = [metric["name"] for metric in data["metrics"]]
    assert set(names) == NAMES and len(names) == len(NAMES), "the grid names every metric once: %s" % sorted(NAMES)
    pt = {metric["name"]: metric["pt"] for metric in data["metrics"]}
    # The columns read left to right and the highlight holds them.
    assert pt["highlightInset"] < pt["stateX"] < pt["stateIconX"] and pt["highlightInset"] < pt["iconX"] <= pt["stateIconX"], pt
    assert pt["highlightRadius"] * 2 <= pt["iconX"], pt
    return data


def kebab(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def text_x(data, start="iconX"):
    pt = {metric["name"]: metric["pt"] for metric in data["metrics"]}
    return pt[start] + pt["iconSize"] + pt["iconGap"]


def css_block(data):
    lines = [BEGIN, ":root {"]
    for metric in data["metrics"]:
        lines.append("  --cmux-menu-%s: %gpx; /* %s */" % (kebab(metric["name"]), metric["pt"], metric["for"]))
    lines.append("  /* The text column of a menu with an icon column: iconX + iconSize + iconGap; with a state column too, from stateIconX. */")
    lines.append("  --cmux-menu-text-x: %gpx;" % text_x(data))
    lines.append("  --cmux-menu-state-text-x: %gpx;" % text_x(data, "stateIconX"))
    lines += ["}", END]
    return "\n".join(lines)


def css(current, data):
    if BEGIN in current:
        start, end = current.index(BEGIN), current.index(END) + len(END)
        return current[:start] + css_block(data) + current[end:]
    at = current.index(ANCHOR) + len(ANCHOR)
    return current[:at] + "\n" + css_block(data) + current[at:]


def swift(data):
    metrics = "\n".join("    /// %s.\n    public static let %s: CGFloat = %g"
                        % (metric["for"][0].upper() + metric["for"][1:], metric["name"], metric["pt"])
                        for metric in data["metrics"])
    return """// GENERATED by scripts/cmux-next/gen-menu-metrics.py from
// {src}. Do not edit; edit the JSON and rerun.

public import CoreGraphics

/// The one row grid of every cmux NEXT menu, shared with the webviews' `--cmux-menu-*` tokens: in
/// points from the menu's leading edge (`trailing` from its trailing edge).
public nonisolated struct MenuMetrics: Sendable {{
    public init() {{}}

{metrics}

    /// Where a row's icon starts: after the state column when any row of the menu has a checkmark or dash.
    public static func iconX(stateColumn: Bool) -> CGFloat {{ stateColumn ? stateIconX : iconX }}

    /// The text column: after the icon column when any row of the menu has an icon, else on it.
    public static func textX(iconColumn: Bool, stateColumn: Bool = false) -> CGFloat {{
        iconX(stateColumn: stateColumn) + (iconColumn ? iconSize + iconGap : 0)
    }}
}}
""".format(src=SOURCE, metrics=metrics)


def main():
    check = "--check" in sys.argv[1:]
    data = load()
    with open(os.path.join(ROOT, CSS_FILE)) as handle:
        current_css = handle.read()
    wanted = {CSS_FILE: css(current_css, data), SWIFT_FILE: swift(data)}
    drifted = []
    for path, text in wanted.items():
        full = os.path.join(ROOT, path)
        old = open(full).read() if os.path.exists(full) else None
        if old == text:
            continue
        if check:
            drifted.append(path)
        else:
            with open(full, "w") as handle:
                handle.write(text)
            print("wrote " + path)
    if drifted:
        print("menu metrics copies drifted from %s: %s\nrun python3 scripts/cmux-next/gen-menu-metrics.py" % (SOURCE, ", ".join(drifted)))
        sys.exit(1)


if __name__ == "__main__":
    main()
