#!/usr/bin/env python3
"""Generate both native popup wire types from the one declarative schema."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "webviews/src/ui/popupProtocol.schema.json"
HEADER = "Generated by scripts/cmux-next/gen-popup-protocol.py. Do not edit."


def wire_type(field, swift=False):
    if "$ref" in field:
        return field["$ref"].rsplit("/", 1)[1]
    if "const" in field and not swift:
        return json.dumps(field["const"])
    kind = field["type"]
    if kind == "array":
        item = wire_type(field["items"], swift)
        return f"[{item}]" if swift else f"{item}[]"
    return ({"string": "String", "number": "Double", "integer": "Int", "boolean": "Bool"} if swift else
            {"string": "string", "number": "number", "integer": "number", "boolean": "boolean"})[kind]


def generate():
    definitions = json.loads(SCHEMA.read_text())["$defs"]
    ts = [f"// {HEADER}", ""]
    outputs = {}
    for name, spec in definitions.items():
        swift = [f"// {HEADER}", "import Foundation", "", f"/// {name} on the native popup wire."]
        if "enum" in spec:
            line = f"export type {name} = " + " | ".join(json.dumps(v) for v in spec["enum"]) + ";"
            if len(line) > 110:
                ts += [f"export type {name} ="]
                ts += ["  | " + json.dumps(v) + (";" if index == len(spec["enum"]) - 1 else "") for index, v in enumerate(spec["enum"])]
                ts += [""]
            else:
                ts += [line, ""]
            swift += [f"public enum {name}: String, Codable, Equatable, Sendable {{"]
            swift += [f"    case `{v}`" for v in spec["enum"]] + ["}", ""]
        else:
            required = spec.get("required", [])
            properties = spec["properties"]
            ts += [f"export interface {name} {{"]
            swift += [f"public struct {name}: Codable, Equatable, Sendable {{"]
            for key, field in properties.items():
                optional = key not in required
                ts += [f"  {key}{'?' if optional else ''}: {wire_type(field)};"]
                swift += [f"    public var `{key}`: {wire_type(field, True)}{'?' if optional else ''}"]
            args = [f"{key}: {wire_type(field, True)}" + ("? = nil" if key not in required else "") for key, field in properties.items()]
            swift += ["", f"    public init({', '.join(args)}) {{"]
            swift += [f"        self.{key} = {key}" for key in properties]
            swift += ["    }", "}", ""]
            ts += ["}", ""]
        outputs[ROOT / f"Packages/macOS/CmuxNext/Sources/CmuxNextDesign/Overlay/Generated/{name}.swift"] = "\n".join(swift)
    outputs[ROOT / "webviews/src/ui/generated/popupProtocol.ts"] = "\n".join(ts)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Stale popup protocol: " + ", ".join(stale))


if __name__ == "__main__":
    main()
