#!/usr/bin/env python3
"""gen-settings-sources.py --swift-out DIR, the SettingsSchemaPlugin build step.

RFD 0048: the settings Swift is not in git; the package's build-tool plugin generates it into its
work directory. Two runs must write the same bytes (a build is reproducible), each file it writes
must be one of its outputs under its Schema file name, an unchanged file must not be rewritten (an
incremental build would recompile it), a file the generator no longer writes must leave DIR, and
the generator never writes into the package's Sources (the copies would compile twice).
"""
import contextlib
import importlib.util
import io
import os
import shutil
import tempfile
import unittest

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
SCRIPT = os.path.join(ROOT, "scripts/cmux-next/gen-settings-sources.py")


def load():
    spec = importlib.util.spec_from_file_location("gen_settings_sources_swift_out", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class SwiftOutTests(unittest.TestCase):
    def setUp(self):
        self.module = load()
        self.out = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.out)

    def run_main(self, *args):
        with contextlib.redirect_stdout(io.StringIO()) as out, contextlib.redirect_stderr(io.StringIO()):
            code = self.module.main(list(args))
        return code, out.getvalue()

    def test_two_runs_write_the_same_bytes_and_only_generated_files(self):
        code, _ = self.run_main("--swift-out", self.out)
        self.assertEqual(code, 0)
        again = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, again)
        self.assertEqual(self.run_main("--swift-out", again)[0], 0)
        written = sorted(os.listdir(self.out))
        self.assertEqual(written, sorted(os.listdir(again)))
        self.assertIn("SettingsSection.generated.swift", written)
        marker = b"// GENERATED by scripts/cmux-next/gen-settings-sources.py"
        for name in written:
            self.assertTrue(name.endswith(".generated.swift"), name)
            with open(os.path.join(self.out, name), "rb") as a, open(os.path.join(again, name), "rb") as b:
                text = a.read()
                self.assertEqual(text, b.read(), name)
                self.assertTrue(text.startswith(marker), name)

    def test_without_swift_out_it_writes_nothing(self):
        schema = os.path.join(ROOT, self.module.SCHEMA_DIR)
        before = sorted(os.listdir(schema)) if os.path.isdir(schema) else []
        code, _ = self.run_main()
        self.assertEqual(code, 2)
        self.assertEqual(before, sorted(os.listdir(schema)) if os.path.isdir(schema) else [])

    def test_a_second_run_rewrites_nothing(self):
        self.run_main("--swift-out", self.out)
        before = {name: os.stat(os.path.join(self.out, name)).st_mtime_ns for name in os.listdir(self.out)}
        code, printed = self.run_main("--swift-out", self.out)
        self.assertEqual(code, 0)
        self.assertNotIn("wrote", printed)
        after = {name: os.stat(os.path.join(self.out, name)).st_mtime_ns for name in os.listdir(self.out)}
        self.assertEqual(before, after)

    def test_a_file_no_longer_generated_leaves_the_directory(self):
        self.run_main("--swift-out", self.out)
        stale = os.path.join(self.out, "SettingsSchema+Gone.generated.swift")
        with open(stale, "w", encoding="utf-8") as handle:
            handle.write("// GENERATED by scripts/cmux-next/gen-settings-sources.py from\n")
        hand = os.path.join(self.out, "Hand.swift")
        with open(hand, "w", encoding="utf-8") as handle:
            handle.write("// not generated\n")
        code, _ = self.run_main("--check", "--swift-out", self.out)
        self.assertNotEqual(code, 0)
        self.run_main("--swift-out", self.out)
        self.assertFalse(os.path.exists(stale))
        self.assertTrue(os.path.exists(hand))

    def test_the_schema_directory_is_untouched(self):
        schema = os.path.join(ROOT, self.module.SCHEMA_DIR)
        before = {name: os.stat(os.path.join(schema, name)).st_mtime_ns for name in os.listdir(schema)}
        self.run_main("--swift-out", self.out)
        after = {name: os.stat(os.path.join(schema, name)).st_mtime_ns for name in os.listdir(schema)}
        self.assertEqual(before, after)


if __name__ == "__main__":
    unittest.main()
