#!/usr/bin/env bash
# scripts/cmux-next/check-daemon-capabilities-fresh.py compares the capability
# lists in DaemonEndpoint.swift with plans/cmux-next/daemon-capabilities.json
# without a build. 67b13e24e84d moved sidebar-layout-v1 from
# unservedByBundledDaemon to optional in Swift only; the stale JSON failed
# every tagged build (2026-10-07).
set -euo pipefail

check="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/check-daemon-capabilities-fresh.py"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }
swift="$tmp/Packages/macOS/CmuxNext/Sources/CmuxNextDaemon/Connection/DaemonEndpoint.swift"
json="$tmp/plans/cmux-next/daemon-capabilities.json"
mkdir -p "$(dirname "$swift")" "$(dirname "$json")"

write_swift() { # optional-identifiers unserved-identifiers [extra-declaration]
  cat > "$swift" <<EOF
public struct DaemonEndpoint: Sendable {
    public var socketPath: String
}

public struct DaemonCapabilities: Sendable {
    private init() {}
    public static let required: [String] = [
        "workspace-registry-v1",
        "attach-initial-size",
    ]

    /// Docs with a "quoted-v1" word and a [bracket].
    public static let workspaceGroups = "workspace-groups-v1"
    public static let sidebarLayout = "sidebar-layout-v1"
    public static let remoteTerminalTabs = "remote-terminal-tabs-v1"
${3:-}

    public static var homeOnly: [String] { [workspaceGroups] }
    public static var optional: [String] { [$1] }
    public static var unservedByBundledDaemon: [String] { [$2] }
}
EOF
}
json_array() { # item... -> the array as Swift's pretty JSONEncoder writes it
  if (($# == 0)); then printf '[\n\n  ]'; return; fi
  local first=1 item
  printf '['
  for item in "$@"; do
    ((first)) || printf ','
    printf '\n    "%s"' "$item"
    first=0
  done
  printf '\n  ]'
}
write_json() { # "optional items" "unserved items"
  # shellcheck disable=SC2086 # word splitting builds the item lists
  {
    printf '{\n  "comment" : "Generated by DaemonCapabilityExportTests from DaemonCapabilities; read by scripts/cmux-next/check-daemon-capabilities.sh.",\n'
    printf '  "optional" : %s,\n' "$(json_array $1)"
    printf '  "required" : %s,\n' "$(json_array attach-initial-size workspace-registry-v1)"
    printf '  "unservedByBundledDaemon" : %s\n}\n' "$(json_array $2)"
  } > "$json"
}
run() { python3 "$check" --repo "$tmp" 2>&1; }

write_swift "workspaceGroups" "remoteTerminalTabs, sidebarLayout"
write_json "workspace-groups-v1" "remote-terminal-tabs-v1 sidebar-layout-v1"
out="$(run)" || fail "a fresh export failed: $out"

# 67b13e24e84d: Swift moves sidebar-layout-v1 to optional, the JSON stays.
write_swift "workspaceGroups,
                                       sidebarLayout" "remoteTerminalTabs"
if out="$(run)"; then fail "a Swift-only move passed: $out"; fi
[[ "$out" == *"sidebar-layout-v1"* ]] || fail "the failure does not name sidebar-layout-v1: $out"
[[ "$out" == *"CMUX_UPDATE_DAEMON_CAPABILITIES=1"* ]] || fail "the failure lacks the regenerate command: $out"

# The JSON regenerated with it passes again.
write_json "sidebar-layout-v1 workspace-groups-v1" "remote-terminal-tabs-v1"
out="$(run)" || fail "the regenerated export failed: $out"

# The base autofix uses the same source parser and renderer to repair a stale
# export without a Swift build.
write_json "workspace-groups-v1" "remote-terminal-tabs-v1"
out="$(python3 "$check" --repo "$tmp" --write 2>&1)" || fail "write mode did not repair the export: $out"
[[ "$out" == *"wrote plans/cmux-next/daemon-capabilities.json"* ]] || fail "write mode lacks its receipt: $out"
out="$(run)" || fail "the write-mode export failed freshness: $out"

# A named constant in no list fails (DaemonCapabilityExportTests checked it with Mirror while the
# catalog had an instance).
write_swift "workspaceGroups,
                                       sidebarLayout" "remoteTerminalTabs" '    public static let orphanThing = "orphan-thing-v1"'
if out="$(run)"; then fail "a constant in no list passed: $out"; fi
[[ "$out" == *"orphanThing"* ]] || fail "the failure does not name the unlisted constant: $out"

# An identifier the parser cannot resolve fails loudly instead of being skipped.
write_swift "workspaceGroups, sidebarLayout, someComputedThing" "remoteTerminalTabs"
if out="$(run)"; then fail "an unresolved identifier passed: $out"; fi
[[ "$out" == *"someComputedThing"* ]] || fail "the failure does not name the unresolved identifier: $out"

# 7558f956c3475 hand-edited an empty list to `[]`. The sets still matched, so
# this check passed, but DaemonCapabilityExportTests.exportIsFresh compares
# bytes and failed on the Mac. The check compares the encoder's bytes too.
write_swift "workspaceGroups, sidebarLayout, remoteTerminalTabs" ""
write_json "remote-terminal-tabs-v1 sidebar-layout-v1 workspace-groups-v1" ""
out="$(run)" || fail "an encoder-shaped empty list failed: $out"
python3 - "$json" <<'EOF'
import sys
path = sys.argv[1]
text = open(path, encoding="utf-8").read()
open(path, "w", encoding="utf-8").write(text.replace(' : [\n\n  ]', ' : []'))
EOF
grep -q '"unservedByBundledDaemon" : \[\]$' "$json" || fail "the fixture lacks the hand-edited [] form: $(cat "$json")"
if out="$(run)"; then fail "a hand-edited [] passed: $out"; fi
[[ "$out" == *"CMUX_UPDATE_DAEMON_CAPABILITIES=1"* ]] || fail "the byte failure lacks the regenerate command: $out"
[[ "$out" == *'+  "unservedByBundledDaemon" : []'* ]] || fail "the byte failure lacks a diff: $out"

# A key order or spacing other than the encoder's fails the same way.
write_json "remote-terminal-tabs-v1 sidebar-layout-v1 workspace-groups-v1" ""
python3 - "$json" <<'EOF'
import sys
path = sys.argv[1]
text = open(path, encoding="utf-8").read()
open(path, "w", encoding="utf-8").write(text.replace('" : ', '": '))
EOF
if out="$(run)"; then fail "a non-encoder separator passed: $out"; fi

# CRLF line endings differ in bytes too; a text-mode read must not hide them.
write_json "remote-terminal-tabs-v1 sidebar-layout-v1 workspace-groups-v1" ""
python3 - "$json" <<'EOF'
import sys
path = sys.argv[1]
data = open(path, "rb").read()
open(path, "wb").write(data.replace(b"\n", b"\r\n"))
EOF
if out="$(run)"; then fail "a CRLF export passed: $out"; fi

# bdce169c4b8af (#21445) put workspace-name-source-v1 in optional and in the
# unserved list; the identify check then failed every dev build. A capability
# in two lists fails here, before any build.
write_swift "workspaceGroups, sidebarLayout" "remoteTerminalTabs, sidebarLayout"
write_json "sidebar-layout-v1 workspace-groups-v1" "remote-terminal-tabs-v1 sidebar-layout-v1"
if out="$(run)"; then fail "a capability in optional and unserved passed: $out"; fi
[[ "$out" == *"in both optional and unservedByBundledDaemon"*"sidebar-layout-v1"* ]] || fail "the failure does not name the overlap: $out"

# The committed export passes as it is.
repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
out="$(python3 "$check" --repo "$repo" 2>&1)" || fail "the committed export failed: $out"

echo "daemon-capabilities-fresh.test.sh: ok"
