#!/usr/bin/env bash
# scripts/cmux-next/check-daemon-capabilities-fresh.py compares the capability
# lists of enum DaemonCapability (DaemonEndpoint.swift) with plans/cmux-next/daemon-capabilities.json
# without a build. 67b13e24e84d moved sidebar-layout-v1 from
# unservedByBundledDaemon to optional in Swift only; the stale JSON failed
# every tagged build (2026-10-07).
set -euo pipefail

check="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/check-daemon-capabilities-fresh.py"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }
swift="$tmp/Packages/macOS/CmuxNext/Sources/CmuxNextDaemon/Connection/DaemonEndpoint.swift"
json="$tmp/plans/cmux-next/daemon-capabilities.json"
mkdir -p "$(dirname "$swift")" "$(dirname "$json")"

arm() { # tier identifiers... -> one `tier` switch arm, or nothing for an empty list
  local tier="$1" names
  names="$(sed -E 's/([A-Za-z_][A-Za-z0-9_]*)/.\1/g' <<<"$2")"
  [[ -n "${2//[[:space:],]/}" ]] || return 0
  printf '        case %s:\n            return .%s\n' "$names" "$tier"
}
write_swift() { # optional-identifiers unserved-identifiers [extra-declaration]
  cat > "$swift" <<EOF
public struct DaemonEndpoint: Sendable {
    public var socketPath: String
}

public enum DaemonCapability: String, CaseIterable, Sendable {
    case workspaceRegistry = "workspace-registry-v1"
    case attachInitialSize = "attach-initial-size"

    /// Docs with a "quoted-v1" word, a [bracket] and a { brace.
    case workspaceGroups = "workspace-groups-v1"
    case sidebarLayout = "sidebar-layout-v1"
    case remoteTerminalTabs = "remote-terminal-tabs-v1"
${3:-}

    public enum Tier: Sendable {
        case required, optional, unservedByBundledDaemon
    }

    public var tier: Tier {
        switch self {
        case .workspaceRegistry, .attachInitialSize:
            return .required
$(arm optional "$1")
$(arm unservedByBundledDaemon "$2")
        }
    }

    public static let required: [String] = names(in: .required)
    public static let homeOnly: [String] = names([.workspaceGroups])
    public static let advertised: [String] = (required + optional).filter { capability in capability != "x" }
}
EOF
}
json_array() { # item... -> the array as Swift's pretty JSONEncoder writes it
  if (($# == 0)); then printf '[\n\n  ]'; return; fi
  local first=1 item
  printf '['
  for item in "$@"; do
    ((first)) || printf ','
    printf '\n    "%s"' "$item"
    first=0
  done
  printf '\n  ]'
}
write_json() { # "optional items" "unserved items"
  # shellcheck disable=SC2086 # word splitting builds the item lists
  {
    printf '{\n  "comment" : "Generated by DaemonCapabilityExportTests from DaemonCapability; read by scripts/cmux-next/check-daemon-capabilities.sh.",\n'
    printf '  "optional" : %s,\n' "$(json_array $1)"
    printf '  "required" : %s,\n' "$(json_array attach-initial-size workspace-registry-v1)"
    printf '  "unservedByBundledDaemon" : %s\n}\n' "$(json_array $2)"
  } > "$json"
}
run() { python3 "$check" --repo "$tmp" 2>&1; }

write_swift "workspaceGroups" "remoteTerminalTabs, sidebarLayout"
write_json "workspace-groups-v1" "remote-terminal-tabs-v1 sidebar-layout-v1"
out="$(run)" || fail "a fresh export failed: $out"

# 67b13e24e84d: Swift moves sidebar-layout-v1 to optional, the JSON stays.
write_swift "workspaceGroups,
                                       sidebarLayout" "remoteTerminalTabs"
if out="$(run)"; then fail "a Swift-only move passed: $out"; fi
[[ "$out" == *"sidebar-layout-v1"* ]] || fail "the failure does not name sidebar-layout-v1: $out"
[[ "$out" == *"CMUX_UPDATE_DAEMON_CAPABILITIES=1"* ]] || fail "the failure lacks the regenerate command: $out"

# The JSON regenerated with it passes again.
write_json "sidebar-layout-v1 workspace-groups-v1" "remote-terminal-tabs-v1"
out="$(run)" || fail "the regenerated export failed: $out"

# The base autofix uses the same source parser and renderer to repair a stale
# export without a Swift build.
write_json "workspace-groups-v1" "remote-terminal-tabs-v1"
out="$(python3 "$check" --repo "$tmp" --write 2>&1)" || fail "write mode did not repair the export: $out"
[[ "$out" == *"wrote plans/cmux-next/daemon-capabilities.json"* ]] || fail "write mode lacks its receipt: $out"
out="$(run)" || fail "the write-mode export failed freshness: $out"

# A capability is a case: a String constant in the catalog is in no list and fails
# (DaemonCapabilityExportTests checked this with Mirror while the catalog had an instance).
write_swift "workspaceGroups,
                                       sidebarLayout" "remoteTerminalTabs" '    public static let orphanThing = "orphan-thing-v1"'
if out="$(run)"; then fail "a constant in no list passed: $out"; fi
[[ "$out" == *"orphanThing"* ]] || fail "the failure does not name the unlisted constant: $out"

# The same with a type annotation (cc7a964ef61's source regex skipped `let name: String = "..."`, so
# a typed constant in no list passed while the Mirror test it replaced failed on it).
write_swift "workspaceGroups,
                                       sidebarLayout" "remoteTerminalTabs" '    public static let orphanTyped: String = "orphan-typed-v1"'
if out="$(run)"; then fail "a typed constant in no list passed: $out"; fi
[[ "$out" == *"orphanTyped"* ]] || fail "the failure does not name the typed constant: $out"

# A computed String static is a constant by another name (`static var orphanComputed: String { ... }`):
# it is in no list either, and the stored-constant regex never saw it.
write_swift "workspaceGroups,
                                       sidebarLayout" "remoteTerminalTabs" '    public static var orphanComputed: String { "orphan-computed-v1" }'
if out="$(run)"; then fail "a computed String static in no list passed: $out"; fi
[[ "$out" == *"orphanComputed"* ]] || fail "the failure does not name the computed static: $out"

# A static that returns a String, and an untyped static (its type could be String), fail the same way.
write_swift "workspaceGroups,
                                       sidebarLayout" "remoteTerminalTabs" '    static func orphanFunc() -> String { "orphan-func-v1" }
    static let orphanAlias = Self.workspaceRegistry.rawValue'
if out="$(run)"; then fail "a String-returning static func and an untyped static passed: $out"; fi
[[ "$out" == *"orphanFunc"* && "$out" == *"orphanAlias"* ]] || fail "the failure does not name both statics: $out"

# The same in an extension of the catalog in another file: the export, check-daemon-capabilities.sh and
# DaemonCompatibility never see it, and this check read DaemonEndpoint.swift only.
write_swift "workspaceGroups,
                                       sidebarLayout" "remoteTerminalTabs"
extension_file="$tmp/Packages/macOS/CmuxNext/Sources/CmuxNextApp/DaemonCapability+Orphan.swift"
mkdir -p "$(dirname "$extension_file")"
cat > "$extension_file" <<'SWIFT'
extension DaemonCapability {
    static var orphanExt: String { "orphan-ext-v1" }
    static let homeAndPersonal: [String] = homeOnly + personalOnHome
}
SWIFT
if out="$(run)"; then fail "a String static in an extension in another file passed: $out"; fi
[[ "$out" == *"orphanExt"*"DaemonCapability+Orphan.swift"* ]] || fail "the failure does not name the extension static and its file: $out"
[[ "$out" != *"homeAndPersonal"* ]] || fail "a typed list in an extension was refused: $out"
rm "$extension_file"

# A case in no arm of `tier` fails (the compiler refuses it too; the check must not lose it).
write_swift "workspaceGroups,
                                       sidebarLayout" "remoteTerminalTabs" '    case orphanCase = "orphan-case-v1"'
if out="$(run)"; then fail "a case in no tier arm passed: $out"; fi
[[ "$out" == *"orphanCase"* ]] || fail "the failure does not name the unplaced case: $out"

# A `default` arm would let a new case compile without a list.
write_swift "workspaceGroups, sidebarLayout" "remoteTerminalTabs"
python3 - "$swift" <<'PY'
import sys
path = sys.argv[1]
text = open(path, encoding="utf-8").read()
open(path, "w", encoding="utf-8").write(text.replace("            return .unservedByBundledDaemon\n",
                                                     "            return .unservedByBundledDaemon\n        default:\n            return .optional\n", 1))
PY
grep -q 'default:' "$swift" || fail "the fixture lacks the default arm"
if out="$(run)"; then fail "a default arm passed: $out"; fi
[[ "$out" == *"default"* ]] || fail "the failure does not name the default arm: $out"

# The old shape (static String constants and hand-kept lists) is refused by name.
cat > "$swift" <<'EOF'
public struct DaemonCapabilities: Sendable {
    public static let required: [String] = ["workspace-registry-v1"]
    public static let tabDrag = "tab-drag-v1"
    public static var optional: [String] { [tabDrag] }
    public static var unservedByBundledDaemon: [String] { [] }
}
EOF
if out="$(run)"; then fail "the hand-kept struct catalog passed: $out"; fi
[[ "$out" == *"enum DaemonCapability"* ]] || fail "the failure does not name the enum: $out"

# An identifier the parser cannot resolve fails loudly instead of being skipped.
write_swift "workspaceGroups, sidebarLayout, someComputedThing" "remoteTerminalTabs"
if out="$(run)"; then fail "an unresolved identifier passed: $out"; fi
[[ "$out" == *"someComputedThing"* ]] || fail "the failure does not name the unresolved identifier: $out"

# 7558f956c3475 hand-edited an empty list to `[]`. The sets still matched, so
# this check passed, but DaemonCapabilityExportTests.exportIsFresh compares
# bytes and failed on the Mac. The check compares the encoder's bytes too.
write_swift "workspaceGroups, sidebarLayout, remoteTerminalTabs" ""
write_json "remote-terminal-tabs-v1 sidebar-layout-v1 workspace-groups-v1" ""
out="$(run)" || fail "an encoder-shaped empty list failed: $out"
python3 - "$json" <<'EOF'
import sys
path = sys.argv[1]
text = open(path, encoding="utf-8").read()
open(path, "w", encoding="utf-8").write(text.replace(' : [\n\n  ]', ' : []'))
EOF
grep -q '"unservedByBundledDaemon" : \[\]$' "$json" || fail "the fixture lacks the hand-edited [] form: $(cat "$json")"
if out="$(run)"; then fail "a hand-edited [] passed: $out"; fi
[[ "$out" == *"CMUX_UPDATE_DAEMON_CAPABILITIES=1"* ]] || fail "the byte failure lacks the regenerate command: $out"
[[ "$out" == *'+  "unservedByBundledDaemon" : []'* ]] || fail "the byte failure lacks a diff: $out"

# A key order or spacing other than the encoder's fails the same way.
write_json "remote-terminal-tabs-v1 sidebar-layout-v1 workspace-groups-v1" ""
python3 - "$json" <<'EOF'
import sys
path = sys.argv[1]
text = open(path, encoding="utf-8").read()
open(path, "w", encoding="utf-8").write(text.replace('" : ', '": '))
EOF
if out="$(run)"; then fail "a non-encoder separator passed: $out"; fi

# CRLF line endings differ in bytes too; a text-mode read must not hide them.
write_json "remote-terminal-tabs-v1 sidebar-layout-v1 workspace-groups-v1" ""
python3 - "$json" <<'EOF'
import sys
path = sys.argv[1]
data = open(path, "rb").read()
open(path, "wb").write(data.replace(b"\n", b"\r\n"))
EOF
if out="$(run)"; then fail "a CRLF export passed: $out"; fi

# bdce169c4b8af (#21445) put workspace-name-source-v1 in optional and in the
# unserved list; the identify check then failed every dev build. A capability
# in two lists fails here, before any build.
write_swift "workspaceGroups, sidebarLayout" "remoteTerminalTabs, sidebarLayout"
write_json "sidebar-layout-v1 workspace-groups-v1" "remote-terminal-tabs-v1 sidebar-layout-v1"
if out="$(run)"; then fail "a capability in optional and unserved passed: $out"; fi
[[ "$out" == *"in both optional and unservedByBundledDaemon"*"sidebar-layout-v1"* ]] || fail "the failure does not name the overlap: $out"

# The committed export passes as it is.
repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
out="$(python3 "$check" --repo "$repo" 2>&1)" || fail "the committed export failed: $out"

echo "daemon-capabilities-fresh.test.sh: ok"
