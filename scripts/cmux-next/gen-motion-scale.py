#!/usr/bin/env python3
"""Write the Swift, CSS and TypeScript copies of the one motion duration scale (Leo 2026-10-20:
"animations all around are a bit slow"; one token file both sides read).

The one scale is schemas/motion-scale/motion-scale.json. This script writes the app's
(CmuxNextDesignTokens/Motion/MotionScale.generated.swift: the Motion tunables' defaults), the webviews'
CSS (the generated block of webviews/src/pages/shared/desktop.css: --cmux-motion-<step> and
--cmux-ease-out) and their TypeScript (webviews/src/motion/scale.generated.ts: for Web Animations
and timers), so a duration changes in one place for all three.

    python3 scripts/cmux-next/gen-motion-scale.py           # write the copies
    python3 scripts/cmux-next/gen-motion-scale.py --check   # exit 1 when a copy drifted
"""
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SOURCE = "schemas/motion-scale/motion-scale.json"
CSS_FILE = "webviews/src/pages/shared/desktop.css"
TS_FILE = "webviews/src/motion/scale.generated.ts"
SWIFT_FILE = "Packages/macOS/CmuxNext/Sources/CmuxNextDesignTokens/Motion/MotionScale.generated.swift"
BEGIN = "/* motion-scale:begin. GENERATED by scripts/cmux-next/gen-motion-scale.py from " + SOURCE + "; do not edit. */"
END = "/* motion-scale:end */"
# The type scale's block comes first in desktop.css; a missing motion block is written after it.
ANCHOR = "/* type-scale:end */"


def load():
    with open(os.path.join(ROOT, SOURCE)) as handle:
        data = json.load(handle)
    durations = [step["ms"] for step in data["steps"]]
    assert durations == sorted(set(durations)), "steps run short to long, one duration each"
    for step in data["steps"]:
        assert set(step) == {"name", "ms", "for"} and step["name"].isidentifier(), step
    ease = data["easeOut"]
    assert len(ease) == 4 and all(0 <= value <= 1 for value in ease), ease
    return data


def bezier(data):
    return "cubic-bezier(%s)" % ", ".join("%g" % value for value in data["easeOut"])


def css_block(data):
    lines = [BEGIN, ":root {"]
    for step in data["steps"]:
        lines.append("  --cmux-motion-%s: %sms; /* %s */" % (step["name"], step["ms"], step["for"]))
    lines.append("  /* Anything entering eases out. */")
    lines.append("  --cmux-ease-out: %s;" % bezier(data))
    lines += ["}", END]
    return "\n".join(lines)


def css(current, data):
    if BEGIN in current:
        start, end = current.index(BEGIN), current.index(END) + len(END)
        return current[:start] + css_block(data) + current[end:]
    at = current.index(ANCHOR) + len(ANCHOR)
    return current[:at] + "\n" + css_block(data) + current[at:]


def ts(data):
    steps = "\n".join("  /** %s. */\n  %s: %s," % (step["for"][0].upper() + step["for"][1:], step["name"], step["ms"])
                      for step in data["steps"])
    return """// GENERATED by scripts/cmux-next/gen-motion-scale.py from
// {src}. Do not edit; edit the JSON and rerun.

/** The one motion duration scale (ms), shared with the app's `MotionScale` and the CSS `--cmux-motion-*`. */
export const MOTION_MS = {{
{steps}
}} as const;

export type MotionStep = keyof typeof MOTION_MS;

/** Anything entering eases out (`--cmux-ease-out`). */
export const MOTION_EASE_OUT = "{ease}";
""".format(src=SOURCE, steps=steps, ease=bezier(data))


def swift(data):
    steps = "\n".join("    /// %s.\n    public static let %s: TimeInterval = %s"
                      % (step["for"][0].upper() + step["for"][1:], step["name"], "%g" % (step["ms"] / 1000))
                      for step in data["steps"])
    ease = ", ".join("%g" % value for value in data["easeOut"])
    return """// GENERATED by scripts/cmux-next/gen-motion-scale.py from
// {src}. Do not edit; edit the JSON and rerun.

public import Foundation

/// The one motion duration scale of cmux NEXT, shared with the webviews' `--cmux-motion-*` tokens:
/// every timed fade is one of `steps`, and every structural move ends visibly by `large`.
public nonisolated struct MotionScale: Sendable {{
    public init() {{}}

{steps}

    /// Every step, short to long.
    public static let steps: [TimeInterval] = [{all}]

    /// The longest a transition may take to end visibly.
    public static let ceiling: TimeInterval = {ceiling}

    /// Anything entering eases out: the control points of the curve.
    public static let easeOut: (Float, Float, Float, Float) = ({ease})
}}
""".format(src=SOURCE, steps=steps, all=", ".join(step["name"] for step in data["steps"]),
           ceiling=data["steps"][-1]["name"], ease=ease)


def main():
    check = "--check" in sys.argv[1:]
    data = load()
    with open(os.path.join(ROOT, CSS_FILE)) as handle:
        current_css = handle.read()
    wanted = {CSS_FILE: css(current_css, data), TS_FILE: ts(data), SWIFT_FILE: swift(data)}
    drifted = []
    for path, text in wanted.items():
        full = os.path.join(ROOT, path)
        old = open(full).read() if os.path.exists(full) else None
        if old == text:
            continue
        if check:
            drifted.append(path)
        else:
            with open(full, "w") as handle:
                handle.write(text)
            print("wrote " + path)
    if drifted:
        print("motion scale copies drifted from %s: %s\nrun python3 scripts/cmux-next/gen-motion-scale.py" % (SOURCE, ", ".join(drifted)))
        sys.exit(1)


if __name__ == "__main__":
    main()
