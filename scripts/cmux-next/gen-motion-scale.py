#!/usr/bin/env python3
"""Write the Swift, CSS and TypeScript copies of the one motion duration scale (Leo 2026-10-20:
"animations all around are a bit slow"; one token file both sides read).

The one scale is schemas/motion-scale/motion-scale.json. This script writes the app's
(CmuxNextDesignTokens/Motion/MotionScale.generated.swift: the Motion tunables' defaults), the webviews'
CSS (the generated block of webviews/src/pages/shared/desktop.css: --cmux-motion-<step>,
--cmux-ease-out, --cmux-ease-spring, and the fold's --cmux-ease-settle over --cmux-motion-settle) and their TypeScript (webviews/src/motion/scale.generated.ts: for Web Animations
and timers), so a duration changes in one place for all three.

The scale's `spinner` is the one period every spinner turns at (Leo 2026-11-07, of a reference desktop
app's spinner: "Let's have all our spinners go at that speed."). It goes to the same three copies
(--cmux-spinner-period, SPINNER_PERIOD_MS, MotionScale.spinnerPeriod), to the shared native spinner
(Packages/Shared/CmuxSpinner: the iPhone app, Home and Screen), to the motion tokens the
Rust crates build from (design-tokens.json motion.loops.spinner) and to the agent-chat sidecar's
stylesheet, which loads no cmux page CSS.

    python3 scripts/cmux-next/gen-motion-scale.py           # write the copies
    python3 scripts/cmux-next/gen-motion-scale.py --check   # exit 1 when a copy drifted
"""
import json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SOURCE = "schemas/motion-scale/motion-scale.json"
CSS_FILE = "webviews/src/pages/shared/desktop.css"
TS_FILE = "webviews/src/motion/scale.generated.ts"
SWIFT_FILE = "Packages/macOS/CmuxNext/Sources/CmuxNextDesignTokens/Motion/MotionScale.generated.swift"
SPINNER_SWIFT_FILE = "Packages/Shared/CmuxSpinner/Sources/CmuxSpinner/CmuxSpinnerPeriod.swift"
# cmux-tui/crates/cmux-motion/build.rs reads its loops from here.
RUST_TOKENS_FILE = "plans/cmux-next/spec-proposals/visuals/design-tokens.json"
AGENT_CHAT_CSS_FILE = "agent-chat/public/app.css"
# What this check reads. scripts/web_lint_prepush.py runs it alone when a push touches one (declared_inputs()).
INPUTS = (SOURCE, CSS_FILE, TS_FILE, SWIFT_FILE, SPINNER_SWIFT_FILE, RUST_TOKENS_FILE, AGENT_CHAT_CSS_FILE)
BEGIN = "/* motion-scale:begin. GENERATED by scripts/cmux-next/gen-motion-scale.py from " + SOURCE + "; do not edit. */"
END = "/* motion-scale:end */"
# The type scale's block comes first in desktop.css; a missing motion block is written after it.
ANCHOR = "/* type-scale:end */"


def load():
    with open(os.path.join(ROOT, SOURCE)) as handle:
        data = json.load(handle)
    durations = [step["ms"] for step in data["steps"]]
    assert durations == sorted(set(durations)), "steps run short to long, one duration each"
    for step in data["steps"]:
        assert set(step) == {"name", "ms", "for"} and step["name"].isidentifier(), step
    ease = data["easeOut"]
    assert len(ease) == 4 and all(0 <= value <= 1 for value in ease), ease
    spring = data["spring"]
    assert set(spring) == {"step", "for", "points"}, spring
    assert spring["step"] in [step["name"] for step in data["steps"]], "the spring runs over one of the steps"
    points = spring["points"]
    stops = [at for _, at in points]
    assert points[0] == [0, 0] and points[-1] == [1, 100], "the spring starts at rest and ends at rest"
    assert stops == sorted(set(stops)), "the spring's stops run forward"
    settle = data["settle"]
    assert set(settle) == {"ms", "for", "bezier"}, settle
    # Its own measured length: visibly at rest by the scale's ceiling, the last few percent of a point after.
    assert isinstance(settle["ms"], int) and 0 < settle["ms"] <= 300, settle
    # Never past its end: both control points' progress stays within 0..1.
    assert len(settle["bezier"]) == 4 and all(0 <= value <= 1 for value in settle["bezier"]), settle
    spinner = data["spinner"]
    assert set(spinner) == {"ms", "for"} and isinstance(spinner["ms"], int) and spinner["ms"] >= 600, spinner
    send = data["send"]
    assert set(send) == {"ms", "ease", "for"} and isinstance(send["ms"], int), send
    assert len(send["ease"]) == 4 and 0 <= send["ease"][0] <= 1 and 0 <= send["ease"][2] <= 1, send
    return data


def spring_linear(data):
    """The spring as a CSS `linear()` easing: `linear(0, 0.21 6%, ..., 1)`."""
    points = data["spring"]["points"]
    inner = ["%g %g%%" % (value, at) for value, at in points[1:-1]]
    return "linear(%s)" % ", ".join(["0"] + inner + ["1"])


def bezier(data, points=None):
    return "cubic-bezier(%s)" % ", ".join("%g" % value for value in (points or data["easeOut"]))


def css_block(data):
    lines = [BEGIN, ":root {"]
    for step in data["steps"]:
        lines.append("  --cmux-motion-%s: %sms; /* %s */" % (step["name"], step["ms"], step["for"]))
    lines.append("  /* Anything entering eases out. */")
    lines.append("  --cmux-ease-out: %s;" % bezier(data))
    lines.append("  /* A selection that travels settles on the one spring, run over --cmux-motion-%s. */" % data["spring"]["step"])
    lines.append("  --cmux-ease-spring: %s;" % spring_linear(data))
    lines.append("  /* A sent prompt's one motion: its room, its bubble and the thread's rise. */")
    lines.append("  --cmux-motion-send: %sms;" % data["send"]["ms"])
    lines.append("  --cmux-ease-send: %s;" % bezier(data, data["send"]["ease"]))
    settle_ms = data["settle"]["ms"]
    lines.append("  /* A fold or Show more that grows or shrinks decelerates into its new height, never past it. */")
    lines.append("  --cmux-motion-settle: %sms;" % settle_ms)
    lines.append("  --cmux-ease-settle: %s;" % bezier(data, data["settle"]["bezier"]))
    lines.append("  /* One turn of every spinner (`cmux-spin`); not a transition. */")
    lines.append("  --cmux-spinner-period: %sms;" % data["spinner"]["ms"])
    lines += ["}", END]
    return "\n".join(lines)


def css(current, data):
    if BEGIN in current:
        start, end = current.index(BEGIN), current.index(END) + len(END)
        return current[:start] + css_block(data) + current[end:]
    at = current.index(ANCHOR) + len(ANCHOR)
    return current[:at] + "\n" + css_block(data) + current[at:]


def ts(data):
    steps = "\n".join("  /** %s. */\n  %s: %s," % (step["for"][0].upper() + step["for"][1:], step["name"], step["ms"])
                      for step in data["steps"])
    return """// GENERATED by scripts/cmux-next/gen-motion-scale.py from
// {src}. Do not edit; edit the JSON and rerun.

/** The one motion duration scale (ms), shared with the app's `MotionScale` and the CSS `--cmux-motion-*`. */
export const MOTION_MS = {{
{steps}
}} as const;

export type MotionStep = keyof typeof MOTION_MS;

/** Anything entering eases out (`--cmux-ease-out`). */
export const MOTION_EASE_OUT = "{ease}";

/**
 * The one spring (`--cmux-ease-spring`): {spring_for}.
 */
export const MOTION_SPRING = "{spring}";

/** The step the spring runs over (`MOTION_MS[MOTION_SPRING_STEP]`). */
export const MOTION_SPRING_STEP: MotionStep = "{spring_step}";

/**
 * A sent prompt's one motion (ms, `--cmux-motion-send`): {send_for}.
 */
export const MOTION_SEND_MS = {send_ms};

/** The sent prompt's curve (`--cmux-ease-send`): a fast start that settles. */
export const MOTION_EASE_SEND = "{send_ease}";

/** The same curve's control points, for a scroll stepped from script. */
export const MOTION_SEND_CURVE = [{send_points}] as const;

/**
 * The settle (`--cmux-ease-settle`, over `--cmux-motion-settle`): {settle_for}.
 */
export const MOTION_SETTLE = "{settle}";

/** How long the settle runs (ms, `--cmux-motion-settle`): measured, not a step of the scale. */
export const MOTION_SETTLE_MS = {settle_ms};

/** One turn of every spinner (ms, `--cmux-spinner-period`); a loop, not a step of the scale. */
export const SPINNER_PERIOD_MS = {spinner};
""".format(send_for=data["send"]["for"], send_ms=data["send"]["ms"], send_ease=bezier(data, data["send"]["ease"]),
           send_points=", ".join("%g" % value for value in data["send"]["ease"]),
           src=SOURCE, steps=steps, ease=bezier(data), spring=spring_linear(data),
           spring_for=data["spring"]["for"], spring_step=data["spring"]["step"], spinner=data["spinner"]["ms"],
           settle=bezier(data, data["settle"]["bezier"]), settle_for=data["settle"]["for"],
           settle_ms=data["settle"]["ms"])


def swift(data):
    steps = "\n".join("    /// %s.\n    public static let %s: TimeInterval = %s"
                      % (step["for"][0].upper() + step["for"][1:], step["name"], "%g" % (step["ms"] / 1000))
                      for step in data["steps"])
    ease = ", ".join("%g" % value for value in data["easeOut"])
    return """// GENERATED by scripts/cmux-next/gen-motion-scale.py from
// {src}. Do not edit; edit the JSON and rerun.

public import Foundation

/// The one motion duration scale of cmux NEXT, shared with the webviews' `--cmux-motion-*` tokens:
/// every timed fade is one of `steps`, and every structural move ends visibly by `large`.
public nonisolated struct MotionScale: Sendable {{
    public init() {{}}

{steps}

    /// Every step, short to long.
    public static let steps: [TimeInterval] = [{all}]

    /// The longest a transition may take to end visibly.
    public static let ceiling: TimeInterval = {ceiling}

    /// Anything entering eases out: the control points of the curve.
    public static let easeOut: (Float, Float, Float, Float) = ({ease})

    /// One turn of every spinner (`MotionLoop.spinner`'s default); a loop, not a step of the scale.
    public static let spinnerPeriod: TimeInterval = {spinner}
}}
""".format(src=SOURCE, steps=steps, all=", ".join(step["name"] for step in data["steps"]),
           ceiling=data["steps"][-1]["name"], ease=ease, spinner="%g" % (data["spinner"]["ms"] / 1000))


# The value line of `motion.loops.spinner` in design-tokens.json, rewritten in place so the rest of
# the file keeps its formatting.
RUST_SPINNER = re.compile(r'("loops": \{\s*"spinner": \{\s*"value": )([0-9.]+)')
# The shared native spinner's default period, on its marked line.
SPINNER_SWIFT = re.compile(r"(TimeInterval = )([0-9.]+)(\) \{ self\.seconds = seconds \} // spinner-period: gen-motion-scale\.py)")
# agent-chat's own copy of the spinner period, on its `:root`.
AGENT_CHAT_SPINNER = re.compile(r"(--cmux-spinner-period: )(\d+)(ms; /\* GENERATED by scripts/cmux-next/gen-motion-scale\.py \*/)")


def rewrite(current, pattern, value, path):
    assert len(pattern.findall(current)) == 1, "%s: no single spinner period line to write" % path
    return pattern.sub(lambda match: match.group(1) + value + (match.group(3) if pattern.groups > 2 else ""), current)


def main():
    check = "--check" in sys.argv[1:]
    data = load()
    with open(os.path.join(ROOT, CSS_FILE)) as handle:
        current_css = handle.read()
    wanted = {CSS_FILE: css(current_css, data), TS_FILE: ts(data), SWIFT_FILE: swift(data)}
    for path, pattern, value in ((RUST_TOKENS_FILE, RUST_SPINNER, repr(data["spinner"]["ms"] / 1000)),
                                 (SPINNER_SWIFT_FILE, SPINNER_SWIFT, "%g" % (data["spinner"]["ms"] / 1000)),
                                 (AGENT_CHAT_CSS_FILE, AGENT_CHAT_SPINNER, str(data["spinner"]["ms"]))):
        with open(os.path.join(ROOT, path)) as handle:
            wanted[path] = rewrite(handle.read(), pattern, value, path)
    drifted = []
    for path, text in wanted.items():
        full = os.path.join(ROOT, path)
        old = open(full).read() if os.path.exists(full) else None
        if old == text:
            continue
        if check:
            drifted.append(path)
        else:
            with open(full, "w") as handle:
                handle.write(text)
            print("wrote " + path)
    if drifted:
        print("motion scale copies drifted from %s: %s\nrun python3 scripts/cmux-next/gen-motion-scale.py" % (SOURCE, ", ".join(drifted)))
        sys.exit(1)


if __name__ == "__main__":
    main()
