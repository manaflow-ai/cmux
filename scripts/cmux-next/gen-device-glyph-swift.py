#!/usr/bin/env python3
"""Generate the Swift device-kind glyph table into a SwiftPM plugin work directory."""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def render(kinds: dict[str, str]) -> str:
    rows = [f'        "{name}": "{symbol}",' for name, symbol in kinds.items() if name != "generic"]
    return f'''// Generated by scripts/cmux-next/gen-device-glyph-swift.py; do not edit.

/// What a device is, as a device-hub record names it (`HubDevice.kind`), and the SF Symbol that kind draws.
/// The table is shared with cmux-device-kind and the web's deviceGlyphKinds.json.
public struct DeviceGlyphKind: Sendable, Hashable {{
    /// The wire name (`mac-mini`).
    public let name: String
    /// The SF Symbol it draws (`macmini`).
    public let symbol: String

    /// The kind `name` names; nil for no name, a name this build does not know (a newer app's)
    /// and `generic`: the caller then draws the icon it drew before kinds existed.
    public init?(name: String?) {{
        guard let name, let symbol = Self.symbols[name] else {{ return nil }}
        self.name = name
        self.symbol = symbol
    }}

    private static let symbols: [String: String] = [
{chr(10).join(rows)}
    ]
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    kinds = json.loads(args.input.read_text())
    if not isinstance(kinds, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in kinds.items()):
        raise SystemExit(f"{args.input}: expected a JSON object of string kind names to symbols")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(kinds))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
