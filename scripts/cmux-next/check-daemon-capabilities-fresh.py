#!/usr/bin/env python3
"""Fails when plans/cmux-next/daemon-capabilities.json is stale against DaemonEndpoint.swift.

The JSON is exported by DaemonCapabilityExportTests (a Swift test, so it needs a
build) and read by check-daemon-capabilities.sh, which runs only inside an app
build. A Swift-only change to the lists (67b13e24e84d moved sidebar-layout-v1
to `optional`) then breaks every tagged build. This check reads the lists from
the Swift source, with no build, in the Linux checks job and in safe-push. Its
`--write` mode uses the same renderer to repair the committed export in the
base-autofix job.

It reads `enum DaemonCapability`: its cases (`case name = "wire-name"`; a case
without a raw value is its name) and the `tier` switch, whose arms place each case
in `required`, `optional` or `unservedByBundledDaemon`. The Swift lists are
derived from `allCases` and the switch has no `default`, so the compiler puts
every new case in a list; this check refuses what would get around that: a
`default` arm, a case in no arm or in two, an arm that names no case, and a
static member of the catalog that is (or may be) a String instead of a case, in
DaemonEndpoint.swift or in an `extension DaemonCapability` in any Sources file:
stored or computed, typed `String` or untyped, or a static func returning one.
cc7a964ef61's regex over `let NAME = "..."` constants missed a typed one, its
hand-kept lists were the registry CLAUDE.md asks to derive, and the gate APIs
(`supports`, `require`, `missingCapabilities`) still take any String, so such a
static compiles at a gate. That stray check is lexical and has known gaps (a
static in a type nested in an extension, a `typealias` of String, a brace inside
a string literal of the catalog body); typed gates close the hole and delete it
(architecture-refactor-DESIGN.md slice B6).

It then renders the export the way DaemonCapabilityExportTests.json does
(JSONEncoder with .prettyPrinted, .sortedKeys and .withoutEscapingSlashes, each
list sorted, plus a trailing newline) and compares bytes, as exportIsFresh
does: 7558f956c3475 hand-edited an empty list to `[]`, which matched as a set
and failed on the Mac.

Usage: check-daemon-capabilities-fresh.py [--repo ROOT] [--rev REV] [--write]
  --rev reads both files from a commit instead of the working tree.
  --write writes the source-derived export after validating the Swift lists.
"""
from __future__ import annotations

import argparse
import difflib
import json
import re
import subprocess
import sys
from pathlib import Path

SWIFT = "Packages/macOS/CmuxNext/Sources/CmuxNextDaemon/Connection/DaemonEndpoint.swift"
SOURCES = "Packages/macOS/CmuxNext/Sources"
JSON = "plans/cmux-next/daemon-capabilities.json"
REGENERATE = ("CMUX_UPDATE_DAEMON_CAPABILITIES=1 swift test --package-path Packages/macOS/CmuxNext "
              "--filter DaemonCapabilityExportTests (on a fleet Mac or cmux-lawrence-2), then commit "
              + JSON)
LISTS = ("required", "optional", "unservedByBundledDaemon")
# DaemonCapabilityExportTests.json's `comment`.
COMMENT = ("Generated by DaemonCapabilityExportTests from DaemonCapability; "
           "read by scripts/cmux-next/check-daemon-capabilities.sh.")


def read(root: Path, rev: str | None, path: str) -> str:
    if rev is None:
        return (root / path).read_bytes().decode("utf-8")
    return subprocess.run(["git", "-C", str(root), "show", f"{rev}:{path}"],
                          check=True, capture_output=True).stdout.decode("utf-8")


def strip_comments(source: str) -> str:
    """Drops // and /* */ comments outside string literals, keeping line breaks."""
    out, i, n = [], 0, len(source)
    while i < n:
        if source.startswith("//", i):
            j = source.find("\n", i)
            i = n if j < 0 else j
        elif source.startswith("/*", i):
            j = source.find("*/", i + 2)
            out.append("\n" * source.count("\n", i, n if j < 0 else j))
            i = n if j < 0 else j + 2
        elif source[i] == '"':
            j = i + 1
            while j < n and source[j] != '"':
                j += 2 if source[j] == "\\" else 1
            out.append(source[i:j + 1])
            i = j + 1
        else:
            out.append(source[i])
            i += 1
    return "".join(out)


def type_body(source: str, kind: str, name: str) -> str | None:
    match = re.search(r"\b" + kind + r"\s+" + name + r"\b[^{]*\{", source)
    if not match:
        return None
    depth, i = 1, match.end()
    while depth and i < len(source):
        depth += {"{": 1, "}": -1}.get(source[i], 0)
        i += 1
    return source[match.end():i - 1]


def depth_one(body: str) -> str:
    """BODY without the contents of its nested braces (members of nested types, accessor bodies)."""
    out, depth = [], 0
    for c in body:
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        elif depth == 0:
            out.append(c)
    return "".join(out)


CASE_DECL = re.compile(r"^[ \t]*(?:(?:indirect)\s+)?case\s+([^\n;]*)", re.M)
CASE_ITEM = re.compile(r'^([A-Za-z_]\w*)\s*(?:=\s*"([^"]*)")?$')
ARM = re.compile(r"\bcase\s+((?:\.\w+\s*,\s*)*\.\w+)\s*:\s*(?:return\s+)?\.(\w+)")
# The catalog's own body and each extension of it (`extension DaemonCapability`, also module-qualified).
CATALOG_TYPE = re.compile(r"\b(enum|extension)\s+(?:[A-Za-z_]\w*\.)?DaemonCapability\b[^{;]*\{")
CATALOG_EXTENSION = re.compile(r"\bextension\s+(?:[A-Za-z_]\w*\.)?DaemonCapability\b")
STATIC_MEMBER = re.compile(r"\b(?:static|class)\s+(?:[a-z]+(?:\([^)]*\))?\s+)*?(let|var|func)\s+([A-Za-z_]\w*|`[^`]+`)")
STRING_TYPE = re.compile(r"^(?:Swift\.)?(?:String|Substring|StaticString)\s*[?!]?$")


def declaration(members: str, start: int) -> str:
    """The declaration text from START to the end of its line, continued while a ( or [ is open."""
    end, depth = start, 0
    while end < len(members) and not (members[end] == "\n" and depth <= 0):
        depth += {"(": 1, ")": -1, "[": 1, "]": -1}.get(members[end], 0)
        end += 1
    return members[start:end]


def type_text(text: str) -> str:
    """TEXT up to its first `=` or `{` outside (), [] and <> (a declared type or a return type), stripped."""
    depth = 0
    for i, c in enumerate(text):
        if c in "([<":
            depth += 1
        elif c in ")]" or (c == ">" and text[i - 1:i] != "-"):
            depth -= 1
        elif depth <= 0 and c in "={":
            return text[:i].strip()
    return text.strip()


def string_statics(members: str) -> list[tuple[str, str]]:
    """(name, why) for each static member of a catalog body (depth-one code, comments stripped) that is or may
    be a String: a stored or computed `let`/`var` typed String or with no type, or a func returning String."""
    out = []
    for match in STATIC_MEMBER.finditer(members):
        kind, name = match.group(1), match.group(2)
        rest = declaration(members, match.end())
        if kind == "func":
            # The return type follows the first `->` after the parameter list closes.
            level, close = 0, len(rest)
            for i, c in enumerate(rest):
                level += {"(": 1, ")": -1}.get(c, 0)
                if c == ")" and level == 0:
                    close = i + 1
                    break
            arrow = rest.find("->", close)
            returns = type_text(rest[arrow + 2:]) if arrow >= 0 else ""
            returns = re.sub(r"\bwhere\b.*", "", returns).strip()
            if STRING_TYPE.match(returns):
                out.append((name, f"`static func {name}` returns {returns}"))
            continue
        stripped = rest.lstrip()
        literal = re.search(r'=\s*("[^"\\]*")', rest)
        value = f" = {literal.group(1)}" if literal else ""
        if not stripped.startswith(":"):
            out.append((name, f"`static {kind} {name}{value}` declares no type, so it may be a String"))
        elif STRING_TYPE.match(type_text(stripped[1:])):
            out.append((name, f"`static {kind} {name}: {type_text(stripped[1:])}{value}`"))
    return out


def catalog_strays(source: str, where: str) -> list[str]:
    """Each static of the catalog (its enum or an extension of it) in SOURCE that is or may be a String.

    check-app-capability-references.py reads every Sources file with it (rule 4), so both checks refuse the
    same members.
    """
    code = strip_comments(source)
    strays = []
    for match in CATALOG_TYPE.finditer(code):
        depth, i = 1, match.end()
        while depth and i < len(code):
            depth += {"{": 1, "}": -1}.get(code[i], 0)
            i += 1
        line = code.count("\n", 0, match.start()) + 1
        for name, why in string_statics(depth_one(code[match.end():i - 1])):
            strays.append(f"{name} ({why}; {match.group(1)} at {where}:{line})")
    return strays


def extension_sources(root: Path, rev: str | None) -> dict[str, str]:
    """{path: text} of the Sources files other than DaemonEndpoint.swift that extend the catalog."""
    if rev is None:
        found = {}
        for path in sorted((root / SOURCES).rglob("*.swift")):
            rel = path.relative_to(root).as_posix()
            if rel == SWIFT:
                continue
            text = path.read_bytes().decode("utf-8", "replace")
            if "DaemonCapability" in text and CATALOG_EXTENSION.search(text):
                found[rel] = text
        return found
    listed = subprocess.run(["git", "-C", str(root), "grep", "-l", "-E",
                             r"extension[[:space:]]+([A-Za-z_][A-Za-z0-9_]*\.)?DaemonCapability([^A-Za-z0-9_]|$)", rev, "--", SOURCES],
                            check=False, capture_output=True).stdout.decode("utf-8")
    paths = [line.split(":", 1)[1] for line in listed.splitlines() if ":" in line]
    texts = {p: read(root, rev, p) for p in paths if p != SWIFT}
    return {p: text for p, text in texts.items() if CATALOG_EXTENSION.search(text)}


def swift_lists(source: str) -> dict[str, list[str]]:
    """The export's lists (plus `unlisted`: the cases in no arm)."""
    return swift_catalog(source)[1]


def swift_catalog(source: str) -> tuple[dict[str, str], dict[str, list[str]]]:
    """({case: wire name}, lists) of `enum DaemonCapability` in SOURCE (check-app-capability-references.py
    reads the same, so both checks parse the catalog one way)."""
    code = strip_comments(source)
    if type_body(code, "struct", "DaemonCapabilities") is not None:
        sys.exit(f"check-daemon-capabilities-fresh: {SWIFT} declares `struct DaemonCapabilities`; the catalog is "
                 "`enum DaemonCapability` (one case per capability, placed by its `tier` switch)")
    body = type_body(code, "enum", "DaemonCapability")
    if body is None:
        sys.exit(f"check-daemon-capabilities-fresh: no `enum DaemonCapability` in {SWIFT}")
    members = depth_one(body)
    cases: dict[str, str] = {}
    for decl in CASE_DECL.finditer(members):
        for item in (part.strip() for part in decl.group(1).split(",")):
            match = CASE_ITEM.match(item)
            if not match:
                sys.exit(f"check-daemon-capabilities-fresh: cannot read the case `{item}` in {SWIFT}; "
                         "write `case name = \"wire-name\"`")
            cases[match.group(1)] = match.group(2) if match.group(2) is not None else match.group(1)
    tier = re.search(r"\bvar\s+tier\s*:\s*Tier\s*\{", body)
    switch = type_body(body[tier.start():], "switch", "self") if tier else None
    if switch is None:
        sys.exit(f"check-daemon-capabilities-fresh: no `var tier: Tier {{ switch self {{ ... }} }}` in {SWIFT}")
    if re.search(r"\bdefault\s*:", switch):
        sys.exit(f"check-daemon-capabilities-fresh: the `tier` switch in {SWIFT} has a `default` arm, so a new case "
                 "compiles without a list; name every case in an arm")
    lists: dict[str, list[str]] = {name: [] for name in LISTS}
    placed: dict[str, int] = {}
    unresolved = []
    for arm in ARM.finditer(switch):
        if arm.group(2) not in lists:
            unresolved.append(f"tier .{arm.group(2)}")
            continue
        for name in (part.strip().lstrip(".") for part in arm.group(1).split(",")):
            if name not in cases:
                unresolved.append(f"{arm.group(2)}: .{name}")
                continue
            placed[name] = placed.get(name, 0) + 1
            lists[arm.group(2)].append(cases[name])
    if unresolved:
        sys.exit("check-daemon-capabilities-fresh: cannot resolve " + ", ".join(unresolved)
                 + f" in the `tier` switch of {SWIFT}: each arm names cases of DaemonCapability and returns "
                 ".required, .optional or .unservedByBundledDaemon")
    lists["unlisted"] = sorted(name for name in cases if name not in placed)
    return cases, lists


def encode(value: object, depth: int = 0) -> str:
    """One value as Foundation's JSONEncoder writes it with .prettyPrinted and
    .sortedKeys: 2-space indent, `" : "` between key and value, and an empty
    array or object as an opening line, a blank line and the closing bracket."""
    pad, inner = "  " * depth, "  " * (depth + 1)
    if isinstance(value, dict):
        if not value:
            return "{\n\n" + pad + "}"
        items = (f"{inner}{encode(k)} : {encode(value[k], depth + 1)}" for k in sorted(value))
        return "{\n" + ",\n".join(items) + "\n" + pad + "}"
    if isinstance(value, list):
        if not value:
            return "[\n\n" + pad + "]"
        return "[\n" + ",\n".join(inner + encode(v, depth + 1) for v in value) + "\n" + pad + "]"
    if isinstance(value, str):
        # .withoutEscapingSlashes: "/" stays bare, which json.dumps never escapes.
        return json.dumps(value, ensure_ascii=False)
    sys.exit(f"check-daemon-capabilities-fresh: cannot encode {type(value).__name__}")


def render(lists: dict[str, list[str]]) -> str:
    export = {"comment": COMMENT, **{name: sorted(lists[name]) for name in LISTS}}
    return encode(export) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--rev")
    parser.add_argument("--write", action="store_true", help="write the source-derived JSON export")
    args = parser.parse_args()
    if args.write and args.rev:
        parser.error("--write cannot be combined with --rev")
    endpoint = read(args.repo, args.rev, SWIFT)
    swift = swift_lists(endpoint)
    problems = []
    strays = catalog_strays(endpoint, SWIFT)
    for path, text in extension_sources(args.repo, args.rev).items():
        strays += catalog_strays(text, path)
    if strays:
        problems.append("a static of DaemonCapability that is (or may be) a String is in no list: " + "; ".join(strays)
                        + ". A capability is a `case` placed in an arm of `tier`; give any other static a "
                        "non-String type")
    # A capability in required/optional must be served by the bundled daemon;
    # one in the unserved list must not. In both, every build fails (#21445).
    for a, b in (("required", "optional"), ("required", "unservedByBundledDaemon"), ("optional", "unservedByBundledDaemon")):
        both = sorted(set(swift[a]) & set(swift[b]))
        if both:
            problems.append(f"in both {a} and {b} in DaemonEndpoint.swift: {', '.join(both)}; keep each in one tier arm")
    if swift["unlisted"]:
        problems.append("in DaemonCapability but in no list: " + ", ".join(swift["unlisted"])
                        + "; a capability is a `case` placed in an arm of `tier` (required, optional, "
                        "unservedByBundledDaemon)")
    for name in LISTS:
        want = swift[name]
        if len(set(want)) != len(want):
            problems.append(f"{name}: listed twice in Swift: {sorted({c for c in want if want.count(c) > 1})}")
    expected = render(swift)
    if args.write and problems:
        print(f"check-daemon-capabilities-fresh: refusing to write an invalid export at {args.repo}", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    if args.write:
        (args.repo / JSON).write_text(expected, encoding="utf-8")
        print(f"check-daemon-capabilities-fresh: wrote {JSON} from DaemonEndpoint.swift")
        return 0
    stored_text = read(args.repo, args.rev, JSON)
    stored = json.loads(stored_text)
    for name in LISTS:
        want, have = swift[name], stored.get(name, [])
        missing, extra = sorted(set(want) - set(have)), sorted(set(have) - set(want))
        if missing:
            problems.append(f"{name}: in DaemonEndpoint.swift, not in the JSON: {', '.join(missing)}")
        if extra:
            problems.append(f"{name}: in the JSON, not in DaemonEndpoint.swift: {', '.join(extra)}")
    diff = [] if stored_text == expected else list(difflib.unified_diff(
        expected.splitlines(keepends=True), stored_text.splitlines(keepends=True),
        f"{JSON} (as DaemonCapabilityExportTests writes it)", JSON, n=1))
    where = f" at {args.rev}" if args.rev else ""
    if problems or diff:
        print(f"check-daemon-capabilities-fresh: {JSON} is stale{where}:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        if diff and not problems:
            print("  same lists, different bytes from the encoder's output:", file=sys.stderr)
        for line in diff[:40]:
            print("    " + line.rstrip("\n"), file=sys.stderr)
        if len(diff) > 40:
            print(f"    ... {len(diff) - 40} more diff lines", file=sys.stderr)
        print(f"  Regenerate: {REGENERATE}", file=sys.stderr)
        return 1
    counts = ", ".join(f"{len(swift[name])} {name}" for name in LISTS)
    print(f"check-daemon-capabilities-fresh: {JSON} matches DaemonEndpoint.swift{where} ({counts})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
