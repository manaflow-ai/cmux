#!/usr/bin/env python3
"""Generate layout CSS and check the hand-written Swift copy against one grid.

Run with --check to reject stale CSS or Swift. This never writes Swift. Menus
retain gen-menu-metrics.py's AppKit metrics; no menu values are duplicated here.

It also holds the spacings Leo settled (schemas/layout-grid/settled-spacing.json, ask-08a8b942a0:
"we need to like enforce the good versions when we find them"): each pinned value must still be
its source's value, and the source must still say `settled-spacing: <id>`.
"""

import argparse
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = 'schemas/layout-grid/layout-grid.json'
CSS_FILE = 'webviews/src/pages/shared/desktop.css'
SWIFT_FILE = 'Packages/macOS/CmuxNext/Sources/CmuxNextDesignTokens/LayoutGrid.swift'
SETTLED = 'schemas/layout-grid/settled-spacing.json'
SETTLED_FIELDS = ('id', 'what', 'value', 'source', 'date', 'words', 'spec')
# A file pin's comment sits on its line or at most this many lines above it.
SETTLED_COMMENT_REACH = 3
BEGIN = f'/* layout-grid:begin. GENERATED by scripts/cmux-next/gen-layout-grid.py from {SOURCE}; do not edit. */'
END = '/* layout-grid:end */'
ANCHOR = '/* menu-metrics:end */'
HALF_STEPS = {'half-step', 'pill-inset'}


def number(value):
    return type(value) in (int, float) and math.isfinite(value)


def validate(data):
    metrics = data['metrics']
    names = [metric['name'] for metric in metrics]
    if len(names) != len(set(names)):
        raise ValueError('each metric must be named once')
    by_name = {metric['name']: metric for metric in metrics}
    if by_name['base']['pt'] != 4 or by_name['half-step']['pt'] != 2:
        raise ValueError('the base grid is 4 pt and the named half-step is 2 pt')
    for metric in metrics:
        name, pt = metric['name'], metric['pt']
        if name.startswith('menu-'):
            raise ValueError('menus use menu-metrics; do not duplicate them in layout-grid')
        if not re.fullmatch(r'[a-z][a-z0-9]*(?:-[a-z0-9]+)*', name):
            raise ValueError(f'invalid CSS token name: {name}')
        if not number(pt) or pt < 0 or type(metric['scaled']) is not bool:
            raise ValueError(f'{name}: expected a nonnegative finite length and explicit scale policy')
        kind = metric['kind']
        if kind not in {'edge', 'center', 'derived', 'halfStep'}:
            raise ValueError(f'{name}: unknown metric kind {kind}')
        if kind == 'halfStep':
            if name not in HALF_STEPS or pt != 2:
                raise ValueError(f'{name}: only named half-steps may use 2 pt')
        elif kind == 'edge' and pt % 4:
            raise ValueError(f'{name}: edges and sizes must sit on the 4 pt grid')
        elif kind in {'center', 'derived'} and not metric.get('formula'):
            raise ValueError(f'{name}: off-grid lines must be derived from edges and boxes')
        formula = metric.get('formula')
        if formula is not None:
            if not formula or any(ref not in by_name or not number(factor) for ref, factor in formula.items()):
                raise ValueError(f'{name}: invalid formula')
            calculated = sum(by_name[ref]['pt'] * factor for ref, factor in formula.items())
            if not math.isclose(pt, calculated, abs_tol=1e-9):
                raise ValueError(f'{name}: {pt} differs from formula result {calculated}')
    # Reject self/cyclic formulas even if their declared numbers happen to match.
    def visit(name, active):
        if name in active:
            raise ValueError(f'{name}: cyclic formula')
        for ref in by_name[name].get('formula', {}):
            visit(ref, active | {name})
    for name in names:
        visit(name, set())
    for glyph, offset in data['opticalOffsets'].items():
        if not re.fullmatch(r'[a-z][a-z0-9-]*', glyph) or set(offset) != {'x', 'y'}:
            raise ValueError(f'{glyph}: optical offset needs named x and y axes')
        if any(not number(value) or abs(value) > 1 for value in offset.values()):
            raise ValueError(f'{glyph}: optical offsets must be at most 1 pt')
    return data


def lengths(data):
    for metric in data['metrics']:
        yield metric['name'], metric['pt'], metric['scaled'], metric['description']
    for glyph, offset in data['opticalOffsets'].items():
        for axis, value in offset.items():
            yield f'optical-{glyph}-{axis}', value, True, f'Measured optical offset for {glyph}'


def css_block(data):
    lines = [BEGIN, ':root {', '  /* Scaled lengths follow the interface scale; native values remain points. */']
    for name, pt, scaled, description in lengths(data):
        value = f'calc({pt:g}px * var(--cmux-interface-scale, 1))' if scaled else f'{pt:g}px'
        lines.append(f'  --grid-{name}: {value}; /* {description}. */')
    lines.extend(['}', END])
    return '\n'.join(lines)


def css(current, data):
    if BEGIN in current:
        start, end = current.index(BEGIN), current.index(END) + len(END)
        return current[:start] + css_block(data) + current[end:]
    at = current.index(ANCHOR) + len(ANCHOR)
    return current[:at] + '\n' + css_block(data) + current[at:]


def swift_name(name):
    first, *rest = name.split('-')
    return first + ''.join(part.title() for part in rest)


def swift_drift(data, source):
    declared = {name: float(value) for name, value in re.findall(
        r'public static let (\w+): CGFloat = (-?\d+(?:\.\d+)?)\s*(?://[^\n]*)?$', source, re.MULTILINE)}
    wanted = {swift_name(name): pt for name, pt, _, _ in lengths(data)}
    return [f'{name} is {declared.get(name, "missing")}, expected {pt:g}'
            for name, pt in wanted.items() if declared.get(name) != pt] + [
                f'{name} has no schema token' for name in declared.keys() - wanted.keys()]


def settled_drift(data, settled, read):
    """Findings for pins in `settled` that left their source; `read(path)` gives a file's text or None."""
    findings, seen = [], set()
    by_name = {metric['name']: metric for metric in data['metrics']}
    for pin in settled['pins']:
        missing = [field for field in SETTLED_FIELDS if pin.get(field) in (None, '', {})]
        if missing:
            findings.append(f'{SETTLED}: pin {pin.get("id")!r} lacks {", ".join(missing)}')
            continue
        name, value, source = pin['id'], pin['value'], pin['source']
        if not isinstance(source, dict) or ('grid' in source) == ('file' in source):
            findings.append(f'{SETTLED}: {name} source must be {{"grid": NAME}} or {{"file": PATH, "pattern": RE}}')
            continue
        if name in seen:
            findings.append(f'{SETTLED}: pin {name} is listed twice')
        seen.add(name)
        tag = f'settled-spacing: {name}'
        tagged = re.compile(re.escape(tag) + r'(?![\w-])')
        why = f'Leo settled {name} = {value:g} on {pin["date"]} ("{pin["words"]}", {pin["spec"]})'
        if 'grid' in source:
            metric = by_name.get(source['grid'])
            if metric is None:
                findings.append(f'{SETTLED}: {name} names no layout-grid metric {source["grid"]!r}')
            elif metric['pt'] != value:
                findings.append(f'{SOURCE}: {source["grid"]} is {metric["pt"]:g}; {why}')
            elif not tagged.search(metric['description']):
                findings.append(f'{SOURCE}: {source["grid"]} description lost "({tag})"')
            continue
        text = read(source.get('file', ''))
        if text is None:
            findings.append(f'{SETTLED}: {name} reads a missing file {source.get("file")!r}')
            continue
        try:
            pattern = re.compile(source.get('pattern', ''), re.MULTILINE)
        except re.error as error:
            findings.append(f'{SETTLED}: {name} pattern does not compile ({error})')
            continue
        if pattern.groups != 1:
            findings.append(f'{SETTLED}: {name} pattern needs exactly one group, the value')
            continue
        matches = list(pattern.finditer(text))
        if len(matches) != 1:
            findings.append(f'{source["file"]}: {name} pattern matches {len(matches)} times, not once')
            continue
        if float(matches[0].group(1)) != value:
            findings.append(f'{source["file"]}: {name} is {matches[0].group(1)}; {why}')
        line = text.count('\n', 0, matches[0].start())
        nearby = text.split('\n')[max(0, line - SETTLED_COMMENT_REACH):line + 1]
        if not any(tagged.search(row) for row in nearby):
            findings.append(f'{source["file"]}:{line + 1}: {name} lost its "{tag}" comment')
    return findings


def read_file(path):
    full = ROOT / path
    return full.read_text() if path and full.is_file() else None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        data = validate(json.loads((ROOT / SOURCE).read_text()))
        current = (ROOT / CSS_FILE).read_text()
        wanted = css(current, data)
        drift = swift_drift(data, (ROOT / SWIFT_FILE).read_text())
        drift += settled_drift(data, json.loads((ROOT / SETTLED).read_text()), read_file)
        if current != wanted:
            if args.check:
                drift.append(f'{CSS_FILE}: run python3 scripts/cmux-next/gen-layout-grid.py')
            else:
                (ROOT / CSS_FILE).write_text(wanted)
                print(f'wrote {CSS_FILE}')
        if drift:
            raise ValueError('; '.join(drift) + '; edit the Swift copy by hand, and change a settled '
                             f'spacing only together with its pin in {SETTLED}')
    except (KeyError, TypeError, ValueError, OSError) as error:
        parser.exit(1, f'layout grid: {error}\n')


if __name__ == '__main__':
    main()
