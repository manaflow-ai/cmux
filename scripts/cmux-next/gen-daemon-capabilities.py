#!/usr/bin/env python3
"""Write `enum DaemonCapability` (CmuxNextDaemon) from cmux-tui/spec/gui-capabilities.json.

The catalog of daemon capabilities the app relies on is that JSON: each entry's Swift case name, wire name
(the case's rawValue), tier and doc comment, in `allCases` order. The Swift enum is not in git: the
DaemonCapabilitiesPlugin build-tool plugin runs this script with --swift-out on every build, and it rewrites
the file only when its bytes change, so an incremental build recompiles nothing. The lists derived from the
tiers (`required`, `optional`, `advertised`, ...) stay hand-written in DaemonEndpoint.swift's
`extension DaemonCapability`.

    python3 scripts/cmux-next/gen-daemon-capabilities.py --swift-out DIR   # write DIR/DaemonCapability.generated.swift
    python3 scripts/cmux-next/gen-daemon-capabilities.py --print           # the Swift on stdout
    python3 scripts/cmux-next/gen-daemon-capabilities.py --check           # exit 1 when the JSON is invalid or not canonical
    python3 scripts/cmux-next/gen-daemon-capabilities.py --format          # rewrite the JSON in its canonical layout

check-daemon-capabilities-fresh.py and check-app-capability-references.py render the Swift with `render`
from the JSON at the revision they read, so they parse exactly what the build compiles.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = "cmux-tui/spec/gui-capabilities.json"
OUTPUT = "DaemonCapability.generated.swift"
TIERS = ("required", "optional", "unservedByBundledDaemon")
HEADER = ("// GENERATED by scripts/cmux-next/gen-daemon-capabilities.py from cmux-tui/spec/gui-capabilities.json.\n"
          "// Do not edit: change the JSON (DaemonCapabilitiesPlugin writes this file on every build).\n")
_IDENTIFIER = re.compile(r"[a-z][A-Za-z0-9]*")
_WIRE = re.compile(r"[a-z0-9][a-z0-9._-]*")
_KEYS = ("case", "wire", "tier", "doc")
_KEYWORDS = frozenset({"default", "self", "init", "case", "class", "struct", "enum", "func", "let", "var", "in",
                       "is", "as", "return", "switch", "where", "while", "for", "if", "else", "do", "try"})


class CatalogError(ValueError):
    """The catalog JSON is not one the generator can turn into the enum."""


def read_text(root: Path, rev: str | None, path: str = SOURCE) -> str | None:
    """The file at ROOT (or at REV in ROOT's git); None when it is not there (a revision before the catalog)."""
    if rev is None:
        file = root / path
        return file.read_text(encoding="utf-8") if file.is_file() else None
    shown = subprocess.run(["git", "-C", str(root), "show", f"{rev}:{path}"], capture_output=True)
    return shown.stdout.decode("utf-8") if shown.returncode == 0 else None


def parse(text: str) -> list[dict]:
    """The catalog's entries, validated: each has a unique Swift identifier and wire name and a known tier."""
    try:
        data = json.loads(text)
    except json.JSONDecodeError as error:
        raise CatalogError(f"{SOURCE} is not JSON: {error}") from error
    if not isinstance(data, dict) or not isinstance(data.get("capabilities"), list):
        raise CatalogError(f"{SOURCE} must be an object with a `capabilities` array")
    extra = set(data) - {"$comment", "capabilities"}
    if extra:
        raise CatalogError(f"{SOURCE}: unknown top-level keys {sorted(extra)}")
    entries, cases, wires = [], set(), set()
    for index, entry in enumerate(data["capabilities"]):
        where = f"{SOURCE} capabilities[{index}]"
        if not isinstance(entry, dict) or set(entry) - set(_KEYS) or not {"case", "wire", "tier"} <= set(entry):
            raise CatalogError(f"{where}: an entry is {{case, wire, tier[, doc]}}")
        case, wire, tier, doc = entry["case"], entry["wire"], entry["tier"], entry.get("doc", [])
        if not isinstance(case, str) or not _IDENTIFIER.fullmatch(case) or case in _KEYWORDS:
            raise CatalogError(f"{where}: case {case!r} is not a lowerCamelCase Swift identifier")
        if not isinstance(wire, str) or not _WIRE.fullmatch(wire):
            raise CatalogError(f"{where}: wire {wire!r} is not a capability name (lowercase, digits, -, _, .)")
        if tier not in TIERS:
            raise CatalogError(f"{where}: tier {tier!r} is not one of {', '.join(TIERS)}")
        if not isinstance(doc, list) or not all(isinstance(line, str) and "\n" not in line for line in doc):
            raise CatalogError(f"{where}: doc is a list of single-line strings")
        if case in cases:
            raise CatalogError(f"{where}: case {case} is listed twice")
        if wire in wires:
            raise CatalogError(f"{where}: wire {wire} is listed twice")
        cases.add(case)
        wires.add(wire)
        entries.append({"case": case, "wire": wire, "tier": tier, "doc": list(doc)})
    if not entries:
        raise CatalogError(f"{SOURCE} lists no capability")
    return entries


def canonical(text: str) -> str:
    """The JSON in its one layout: the comment, then one line per entry and its doc lines below it."""
    data = json.loads(text)
    entries = parse(text)
    dump = lambda value: json.dumps(value, ensure_ascii=False)  # noqa: E731
    lines = ["{", '  "$comment": [']
    comment = data.get("$comment", [])
    lines += [f"    {dump(line)}" + ("," if i < len(comment) - 1 else "") for i, line in enumerate(comment)]
    lines += ["  ],", '  "capabilities": [']
    for i, entry in enumerate(entries):
        head = f'    {{"case": {dump(entry["case"])}, "wire": {dump(entry["wire"])}, "tier": {dump(entry["tier"])}'
        tail = "," if i < len(entries) - 1 else ""
        if entry["doc"]:
            lines.append(head + ', "doc": [')
            lines += [f"      {dump(line)}" + ("," if j < len(entry["doc"]) - 1 else "")
                      for j, line in enumerate(entry["doc"])]
            lines.append("    ]}" + tail)
        else:
            lines.append(head + "}" + tail)
    lines += ["  ]", "}"]
    return "\n".join(lines) + "\n"


def _arm(names: list[str], tier: str) -> list[str]:
    """One `case .a, .b:` arm, wrapped under 120 columns."""
    out, line = [], "        case "
    for i, name in enumerate(names):
        item = f".{name}" + ("," if i < len(names) - 1 else ":")
        if len(line) + len(item) + 1 > 120 and line.strip() != "case":
            out.append(line.rstrip())
            line = "             "
        line += item + " "
    out.append(line.rstrip())
    out.append(f"            return .{tier}")
    return out


def render(entries: list[dict]) -> str:
    """The Swift of `enum DaemonCapability`: its cases, `Tier` and the exhaustive `tier` switch."""
    lines = [HEADER, "/// A daemon capability the GUI relies on (plans/cmux-next/cmux-tui-contract.md 2.2): one case per",
             "/// wire name, which is its `rawValue`. The cases, their tiers and docs are cmux-tui/spec/gui-capabilities.json.",
             "///",
             "/// Every case is in exactly one ``Tier``. ``tier`` is an exhaustive `switch` without a `default`, and",
             "/// ``required``, ``optional`` and ``unservedByBundledDaemon`` are derived from `allCases`",
             "/// (DaemonEndpoint.swift): no list is kept by hand. DaemonCapabilityExportTests writes them to",
             "/// plans/cmux-next/daemon-capabilities.json, and scripts/cmux-next/check-daemon-capabilities-fresh.py",
             "/// checks that export against the JSON without a build.",
             "///",
             "/// ```swift",
             "/// guard daemon.supports(DaemonCapability.tabDrag.rawValue) else { return }",
             "/// ```",
             "public enum DaemonCapability: String, CaseIterable, Sendable {"]
    for entry in entries:
        lines += [f"    /// {line}".rstrip() for line in entry["doc"]]
        lines.append(f"    case {entry['case']} = {json.dumps(entry['wire'])}")
    lines += [
        "",
        "    /// Which list a capability is in.",
        "    public enum Tier: Sendable {",
        "        /// The GUI refuses a daemon without it.",
        "        case required",
        "        /// The bundled daemon serves it (check-daemon-capabilities.sh fails the build when it does",
        "        /// not); the GUI still checks it per daemon with `DaemonIdentity.supports`.",
        "        case optional",
        "        /// App code waiting for a daemon half that no branch has yet; the list only shrinks.",
        "        case unservedByBundledDaemon",
        "    }",
        "",
        "    /// The list this capability is in: each entry's `tier` in the JSON.",
        "    public var tier: Tier {",
        "        switch self {",
    ]
    for tier in TIERS:
        names = [entry["case"] for entry in entries if entry["tier"] == tier]
        if names:
            lines += _arm(names, tier)
    lines += ["        }", "    }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=Path, default=ROOT)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--swift-out", type=Path, help="write DIR/" + OUTPUT + " when its bytes change")
    mode.add_argument("--print", action="store_true", help="print the Swift")
    mode.add_argument("--check", action="store_true", help="exit 1 when the JSON is invalid or not canonical")
    mode.add_argument("--format", action="store_true", help="rewrite the JSON in its canonical layout")
    args = parser.parse_args()
    text = read_text(args.repo, None)
    if text is None:
        print(f"gen-daemon-capabilities: {args.repo / SOURCE} is missing", file=sys.stderr)
        return 2
    try:
        entries = parse(text)
        layout = canonical(text)
    except CatalogError as error:
        print(f"gen-daemon-capabilities: {error}", file=sys.stderr)
        return 1
    if args.check:
        if text != layout:
            print(f"gen-daemon-capabilities: {SOURCE} is not in its canonical layout; run "
                  "python3 scripts/cmux-next/gen-daemon-capabilities.py --format", file=sys.stderr)
            return 1
        print(f"gen-daemon-capabilities: {SOURCE} is valid ({len(entries)} capabilities)")
        return 0
    if args.format:
        if text != layout:
            (args.repo / SOURCE).write_text(layout, encoding="utf-8")
        return 0
    swift = render(entries)
    if args.print:
        sys.stdout.write(swift)
        return 0
    args.swift_out.mkdir(parents=True, exist_ok=True)
    out = args.swift_out / OUTPUT
    if not out.is_file() or out.read_text(encoding="utf-8") != swift:
        out.write_text(swift, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
