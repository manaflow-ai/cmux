#!/usr/bin/env python3
"""Write the copies of the one design scale (spacing, controls, icons, radii, glass, elevation and the
colour roles) and the Tailwind theme every Tailwind entry imports.

The sources are schemas/design-scale/design-scale.json, schemas/type-scale/type-scale.json and
schemas/motion-scale/motion-scale.json. This script writes:

- the design-scale block of webviews/src/pages/shared/desktop.css (--ds-*, --elevation-*, --ds-color-*);
- webviews/src/ui/theme.generated.css: Tailwind 4 `@theme inline` naming those variables, so p-3,
  rounded-md, text-body, bg-hover, shadow-elevation-2 and duration-quick resolve to our tokens;
- webviews/src/ui/designTokens.generated.ts: the same list for the gallery's token sheet and tests.

    python3 scripts/cmux-next/gen-design-scale.py           # write the copies
    python3 scripts/cmux-next/gen-design-scale.py --check   # exit 1 when a copy drifted
"""
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SOURCE = "schemas/design-scale/design-scale.json"
TYPE_SOURCE = "schemas/type-scale/type-scale.json"
MOTION_SOURCE = "schemas/motion-scale/motion-scale.json"
CSS_FILE = "webviews/src/pages/shared/desktop.css"
THEME_FILE = "webviews/src/ui/theme.generated.css"
TS_FILE = "webviews/src/ui/designTokens.generated.ts"
BEGIN = "/* design-scale:begin. GENERATED by scripts/cmux-next/gen-design-scale.py from " + SOURCE + "; do not edit. */"
END = "/* design-scale:end */"
# The type scale's own aliases (gen-type-scale.py): menu rows and composer controls, reading content.
TYPE_ALIASES = ["control", "content"]


def read(path):
    with open(os.path.join(ROOT, path)) as handle:
        return json.load(handle)


def load():
    data = read(SOURCE)
    for step in data["spacing"]["steps"]:
        assert step["px"] % 4 == 0, step
    for group in ("controls", "icons", "radii"):
        sizes = [entry["px"] for entry in data[group]]
        assert sizes == sorted(set(sizes)), "%s run small to large, one size each" % group
    assert [entry["px"] for entry in data["icons"]] == [12, 14, 16, 20], "grid.md's icon scale"
    for level in data["glass"]:
        assert 0 < level["tint"] < 90, "glass, never opaque (surface-roles nearOpaque 0.9): %s" % level
    assert len(data["elevation"]) == 2, "exactly two shadows"
    for color in data["colors"]:
        assert color["var"].startswith("--cmux-"), "a colour role names a host variable: %s" % color
        assert "#" not in color["var"], color
    return data, read(TYPE_SOURCE), read(MOTION_SOURCE)


def px(value):
    return "%gpx" % value


def glass_vars(level):
    blur = level.get("blurName", "blur")
    return ("--ds-glass-%s-tint" % level["name"], "%d%%" % level["tint"]), ("--ds-glass-%s-%s" % (level["name"], blur), level["blur"])


def color_value(color):
    inner = color["fallback"]
    if color.get("app"):
        inner = "var(%s, %s)" % (color["app"], inner)
    return "var(%s, %s)" % (color["var"], inner)


def shadow(entry, mode):
    return "%s color-mix(in srgb, black %d%%, transparent)" % (entry["geometry"], entry[mode])


def css_block(data):
    out = [BEGIN, ":root {"]
    for step in data["spacing"]["steps"]:
        out.append("  --ds-space-%s: %s;" % (step["name"], px(step["px"])))
    for size in data["spacing"]["layout"]:
        out.append("  --ds-space-%d: %s; /* layout gap */" % (size, px(size)))
    for control in data["controls"]:
        out.append("  --ds-control-%s: %s; /* %s */" % (control["name"], px(control["px"]), control["for"]))
    for icon in data["icons"]:
        out.append("  --ds-icon-%s: %s; /* %s */" % (icon["name"], px(icon["px"]), icon["for"]))
    for radius in data["radii"]:
        out.append("  --ds-radius-%s: %s; /* %s */" % (radius["name"], px(radius["px"]), radius["for"]))
    for radius in data["namedRadii"]:
        value = radius.get("var") or px(radius["px"])
        note = " /* %s */" % radius["for"] if radius.get("for") else ""
        out.append("  --ds-radius-%s: %s;%s" % (radius["name"], value, note))
    for level in data["glass"]:
        (tint_name, tint), (blur_name, blur) = glass_vars(level)
        out.append("  /* glass %s: %s */" % (level["name"], level["for"]))
        out.append("  %s: %s;" % (tint_name, tint))
        out.append("  %s: %s;" % (blur_name, blur))
    out.append("  --ds-glass-edge: var(--cmux-hairline);")
    for entry in data["elevation"]:
        out.append("  --elevation-%s: %s; /* %s */" % (entry["name"], shadow(entry, "light"), entry["for"]))
    for color in data["colors"]:
        out.append("  --ds-color-%s: %s; /* %s */" % (color["name"], color_value(color), color["for"]))
    out.append("}")
    dark = ["    --elevation-%s: %s;" % (entry["name"], shadow(entry, "dark")) for entry in data["elevation"]]
    out.append("@media (prefers-color-scheme: dark) {")
    out.append('  :root:not([data-theme="light"]) {')
    out += dark
    out += ["  }", "}", ':root[data-theme="dark"] {']
    out += [line[2:] for line in dark]
    out += ["}", END]
    return "\n".join(out)


def css(current, data):
    start, end = current.index(BEGIN), current.index(END) + len(END)
    return current[:start] + css_block(data) + current[end:]


def theme(data, type_scale, motion):
    out = [
        "/* GENERATED by scripts/cmux-next/gen-design-scale.py from %s, %s and %s; do not edit." % (SOURCE, TYPE_SOURCE, MOTION_SOURCE),
        "   The one Tailwind theme: every Tailwind entry imports it before its own @theme, so a surface's",
        "   own names (the agent pane's text-fg, Settings' border-edge) still win where they differ. Each",
        "   value names a token of pages/shared/desktop.css (loaded first everywhere), never a literal, so",
        "   light, dark and the terminal theme reach the utilities through the variables. */",
        "@theme inline {",
        "  /* p-1 is 4px, p-3 12px, gap-6 24px: the grid base, which follows the interface scale. */",
        "  --spacing: %s;" % data["spacing"]["unit"],
    ]
    for control in data["controls"]:
        out.append("  --spacing-control-%s: var(--ds-control-%s);" % (control["name"], control["name"]))
    for icon in data["icons"]:
        out.append("  --spacing-icon-%s: var(--ds-icon-%s);" % (icon["name"], icon["name"]))
    for radius in data["radii"] + data["namedRadii"]:
        out.append("  --radius-%s: var(--ds-radius-%s);" % (radius["name"], radius["name"]))
    for step in [step["name"] for step in type_scale["steps"]] + TYPE_ALIASES:
        out.append("  --text-%s: var(--text-%s);" % (step, step))
        out.append("  --text-%s--line-height: var(--text-%s--line-height);" % (step, step))
        if step != "content":
            out.append("  --text-%s--letter-spacing: var(--text-%s--letter-spacing);" % (step, step))
    for weight in type_scale["weights"]:
        out.append("  --font-weight-%s: var(--weight-%s);" % (weight["name"], weight["name"]))
    out.append("  --font-ui: var(--font-ui);")
    for color in data["colors"]:
        out.append("  --color-%s: var(--ds-color-%s);" % (color["name"], color["name"]))
    for entry in data["elevation"]:
        out.append("  --shadow-elevation-%s: var(--elevation-%s);" % (entry["name"], entry["name"]))
    for step in motion["steps"]:
        out.append("  --transition-duration-%s: var(--cmux-motion-%s);" % (step["name"], step["name"]))
    out.append("  --ease-standard: var(--cmux-ease-out);")
    out.append("}")
    return "\n".join(out) + "\n"


def ts(data, type_scale, motion):
    def entries(rows):
        return "\n".join("  " + json.dumps(row, separators=(", ", ": ")) + "," for row in rows)

    spacing = [{"name": step["name"], "variable": "--ds-space-%s" % step["name"], "px": step["px"]}
               for step in data["spacing"]["steps"]]
    spacing += [{"name": str(size), "variable": "--ds-space-%d" % size, "px": size}
                for size in data["spacing"]["layout"]]
    controls = [{"name": c["name"], "variable": "--ds-control-%s" % c["name"], "px": c["px"], "for": c["for"]} for c in data["controls"]]
    icons = [{"name": i["name"], "variable": "--ds-icon-%s" % i["name"], "px": i["px"], "for": i["for"]} for i in data["icons"]]
    radii = [{"name": r["name"], "variable": "--ds-radius-%s" % r["name"], "px": r.get("px"), "for": r.get("for", "")}
             for r in data["radii"] + data["namedRadii"]]
    glass = []
    for level in data["glass"]:
        (tint_name, _), (blur_name, _) = glass_vars(level)
        glass.append({"name": level["name"], "tint": tint_name, "blur": blur_name, "tintPercent": level["tint"], "filter": level["blur"], "for": level["for"]})
    elevation = [{"name": e["name"], "variable": "--elevation-%s" % e["name"], "for": e["for"]} for e in data["elevation"]]
    colors = [{"name": c["name"], "variable": "--ds-color-%s" % c["name"], "value": color_value(c), "for": c["for"]} for c in data["colors"]]
    text = [{"name": s["name"], "variable": "--text-%s" % s["name"], "px": s["size"], "lineHeight": s["lineHeight"], "for": s["for"]} for s in type_scale["steps"]]
    motion_rows = [{"name": s["name"], "variable": "--cmux-motion-%s" % s["name"], "ms": s["ms"], "for": s["for"]} for s in motion["steps"]]
    sections = [
        ("SPACING", "Spacing: Tailwind's unit is the grid base, so `p-N` is N x 4 px.", spacing),
        ("CONTROLS", "Control heights.", controls),
        ("ICONS", "The icon scale (grid.md): 12, 14, 16, 20.", icons),
        ("RADII", "Corner radii.", radii),
        ("GLASS", "Glass levels: the surface's tint percentage and the backdrop filter.", glass),
        ("ELEVATION", "The two shadows.", elevation),
        ("COLORS", "Colour roles, derived from the active terminal theme by the host.", colors),
        ("TEXT", "The type scale (schemas/type-scale).", text),
        ("MOTION", "The motion scale (schemas/motion-scale).", motion_rows),
    ]
    body = "\n\n".join("/** %s */\nexport const %s = [\n%s\n] as const;" % (doc, name, entries(rows)) for name, doc, rows in sections)
    return ("// GENERATED by scripts/cmux-next/gen-design-scale.py from %s,\n// %s and %s. Do not edit; edit the JSON and rerun.\n\n%s\n\n"
            "/** The one ease-out every arrival uses (the Tailwind ease). */\nexport const EASE_STANDARD = \"var(--cmux-ease-out)\";\n"
            % (SOURCE, TYPE_SOURCE, MOTION_SOURCE, body))


def main():
    check = "--check" in sys.argv[1:]
    data, type_scale, motion = load()
    with open(os.path.join(ROOT, CSS_FILE)) as handle:
        current_css = handle.read()
    wanted = {CSS_FILE: css(current_css, data), THEME_FILE: theme(data, type_scale, motion), TS_FILE: ts(data, type_scale, motion)}
    drifted = []
    for path, text in wanted.items():
        full = os.path.join(ROOT, path)
        old = open(full).read() if os.path.exists(full) else None
        if old == text:
            continue
        if check:
            drifted.append(path)
        else:
            with open(full, "w") as handle:
                handle.write(text)
            print("wrote " + path)
    if drifted:
        print("design scale copies drifted from %s: %s\nrun python3 scripts/cmux-next/gen-design-scale.py" % (SOURCE, ", ".join(drifted)))
        sys.exit(1)


if __name__ == "__main__":
    main()
