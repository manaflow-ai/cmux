"""Turns collected results into the matrix (JSON and Markdown)."""
import json
import os

# Rows whose failure is a documented decision, not a bug
# (plans/cmux-next/browser.md, "Extension APIs cmux does not support").
INTENTIONAL = {
    ("identity", "getAuthToken"): ("no Google sign-in in cmux; the web OAuth fallback (fork API 13) needs a real "
                                   "oauth2.client_id that Google accepts, and the fixture's is not one"),
}

ORDER = {"pass": 0, "pending": 1, "unverified": 2, "unsupported": 3, "error": 4, "fail": 5, "missing": 6}


def classify(result):
    status = result.get("status", "missing")
    reason = INTENTIONAL.get((result.get("api"), result.get("test")))
    if status == "fail" and reason:
        return "unsupported", f"intentional: {reason}; error: {result.get('detail', '')}"
    return status, result.get("detail", "")


def rows(snapshot):
    out = []
    for result in snapshot["results"]:
        status, detail = classify(result)
        out.append({"suite": result.get("suite"), "api": result.get("api"), "test": result.get("test"),
                    "status": status, "detail": detail})
    out.sort(key=lambda r: (r["suite"] or "", r["api"] or "", r["test"] or ""))
    return out


def counts(table):
    total = {}
    for row in table:
        total[row["status"]] = total.get(row["status"], 0) + 1
    return total


def markdown(table, title, header_lines=()):
    lines = [f"### {title}", ""]
    lines += list(header_lines)
    summary = counts(table)
    lines.append("Counts: " + ", ".join(f"{k} {summary[k]}" for k in sorted(summary, key=lambda k: ORDER.get(k, 9))))
    lines += ["", "| Suite | API | Check | Result | Detail |", "| --- | --- | --- | --- | --- |"]
    for row in table:
        detail = str(row["detail"]).replace("|", "\\|").replace("\n", " ")[:220]
        lines.append(f"| {row['suite']} | {row['api']} | {row['test']} | {row['status']} | {detail} |")
    return "\n".join(lines) + "\n"


def write(path_json, path_md, table, title, header_lines=()):
    with open(path_json, "w") as out:
        json.dump(table, out, indent=2)
    with open(path_md, "w") as out:
        out.write(markdown(table, title, header_lines))


def _load(run_dir):
    with open(os.path.join(run_dir, "matrix.json")) as handle:
        return json.load(handle)


def _merge_store(store_dirs):
    """Rows of several store runs; a later run replaces an extension's rows."""
    merged, rerun = {}, set()
    for index, run_dir in enumerate(store_dirs):
        by_extension = {}
        for row in _load(run_dir):
            by_extension.setdefault(row["api"], []).append(row)
        for extension_id, rows in by_extension.items():
            if index and extension_id in merged:
                rerun.add(extension_id)
            merged[extension_id] = rows
    return [row for rows in merged.values() for row in rows], rerun


def write_report(path, api_dir, store_dir):
    """plans/cmux-next/extensions-matrix.md from an api run and one or more
    store runs (comma-separated; later runs replace an extension's rows)."""
    store_dirs = store_dir.split(",")
    api = _load(api_dir)
    store, rerun = _merge_store(store_dirs)
    for row in store:
        # The harness, not the extension, failed (socket or CDP timeout under load).
        if row["status"] == "fail" and (row["test"] in ("batch", "runner") or "runner error" in str(row["detail"])):
            row["status"] = "error"
    extensions = {}
    for row in store:
        extensions.setdefault((row["suite"], row["api"]), []).append(row)
    verdicts = {}
    for key, checks in extensions.items():
        statuses = {c["status"] for c in checks}
        verdicts[key] = ("unavailable" if statuses == {"unsupported"} and checks[0]["test"] == "install"
                         else "fail" if "fail" in statuses else "not checked (harness error)" if "error" in statuses else "pass")
    per_extension = {}
    for verdict in verdicts.values():
        per_extension[verdict] = per_extension.get(verdict, 0) + 1
    api_counts = counts(api)
    lines = [
        "# Chrome extensions: end-to-end matrix",
        "",
        "Generated by `scripts/cmux-next/ext-e2e.py report` from the runs "
        f"`{os.path.basename(api_dir)}` and {', '.join(f'`{os.path.basename(d)}`' for d in store_dirs)}"
        f"{f' ({len(rerun)} extensions re-run in the later store run after a timeout or failure)' if rerun else ''}. "
        "How the suites work and what cmux does "
        "not support: plans/cmux-next/browser.md, \"Chrome extensions: end-to-end verification\".",
        "",
        "The Chrome Web Store has more than 100,000 extensions; this matrix covers the chrome.* API surface and "
        f"{len(verdicts)} listed real extensions, not every extension.",
        "",
        "Summary:",
        "",
        f"- API checks: {len(api)} ({', '.join(f'{k} {v}' for k, v in sorted(api_counts.items(), key=lambda i: ORDER.get(i[0], 9)))}).",
        f"- Real extensions: {len(verdicts)} ({', '.join(f'{k} {v}' for k, v in sorted(per_extension.items()))}); "
        f"checks {', '.join(f'{k} {v}' for k, v in sorted(counts(store).items(), key=lambda i: ORDER.get(i[0], 9)))}.",
        "",
        "## Real extensions, one line each",
        "",
        "| Extension | Id | Verdict | Failed checks |",
        "| --- | --- | --- | --- |",
    ]
    for (name, extension_id), verdict in sorted(verdicts.items()):
        failed = "; ".join(f"{c['test']}: {str(c['detail'])[:90]}".replace("|", "\\|")
                           for c in extensions[(name, extension_id)] if c["status"] in ("fail", "unsupported", "error"))
        lines.append(f"| {name} | `{extension_id}` | {verdict} | {failed} |")
    lines.append("")
    body = "\n".join(lines) + "\n\n" + markdown(api, "API conformance").replace("### ", "## ") + "\n" + \
        markdown(store, "Real extensions, every check").replace("### ", "## ")
    with open(path, "w") as out:
        out.write(body)
