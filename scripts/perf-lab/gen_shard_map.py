#!/usr/bin/env python3
"""The perf lab's shard map: each T0/T1/T2 story bound to one waterfall shard of each lab class.

    python3 -I scripts/perf-lab/gen_shard_map.py            # rewrite shard_map.json from stories.d/
    python3 -I scripts/perf-lab/gen_shard_map.py --check    # exit 1 when shard_map.json is stale
    python3 -I scripts/perf-lab/lab.py shard-map [--check]  # the same, as a lab.py command

Chrome binds every story to one fixed device: tools/perf/core/shard_maps/*.json are generated by
tools/perf/generate_perf_sharding.py from measured story times, and the number of shards per builder comes
from tools/perf/core/bot_platforms.py (`num_shards`). LAYOUT below is that table for the lab
(p12-perf-process.md 3.1), and the packing is the same greedy bin packing on story seconds: longest story first,
onto the least-loaded shard. The scheduler (scheduler.py) runs a story only on its owner shard's host; pool.json
(task 130) names the host that holds each shard. A story is never moved when its host is down; that point is a gap.

Stdlib only; loads catalog.py by file path, so it runs under `python3 -I`.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]


def _load_sibling(name: str):
    module_name = f"perf_lab_{name}"
    if module_name in sys.modules:
        return sys.modules[module_name]
    spec = importlib.util.spec_from_file_location(module_name, HERE / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module  # before exec: dataclasses resolve their module through sys.modules
    spec.loader.exec_module(module)
    return module


SCHEMA = "cmux-perf-shard-map/v1"
SHARD_MAP_PATH = "scripts/perf-lab/shard_map.json"
SHARDED_TIERS = ("T0", "T1", "T2")

# Lab class -> waterfall shards and the tiers they run (p12-perf-process.md 3.1 and 3.3; bot_platforms.py
# num_shards). T0 runs only on the 2 M6 waterfall minis; T1 runs on every class; T2 on the other classes.
LAYOUT: dict[str, dict[str, object]] = {
    "m6": {"shards": 2, "tiers": ("T0", "T1")},
    "cmux20-bench": {"shards": 1, "tiers": ("T1", "T2")},
    "aws-m4pro": {"shards": 1, "tiers": ("T1", "T2")},
}

# How often each tier starts a round on a shard (scheduler.py BATCH_INTERVAL, T1_INTERVAL, the lab day). A shard
# whose stories of a tier take longer than that keeps its host busy with that tier and starves the lower tiers.
TIER_INTERVAL_SECONDS = {"T0": 10 * 60, "T1": 2 * 3600, "T2": 24 * 3600}


def pack(stories: Iterable[tuple[str, int]], shards: int) -> tuple[list[list[str]], list[int]]:
    """Greedy bin packing: longest story first, onto the least-loaded shard (lowest index on a tie).

    Returns each shard's story ids (sorted) and its summed seconds. Deterministic for a given input.
    """
    if shards < 1:
        raise ValueError(f"a lab class needs at least 1 shard, not {shards}")
    bins: list[list[str]] = [[] for _ in range(shards)]
    loads = [0] * shards
    for story_id, seconds in sorted(stories, key=lambda item: (-item[1], item[0])):
        index = min(range(shards), key=lambda i: (loads[i], i))
        bins[index].append(story_id)
        loads[index] += seconds
    return [sorted(b) for b in bins], loads


def generate(stories: Iterable[object], layout: Mapping[str, Mapping[str, object]] = LAYOUT) -> dict:
    """The shard map document for stories with `id`, `tier` and `seconds` (catalog.Story or scheduler.StorySpec)."""
    by_tier: dict[str, list[tuple[str, int]]] = {tier: [] for tier in SHARDED_TIERS}
    for story in stories:
        if story.tier in by_tier:
            by_tier[story.tier].append((story.id, int(story.seconds)))
    classes = {}
    for name in sorted(layout):
        spec = layout[name]
        count = int(spec["shards"])
        tiers = [tier for tier in SHARDED_TIERS if tier in spec["tiers"]]
        shards = [{"index": i, "seconds": {}, "stories": {}} for i in range(count)]
        for tier in tiers:
            bins, loads = pack(by_tier[tier], count)
            for i in range(count):
                shards[i]["stories"][tier] = bins[i]
                shards[i]["seconds"][tier] = loads[i]
        classes[name] = {"tiers": tiers, "shards": shards}
    return {
        "schema": SCHEMA,
        "generated_by": "scripts/perf-lab/gen_shard_map.py (do not edit; run it after a stories.d/ change)",
        "classes": classes,
    }


def overloads(document: Mapping) -> list[str]:
    """Each shard whose seconds for a tier exceed that tier's interval, as a line for the person who sizes LAYOUT."""
    lines = []
    for name, entry in sorted(document["classes"].items()):
        for shard in entry["shards"]:
            for tier, seconds in sorted(shard["seconds"].items()):
                interval = TIER_INTERVAL_SECONDS[tier]
                if seconds > interval:
                    stretched = "; until then the scheduler starts its T1 rounds less often" if tier == "T1" else ""
                    lines.append(f"{name}/{shard['index']}: {tier} takes {seconds} s, over its {interval} s interval; "
                                 f"add a shard to LAYOUT[{name!r}]{stretched}")
    return lines


def render(document: Mapping) -> str:
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def catalog_stories(root: Path) -> Sequence[object]:
    catalog = _load_sibling("catalog")
    return catalog.load_catalog(root).stories


# ---------- commands (lab.py protocol, task 005) ----------

LAB_COMMANDS = {
    "shard-map": "Bind each T0/T1/T2 story to one waterfall shard per lab class (bin packing on seconds); --check.",
}


def add_arguments(command: str, parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help=argparse.SUPPRESS)
    parser.add_argument("--check", action="store_true", help="exit 1 when shard_map.json is not the generated map")


def run(command: str, args: argparse.Namespace, out=None, err=None) -> int:
    out = out or sys.stdout
    err = err or sys.stderr
    catalog = _load_sibling("catalog")
    try:
        stories = catalog_stories(args.root)
    except (catalog.CatalogError, OSError, SyntaxError) as error:
        print(f"shard-map: {error}", file=err)
        return 2
    document = generate(stories)
    for line in overloads(document):
        print(f"shard-map: warning: {line}", file=err)
    text = render(document)
    path = args.root / SHARD_MAP_PATH
    if args.check:
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            print(f"shard-map: {SHARD_MAP_PATH} is current", file=out)
            return 0
        reason = "does not exist" if current is None else "is stale"
        print(f"shard-map: {SHARD_MAP_PATH} {reason}; run `python3 -I scripts/perf-lab/gen_shard_map.py`", file=err)
        return 1
    path.write_text(text, encoding="utf-8")
    print(f"shard-map: wrote {SHARD_MAP_PATH}", file=out)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="gen_shard_map.py", description=LAB_COMMANDS["shard-map"])
    add_arguments("shard-map", parser)
    return run("shard-map", parser.parse_args(argv))


if __name__ == "__main__":
    sys.exit(main())
