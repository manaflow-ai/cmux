KINDS = ("area", "situation", "unit")
# A step every change routes (`**`, or no inputs) is not a targeted test for any one path.
CATCH_ALL = {"**", "**/*"}


def glob_regex(glob: str) -> str:
    """ci/steps.toml's glob syntax (scripts/ci/ci_steps.py glob_pattern): ** crosses '/', * and ? do not."""
    out: list[str] = []
    i = 0
    while i < len(glob):
        if glob.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif glob.startswith("**", i):
            out.append(".*")
            i += 2
        elif glob[i] == "*":
            out.append("[^/]*")
            i += 1
        elif glob[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(glob[i]))
            i += 1
    return "".join(out) + r"\Z"


WILDCARD = re.compile(r"[*?\[]")


def literal_prefix(glob: str) -> str:
    """The leading folders with no wildcard: the bucket a glob is filed under. A glob with no wildcard is its own
    bucket (an exact path, or a folder: `a/b` also covers everything under it, as the coverage map writes paths)."""
    m = WILDCARD.search(glob)
    if m is None:
        return glob
    cut = glob.rfind("/", 0, m.start())
    return glob[:cut] if cut != -1 else ""


def pattern_of(glob: str) -> str:
    """The regex a map glob means. A bare folder or file path (no wildcard) covers itself and everything under it,
    as the coverage map writes paths."""
    if any(ch in glob for ch in "*?["):
        return glob_regex(glob)
    return re.escape(glob.rstrip("/")) + r"(?:/.*)?\Z"


@dataclass
class Rule:
    kind: str
    name: str
    globs: tuple[str, ...]
    order: int
    benches: tuple[str, ...] = ()
    tests: tuple[str, ...] = ()
    template: str = ""
    budget: str = ""
    run: tuple[str, ...] = ()
    budget_s: float | None = None
    situations: tuple[str, ...] = ()
    generated: bool = False
    ignore: tuple[tuple[bool, str], ...] = ()
    raw: dict = field(default_factory=dict)

    def ignores(self, path: str) -> bool:
        """ci/steps.toml `ignore`: the last glob that matches decides; a `!glob` takes the path back."""
        for negate, pattern in self.ignore:
            if re.match(pattern, path):
                return not negate
        return False


@dataclass
class Hit:
    path: str
    area: Rule | None
    unit: Rule | None
    situations: list[Rule]
    steps: list[Rule] = field(default_factory=list)

    @property
    def mapped(self) -> bool:
        return self.area is not None or self.unit is not None

    @property
    def default_area(self) -> str:
        return "default:" + (self.path.split("/", 1)[0] if "/" in self.path else "(root)")


class MapError(ValueError):
    pass


def parse_steps(text: str, start: int = 0) -> list[Rule]:
    """ci/steps.toml's targeted steps as rules of kind `step`: the CI already routes these by path."""
    doc = tomllib.loads(text)
    rules = []
    for name, step in doc.get("step", {}).items():
        inputs = tuple(g for g in step.get("inputs", ()) if not g.startswith("!"))
        if not inputs or CATCH_ALL & set(inputs):
            continue
        ignore = tuple((g.startswith("!"), glob_regex(g.lstrip("!"))) for g in reversed(step.get("ignore", ())))
        rules.append(Rule(kind="step", name=name, globs=inputs, order=start + len(rules),
                          tests=(f"ci/run --step {name}",), budget=step.get("title", ""), ignore=ignore, raw=step))
    return rules


def parse(text: str) -> list[Rule]:
    doc = tomllib.loads(text)
    unknown = set(doc) - set(KINDS) - {"schema"}
    if unknown:
        raise MapError(f"relevance map: unknown tables {sorted(unknown)} (kinds: {', '.join(KINDS)})")
    rules: list[Rule] = []
    for kind in KINDS:
        for entry in doc.get(kind, []):
            name = entry.get("name")
            globs = entry.get("paths")
            if not name or not globs or not all(isinstance(g, str) and g and not g.startswith("/") for g in globs):
                raise MapError(f"relevance map: a [[{kind}]] needs a name and repo-relative `paths` ({entry!r})")
            run, budget_s = entry.get("run", []), entry.get("budget_s")
            if not isinstance(run, list) or not all(isinstance(c, str) and c.strip() for c in run):
                raise MapError(f"relevance map: [[{kind}]] {name}: `run` is a list of shell commands ({run!r})")
            if budget_s is not None and (isinstance(budget_s, bool) or not isinstance(budget_s, (int, float))
                                         or budget_s <= 0):
                raise MapError(f"relevance map: [[{kind}]] {name}: `budget_s` is a positive number ({budget_s!r})")
            rules.append(Rule(kind=kind, name=name, globs=tuple(globs), order=len(rules),
                              run=tuple(run), budget_s=float(budget_s) if budget_s is not None else None,
                              benches=tuple(entry.get("benches", ())), tests=tuple(entry.get("tests", ())),
                              template=entry.get("template", ""), budget=entry.get("budget", ""),
                              situations=tuple(entry.get("situations", ())), generated=kind == "unit", raw=entry))
    return rules


class Index:
    """Globs filed by literal prefix. `match(path)` reads only the buckets of the path's ancestors."""

    def __init__(self, rules: list[Rule]):
        self.rules = rules
        self.buckets: dict[str, list[tuple[Rule, str, int]]] = {}
        self._compiled: dict[str, list[tuple[Rule, re.Pattern[str], int]]] = {}
        self.situation_by_name: dict[str, list[Rule]] = {}
        # Every rule of one (kind, name): plan() merges an area filed twice into one entry (_area_entry), read here
        # once per index rather than by a scan of every rule per matched area (the Bench tooling bench, 0.096 s).
        self.by_name: dict[tuple[str, str], list[Rule]] = {}
        for rule in rules:
            self.by_name.setdefault((rule.kind, rule.name), []).append(rule)
            for glob in rule.globs:
                prefix = literal_prefix(glob).rstrip("/")
                # Specificity: literal characters before the first wildcard, so `a/b/c.swift` beats `a/b/**`.
                self.buckets.setdefault(prefix, []).append((rule, glob, len(prefix)))
            if rule.kind == "situation":
                self.situation_by_name.setdefault(rule.name, []).append(rule)

    def _bucket(self, key: str) -> list[tuple[Rule, re.Pattern[str], int]]:
        got = self._compiled.get(key)
        if got is None:
            got = [(r, re.compile(pattern_of(g)), spec) for r, g, spec in self.buckets.get(key, ())]
            self._compiled[key] = got
        return got

    def candidates(self, path: str):
        keys = [""]
        i = path.find("/")
        while i != -1:
            keys.append(path[:i])
            i = path.find("/", i + 1)
        keys.append(path)
        for key in keys:
            if key in self.buckets:
                yield from self._bucket(key)

    def match(self, path: str) -> Hit:
        best: dict[str, tuple[int, int, Rule]] = {}
        situations: dict[str, Rule] = {}
        steps: dict[str, Rule] = {}
        for rule, pattern, spec in self.candidates(path):
            if not pattern.match(path):
                continue
            if rule.kind == "situation":
                situations.setdefault(rule.name, rule)
                continue
            if rule.kind == "step":
                if not rule.ignores(path):
                    steps.setdefault(rule.name, rule)
                continue
            cur = best.get(rule.kind)
            if cur is None or (spec, -rule.order) > (cur[0], -cur[1]):
                best[rule.kind] = (spec, rule.order, rule)
        sits = sorted(situations.values(), key=lambda r: r.order)
        return Hit(path, best.get("area", (0, 0, None))[2], best.get("unit", (0, 0, None))[2], sits,
                   sorted(steps.values(), key=lambda r: r.order))


class Scan:
    """The old way: every glob of every rule, compiled once, tried in turn for each path. The oracle the property
    test checks the index against, and the "before" arm of the relevance-lookup bench."""

    def __init__(self, rules: list[Rule]):
        self.rules = rules
        self.globs = [(rule, re.compile(pattern_of(g)), len(literal_prefix(g).rstrip("/")))
                      for rule in rules for g in rule.globs]

    def match(self, path: str) -> Hit:
        best: dict[str, tuple[int, int, Rule]] = {}
        situations: dict[str, Rule] = {}
        steps: dict[str, Rule] = {}
        for rule, pattern, spec in self.globs:
            if not pattern.match(path):
                continue
            if rule.kind == "situation":
                situations.setdefault(rule.name, rule)
                continue
            if rule.kind == "step":
                if not rule.ignores(path):
                    steps.setdefault(rule.name, rule)
                continue
            cur = best.get(rule.kind)
            if cur is None or (spec, -rule.order) > (cur[0], -cur[1]):
                best[rule.kind] = (spec, rule.order, rule)
        return Hit(path, best.get("area", (0, 0, None))[2], best.get("unit", (0, 0, None))[2],
                   sorted(situations.values(), key=lambda r: r.order), sorted(steps.values(), key=lambda r: r.order))


def naive_match(rules: list[Rule], path: str) -> Hit:
    return Scan(rules).match(path)


def load_rules(path: Path = MAP, steps: Path | None = STEPS) -> list[Rule]:
    rules = parse(path.read_text(encoding="utf-8"))
    if steps is not None and steps.is_file():
        rules += parse_steps(steps.read_text(encoding="utf-8"), start=len(rules))
    return rules


def load(path: Path = MAP, steps: Path | None = STEPS) -> Index:
    return Index(load_rules(path, steps))


# ---- what a set of paths needs -------------------------------------------------------------------------------

def _area_entry(same: list[Rule]) -> dict:
    """One plan entry for every [[area]] of one name: a name filed twice (docs/benches/coverage-map.md's row and a
    hand-tuned one) is one area, so a path matching either gets both entries' benches, tests and `run` commands, under
    the tightest budget_s. The first entry alone dropped the second's `run` (Model picker search ran no bench)."""
    first = same[0]
    budgets = [r.budget_s for r in same if r.budget_s is not None]
    return {"name": first.name, "kind": first.kind,
            "benches": list(dict.fromkeys(b for r in same for b in r.benches)),
            "tests": list(dict.fromkeys(t for r in same for t in r.tests)),
            "budget": next((r.budget for r in same if r.budget), ""),
            "run": list(dict.fromkeys(c for r in same for c in r.run)),
            "budget_s": min(budgets) if budgets else None, "paths": []}


def plan(index: Index, paths: list[str]) -> dict:
    """The benches, tests and templates a change's paths need, and the paths only a default covers."""
    hits = [index.match(p) for p in paths]
    areas: dict[str, dict] = {}
    templates: dict[str, dict] = {}
    unmapped: list[str] = []
    rows = []
    for h in hits:
        if h.area is None and h.unit is None:
            unmapped.append(h.path)
        for rule in (h.area, h.unit):
            if rule is None:
                continue
            a = areas.get(rule.name)
            if a is None:
                a = areas[rule.name] = _area_entry(index.by_name.get((rule.kind, rule.name)) or [rule])
            a["paths"].append(h.path)
        sit_rules = list(h.situations)
        for name in (h.area.situations if h.area else ()):
            sit_rules += index.situation_by_name.get(name, ())
        for s in sit_rules:
            t = templates.setdefault(s.name, {"situation": s.name, "template": s.template, "paths": []})
            if h.path not in t["paths"]:
                t["paths"].append(h.path)
        rows.append({"path": h.path, "area": h.area.name if h.area else None,
                     "unit": h.unit.name if h.unit else None, "ci_steps": [s.name for s in h.steps],
                     "situations": sorted({s.name for s in sit_rules}),
                     "default": None if h.mapped else h.default_area})
    benches = sorted({b for a in areas.values() for b in a["benches"]})
    tests = list(dict.fromkeys([t for a in areas.values() for t in a["tests"]]
                               + [t for t in (self_test(h.path) for h in hits) if t]))
    defaults = sorted({index.match(p).default_area for p in unmapped})
    ci_steps = sorted({s.name for h in hits for s in h.steps})
    return {"schema": "cmux-bench/for-paths/v1", "paths": rows, "areas": list(areas.values()), "benches": benches,
            "ci_steps": ci_steps,
            "tests": tests, "templates": list(templates.values()), "unmapped": unmapped, "defaults": defaults}


# ---- running the benches a change selects ---------------------------------------------------------------------

# A bench may print its own measurement; it beats wall time (which counts process start and the TOML load).
MEASURED = re.compile(r"^bench_seconds=([0-9]+(?:\.[0-9]+)?)\s*$", re.M)
OVER, OK, MISSING, ERROR, TIMEOUT = "over-budget", "ok", "missing", "error", "timeout"
# Every repeat more than baselines.THRESHOLD over the area's nightly baseline (baselines.judge).
REGRESSED = "regressed"


def runs_for(plan_: dict) -> list[dict]:
    """The commands a plan's areas name, each once, under the tightest budget any of its areas sets."""
    out: dict[str, dict] = {}
    for a in plan_["areas"]:
        for cmd in a.get("run", ()):
            r = out.setdefault(cmd, {"cmd": cmd, "areas": [], "budget_s": None})
            r["areas"].append(a["name"])
            if a.get("budget_s") is not None:
                r["budget_s"] = a["budget_s"] if r["budget_s"] is None else min(r["budget_s"], a["budget_s"])
    return list(out.values())


def _measure(cmd: str, timeout: float, root: Path) -> tuple[str, float | None, str, str]:
    """One run of a bench command: (status, seconds, how it was measured, detail)."""
    t = time.perf_counter()
    try:
        res = subprocess.run(["bash", "-c", cmd], cwd=root, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return TIMEOUT, time.perf_counter() - t, "wall", f"killed at the {timeout:g} s timeout"
    except OSError as err:
        return MISSING, None, "", str(err)
    wall = time.perf_counter() - t
    tail = (res.stderr or res.stdout).strip().splitlines()[-1:] or [""]
    if res.returncode == 127 or "No such file or directory" in res.stderr and res.returncode != 0:
        return MISSING, None, "", tail[0][:200]
    if res.returncode != 0:
        return ERROR, None, "", f"exit {res.returncode}: {tail[0][:200]}"
    found = MEASURED.findall(res.stdout)
    return OK, (float(found[-1]) if found else wall), ("bench" if found else "wall"), ""


def run_one(run: dict, timeout: float, root: Path = ROOT, repeats: int = 1) -> dict:
    """Run one bench command `repeats` times (stopping at the first run that does not measure). Only a measured
    result over its budget is OVER, judged on the median; a missing tool, an error or a timeout under no budget is
    a warning (fail open). `repeats_s` keeps every measurement for the baseline rule (baselines.judge)."""
    budget = run["budget_s"]
    reps: list[float] = []
    how = ""
    for _ in range(max(1, repeats)):
        status, seconds, how_, detail = _measure(run["cmd"], timeout, root)
        if status == TIMEOUT:
            status = OVER if budget is not None and seconds > budget else TIMEOUT
            return {**run, "status": status, "seconds": round(seconds, 4), "repeats_s": reps, "detail": detail}
        if status != OK:
            return {**run, "status": status, "seconds": None, "repeats_s": reps, "detail": detail}
        reps.append(round(seconds, 4))
        how = how_
    median = round(statistics.median(reps), 4)
    status = OVER if budget is not None and median > budget else OK
    return {**run, "status": status, "seconds": median, "repeats_s": reps, "measured": how, "detail": ""}


def run_benches(plan_: dict, timeout: float = 120, root: Path = ROOT, repeats: int = 1,
                baseline_docs: dict | None = None) -> list[dict]:
    """Every bench the plan's areas name. With baseline_docs (baselines.fetch), each result also carries its
    baseline and the 3-repeat verdict; only a REGRESSED verdict changes an OK status."""
    results = [run_one(r, timeout, root, repeats) for r in runs_for(plan_)]
    if baseline_docs is None:
        return results
    from . import baselines
    for r in results:
        value, area = baselines.lookup(baseline_docs, r["areas"], r["cmd"])
        verdict = baselines.judge(r.get("repeats_s") or [], value) if r["status"] in (OK, OVER) else \
            baselines.NO_MEASURE
        r.update(baseline_s=value, baseline_area=area or None, verdict=verdict)
        if verdict == baselines.REGRESSED and r["status"] == OK:
            r["status"] = REGRESSED
    return results


def scaled(rules: list[Rule], scale: int) -> list[Rule]:
    """The map's rules plus scale - 1 copies under fresh top folders: scale times the rules, same shape."""
    big = list(rules)
    for k in range(1, scale):
        big += [Rule(kind=r.kind, name=f"{r.name}#{k}", order=len(big) + i, ignore=r.ignore,
                     globs=tuple(f"x{k}/{g}" for g in r.globs)) for i, r in enumerate(rules)]
    return big


def self_bench(n: int = 2000, scale: int = 1, root: Path = ROOT) -> float:
    """Seconds for load + plan on n tracked paths, with scale times the rules: the for-paths budget, as a bench."""
    files = _tracked(root)
    paths = random.Random(3).sample(files, min(n, len(files)))
    t = time.perf_counter()
    rules = load_rules()
    index = Index(scaled(rules, scale) if scale > 1 else rules)
    plan(index, paths)
    return time.perf_counter() - t


def coverage(index: Index, changes: list[list[str]]) -> dict:
    """Of the paths changed (one list per merged pull request), how many a hand area or a unit maps."""
    total = by_area = by_unit = checked = 0
    misses: dict[str, int] = {}
    unchecked: dict[str, int] = {}
    for paths in changes:
        for p in paths:
            total += 1
            h = index.match(p)
            if self_test(p) or h.steps or any(r is not None and (r.tests or r.benches) for r in (h.area, h.unit)):
                checked += 1
            else:
                key = "/".join(p.split("/")[:2])
                unchecked[key] = unchecked.get(key, 0) + 1
            if h.area is not None:
                by_area += 1
            elif h.unit is not None:
                by_unit += 1
            else:
                key = "/".join(p.split("/")[:2])
                misses[key] = misses.get(key, 0) + 1
    pct = lambda n: round(100.0 * n / total, 2) if total else 0.0  # noqa: E731
    return {"changes": len(changes), "paths": total, "area_pct": pct(by_area), "unit_pct": pct(by_unit),
            "mapped_pct": pct(by_area + by_unit), "checked_pct": pct(checked),
            "top_misses": sorted(misses.items(), key=lambda kv: -kv[1])[:25],
            "top_unchecked": sorted(unchecked.items(), key=lambda kv: -kv[1])[:25]}


SELF_TESTS = (re.compile(r"(?:.*/)?tests?/test_[^/]*\.py\Z"), re.compile(r".*\.test\.tsx?\Z"),
              re.compile(r".*/Tests/[^/]+/.*\.swift\Z"))


def self_test(path: str) -> str | None:
    """A changed test file is its own targeted test: the command that runs it, when one is that plain."""
    if SELF_TESTS[0].match(path):
        return f"python3 -I {path}"
    if SELF_TESTS[1].match(path) and path.startswith("webviews/"):
        return f"bash scripts/ci/run-webviews-tests.sh {path.removeprefix('webviews/')}"
    return None


def merged_changes(days: int, refs: tuple[str, ...] = ("origin/feat-cmux-next", "origin/main"),
                   root: Path = ROOT) -> list[list[str]]:
    """The paths of each first-parent commit (a squash-merged pull request) on the base branches in the last N
    days, read from the local git history: no GitHub API call."""
    out: list[list[str]] = []
    seen: set[str] = set()
    for ref in refs:
        res = subprocess.run(["git", "log", f"--since={days}.days", "--first-parent", "--no-merges", "--format=@%H",
                              "--name-only", ref], cwd=root, capture_output=True, text=True)
        if res.returncode != 0:
            continue
        cur: list[str] | None = None
        skip = False
        for line in res.stdout.splitlines():
            if line.startswith("@"):
                sha = line[1:]
                skip = sha in seen
                seen.add(sha)
                cur = []
                if not skip:
                    out.append(cur)
            elif line and cur is not None and not skip:
                cur.append(line)
    return out


# ---- the generated section -----------------------------------------------------------------------------------

def _tracked(root: Path) -> list[str]:
    res = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True)
    return [p for p in res.stdout.decode().split("\0") if p]


def _crate_name(root: Path, crate_dir: str) -> str:
    try:
        doc = tomllib.loads((root / crate_dir / "Cargo.toml").read_text(encoding="utf-8"))
        return doc.get("package", {}).get("name") or crate_dir.rsplit("/", 1)[-1]
    except (OSError, tomllib.TOMLDecodeError):
        return crate_dir.rsplit("/", 1)[-1]


def generate_units(root: Path = ROOT, files: list[str] | None = None) -> list[dict]:
    """One unit per testable folder of the repo layout, with the command that tests just that folder."""
    files = files if files is not None else _tracked(root)
    dirs: set[str] = set()
    for f in files:
        parts = f.split("/")
        for depth in range(1, min(len(parts), 6)):
            dirs.add("/".join(parts[:depth]))
    units: list[dict] = []

    def add(name: str, path: str, tests: list[str] | None = None):
        units.append({"name": name, "paths": [path + "/**"], "tests": tests or []})

    for d in sorted(dirs):
        parts = d.split("/")
        # Rust crates: cmux-tui/crates/X, cmux-next-ios/rust/crates/X, any */crates/X with a Cargo.toml.
        if len(parts) >= 2 and parts[-2] == "crates" and (root / d / "Cargo.toml").is_file():
            workspace = "/".join(parts[:-2])
            crate = _crate_name(root, d)
            add(f"rust:{crate}", d, [f"cargo test --manifest-path {workspace}/Cargo.toml -p {crate}"])
        # Swift packages: <pkg>/Sources/<Module> and <pkg>/Tests/<Target> with a Package.swift beside them.
        elif len(parts) >= 3 and parts[-2] in ("Sources", "Tests") and (root / "/".join(parts[:-2]) / "Package.swift").is_file():
            pkg = "/".join(parts[:-2])
            module = parts[-1]
            target = module if parts[-2] == "Tests" else module + "Tests"
            has_tests = parts[-2] == "Tests" or (root / pkg / "Tests" / target).is_dir()
            add(f"swift:{module}", d, [f"swift test --package-path {pkg} --filter {target}"] if has_tests else [])
        # webviews/src/<folder>: its colocated tests.
        elif len(parts) == 3 and parts[:2] == ["webviews", "src"] and (root / d).is_dir():
            add(f"web:{parts[2]}", d, [f"bash scripts/ci/run-webviews-tests.sh src/{parts[2]}"])
        # Second-level folders of the tooling trees.
        elif len(parts) == 2 and parts[0] in ("scripts", "schemas", "docs", "tests", "webviews", "web", "backend",
                                              "workers", "evals", "examples", "first-party-apps", ".github",
                                              "plans", "skills", "release-notes", "design", "experiments",
                                              "Native", "ci", "persisted-formats") and (root / d).is_dir():
            add(f"{parts[0].lstrip('.')}:{parts[1]}", d)
        # Rust workspace roots and language bindings.
        elif len(parts) == 2 and parts[0] == "cmux-tui" and (root / d).is_dir() and parts[1] != "crates":
            add(f"cmux-tui:{parts[1]}", d)
        elif len(parts) == 3 and parts[:2] == ["cmux-tui", "bindings"] and (root / d).is_dir():
            add(f"binding:{parts[2]}", d)
    return units


def render_units(units: list[dict]) -> str:
    def q(s: str) -> str:
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    out = [GENERATED_MARK, ""]
    for u in units:
        out.append("[[unit]]")
        out.append(f"name = {q(u['name'])}")
        out.append("paths = [" + ", ".join(q(p) for p in u["paths"]) + "]")
        if u["tests"]:
            out.append("tests = [" + ", ".join(q(t) for t in u["tests"]) + "]")
        out.append("")
    return "\n".join(out)


def rewrite(path: Path = MAP, root: Path = ROOT) -> bool:
    """Regenerate the section below GENERATED_MARK; keep everything above it. True when the file changed."""
    text = path.read_text(encoding="utf-8")
    head = text.split(GENERATED_MARK, 1)[0].rstrip("\n") + "\n\n"
    new = head + render_units(generate_units(root))
    if new != text:
        path.write_text(new, encoding="utf-8")
        return True
    return False
