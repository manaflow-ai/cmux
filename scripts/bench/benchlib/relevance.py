"""The relevance map: path glob -> product area -> the benches, tests and check templates that cover it.

Leo, 2026-11-27: "like we can have fast retrieval of bench reference per product area".

`docs/benches/relevance-map.toml` holds three kinds of rule:

  [[area]]       hand-tuned: a risky area (the same name and paths as docs/benches/coverage-map.md's risky paths
                 table), its benches, targeted tests and budget.
  [[situation]]  hand-tuned: a kind of change (main thread, bridge, protocol, persisted format, migration, visible
                 UI) and the check template under docs/benches/templates/ that fits it.
  [[unit]]       generated from the repo layout (`cmux-bench for-paths --write`): one per Rust crate, Swift module
                 or test target, webviews/src folder, scripts/ folder... with the command that tests just that unit.

A path takes the most specific area (longest literal prefix, then file order), the most specific unit, and every
situation it matches. A path no area and no unit matches falls back to its top-level folder's default and warns:
fail open, never a block.

Lookup is a prefix table, not a scan per path: every glob is filed under its literal leading folders
("cmux-tui/crates/acpmux" for `cmux-tui/crates/acpmux/**`), and a path consults only the buckets of its own
ancestors (depth + 1 dict lookups), then confirms the few candidates with their compiled pattern. Patterns compile
on first use, so a query that touches three buckets compiles three buckets' globs. `naive_match` is the old
whole-table scan, kept as the oracle the property test compares against.
"""
