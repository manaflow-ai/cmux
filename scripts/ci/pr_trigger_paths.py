#!/usr/bin/env python3
"""A pull request workflow starts a run only when its change can matter: trigger `paths:`, or a written reason.

    pr_trigger_paths.py detect                    # every PR-triggered workflow has `paths:` or an every_pr reason
    pr_trigger_paths.py check                     # each derived workflow's `paths:` is exactly what its decider says
    pr_trigger_paths.py paths --workflow WF       # the `paths:` its decider derives, one per line
    pr_trigger_paths.py write [--workflow WF]     # rewrite each derived workflow's `paths:` block in place
    pr_trigger_paths.py replay --diffs DIR [--base feat-cmux-next] [--repo OLD]
                                                  # the workflows each changed-path list (DIR/*.txt) would start

Why the trigger and not a job: a workflow run takes a queue slot from the moment GitHub creates it, even when every
job in it skips (`if:` false, or a router job that decides there is nothing to do). On 2026-11-19 manaflow-ai/cmux
had 7,800 queued runs, about 1,900 created an hour against about 90 running, and 46 pull request heads had made 851
runs: 18.5 per head, 29 workflows with no paths filter at all. A `needs: router` gate saves the job, not the run.
So a workflow that decides by the changed paths gets those paths as its trigger filter, generated from the same
decider it runs, and this keeps the two equal.

scripts/ci/pr-trigger-paths.json holds the two lists:

  - "derived": workflow -> {decider, why}: its `on.pull_request[_target].paths` is generated by DECIDER below from
    the decider's own source of truth (tab_switch_gate.SCOPE, classic-auto-deploy.json, ...) plus every repository
    path the workflow names (a script it runs is an input). `check` fails when the block differs from the decider.
  - "every_pr": workflow -> reason it starts on every pull request (a required context that must report, a check
    that reads the body or labels, a per-PR close event, a main-only workflow). `detect` fails on any workflow
    with a pull_request or pull_request_target trigger that has no `paths:` and no entry here, and on an entry
    whose workflow is gone or now filtered.

`paths-ignore` alone is not a filter here: a docs-only ignore still starts the workflow on nearly every head.

GitHub's filter reads at most the first 300 changed files of a pull request: a larger change whose matching file is
past the 300th starts no run. Every derived workflow is advisory or warns on feat-cmux-next, and the feat-cmux-next
push still runs the push-triggered ones, so that miss is a fix-forward, not a hole in a merge gate.

Test: tests/test_ci_pr_trigger_paths.py, run by whoever changes a PR workflow or a decider's source (no CI step: written
under the 2026-10-23 no-new-CI rule, since lifted). It needs a full checkout (cmux-ci test) for rust-workspaces.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Callable

ROOT = Path(__file__).resolve().parents[2]
MAP = "scripts/ci/pr-trigger-paths.json"
WORKFLOWS = ".github/workflows"
PR_EVENTS = ("pull_request", "pull_request_target")
GENERATED = "# Generated by scripts/ci/pr_trigger_paths.py from {source}; run its `write` after editing that."
# Characters GitHub's filter reads differently from the deciders' globs (`?` is "zero or one of the previous
# character" there, `+`, `[]` and a leading `!` are operators): a decider glob with one is refused, never guessed.
FILTER_SPECIAL = re.compile(r"[?+\[\]]")
# A repository path a workflow names: a script it runs, a test, a local action. Same shape affected_jobs.py reads.
NAMED_PATH = re.compile(
    r"(?<![\w/.$-])(?:\./)?((?:scripts|\.github/actions|\.github/scripts|tests|ios/scripts)/[A-Za-z0-9_./-]*[A-Za-z0-9_])")


# --- reading a workflow's triggers, without a YAML library ---------------------------------------------------------

def _flow_list(value: str) -> list[str] | None:
    value = value.strip()
    if value.startswith("[") and value.endswith("]"):
        return [item.strip().strip("'\"") for item in value[1:-1].split(",") if item.strip()]
    return None


def triggers(text: str) -> dict[str, dict[str, list[str] | None] | None]:
    """The `on:` block: event -> {key: list | None} (None: the event has no settings). Handles `on: x`, `on: [x, y]`,
    block mappings two spaces deep, flow lists and block lists four spaces deep."""
    lines = text.splitlines()
    found: dict[str, dict[str, list[str] | None] | None] = {}
    start = next((i for i, line in enumerate(lines) if re.match(r"^(on|\"on\"|'on'):", line)), None)
    if start is None:
        return found
    inline = lines[start].split(":", 1)[1].split("#", 1)[0].strip()
    if inline:
        listed = _flow_list(inline)
        return {name: None for name in (listed if listed is not None else [inline])}
    event, key = None, None
    for line in lines[start + 1:]:
        if re.match(r"^\S", line):
            break
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if match := re.match(r"^  ([A-Za-z_]+):\s*(.*)$", line):
            event, key = match.group(1), None
            rest = match.group(2).split("#", 1)[0].strip()
            found[event] = None if not rest or rest in ("null", "~", "{}") else {}
            continue
        if event is None:
            continue
        if match := re.match(r"^    ([A-Za-z_-]+):\s*(.*)$", line):
            key = match.group(1)
            rest = match.group(2).split("#", 1)[0].strip()
            settings = found[event] if isinstance(found[event], dict) else {}
            found[event] = settings
            settings[key] = _flow_list(rest) if rest else []
            if rest and settings[key] is None:
                settings[key] = [rest.strip("'\"")]
            continue
        if key is not None and (match := re.match(r'^      - +(.*?)\s*$', line)):
            value = match.group(1)
            if quoted := re.match(r"""^(['"])(.*?)\1(?:\s+#.*)?$""", value):
                # A quoted item with a trailing comment: the quotes end the scalar, the comment is not part of it.
                value = quoted.group(2)
            else:
                value = value.split(" #", 1)[0].strip()
            found[event][key].append(value.strip("'\""))  # type: ignore[index, union-attr]
    return found


def pr_events(text: str) -> dict[str, dict[str, list[str] | None]]:
    return {event: (settings or {}) for event, settings in triggers(text).items() if event in PR_EVENTS}


def filtered(settings: dict[str, list[str] | None]) -> bool:
    return "paths" in settings


# --- GitHub's filter ----------------------------------------------------------------------------------------------

def glob_regex(glob: str) -> re.Pattern[str]:
    """GitHub's `paths:` glob: `**/` is any number of folders (none too), `**` anything, `*` one segment's worth."""
    out, i = [], 0
    while i < len(glob):
        if glob.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif glob.startswith("**", i):
            out.append(".*")
            i += 2
        elif glob[i] == "*":
            out.append("[^/]*")
            i += 1
        else:
            out.append(re.escape(glob[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$")


def starts(globs: list[str], paths: list[str]) -> bool:
    """Whether a `paths:` list starts the workflow for a change to PATHS: in order, a `!` pattern drops a path an
    earlier pattern took and a later positive one takes it back; any path still taken starts it."""
    compiled = [(glob.startswith("!"), glob_regex(glob.lstrip("!"))) for glob in globs]
    for path in paths:
        taken = False
        for negative, pattern in compiled:
            if pattern.match(path):
                taken = not negative
        if taken:
            return True
    return False


# --- the deciders -------------------------------------------------------------------------------------------------

def _load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    sys.modules[name] = module  # a dataclass in it looks its module up by name
    spec.loader.exec_module(module)
    return module


def tab_switch(root: Path, files: set[str]) -> tuple[list[str], list[str]]:
    """tab_switch_gate.py SCOPE (minus EXCLUDE) is the whole of what puts a change in scope; anything else is green
    at once with no Mac. The scope job also runs the gate's tests."""
    gate = _load(root / "scripts/cmux-next/tab_switch_gate.py", "pr_trigger_tab_switch_gate")
    return list(gate.SCOPE), ["!" + glob for glob in gate.EXCLUDE]


def classic_api(root: Path, files: set[str]) -> tuple[list[str], list[str]]:
    """scripts/ci/classic-auto-deploy.json's guarded deploys: the guard fails (into main) or warns (into
    feat-cmux-next) only when a changed path is in one. Excludes are kept only when every guarded deploy has them."""
    config = json.loads((root / "scripts/ci/classic-auto-deploy.json").read_text(encoding="utf-8"))
    guarded = [deploy for deploy in config["deploys"] if deploy.get("guarded")]
    include = [glob for deploy in guarded for glob in deploy["paths"]]
    excludes = [set(deploy.get("exclude", [])) for deploy in guarded]
    common = sorted(set.intersection(*excludes)) if excludes else []
    return include + ["scripts/ci/classic-auto-deploy.json"], ["!" + glob for glob in common]


def classic_frozen(root: Path, files: set[str]) -> tuple[list[str], list[str]]:
    """.github/classic-frozen.txt's globs: the guard holds a pull request into main only when it changes one."""
    guard = _load(root / "scripts/ci/classic_frozen_guard.py", "pr_trigger_classic_frozen_guard")
    rules = guard.parse((root / ".github/classic-frozen.txt").read_text(encoding="utf-8"))
    return [rule["glob"] for rule in rules] + [".github/classic-frozen.txt"], []


def rust_workspaces(root: Path, files: set[str]) -> tuple[list[str], list[str]]:
    """.github/scripts/rust-workspaces.py: the plan job checks that every Cargo workspace is listed and every
    Cargo.lock matches its manifests (any manifest or lock in the tree), then plans each `run = true` workspace a
    change reaches (its members, every package they use by path, the manifest of the workspace above each, the files
    their sources read by literal path, and its listed inputs). A change to EVERYTHING plans every workspace."""
    module = _load(root / ".github/scripts/rust-workspaces.py", "pr_trigger_rust_workspaces")
    missing = [path for path in module.git(root, "ls-files", "--", "*Cargo.toml").split("\n")
               if path.endswith("Cargo.toml") and not (root / path).is_file()]
    if missing:
        raise SystemExit(f"pr_trigger_paths: rust-workspaces needs every Cargo.toml on disk ({missing[0]} is not: a "
                         "sparse checkout); run it in a full checkout (cmux-ci test)")
    tree = module.Tree(root)
    globs = sorted(module.EVERYTHING) + [
        "**/Cargo.toml", "**/Cargo.lock", "**/rust-toolchain.toml", "**/rust-toolchain", "**/.cargo/**",
        "scripts/cmux-next/cargo-locks.py",
    ]
    for entry in module.load_list(root):
        if entry.get("run") is not True:
            continue
        reach = tree.reach(entry["root"])
        globs += [f"{directory}/**" for directory in sorted(reach)]
        globs += sorted(f"{above}/Cargo.toml" for above in map(tree.workspace_above, reach) if above)
        for path in sorted(tree.read_paths(reach) | set(entry.get("inputs", []))):
            path = path.rstrip("/")
            # plan() matches with under(): "." (a source joining "../.." to the root) matches no changed path, and an
            # untracked path (a build output) is never in a change.
            if path in ("", ".") or not any(file == path or file.startswith(path + "/") for file in files):
                continue
            globs.append(path if path in files else f"{path}/**")
    # Markdown under a reached folder (a crate README) is prose no workspace builds from: excluded, as the docs-only
    # block does (scripts/ci/docs_only_paths.py). Put back after it: each Markdown file a source reads by literal path,
    # and each one under these globs the block itself puts back (an include_str! file, a fixture, a SKILL.md).
    docs = _load(root / "scripts/ci/docs_only_paths.py", "pr_trigger_docs_only_paths")
    reads = sorted(glob for glob in globs if glob.endswith(".md") and "*" not in glob)
    block = sorted(path for path in files if path.endswith(".md") and not docs.is_docs(path)
                   and docs.filters.admits("paths", globs, path))
    return globs, ["!**/*.md", *dict.fromkeys(reads + block)]


DECIDERS: dict[str, Callable[[Path, set[str]], tuple[list[str], list[str]]]] = {
    "tab_switch": tab_switch,
    "classic_api": classic_api,
    "classic_frozen": classic_frozen,
    "rust_workspaces": rust_workspaces,
}
SOURCES = {
    "tab_switch": "scripts/cmux-next/tab_switch_gate.py SCOPE and EXCLUDE",
    "classic_api": "scripts/ci/classic-auto-deploy.json (guarded deploys)",
    "classic_frozen": ".github/classic-frozen.txt",
    "rust_workspaces": ".github/scripts/rust-workspaces.py (run workspaces' reach)",
}


def tracked(root: Path) -> set[str]:
    out = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], capture_output=True, text=True, check=True).stdout
    return {path for path in out.split("\0") if path}


def named_paths(text: str, files: set[str]) -> list[str]:
    """Repository paths a workflow names that exist: a file, or a folder (as FOLDER/**)."""
    found = set()
    # Comments name files too (this script, in the generated line): only what the workflow runs counts.
    code = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))
    for name in NAMED_PATH.findall(code):
        name = name.rstrip("/.")
        if name in files:
            found.add(name)
        elif any(path.startswith(name + "/") for path in files):
            found.add(name + "/**")
    return sorted(found)


def derive(root: Path, workflow: str, decider: str, files: set[str] | None = None) -> list[str]:
    """The `paths:` list for WORKFLOW: the decider's globs, the workflow file, every path it names; `!` excludes
    last. Deduplicated, in first-seen order (positives sorted), so the block is stable."""
    files = files if files is not None else tracked(root)
    include, exclude = DECIDERS[decider](root, files)
    text = (root / workflow).read_text(encoding="utf-8")
    include = include + [workflow] + named_paths(text, files)
    for glob in include + exclude:
        if FILTER_SPECIAL.search(glob.lstrip("!")) or glob.lstrip("!").startswith("!"):
            raise ValueError(f"{workflow}: decider {decider} gives {glob!r}, which GitHub's filter reads differently")
    positives = sorted(dict.fromkeys(include))
    # A glob inside another's folder ("D/**" takes "D/x" and "D/y/**") or a file a "**/NAME" glob takes adds nothing.
    folders = [glob[:-3] for glob in positives if glob.endswith("/**") and "*" not in glob[:-3]]
    anywhere = [glob[3:] for glob in positives if glob.startswith("**/") and "*" not in glob[3:] and "/" not in glob[3:]]
    positives = [glob for glob in positives
                 if not any(glob != f"{folder}/**" and glob.startswith(folder + "/") for folder in folders)
                 and not (not glob.startswith("**/") and glob.rsplit("/", 1)[-1] in anywhere and "*" not in glob)]
    # The second list is kept whole and in order: excludes, then the files put back after them (GitHub lets the last
    # matching pattern win), even when a put-back file is also one of the positives above.
    return positives + list(dict.fromkeys(exclude))


# --- the map, and the two checks ----------------------------------------------------------------------------------

def load_map(root: Path) -> dict:
    data = json.loads((root / MAP).read_text(encoding="utf-8"))
    for name in ("derived", "every_pr"):
        data.setdefault(name, {})
    return data


def workflow_files(root: Path) -> list[str]:
    return sorted(f"{WORKFLOWS}/{path.name}" for path in (root / WORKFLOWS).iterdir()
                  if path.suffix in (".yml", ".yaml"))


def detect(root: Path) -> list[str]:
    """The detector: a PR-triggered workflow with no `paths:` on every PR event and no every_pr reason; an every_pr
    entry that is gone, filtered or has no reason; a derived entry that names no decider."""
    data = load_map(root)
    every, derived = data["every_pr"], data["derived"]
    problems = []
    for workflow in workflow_files(root):
        events = pr_events((root / workflow).read_text(encoding="utf-8"))
        if not events:
            if workflow in every or workflow in derived:
                problems.append(f"{MAP}: {workflow} has no pull_request trigger; drop its entry")
            continue
        open_events = [event for event, settings in events.items() if not filtered(settings)]
        if open_events and workflow not in every:
            problems.append(
                f"{workflow} starts a run on every pull request ({', '.join(open_events)} has no `paths:`): give it "
                f"the `paths:` its jobs decide by (a decider in scripts/ci/pr_trigger_paths.py, listed under "
                f"\"derived\" in {MAP}), or list it under \"every_pr\" with the reason it must start on every head")
        if not open_events and workflow in every:
            problems.append(f"{MAP}: {workflow} is under every_pr but filters every pull request event by `paths:`; "
                            "drop the entry")
    for workflow, reason in every.items():
        if not (root / workflow).is_file():
            problems.append(f"{MAP}: every_pr names {workflow}, which does not exist")
        if not isinstance(reason, str) or len(reason.strip()) < 20:
            problems.append(f"{MAP}: every_pr {workflow} needs a reason (why it must start on every head)")
        if workflow in derived:
            problems.append(f"{MAP}: {workflow} is both derived and every_pr")
    for workflow, entry in derived.items():
        if entry.get("decider") not in DECIDERS:
            problems.append(f"{MAP}: derived {workflow} names decider {entry.get('decider')!r}, not one of "
                            f"{', '.join(sorted(DECIDERS))}")
        if not (root / workflow).is_file():
            problems.append(f"{MAP}: derived names {workflow}, which does not exist")
    return problems


def check(root: Path) -> list[str]:
    """Each derived workflow filters every PR event by exactly the paths its decider derives, under the generated
    comment, so an edit to the decider's source shows here, not as a run that never started."""
    data = load_map(root)
    files = tracked(root)
    problems = []
    for workflow, entry in sorted(data["derived"].items()):
        if entry.get("decider") not in DECIDERS or not (root / workflow).is_file():
            continue  # detect names it
        want = derive(root, workflow, entry["decider"], files)
        text = (root / workflow).read_text(encoding="utf-8")
        events = pr_events(text)
        if not events:
            problems.append(f"{workflow}: derived, but it has no pull_request trigger")
        for event, settings in events.items():
            have = settings.get("paths")
            if have is None:
                problems.append(f"{workflow}: on.{event} has no `paths:`; run `python3 {MAP[:-len('-paths.json')]}"
                                f"_paths.py write --workflow {workflow}`".replace("pr-trigger_paths", "pr_trigger_paths"))
                continue
            if have != want:
                missing = [glob for glob in want if glob not in have]
                extra = [glob for glob in have if glob not in want]
                problems.append(f"{workflow}: on.{event}.paths is not what {SOURCES[entry['decider']]} derives "
                                f"(missing {missing[:5]}, extra {extra[:5]}); run `python3 scripts/ci/"
                                f"pr_trigger_paths.py write --workflow {workflow}`")
        if GENERATED.format(source=SOURCES[entry["decider"]]) not in text:
            problems.append(f"{workflow}: the `paths:` block has lost its generated comment")
    return problems


def write(root: Path, workflow: str, decider: str) -> bool:
    """Rewrite WORKFLOW's `paths:` under every PR event in place (last in each event's block). True when it changed."""
    want = derive(root, workflow, decider)
    path = root / workflow
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    comment = "    " + GENERATED.format(source=SOURCES[decider]) + "\n"
    block = [comment, "    paths:\n"] + [f'      - "{glob}"\n' for glob in want]
    out, i, in_on, event = [], 0, False, None
    while i < len(lines):
        line = lines[i]
        if re.match(r"^on:\s*$", line):
            in_on = True
        elif in_on and re.match(r"^\S", line):
            in_on = False
        if in_on and (match := re.match(r"^  ([A-Za-z_]+):", line)):
            if event in PR_EVENTS:
                out.extend(block)
            event = match.group(1)
        elif not in_on and event is not None:
            if event in PR_EVENTS:
                out.extend(block)
            event = None
        if in_on and event in PR_EVENTS:
            if line.startswith("    # Generated by scripts/ci/pr_trigger_paths.py"):
                i += 1
                continue
            if re.match(r"^    paths:\s*$", line):
                i += 1
                while i < len(lines) and (lines[i].startswith("      ") or not lines[i].strip()):
                    i += 1
                continue
            if re.match(r"^  (pull_request|pull_request_target):\s*$", line) and \
                    (i + 1 >= len(lines) or not lines[i + 1].startswith("    ")):
                out.append(line)
                i += 1
                continue
        out.append(line)
        i += 1
    # A trailing blank line belongs after the paths block, not inside the event.
    text = "".join(out)
    block_re = r"(    # Generated by scripts/ci/pr_trigger_paths\.py[^\n]*\n    paths:\n(?:      - [^\n]*\n)+)"
    text = re.sub(r"\n\n+" + block_re, lambda m: "\n" + m.group(1), text)
    text = re.sub(block_re + r"(?=[^\s])", lambda m: m.group(1) + "\n", text)
    changed = text != path.read_text(encoding="utf-8")
    if changed:
        path.write_text(text, encoding="utf-8")
    return changed


# --- replay -------------------------------------------------------------------------------------------------------

def would_start(text: str, base: str, changed: list[str]) -> bool:
    """Whether a synchronize of a pull request into BASE changing CHANGED starts this workflow (branches, types and
    paths of its pull_request and pull_request_target triggers)."""
    for settings in pr_events(text).values():
        types = settings.get("types")
        if types is not None and "synchronize" not in types and "opened" not in types:
            continue
        branches = settings.get("branches")
        if branches is not None and not any(glob_regex(b).match(base) for b in branches):
            continue
        ignored = settings.get("branches-ignore")
        if ignored is not None and any(glob_regex(b).match(base) for b in ignored):
            continue
        paths = settings.get("paths")
        if paths is not None and not starts(paths, changed):
            continue
        ignore = settings.get("paths-ignore")
        if ignore is not None and all(starts(ignore, [path]) for path in changed):
            continue
        return True
    return False


def replay(root: Path, diffs: Path, base: str) -> dict:
    texts = {workflow: (root / workflow).read_text(encoding="utf-8") for workflow in workflow_files(root)}
    per_pr = {}
    for diff in sorted(diffs.glob("*.txt")):
        changed = [line.strip() for line in diff.read_text(encoding="utf-8").splitlines() if line.strip()]
        per_pr[diff.stem] = sorted(w for w, text in texts.items() if would_start(text, base, changed))
    counts: dict[str, int] = {}
    for started in per_pr.values():
        for workflow in started:
            counts[workflow] = counts.get(workflow, 0) + 1
    total = sum(len(started) for started in per_pr.values())
    return {"heads": len(per_pr), "runs": total, "per_head": round(total / max(1, len(per_pr)), 2),
            "by_workflow": dict(sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))), "per_pr": per_pr}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=Path, default=ROOT)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("detect")
    sub.add_parser("check")
    one = sub.add_parser("paths")
    one.add_argument("--workflow", required=True)
    rewrite = sub.add_parser("write")
    rewrite.add_argument("--workflow")
    again = sub.add_parser("replay")
    again.add_argument("--diffs", type=Path, required=True)
    again.add_argument("--base", default="feat-cmux-next")
    args = parser.parse_args(argv)
    root = args.repo.resolve()
    if args.command in ("detect", "check"):
        problems = detect(root) if args.command == "detect" else check(root)
        for problem in problems:
            print(f"::error::{problem}")
        return 1 if problems else 0
    derived = load_map(root)["derived"]
    if args.command == "paths":
        print("\n".join(derive(root, args.workflow, derived[args.workflow]["decider"])))
        return 0
    if args.command == "write":
        for workflow, entry in sorted(derived.items()):
            if args.workflow in (None, workflow):
                print(f"{workflow}: {'rewritten' if write(root, workflow, entry['decider']) else 'unchanged'}")
        return 0
    print(json.dumps(replay(root, args.diffs, args.base), indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
