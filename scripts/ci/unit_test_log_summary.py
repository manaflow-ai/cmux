#!/usr/bin/env python3
"""Summarize every unit-shard decision from one streaming xcodebuild-log pass."""

from __future__ import annotations

import argparse
import io
import itertools
import re
import sys
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field


PACKAGE_RESOLUTION_FAILURE = "Could not resolve package dependencies"
HOST_RESTART = "Restarting after unexpected exit, crash, or test timeout"
EXECUTED_SUMMARY = re.compile(
    r"\b(?:Executed|Test run with)\s+(\d+)\s+tests?\b"
)
EXPECTED_FAILURE_SUMMARY = re.compile(r"Executed.*tests?.*with.*failures?")
TEST_EVENT = re.compile(
    r"\bTest (?P<swift_started>[A-Za-z0-9_]+\(\)) started\b"
    r"|(?:✔|✘) Test (?P<swift_completed>[A-Za-z0-9_]+\(\))"
    r"|Test Case '-\[(?P<xctest_started>[A-Za-z0-9_.]+ [A-Za-z0-9_]+)\]' started"
    r"|Test Case '-\[(?P<xctest_completed>[A-Za-z0-9_.]+ [A-Za-z0-9_]+)\]' (?:passed|failed)"
)


@dataclass
class UnitTestLogSummary:
    package_resolution_failed: bool = False
    host_deaths: int = 0
    tests_seen: int = 0
    expected_failures_only: bool = False
    pending_occurrences: dict[int, str] = field(default_factory=dict)
    pending_by_name: dict[str, list[int]] = field(default_factory=dict)
    next_occurrence: int = 0

    def consume(self, line: str) -> None:
        """Fold one log line into the bounded shard-decision state."""
        if PACKAGE_RESOLUTION_FAILURE in line:
            self.package_resolution_failed = True
        if HOST_RESTART in line:
            self.host_deaths += 1

        for match in EXECUTED_SUMMARY.finditer(line):
            self.tests_seen = max(self.tests_seen, int(match.group(1)))
        if EXPECTED_FAILURE_SUMMARY.search(line):
            # Only the last XCTest failure summary decides; accept singular and plural counts.
            self.expected_failures_only = "(0 unexpected)" in line

        for match in TEST_EVENT.finditer(line):
            started = match.group("swift_started") or match.group("xctest_started")
            completed = match.group("swift_completed") or match.group("xctest_completed")
            if started:
                occurrence = self.next_occurrence
                self.next_occurrence += 1
                self.pending_occurrences[occurrence] = started
                self.pending_by_name.setdefault(started, []).append(occurrence)
            elif completed:
                occurrences = self.pending_by_name.get(completed)
                if occurrences:
                    self.pending_occurrences.pop(occurrences.pop(), None)
                    if not occurrences:
                        del self.pending_by_name[completed]

    def lost_tests(self, limit: int) -> Iterator[str]:
        """Return pending invocation names in start order, bounded for diagnostics."""
        return itertools.islice(self.pending_occurrences.values(), limit)


def summarize(lines: Iterable[str]) -> UnitTestLogSummary:
    summary = UnitTestLogSummary()
    for line in lines:
        summary.consume(line)
    return summary


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("log", help="xcodebuild log to inspect")
    parser.add_argument("--env-output", required=True)
    parser.add_argument("--lost-output", required=True)
    parser.add_argument("--lost-limit", type=int, default=20)
    args = parser.parse_args()
    if args.lost_limit < 1:
        parser.error("--lost-limit must be a positive integer")
    return args


def main() -> int:
    args = parse_args()
    try:
        with io.open(args.log, encoding="utf-8", errors="replace") as handle:
            summary = summarize(handle)

        # These are fixed integer assignments generated by this script, never log content.
        # The workflow may therefore source the file without evaluating untrusted test output.
        with io.open(args.env_output, "w", encoding="utf-8") as handle:
            handle.write(
                f"PACKAGE_RESOLUTION_FAILED={int(summary.package_resolution_failed)}\n"
                f"HOST_DEATHS={summary.host_deaths}\n"
                f"TESTS_SEEN={summary.tests_seen}\n"
                f"EXPECTED_FAILURES_ONLY={int(summary.expected_failures_only)}\n"
            )
        with io.open(args.lost_output, "w", encoding="utf-8") as handle:
            for name in summary.lost_tests(args.lost_limit):
                handle.write(f"{name}\n")
    except OSError as error:
        print(f"unit_test_log_summary.py: log analysis failed: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
