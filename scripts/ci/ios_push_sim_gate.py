#!/usr/bin/env python3
"""Prove APNs injection -> visible banner -> tap -> ready chat on a leased simulator.

Consumes unsealed payloads generated by the production sender. Does not build,
boot, acquire a lease, or use Apple's APNs. See docs/ci/ios-push-gate.md.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import re
import resource
import subprocess
import time
import uuid


def nodes(tree):
    for node in tree if isinstance(tree, list) else [tree]:
        if not isinstance(node, dict):
            raise ValueError("AX tree contains a non-object")
        yield node
        yield from nodes(node.get("children") or [])


def marks(tree):
    for node in nodes(tree):
        if node.get("AXUniqueId") == "debug.open-marks":
            value = json.loads(node.get("AXLabel") or node.get("AXValue") or "null")
            if isinstance(value, dict) and type(value.get("cycle")) is int:
                return value
    return None


def ready(value, before):
    if not value or value.get("cycle", 0) <= before or value.get("trigger") != "notification_tap":
        return False
    valid = lambda n: type(n) in (int, float) and math.isfinite(n) and n >= 0
    return valid(value.get("route_opened")) and any(
        valid(value.get(key)) for key in ("chat_composer_ready", "terminal_ready")
    )


def banner(tree, marker):
    for node in nodes(tree):
        if node.get("AXUniqueId") == "NotificationShortLookView":
            text = " ".join(str(n.get("AXLabel") or "") for n in nodes(node))
            if marker in text:
                return node
    return None


def payload(path):
    raw = Path(path).read_bytes()
    body = json.loads(raw)
    mobile = body.get("cmuxMobile", {})
    marker = mobile.get("eventId")
    if not isinstance(marker, str) or len(marker) < 8:
        raise ValueError("payload must have a unique eventId of at least 8 characters")
    if mobile.get("mac") != "mac-studio" or mobile.get("sessionId") != "mock-t-claude":
        raise ValueError("payload must target the Demo mock Mac and Claude session")
    alert = body.get("aps", {}).get("alert", {})
    if not isinstance(alert, dict) or marker not in " ".join(str(v) for v in alert.values()):
        raise ValueError("production payload alert must visibly contain its eventId")
    if len(raw) > 4096:
        raise ValueError("APNs payload exceeds 4096 bytes")
    return marker, hashlib.sha256(raw).hexdigest()


class Detector:
    def __init__(self, args, report):
        self.args, self.report = args, report
        self.deadline = time.monotonic() + args.timeout

    def run(self, *argv, env=None):
        env = dict(os.environ if env is None else env)
        if self.args.sim_set:
            env["CORE_SIMULATOR_DEVICE_SET_PATH"] = str(self.args.sim_set)
            if argv[:2] == ("xcrun", "simctl"):
                argv = (*argv[:2], "--set", str(self.args.sim_set), *argv[2:])
        left = self.deadline - time.monotonic()
        if left <= 0:
            raise TimeoutError("push simulator gate exceeded its total deadline")
        result = subprocess.run(argv, text=True, capture_output=True, env=env, timeout=min(15, left))
        if result.returncode:
            raise RuntimeError(f"{argv[:3]} exit {result.returncode}: {result.stderr[-1200:]}")
        return result.stdout

    def tree(self):
        tree = json.loads(self.run("axe", "describe-ui", "--udid", self.args.udid))
        self.report["last_ax_tree"] = tree
        return tree

    def wait(self, name, predicate, timeout=20):
        end = min(self.deadline, time.monotonic() + timeout)
        while time.monotonic() < end:
            value = predicate(self.tree())
            if value is not None and value is not False:
                return value
            time.sleep(min(0.25, max(0, end - time.monotonic())))
        raise TimeoutError(f"no {name} within {timeout}s")

    def tap(self, node):
        frame = node.get("frame", {})
        if frame.get("width", 0) <= 0 or frame.get("height", 0) <= 0:
            raise ValueError("cannot tap an invisible AX element")
        self.run("axe", "tap", "--udid", self.args.udid,
                 "-x", str(frame["x"] + frame["width"] / 2),
                 "-y", str(frame["y"] + frame["height"] / 2), "--tap-style", "simulator")

    def launch(self):
        primer = "push-permission-" + uuid.uuid4().hex
        env = dict(os.environ)
        env.update({"SIMCTL_CHILD_CMUX_MOBILE_MOCK_AUTH": "1",
                    "SIMCTL_CHILD_CMUX_MOBILE_LAUNCH_MARKS": "1",
                    # Local primer proves permission has completed before remote injection.
                    # No cmuxMobile event: it cannot route or satisfy a tested payload's marker.
                    "SIMCTL_CHILD_CMUX_MOBILE_DEV_SERVICE_PUSH": json.dumps({"aps": {
                        "alert": {"title": "Push gate setup", "body": primer}}})})
        self.run("xcrun", "simctl", "launch", "--terminate-running-process", self.args.udid,
                 self.args.bundle, "-cmuxMobile.setupComplete", "YES", "-cmux-mobile-tab", "home",
                 "-cmux-mobile-no-restore", "-cmux-mobile-term-no-intro", env=env)

        permission_ready = False

        def prepared(tree):
            nonlocal permission_ready
            all_nodes = list(nodes(tree))
            # These interactions are scoped to the leased test simulator.
            for n in all_nodes:
                if n.get("AXLabel") == "Allow" and "Button" in n.get("type", ""):
                    self.tap(n)
                    return None
            if any(n.get("AXUniqueId") == "setup.teams.choose" for n in all_nodes):
                for n in all_nodes:
                    if n.get("AXLabel") == "Manaflow" and "Button" in n.get("type", ""):
                        self.tap(n)
                        return None
                return None
            permission_ready = permission_ready or banner(tree, primer) is not None
            return marks(tree) if permission_ready else None

        return self.wait("permission primer delivery and Demo app open marks after setup", prepared, timeout=30)

    def check(self, mode, path, marker, digest):
        self.report["stage"] = mode
        before = self.launch()["cycle"]
        if mode == "background":
            self.run("axe", "button", "--udid", self.args.udid, "home")
            self.wait("app moved to background", lambda tree: marks(tree) is None)
        if banner(self.tree(), marker):
            raise RuntimeError("matching banner already visible before injection; stale evidence")
        start = time.monotonic()
        self.run("xcrun", "simctl", "push", self.args.udid, self.args.bundle, str(path))
        shown = self.wait("injected notification banner", lambda tree: banner(tree, marker))
        delivery_seconds = time.monotonic() - start
        self.tap(shown)
        result = self.wait("new notification tap reaching ready chat", lambda tree:
                           (value if ready(value := marks(tree), before) else None))
        self.report["cases"].append({"mode": mode, "event_id": marker, "payload_sha256": digest,
                                     "delivery_seconds": delivery_seconds, "marks": result,
                                     "elapsed_seconds": time.monotonic() - start, "passed": True})

    def check_all(self):
        devices = json.loads(self.run("xcrun", "simctl", "list", "devices", "--json"))
        device = next((d for group in devices["devices"].values() for d in group
                       if d["udid"].lower() == self.args.udid.lower()), None)
        if not device or device.get("state") != "Booted":
            raise ValueError("explicit leased simulator must already be booted")
        paths = [self.args.foreground_payload, self.args.background_payload]
        inputs = [payload(path) for path in paths]
        if inputs[0][0] == inputs[1][0]:
            raise ValueError("foreground and background payloads require distinct eventIds")
        for mode, path, (marker, digest) in zip(("foreground", "background"), paths, inputs):
            self.check(mode, path, marker, digest)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--udid", required=True, help="explicit fleet-leased warm simulator UUID")
    parser.add_argument("--sim-set", type=Path, help="fleet lease's private simulator device set")
    parser.add_argument("--bundle", required=True, help="exact-head installed Demo bundle")
    parser.add_argument("--sha", required=True, help="build source SHA asserted by fleet artifact receipt")
    parser.add_argument("--foreground-payload", type=Path, required=True)
    parser.add_argument("--background-payload", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--timeout", type=float, default=150)
    args = parser.parse_args()
    if not re.fullmatch(r"[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}", args.udid):
        parser.error("--udid must be an explicit simulator UUID, never 'booted'")
    if not re.fullmatch(r"[0-9a-f]{40}", args.sha) or not 0 < args.timeout <= 300:
        parser.error("--sha requires a full lowercase commit SHA; timeout must be in (0, 300]")
    start = time.monotonic()
    report = {"schema": "cmux.ios-push-sim.v1", "source_sha": args.sha, "udid": args.udid,
              "sim_set": str(args.sim_set) if args.sim_set else None,
              "bundle": args.bundle, "cases": [], "passed": False,
              "limitations": ["Apple APNs network, credentials and delivery are not exercised",
                              "simctl does not run the Notification Service Extension lifecycle",
                              "background case is tap-to-wake, not silent push or killed-app cold wake"]}
    try:
        Detector(args, report).check_all()
        report["passed"] = True
    except (OSError, ValueError, KeyError, RuntimeError, TimeoutError, subprocess.SubprocessError) as error:
        report["error"] = str(error)
    report["wall_seconds"] = time.monotonic() - start
    usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    own = resource.getrusage(resource.RUSAGE_SELF)
    report["driver_cpu_seconds"] = usage.ru_utime + usage.ru_stime + own.ru_utime + own.ru_stime
    report["cpu_scope"] = "driver and its child commands; excludes simulator services and app"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k: v for k, v in report.items() if k != "last_ax_tree"}))
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
