"""Phone-side controls and the private Mac input probe for pair-e2e sharing.

AXe and simctl both target the run's freshly created simulator by UDID. Frame
captures and probe events stay in the rig's private work directory.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import subprocess
import re
import time

from cmux_next_screen_sharing_proof import Phone as ScreenProofPhone, positive_fps


ROOT = Path(__file__).resolve().parents[2]


# How long Settings may take to show its Screen Sharing row (it needs the account's live data).
SETTINGS_ROW_WAIT = 240
# The hub lists the share host Online once its user socket is up; that can lag the phone's page.
SHARE_ROW_WAIT = 90


class PairShareFailure(RuntimeError):
    """A fixed, private diagnostic for a failed share leg."""


class PairInputProbe:
    """Run InputProbe and the Vision OCR helper for one pair-e2e share leg."""

    def __init__(self, work):
        self.work = Path(work)
        self.events_path = self.work / "share-input.jsonl"
        self.ocr = self.work / "share-ocr"
        self.binary = self.work / "share-input-probe"
        self.log_path = self.work / "share-input-probe.log"
        self.process = None

    def __enter__(self):
        self.work.mkdir(mode=0o700, parents=True, exist_ok=True)
        source = ROOT / "cmux-next-ios/verify/screen-sharing/InputProbe.swift"
        ocr_source = ROOT / "cmux-next-ios/verify/e2e/ocr.swift"
        try:
            subprocess.run(["xcrun", "swiftc", "-O", str(source), "-o", str(self.binary)],
                           check=True, capture_output=True, timeout=120)
            subprocess.run(["xcrun", "swiftc", str(ocr_source), "-o", str(self.ocr)],
                           check=True, capture_output=True, timeout=120)
            self.events_path.unlink(missing_ok=True)
            with self.log_path.open("w") as log:
                self.process = subprocess.Popen([str(self.binary), str(self.events_path)],
                                                stdout=log, stderr=subprocess.STDOUT,
                                                start_new_session=True)
        except (OSError, subprocess.SubprocessError) as error:
            self.__exit__(None, None, None)
            raise PairShareFailure(f"input probe setup failed ({type(error).__name__})") from None
        return self

    def events(self):
        try:
            data = self.events_path.read_bytes()
        except FileNotFoundError:
            return []
        if len(data) > 1024 * 1024:
            raise PairShareFailure("input probe log exceeded its bound")
        result = []
        for line in data.splitlines():
            if not line.endswith(b"}"):
                continue
            try:
                row = json.loads(line)
            except ValueError:
                continue
            if isinstance(row, dict):
                result.append(row)
        return result

    def verify_click(self, since, timeout=35):
        """Require a fresh left click generated by the phone's direct tap."""
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if self.process is None or self.process.poll() is not None:
                raise PairShareFailure("InputProbe exited before the phone tap")
            events = self.events()
            fresh = [event for event in events
                     if event.get("kind") in ("left-down", "left-up")
                     and isinstance(event.get("t"), (int, float))
                     and event["t"] >= since]
            for down, up in zip(fresh, fresh[1:]):
                if (down.get("kind") == "left-down" and up.get("kind") == "left-up"
                        and down.get("clicks") == 1 and up.get("clicks") == 1
                        and up.get("drags") == 0
                        and down.get("x") == up.get("x") and down.get("y") == up.get("y")):
                    return [down, up]
            time.sleep(0.5)
        raise PairShareFailure("phone tap did not reach InputProbe")

    def __exit__(self, *_):
        process = self.process
        self.process = None
        if process and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=10)



# The viewer's own session lines (ScreenSharingViewer's `screen-sharing` log): a transport switch,
# an rd/1 close and the end reason, the phone's half of the share-host log.
VIEWER_LOG_LINE = re.compile(r"(host serves \S+: reattaching for it|rd closed: .*|viewer ended: .*)$")


def viewer_log(lines, limit=6):
    """The phone's last session lines, cut to 160 characters each, joined with ` | `."""
    found = [m.group(1)[:160] for m in map(VIEWER_LOG_LINE.search, (l.rstrip() for l in lines)) if m]
    return " | ".join(found[-limit:]) or "no viewer session lines"


# rd/1's meter line: "30 fps · 812 kbps · 1280×800 · lan".
RD_METER_LINE = re.compile(r"[0-9]+(?:\.[0-9]+)? fps · [0-9]+ kbps")


def _digest(text):
    return hashlib.sha256(text.lower().encode()).hexdigest()[:8]


def row_status(node):
    """The status word of one Mac row's label (ScreenSharingMacRow.status), or "?"."""
    label = str(node.get("AXLabel", ""))
    return next((word for word in ("Offline", "Not shared", "Blocked", "Sharing") if word in label), "?")


def alert_state(nodes, name):
    """Which known alert title is on screen after a row tap, in fixed words (no other text)."""
    titles = {"is offline": f"{name} is offline", "isn't sharing": f"{name} isn't sharing its screen",
              "doesn't allow": f"{name} doesn't allow this iPhone", "allows View Only": f"{name} allows View Only",
              "not one of your devices": f"{name} isn't one of your devices", "couldn't reach": f"Couldn't reach {name}",
              "couldn't share": f"Couldn't share {name}"}
    labels = {str(node.get("AXLabel", "")) for node in nodes}
    shown = [key for key, title in titles.items() if title in labels]
    return f"alert: {', '.join(shown) or 'none'}"


def screen_sharing_page_state(nodes, name=None, device_id=None):
    """What the Screen Sharing list showed: its state row (finding, failed, empty) and each Mac
    row as a short id digest, whether its name is the rig Mac's, and its status line; the count of
    name-keyed rows and a missing page. No ids or other Macs' names are printed."""
    identifiers = {str(node.get(key, "")) for node in nodes for key in ("AXIdentifier", "AXUniqueId")}
    states = [state for state in ("finding", "failed", "empty") if f"screenSharing.{state}" in identifiers]
    prefix = "screenSharing.device."
    rows = []
    for node in nodes:
        identifier = str(node.get("AXIdentifier") or node.get("AXUniqueId") or "")
        if not identifier.startswith(prefix):
            continue
        label = str(node.get("AXLabel", ""))
        named = bool(name) and label.startswith(name)
        status = row_status(node)
        rows.append(f"{_digest(identifier[len(prefix):])}{' (rig name)' if named else ''} {status}")
    text = f"page state: {', '.join(states) or 'none'}; Mac rows: {len(rows)}"
    if rows:
        text += " [" + "; ".join(rows) + "]"
    # Rows keyed by name mean the app never saw CMUX_PAIR_E2E_SHARE_RECEIPT (or is not DEBUG);
    # no page node means the phone is on another screen. Counts and fixed words only.
    by_name = sum(1 for node in nodes
                  if str(node.get("AXIdentifier") or node.get("AXUniqueId") or "").startswith("screenSharing.mac."))
    if by_name:
        text += f"; rows keyed by name: {by_name}"
    if not states and not rows and "screenSharing.page" not in identifiers:
        text += f"; no Screen Sharing page ({len(nodes)} nodes{_screen_summary(nodes)})"
    if device_id:
        text += f"; wanted {_digest(device_id)}"
    return text


_ID_TAIL = re.compile(r"[0-9a-fA-F-]{16,}$")


def _screen_summary(nodes, limit=12):
    """Which screen the phone is on, from fixed UI text: its headings and accessibility ids (a
    trailing id is digested). Empty when the tree has neither."""
    headings = []
    ids = []
    for node in nodes:
        identifier = str(node.get("AXIdentifier") or node.get("AXUniqueId") or "")
        if identifier:
            tail = _ID_TAIL.search(identifier)
            if tail:
                identifier = identifier[:tail.start()] + _digest(tail.group(0))
            if identifier not in ids:
                ids.append(identifier)
        if str(node.get("type", "")) in ("Heading", "NavigationBar"):
            label = str(node.get("AXLabel", ""))
            if label and label not in headings:
                headings.append(label)
    parts = []
    if headings:
        parts.append("headings: " + ", ".join(headings[:limit]))
    if ids:
        parts.append("ids: " + ", ".join(ids[:limit]) + (" …" if len(ids) > limit else ""))
    return ("; " + "; ".join(parts)) if parts else ""


# The viewer's cards and alerts, by title, as fixed words (cmux-next-ios ScreenSharingPage).
_VIEWER_TITLES = (
    ("Connecting to {}…", "connecting"),
    ("Waiting for {}", "waiting for approval"),
    ("Starting the screen…", "starting the screen"),
    ("Reconnecting to {}…", "reconnecting"),
    ("{} declined", "declined"),
    ("{} doesn't allow this iPhone", "refused: no permission"),
    ("{} allows View Only", "refused: view only"),
    ("{} is offline", "refused: offline"),
    ("{} isn't sharing its screen", "refused: not shared"),
    ("{} isn't one of your devices", "refused: not found"),
    ("Couldn't reach {}", "refused: other"),
    ("Sharing ended", "ended"),
    ("Couldn't share {}", "share problem"),
)
_VIEWER_DETAILS = (
    ("didn't turn on sharing", "no sharing before the deadline"),
    ("isn't available yet", "no share carrier"),
    ("The device hub could not start the session", "hub refused the session"),
    ("stopped sharing", "host stopped"),
    ("turned off Share This Mac", "sharing off"),
    ("went offline", "peer offline"),
    ("Nobody answered", "expired"),
    ("connection to", "connection dropped"),
    ("is over", "session over, reason not one the phone names"),
    ("changed this iPhone's access", "permission revoked"),
    ("signed out", "signed out"),
    ("was removed from your devices", "viewer removed"),
)


def viewer_state(nodes, name=""):
    """What the phone showed instead of a frame: the viewer card or alert, the views present, the
    rd/1 status capsule and meter line, all as fixed words or numbers, never free text."""
    labels = [str(node.get("AXLabel", "")) for node in nodes]
    identifiers = {str(node.get(key, "")) for node in nodes for key in ("AXIdentifier", "AXUniqueId")}
    cards = [word for title, word in _VIEWER_TITLES if title.format(name) in labels]
    details = [word for text, word in _VIEWER_DETAILS if any(text in label for label in labels)]
    views = [view for view in ("screen.view", "screen.stats", "macScreen.stream", "browser.stream", "browser.meter",
                               "macScreen.status", "macScreen.close", "screenSharing.page") if view in identifiers]
    meter = next((RD_METER_LINE.search(label).group(0) for label in labels if RD_METER_LINE.search(label)), "none")
    text = f"viewer: {', '.join(cards) or 'no card'}"
    if details:
        text += f" ({', '.join(details)})"
    return text + f"; views: {', '.join(views) or 'none'}; meter: {meter}"


class PairSharePhone(ScreenProofPhone):
    """Drive the phone's real Settings > Screen Sharing flow."""

    def control(self, identifier):
        return self.ui.control(lambda node: (node.get("AXIdentifier") == identifier
                                             or node.get("AXUniqueId") == identifier),
                               "Screen Sharing control")

    def launch(self):
        # PhoneUI.launch passes the SIMCTL_CHILD_* receipt flag through to the
        # app. The app logs only a digest of the signed nonce in DEBUG builds.
        # With the Mac app closed the daemon serves the phone over rd/1, whose
        # viewer (MacScreenRdView) shows its frame rate only with the meter flag (browser.meter).
        # Settings, then its Screen Sharing row, as a person gets there. The page itself is not
        # opened by launch argument: the app builds the Screen Sharing service only once the
        # account resolves, and a page pushed before that stays blank (run 45757908357: a
        # Back button and the tab bar, no heading). The row appears only once the service does.
        self.ui.launch(["-cmux-mobile-no-restore", "-cmux-mobile-tab", "settings",
                        "-cmux-mobile-browser-meter"])
        # Live data can come minutes after launch (run 45784488782 paired 181 s after its launch).
        deadline = time.monotonic() + SETTINGS_ROW_WAIT
        while (row := self._screen_sharing_row()) is None and time.monotonic() < deadline:
            time.sleep(1)
        if row is None:
            try:
                self.screenshot("settings-row-missing")
            except Exception:  # noqa: BLE001 - the text below is the diagnostic; the image is extra
                pass
            nodes = self.ui.find(lambda node: True)
            settings_ids = sorted({str(node.get("AXIdentifier") or node.get("AXUniqueId") or "") for node in nodes}
                                  - {""})
            settings_ids = [i for i in settings_ids if i.startswith("settings.")]
            raise PairShareFailure(f"Settings showed no Screen Sharing row in {SETTINGS_ROW_WAIT} s, so the app built no "
                                   f"Screen Sharing service ({len(nodes)} nodes; settings rows: "
                                   f"{', '.join(settings_ids) or 'none'}{_screen_summary(nodes)})")
        self.ui.tap(row)

    def _screen_sharing_row(self):
        # The row's identifier can sit on the link and on its label (run 45768668186 matched no
        # single node): tap the first visible one, a Button when there is one.
        rows = self.ui.find(lambda node: "settings.screenSharing" in (node.get("AXIdentifier"),
                                                                      node.get("AXUniqueId")))
        buttons = [row for row in rows if row.get("type") == "Button"]
        return (buttons or rows or [None])[0]

    def request_share(self, name, device_id):
        # The hub and the share host may spell the same id in different case; the phone itself
        # compares ids lowercased (ScreenSharingService).
        exact_id = ("screenSharing.device." + device_id).lower()
        deadline = time.monotonic() + SHARE_ROW_WAIT
        row = None
        nodes = []
        attempt = 0
        while time.monotonic() < deadline:
            nodes = self.ui.find(lambda node: True)
            matches = [node for node in nodes if exact_id in (str(node.get("AXIdentifier", "")).lower(),
                                                              str(node.get("AXUniqueId", "")).lower())]
            if len(matches) > 1:
                raise PairShareFailure("ambiguous Mac row")
            row = matches[0] if matches else None
            # With the app closed and consent off the share host lists Online and not shared, and
            # only then does a tap offer Share (an Offline row asks "is offline" instead; run
            # 45817624546 tapped the row and saw no Share alert). The hub's list can lag the host.
            if row is not None and row_status(row) == "Not shared":
                break
            # Alternate a pull to refresh (the page rereads the hub's list) with a scroll the other way.
            gesture = "scroll-down" if attempt % 2 == 0 else "scroll-up"
            attempt += 1
            self.ui.run(["axe", "gesture", gesture, "--udid", self.ui.udid], check=False)
            time.sleep(1)
        if row is None or row_status(row) != "Not shared":
            shot = "share-row-missing" if row is None else "share-row-not-offered"
            try:
                self.screenshot(shot)
            except Exception:  # noqa: BLE001 - the text below is the diagnostic; the image is extra
                pass
            what = "was not visible" if row is None else f"never read Not shared in {SHARE_ROW_WAIT} s"
            raise PairShareFailure(f"the rig Mac row {what} "
                                   f"({screen_sharing_page_state(nodes, name, device_id)})")
        self.ui.tap(row)
        title = f"{name} isn't sharing its screen"
        try:
            self.ui.control(lambda node: node.get("type") == "StaticText"
                            and str(node.get("AXLabel", "")) == title, "Share alert")
        except RuntimeError as error:
            try:
                self.screenshot("share-alert-missing")
            except Exception:  # noqa: BLE001 - the text below is the diagnostic; the image is extra
                pass
            after = self.ui.find(lambda node: True)
            raise PairShareFailure(f"{error} after tapping a Not shared row ({alert_state(after, name)}; "
                                   f"{screen_sharing_page_state(after, name, device_id)}; "
                                   f"{viewer_state(after, name)})") from None
        button = self.ui.control(lambda node: node.get("type") == "Button"
                                 and str(node.get("AXLabel", "")) == f"Share {name}",
                                 "Share alert button")
        self.ui.tap(button)

    def stats(self):
        """The frame-rate line of whichever viewer is up: WebRTC's screen.stats,
        or rd/1's browser.meter (its fps line is a child text of the meter)."""
        rows = self.ui.find(lambda node: (node.get("AXIdentifier") == "screen.stats"
                                          or node.get("AXUniqueId") == "screen.stats"))
        if len(rows) > 1:
            raise PairShareFailure("ambiguous phone stats")
        if rows:
            return str(rows[0].get("AXLabel", ""))
        meter = self.ui.find(lambda node: RD_METER_LINE.search(str(node.get("AXLabel", ""))) is not None)
        return str(meter[0].get("AXLabel", "")) if meter else ""

    def wait_frame(self, timeout=60, name=""):
        deadline = time.monotonic() + timeout
        fps_seen = False
        while time.monotonic() < deadline:
            fps = positive_fps(self.stats())
            fps_seen = fps_seen or bool(fps)
            if fps and self.live_frame("share-frame"):
                return self.screenshots / "share-frame.png"
            time.sleep(1)
        state = viewer_state(self.ui.find(lambda node: True), name)
        raise PairShareFailure("phone did not receive a decoded Mac frame ("
                               f"{state}; frame rate above zero seen: {fps_seen})")

    def screen_view(self):
        """WebRTC draws into screen.view; rd/1 (the Mac app closed) into the Mac screen viewer's
        macScreen.stream (MacScreenRdView, since #51849), or browser.stream on a build before it."""
        for identifier in ("screen.view", "macScreen.stream", "browser.stream"):
            found = self.ui.find(lambda node, i=identifier: (node.get("AXIdentifier") == i
                                                            or node.get("AXUniqueId") == i))
            if len(found) > 1:
                raise PairShareFailure("ambiguous phone screen view")
            if found:
                return found[0]
        return self.control("screen.view")

    def tap_center(self):
        view = self.screen_view()
        frame = view.get("frame") or {}
        if frame.get("width", 0) <= 0 or frame.get("height", 0) <= 0:
            raise PairShareFailure("phone screen view has no visible frame")
        timestamp = time.time()
        self.ui.tap({**view, "frame": {"x": frame["x"] + frame["width"] * 0.5,
                                        "y": frame["y"] + frame["height"] * 0.55,
                                        "width": 1, "height": 1}})
        return timestamp
