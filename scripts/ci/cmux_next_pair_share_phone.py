"""Phone-side controls and the private Mac input probe for pair-e2e sharing.

AXe and simctl both target the run's freshly created simulator by UDID. Frame
captures and probe events stay in the rig's private work directory.
"""

from __future__ import annotations

import json
from pathlib import Path
import subprocess
import re
import time

from cmux_next_screen_sharing_proof import Phone as ScreenProofPhone, positive_fps


ROOT = Path(__file__).resolve().parents[2]


class PairShareFailure(RuntimeError):
    """A fixed, private diagnostic for a failed share leg."""


class PairInputProbe:
    """Run InputProbe and the Vision OCR helper for one pair-e2e share leg."""

    def __init__(self, work):
        self.work = Path(work)
        self.events_path = self.work / "share-input.jsonl"
        self.ocr = self.work / "share-ocr"
        self.binary = self.work / "share-input-probe"
        self.log_path = self.work / "share-input-probe.log"
        self.process = None

    def __enter__(self):
        self.work.mkdir(mode=0o700, parents=True, exist_ok=True)
        source = ROOT / "cmux-next-ios/verify/screen-sharing/InputProbe.swift"
        ocr_source = ROOT / "cmux-next-ios/verify/e2e/ocr.swift"
        try:
            subprocess.run(["xcrun", "swiftc", "-O", str(source), "-o", str(self.binary)],
                           check=True, capture_output=True, timeout=120)
            subprocess.run(["xcrun", "swiftc", str(ocr_source), "-o", str(self.ocr)],
                           check=True, capture_output=True, timeout=120)
            self.events_path.unlink(missing_ok=True)
            with self.log_path.open("w") as log:
                self.process = subprocess.Popen([str(self.binary), str(self.events_path)],
                                                stdout=log, stderr=subprocess.STDOUT,
                                                start_new_session=True)
        except (OSError, subprocess.SubprocessError) as error:
            self.__exit__(None, None, None)
            raise PairShareFailure(f"input probe setup failed ({type(error).__name__})") from None
        return self

    def events(self):
        try:
            data = self.events_path.read_bytes()
        except FileNotFoundError:
            return []
        if len(data) > 1024 * 1024:
            raise PairShareFailure("input probe log exceeded its bound")
        result = []
        for line in data.splitlines():
            if not line.endswith(b"}"):
                continue
            try:
                row = json.loads(line)
            except ValueError:
                continue
            if isinstance(row, dict):
                result.append(row)
        return result

    def verify_click(self, since, timeout=35):
        """Require a fresh left click generated by the phone's direct tap."""
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if self.process is None or self.process.poll() is not None:
                raise PairShareFailure("InputProbe exited before the phone tap")
            events = self.events()
            fresh = [event for event in events
                     if event.get("kind") in ("left-down", "left-up")
                     and isinstance(event.get("t"), (int, float))
                     and event["t"] >= since]
            for down, up in zip(fresh, fresh[1:]):
                if (down.get("kind") == "left-down" and up.get("kind") == "left-up"
                        and down.get("clicks") == 1 and up.get("clicks") == 1
                        and up.get("drags") == 0
                        and down.get("x") == up.get("x") and down.get("y") == up.get("y")):
                    return [down, up]
            time.sleep(0.5)
        raise PairShareFailure("phone tap did not reach InputProbe")

    def __exit__(self, *_):
        process = self.process
        self.process = None
        if process and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=10)



# rd/1's meter line: "30 fps · 812 kbps · 1280×800 · lan".
RD_METER_LINE = re.compile(r"[0-9]+(?:\.[0-9]+)? fps · [0-9]+ kbps")


def screen_sharing_page_state(nodes):
    """What the Screen Sharing list showed, in fixed words (no Mac names or ids): its state row
    (finding, failed, empty) and how many Mac rows it drew."""
    identifiers = {str(node.get(key, "")) for node in nodes for key in ("AXIdentifier", "AXUniqueId")}
    states = [state for state in ("finding", "failed", "empty") if f"screenSharing.{state}" in identifiers]
    rows = sum(1 for identifier in identifiers if identifier.startswith("screenSharing.device."))
    return f"page state: {', '.join(states) or 'none'}; Mac rows: {rows}"


class PairSharePhone(ScreenProofPhone):
    """Drive the phone's real Settings > Screen Sharing flow."""

    def control(self, identifier):
        return self.ui.control(lambda node: (node.get("AXIdentifier") == identifier
                                             or node.get("AXUniqueId") == identifier),
                               "Screen Sharing control")

    def launch(self):
        # PhoneUI.launch passes the SIMCTL_CHILD_* receipt flag through to the
        # app. The app logs only a digest of the signed nonce in DEBUG builds.
        # With the Mac app closed the daemon serves the phone over rd/1, whose
        # view shows its frame rate only with the meter flag (browser.meter).
        self.ui.launch(["-cmux-mobile-no-restore", "-cmux-mobile-settings-page", "screenSharing",
                        "-cmux-mobile-browser-meter"])

    def request_share(self, name, device_id):
        # The hub and the share host may spell the same id in different case; the phone itself
        # compares ids lowercased (ScreenSharingService).
        exact_id = ("screenSharing.device." + device_id).lower()
        deadline = time.monotonic() + 90
        row = None
        nodes = []
        while time.monotonic() < deadline:
            nodes = self.ui.find(lambda node: True)
            matches = [node for node in nodes if exact_id in (str(node.get("AXIdentifier", "")).lower(),
                                                              str(node.get("AXUniqueId", "")).lower())]
            if len(matches) > 1:
                raise PairShareFailure("ambiguous Mac row")
            if matches:
                row = matches[0]
                break
            self.ui.run(["axe", "gesture", "scroll-up", "--udid", self.ui.udid], check=False)
            time.sleep(1)
        if row is None:
            raise PairShareFailure(f"the rig Mac row was not visible ({screen_sharing_page_state(nodes)})")
        self.ui.tap(row)
        title = f"{name} isn't sharing its screen"
        self.ui.control(lambda node: node.get("type") == "StaticText"
                        and str(node.get("AXLabel", "")) == title, "Share alert")
        button = self.ui.control(lambda node: node.get("type") == "Button"
                                 and str(node.get("AXLabel", "")) == f"Share {name}",
                                 "Share alert button")
        self.ui.tap(button)

    def stats(self):
        """The frame-rate line of whichever viewer is up: WebRTC's screen.stats,
        or rd/1's browser.meter (its fps line is a child text of the meter)."""
        rows = self.ui.find(lambda node: (node.get("AXIdentifier") == "screen.stats"
                                          or node.get("AXUniqueId") == "screen.stats"))
        if len(rows) > 1:
            raise PairShareFailure("ambiguous phone stats")
        if rows:
            return str(rows[0].get("AXLabel", ""))
        meter = self.ui.find(lambda node: RD_METER_LINE.search(str(node.get("AXLabel", ""))) is not None)
        return str(meter[0].get("AXLabel", "")) if meter else ""

    def wait_frame(self, timeout=60):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if positive_fps(self.stats()) and self.live_frame("share-frame"):
                return self.screenshots / "share-frame.png"
            time.sleep(1)
        raise PairShareFailure("phone did not receive a decoded Mac frame")

    def screen_view(self):
        """WebRTC draws into screen.view; rd/1 (the Mac app closed) into browser.stream."""
        for identifier in ("screen.view", "browser.stream"):
            found = self.ui.find(lambda node, i=identifier: (node.get("AXIdentifier") == i
                                                            or node.get("AXUniqueId") == i))
            if len(found) > 1:
                raise PairShareFailure("ambiguous phone screen view")
            if found:
                return found[0]
        return self.control("screen.view")

    def tap_center(self):
        view = self.screen_view()
        frame = view.get("frame") or {}
        if frame.get("width", 0) <= 0 or frame.get("height", 0) <= 0:
            raise PairShareFailure("phone screen view has no visible frame")
        timestamp = time.time()
        self.ui.tap({**view, "frame": {"x": frame["x"] + frame["width"] * 0.5,
                                        "y": frame["y"] + frame["height"] * 0.55,
                                        "width": 1, "height": 1}})
        return timestamp
