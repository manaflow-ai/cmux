#!/usr/bin/env python3
"""ROUNDTRIP lines (cmux-tui/crates/acpmux/tests/round_trip_audit.rs) -> a markdown table per flow.

usage: round-trip-audit-report.py LINES_FILE... [--out FILE]

Each flow gets one table per pair: step, rpc, caller, waits_on, verdict, p50 ms for every
(profile, load) seen, bytes up/down, and the one-line why. A step with no number shows the
reason. Totals per flow and pair: the waits today (every step the client waits on, in order)
against the waits if every step that is not `needed` goes (deletable, pipelinable and optimistic
all stop being a serial wait), and the p50 ms of the steps that were measured.
"""
import json
import statistics
import sys
from collections import defaultdict


def load(paths):
    rows = []
    for p in paths:
        with open(p, encoding="utf-8", errors="replace") as f:
            for line in f:
                i = line.find("ROUNDTRIP {")
                if i < 0:
                    continue
                try:
                    rows.append(json.loads(line[i + len("ROUNDTRIP "):]))
                except ValueError:
                    pass
    return rows


def p50(xs):
    return statistics.median(xs) if xs else None


def fmt(v):
    return "-" if v is None else (f"{v:.0f}" if v >= 100 else f"{v:.1f}")


def main(argv):
    out = None
    paths = []
    it = iter(argv)
    for a in it:
        if a == "--out":
            out = next(it)
        else:
            paths.append(a)
    rows = load(paths)
    if not rows:
        sys.exit("round-trip-audit-report: no ROUNDTRIP lines")
    cols = sorted({(r["profile"], r["load"]) for r in rows})
    flows = defaultdict(lambda: defaultdict(dict))  # flow -> pair -> step -> info
    for r in rows:
        s = flows[r["flow"]][r["pair"]].setdefault(
            r["step"],
            {"r": r, "ms": defaultdict(list), "up": [], "down": [], "reason": None, "fails": defaultdict(int)},
        )
        if r.get("ms") is not None:
            s["ms"][(r["profile"], r["load"])].append(r["ms"])
            s["up"].append(r.get("up_bytes") or 0)
            s["down"].append(r.get("down_bytes") or 0)
        else:
            s["reason"] = r.get("reason") or s["reason"]
            if str(r.get("reason", "")).startswith("run failed"):
                s["fails"][(r["profile"], r["load"])] += 1
    md = ["# Round-trip audit", "", "Generated by `scripts/measure/round-trip-audit-report.py`; "
          "p50 ms per (profile, load); `-` = not measured (reason in the last column).", ""]
    for flow in sorted(flows):
        md += [f"## {flow}", ""]
        for pair in sorted(flows[flow]):
            steps = flows[flow][pair]
            md += [f"### {pair}", ""]
            head = ["step", "rpc", "caller", "waits on", "verdict"] + [f"{p} {l} ms" for p, l in cols] + ["up B", "down B", "why / reason"]
            md += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
            now = needed = 0
            now_ms = need_ms = 0.0
            for n in sorted(steps):
                s = steps[n]
                r = s["r"]
                nums = [p50(s["ms"].get(c, [])) for c in cols]
                measured = any(v is not None for v in nums)
                why = r["why"] if measured else f'{r["why"]} (not measured: {s["reason"]})'
                if measured and r.get("stand_in"):
                    why += f' (stand-in: {r["stand_in"]})'
                runs = ", ".join(f"{p} {l} n={len(s['ms'].get((p, l), []))}" + (f" fail={s['fails'][(p, l)]}" if s["fails"].get((p, l)) else "") for p, l in cols)
                if measured:
                    why += f" [{runs}]"
                    if s["fails"]:
                        why += f" (a failed run: {s['reason']})"
                md.append("| " + " | ".join(
                    [str(n), f'`{r["rpc"]}`', r["caller"], str(r["waits_on"]), r["verdict"]]
                    + [fmt(v) for v in nums]
                    + [fmt(p50(s["up"])) if s["up"] else "-", fmt(p50(s["down"])) if s["down"] else "-", why.replace("|", "/")]
                ) + " |")
                now += 1
                if r["verdict"] == "needed":
                    needed += 1
                first = next((v for v in nums if v is not None), None)
                if first is not None:
                    now_ms += first
                    if r["verdict"] == "needed":
                        need_ms += first
            md += ["", f"Totals ({pair}, {flow}): waits now {now}; waits if every non-needed one goes {needed}; "
                   f"measured p50 ms now {fmt(now_ms)} (first column), of which needed {fmt(need_ms)}.", ""]
    text = "\n".join(md) + "\n"
    if out:
        with open(out, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
