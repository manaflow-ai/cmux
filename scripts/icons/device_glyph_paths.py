#!/usr/bin/env python3
"""Writes webviews/src/ui/deviceGlyphPaths.ts: the vector paths of the SF Symbols the device kinds
name (cmux-tui/crates/cmux-device-kind, its table webviews/src/ui/deviceGlyphKinds.json), so the
web draws the glyph the native views draw as the system symbol.

Input: the JSON scripts/icons/sf_pdf_paths.py reads from the PDFs scripts/icons/export_sf_symbols.swift
draws on a Mac (every symbol at one point size and weight, so their relative sizes are Apple's own).

Every glyph shares one 20x16 viewBox and one scale: the scale at which macbook.gen2 has the ink width
of the composer's MacBook (webviews/src/agent-session/acpmux/MacBookGlyph.tsx, cmux#42292), and each
glyph's ink centered on that MacBook's center (10, 8.2). So a Mac mini, a server and an iPhone stand
at the same optical size and on the same center line in every row. `--weight` picks the export's weight;
`--scale` multiplies the shared scale (gallery variants).

Usage: device_glyph_paths.py PATHS.json [--weight regular] [--scale 1] [--check]
"""
import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
KINDS = REPO / "webviews" / "src" / "ui" / "deviceGlyphKinds.json"
OUT = REPO / "webviews" / "src" / "ui" / "deviceGlyphPaths.ts"
# MacBookGlyph.tsx: its path spans x 0.029..19.971 and y 2.575..13.825 before
# `translate(1.75 1.435) scale(0.825)`.
MACBOOK_INK_WIDTH = (19.97081 - 0.02919) * 0.825
CENTER = (10.0, 1.435 + (2.575 + 13.825) / 2 * 0.825)
NUM = re.compile(r"-?\d+(?:\.\d+)?")


def points(d):
    values = [float(v) for v in NUM.findall(d)]
    return list(zip(values[0::2], values[1::2]))


def ink_box(layers):
    pts = [p for layer in layers for p in points(layer["d"])]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def transform(d, k, dx, dy):
    out, i = [], 0
    for token in re.findall(r"[MLCZ]|-?\d+(?:\.\d+)?", d):
        if token in "MLCZ":
            out.append(token)
            i = 0
            continue
        v = float(token)
        v = v * k + (dx if i % 2 == 0 else dy)
        i += 1
        out.append(f"{v:.3f}".rstrip("0").rstrip("."))
    text = " ".join(out)
    return re.sub(r"([MLCZ]) ", r"\1", text)


def glyphs(paths, weight, scale):
    """Each symbol's layers, scaled and centered, as [(symbol, [{"d", "rule"?}])]."""
    kinds = json.loads(KINDS.read_text())
    symbols = list(dict.fromkeys(kinds.values()))
    mac = paths[f"macbook.gen2@{weight}"]["layers"]
    x0, _, x1, _ = ink_box(mac)
    k = MACBOOK_INK_WIDTH / (x1 - x0) * scale
    rows = []
    for symbol in symbols:
        entry = paths.get(f"{symbol}@{weight}")
        if entry is None:
            sys.exit(f"no export of {symbol}@{weight}")
        layers = [l for l in entry["layers"] if l["rule"] in ("nonzero", "evenodd") and l["d"]]
        if not layers:
            sys.exit(f"{symbol}@{weight} drew no vector fill (a raster?)")
        bx0, by0, bx1, by1 = ink_box(layers)
        dx = CENTER[0] - (bx0 + bx1) / 2 * k
        dy = CENTER[1] - (by0 + by1) / 2 * k
        drawn = []
        for layer in layers:
            item = {"d": transform(layer["d"], k, dx, dy)}
            if layer["rule"] == "evenodd":
                item["rule"] = "evenodd"
            drawn.append(item)
        rows.append((symbol, drawn))
    return rows


def entries(rows, indent):
    lines = []
    for symbol, drawn in rows:
        lines.append(f"{indent}{json.dumps(symbol)}: [")
        for item in drawn:
            rule = ', rule: "evenodd"' if item.get("rule") else ""
            lines.append(f"{indent}  {{ d: {json.dumps(item['d'])}{rule} }},")
        lines.append(f"{indent}],")
    return lines


def build(paths, weight, scale):
    rows = glyphs(paths, weight, scale)
    lines = [
        "// Generated by scripts/icons/device_glyph_paths.py from SF Symbols exported on a Mac",
        "// (scripts/icons/export_sf_symbols.swift); do not edit. One 20x16 viewBox and one scale for",
        f"// every glyph ({weight} weight), each centered on the composer MacBook's center.",
        'export const DEVICE_GLYPH_VIEWBOX = "0 0 20 16";',
        "",
        'export type DeviceGlyphLayer = { d: string; rule?: "evenodd" };',
        "",
        "export const DEVICE_GLYPH_PATHS: Readonly<Record<string, readonly DeviceGlyphLayer[]>> = {",
    ]
    lines += entries(rows, "  ")
    lines.append("};")
    return "\n".join(lines) + "\n"


# The gallery's candidates beside the shipped look (DeviceGlyph.gallery.tsx).
VARIANTS = {"medium": ("medium", 1.0), "light": ("light", 1.0), "large": ("regular", 1.12)}


def build_variants(paths):
    lines = [
        "// Generated by scripts/icons/device_glyph_paths.py --variants; do not edit. The device glyph",
        "// gallery's candidate looks (DeviceGlyph.gallery.tsx), beside the shipped deviceGlyphPaths.ts.",
        'import type { DeviceGlyphLayer } from "./deviceGlyphPaths";',
        "",
        "export const DEVICE_GLYPH_VARIANTS: Readonly<",
        "  Record<string, Readonly<Record<string, readonly DeviceGlyphLayer[]>>>",
        "> = {",
    ]
    for name, (weight, scale) in VARIANTS.items():
        lines.append(f"  {name}: {{")
        lines += entries(glyphs(paths, weight, scale), "    ")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("paths")
    parser.add_argument("--weight", default="regular")
    parser.add_argument("--scale", type=float, default=1.0)
    parser.add_argument("--out", default=str(OUT))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--variants", action="store_true", help="write deviceGlyphVariants.ts instead")
    args = parser.parse_args()
    paths = json.loads(Path(args.paths).read_text())
    if args.variants:
        text, out = build_variants(paths), OUT.with_name("deviceGlyphVariants.ts")
    else:
        text, out = build(paths, args.weight, args.scale), Path(args.out)
    if args.check:
        sys.exit(0 if out.exists() and out.read_text() == text else f"{out} is stale")
    out.write_text(text)


if __name__ == "__main__":
    main()
