#!/usr/bin/env python3
"""Regenerates CmuxiOSTerminal/Input/TerminalPhysicalKeys.swift from a
ghostty-next checkout: HID usage (page 7) -> mac virtual key code, the native
key code GhosttyNextKit takes on iOS (plans/cmux-next/ios-keyboard.md KB4).

usage: ios/scripts/gen-terminal-physical-keys.py <ghostty-next checkout> <sha>
"""
import re
import sys

checkout, sha = sys.argv[1], sys.argv[2]
src = open(f"{checkout}/src/input/keycodes.zig").read()
start = src.index("pub const raw_entries")
rows = re.findall(r'\.\{\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),'
                  r'\s*(0x[0-9a-fA-F]+),\s*"(\w*)"\s*\}', src[start:])
lines = []
seen = set()
for usb, _evdev, _xkb, _win, mac, code in rows:
    u, m = int(usb, 16), int(mac, 16)
    usage = u & 0xFFFF
    # Page 7 only; 0xffff and 0 (except KeyA, which is 0) mean "no mac key".
    if u >> 16 != 7 or m == 0xFFFF or (m == 0 and code != "KeyA") or usage in seen:
        continue
    seen.add(usage)
    lines.append(f"        0x{usage:04x}: 0x{m:04x}, // {code}")
print(f"""// Generated by ios/scripts/gen-terminal-physical-keys.py from ghostty-next
// src/input/keycodes.zig at manaflow-ai/ghostty-next {sha}. Do not edit by hand.

/// The physical key table between UIKit and GhosttyNextKit: UIKit reports a
/// key's USB HID usage (page 7), and Ghostty on iOS takes the mac virtual key
/// code as its native key code (the keycodes.zig native column for .ios).
/// Physical keys only; Ghostty's encoder does all key encoding (decisions D5,
/// KB4). Remove it when ghostty-next takes HID usages on iOS.
enum TerminalPhysicalKeys {{
    /// HID usage (page 7) to mac virtual key code.
    static let macKeyCode: [UInt16: UInt32] = [""")
print("\n".join(lines))
print("""    ]
}""")
