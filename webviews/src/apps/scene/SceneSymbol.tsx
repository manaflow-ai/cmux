/** The host's drawing of any SF Symbol: `<base><name>.png`, a black template image (the mount
 * reply's `symbol_base`, ``AppsPanelsPageProvider``). Absent where the host draws none. */
export type SceneSymbolResolver = (name: string) => string | undefined;

/** Lowercase words of letters and digits joined by single dots, at most 128 bytes: the names the
 * host draws (`IconValue.isSymbolName`); anything else never becomes a URL. */
export function isSceneSymbolName(name: string): boolean {
  return name.length > 0 && name.length <= 128 && /^[a-z0-9]+(?:\.[a-z0-9]+)*$/.test(name);
}

/** `<base><name>.png` for a symbol name under a host's `symbol_base`, else undefined. */
export function symbolImageURL(base: string | undefined, name: string): string | undefined {
  return base && base.endsWith("/") && isSceneSymbolName(name) ? `${base}${name}.png` : undefined;
}

export const SymbolContext = createContext<SceneSymbolResolver | undefined>(undefined);

/** How a scene symbol draws: a pack icon, or the host's image of the SF Symbol. */
export type SceneSymbolSource = { icon: string } | { image: string };

/** The native renderer's order (`NSImage.icon(symbol:)`): the icon the catalog has stand for the
 * symbol, a pack icon of that name, else the SF Symbol itself, which the host draws. Without a
 * host, a common symbol draws its nearest pack icon and any other the neutral missing glyph. */
export function sceneSymbolSource(
  value: unknown,
  pack: IconPack = bundledIconPack,
  resolveSymbol?: SceneSymbolResolver,
): SceneSymbolSource {
  const name = sceneText(value);
  const has = (icon: string | undefined): icon is string => !!icon && Object.hasOwn(pack.icons, icon);
  const aliased = Object.hasOwn(CATALOG, name) ? CATALOG[name] : undefined;
  if (has(aliased)) return { icon: aliased };
  if (has(name)) return { icon: name };
  const image = resolveSymbol?.(name);
  if (image) return { image };
  const mapped = Object.hasOwn(SYMBOLS, name) ? SYMBOLS[name] : undefined;
  return { icon: has(mapped) ? mapped : MISSING_ICON };
}

/** The pack icon for a symbol (a Session Info section's title icon takes a pack name only). */
export function appSceneIcon(value: unknown): string {
  const source = sceneSymbolSource(value);
  return "icon" in source ? source.icon : MISSING_ICON;
}

/** Unknown SF names deliberately draw a neutral fallback without an icon-pack warning. */
export function SceneSymbol({
  symbol,
  size = 14,
  color,
  className,
}: {
  symbol: unknown;
  size?: number;
  color?: string;
  className?: string;
}) {
  const { pack } = useIcons();
  const source = sceneSymbolSource(symbol, pack, useContext(SymbolContext));
  if ("icon" in source) return <Icon name={source.icon} size={size} row fit color={color} className={className} />;
  const mask = `url("${source.image}") center / contain no-repeat`;
  const style: CSSProperties = {
    display: "inline-block",
    flex: "none",
    width: size,
    height: size,
    backgroundColor: color ?? "currentColor",
    mask,
    WebkitMask: mask,
  };
  return <span className={className} style={style} data-symbol={sceneText(symbol)} aria-hidden />;
}
