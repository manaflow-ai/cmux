import { expect, test } from "bun:test";
import { IrError } from "../codegen/ir";
import { generate } from "../codegen/acpmux";

const source = "cmux-tui/crates/acpmux/spec/acpmux-protocol.json";

function sampleIr(): Record<string, unknown> {
  return {
    version: "1",
    methods: [
      {
        name: "_acpmux/sessions",
        kind: "request",
        params: { $ref: "#/types/SessionsParams" },
        result: { $ref: "#/types/SessionsResult" },
      },
      { name: "initialize", kind: "request", acp: true, params: true, result: true },
      { name: "session/cancel", kind: "client_notification", acp: true, params: true },
      { name: "_acpmux/session_state", kind: "notification", params: { $ref: "#/types/SessionState" } },
      { name: "session/request_permission", kind: "server_request", acp: true, params: true, result: true },
      { name: "_acpmux/disconnected", kind: "client_local", params: true },
    ],
    types: {
      SessionState: {
        description: "A session's run state changed.",
        properties: {
          sessionId: { type: "string" },
          state: { $ref: "#/types/RunState" },
          title: { description: "Null until the agent names it.", type: ["string", "null"] },
        },
        required: ["sessionId", "state", "title"],
        type: "object",
      },
      RunState: { enum: ["idle", "running", "waiting"], type: "string" },
      SessionsParams: {
        properties: { limit: { format: "uint32", minimum: 0, type: ["integer", "null"] } },
        type: "object",
      },
      SessionsResult: {
        properties: { sessions: { items: { $ref: "#/types/SessionState" }, type: "array" } },
        required: ["sessions"],
        type: "object",
      },
    },
  };
}

test("types.ts renders each IR type, sorted, with nullable, enum and $ref", () => {
  const types = generate(sampleIr(), { source })["types.ts"];
  expect(
    types.startsWith(
      `// @generated by webviews/scripts/acpmux-protocol-codegen.ts from ${source}. Do not edit; rerun the codegen.\n\n`,
    ),
  ).toBe(true);
  expect(types).toContain(`export type RunState = "idle" | "running" | "waiting";`);
  expect(types).toContain("/** A session's run state changed. */\nexport type SessionState = {");
  expect(types).toContain("  state: RunState;");
  expect(types).toContain("  /** Null until the agent names it. */\n  title: (string | null);");
  expect(types).toContain("  limit?: (number | null);");
  expect(types).toContain("  sessions: SessionState[];");
  const order = ["RunState", "SessionState", "SessionsParams", "SessionsResult"].map((name) =>
    types.indexOf(` ${name} `),
  );
  expect(order).toEqual([...order].sort((a, b) => a - b));
});

test("methods.ts maps typed and untyped methods by kind", () => {
  const methods = generate(sampleIr(), { source })["methods.ts"];
  expect(methods).toContain(`import type { SessionState, SessionsParams, SessionsResult } from "./types";`);
  expect(methods).toContain(`  "_acpmux/sessions": { params: SessionsParams; result: SessionsResult };`);
  expect(methods).toContain(`  "initialize": { params: unknown; result: unknown };`);
  expect(methods).toContain(`export interface AcpmuxClientNotifications {\n  "session/cancel": unknown;\n}`);
  expect(methods).toContain(`export interface AcpmuxNotifications {\n  "_acpmux/session_state": SessionState;\n}`);
  expect(methods).toContain(
    `export interface AcpmuxServerRequests {\n  "session/request_permission": { params: unknown; result: unknown };\n}`,
  );
  expect(methods).toContain("export type AcpmuxRequestName = keyof AcpmuxRequests;");
  expect(methods).toContain(`  { name: "_acpmux/sessions", kind: "request", acp: false, typed: true },`);
  expect(methods).toContain(`  { name: "initialize", kind: "request", acp: true, typed: false },`);
  expect(methods).toContain(`  { name: "_acpmux/disconnected", kind: "client_local", acp: false, typed: false },`);
  // client_local methods are listed for tools but are never on the wire maps.
  expect(methods.match(/"_acpmux\/disconnected"/g)?.length).toBe(1);
});

test("output is deterministic, including under reordered type keys", () => {
  const first = generate(sampleIr(), { source });
  const shuffled = sampleIr();
  shuffled.types = Object.fromEntries(Object.entries(shuffled.types as object).reverse());
  expect(generate(sampleIr(), { source })).toEqual(first);
  expect(generate(shuffled, { source })).toEqual(first);
});

test("refuses malformed IR", () => {
  const unknownRef = sampleIr();
  (unknownRef.methods as Array<Record<string, unknown>>)[0].params = { $ref: "#/types/Missing" };
  expect(() => generate(unknownRef, { source })).toThrow(IrError);

  const inline = sampleIr();
  (inline.methods as Array<Record<string, unknown>>)[0].params = { type: "object" };
  expect(() => generate(inline, { source })).toThrow(/must be true or/);

  const noResult = sampleIr();
  delete (noResult.methods as Array<Record<string, unknown>>)[1].result;
  expect(() => generate(noResult, { source })).toThrow(/needs result/);

  const badKind = sampleIr();
  (badKind.methods as Array<Record<string, unknown>>)[0].kind = "push";
  expect(() => generate(badKind, { source })).toThrow(/unknown kind/);
});
