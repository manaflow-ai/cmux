// Generates the typed acpmux method map from the daemon's IR
// (`cmux-tui/crates/acpmux/spec/acpmux-protocol.json`, emitted by `acpmux::protocol::ir`).
// Pure: takes the IR, returns file contents. scripts/acpmux-protocol-codegen.ts writes or checks
// them. Schema compilation is the pane protocol's (src/protocol/codegen/schema.ts), so both
// protocols accept and refuse the same JSON Schema subset.

import { IrError, type JsonSchema } from "./ir";
import { docComment, refName, renderType } from "./schema";

export interface GenerateOptions {
  /** Shown in the header; keep it repo-relative so --check output is stable across checkouts. */
  source: string;
}

export type GeneratedFiles = Record<"types.ts" | "methods.ts", string>;

export const METHOD_KINDS = [
  "request",
  "client_notification",
  "notification",
  "server_request",
  "client_local",
] as const;
export type MethodKind = (typeof METHOD_KINDS)[number];

export interface AcpmuxIrMethod {
  name: string;
  kind: MethodKind;
  acp: boolean;
  params: JsonSchema;
  /** Present only for request and server_request. */
  result?: JsonSchema;
}

export interface AcpmuxIr {
  version: string;
  methods: AcpmuxIrMethod[];
  types: Record<string, JsonSchema>;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isSchema(value: unknown): value is JsonSchema {
  return typeof value === "boolean" || isRecord(value);
}

function hasResult(kind: MethodKind): boolean {
  return kind === "request" || kind === "server_request";
}

/** Checks the IR's top-level shape and returns it typed. Schema keywords are checked by renderType. */
export function parseAcpmuxIr(raw: unknown): AcpmuxIr {
  if (!isRecord(raw)) throw new IrError("IR must be a JSON object");
  if (typeof raw.version !== "string" || !raw.version) throw new IrError("version must be a non-empty string");
  if (!Array.isArray(raw.methods)) throw new IrError("methods must be an array");
  if (!isRecord(raw.types) || !Object.values(raw.types).every(isSchema)) {
    throw new IrError("types must be an object of schemas");
  }
  const seen = new Set<string>();
  const methods = raw.methods.map((entry, index): AcpmuxIrMethod => {
    const where = `methods[${index}]`;
    if (!isRecord(entry)) throw new IrError(`${where} must be an object`);
    const { name, kind, acp, params, result } = entry;
    if (typeof name !== "string" || !name) throw new IrError(`${where}.name must be a non-empty string`);
    if (seen.has(name)) throw new IrError(`method ${name} is declared twice`);
    seen.add(name);
    if (!METHOD_KINDS.includes(kind as MethodKind))
      throw new IrError(`method ${name}: unknown kind ${JSON.stringify(kind)}`);
    const methodKind = kind as MethodKind;
    if (acp !== undefined && acp !== true) throw new IrError(`method ${name}: acp must be true or absent`);
    if (!isSchema(params)) throw new IrError(`method ${name}: params must be a schema`);
    if (hasResult(methodKind) !== (result !== undefined)) {
      throw new IrError(`method ${name}: a ${methodKind} ${hasResult(methodKind) ? "needs" : "has no"} result`);
    }
    if (result !== undefined && !isSchema(result)) throw new IrError(`method ${name}: result must be a schema`);
    return { name, kind: methodKind, acp: acp === true, params, ...(result === undefined ? {} : { result }) };
  });
  return { version: raw.version, methods, types: raw.types as Record<string, JsonSchema> };
}

function header(options: GenerateOptions): string {
  return `// @generated by webviews/scripts/acpmux-protocol-codegen.ts from ${options.source}. Do not edit; rerun the codegen.\n\n`;
}

/** `unknown` for an untyped (`true`) slot, else the referenced type's name. The IR has no inline schemas. */
function slotType(schema: JsonSchema, types: Record<string, JsonSchema>, where: string): string | null {
  if (schema === true) return null;
  if (typeof schema === "object" && typeof schema.$ref === "string" && Object.keys(schema).length === 1) {
    return refName(schema.$ref, types, where);
  }
  throw new IrError(`${where}: must be true or {"$ref": "#/types/<Name>"}`);
}

function sortedTypes(ir: AcpmuxIr): Array<[string, JsonSchema]> {
  return Object.entries(ir.types).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

function generateTypes(ir: AcpmuxIr, options: GenerateOptions): string {
  const blocks = sortedTypes(ir).map(([name, schema]) => {
    const rendered = renderType(schema, ir.types, `types.${name}`);
    const declaration =
      rendered.startsWith("{\n") && !rendered.includes("} &")
        ? `export interface ${name} ${rendered}`
        : `export type ${name} = ${rendered};`;
    return docComment(schema, "") + declaration;
  });
  return `${header(options)}${blocks.length > 0 ? blocks.join("\n\n") : "export {};"}\n`;
}

interface Slots {
  method: AcpmuxIrMethod;
  params: string | null;
  result: string | null;
}

function generateMethods(ir: AcpmuxIr, options: GenerateOptions): string {
  const slots: Slots[] = ir.methods.map((method) => ({
    method,
    params: slotType(method.params, ir.types, `method ${method.name} params`),
    result: method.result === undefined ? null : slotType(method.result, ir.types, `method ${method.name} result`),
  }));
  const used = [...new Set(slots.flatMap((slot) => [slot.params, slot.result]).filter((name) => name !== null))].sort();
  const key = (name: string) => JSON.stringify(name);
  const lines = [header(options).trimEnd(), ""];
  if (used.length > 0) lines.push(`import type { ${used.join(", ")} } from "./types";`, "");

  const map = (title: string, doc: string, kind: MethodKind, member: (slot: Slots) => string) => {
    const rows = slots
      .filter((slot) => slot.method.kind === kind)
      .map((slot) => `  ${key(slot.method.name)}: ${member(slot)};`);
    const body = rows.length > 0 ? [`export interface ${title} {`, ...rows, "}"] : [`export interface ${title} {}`];
    lines.push(`/** ${doc} */`, ...body, "");
  };
  const request = (slot: Slots) => `{ params: ${slot.params ?? "unknown"}; result: ${slot.result ?? "unknown"} }`;
  const params = (slot: Slots) => slot.params ?? "unknown";
  map("AcpmuxRequests", "Client to daemon requests.", "request", request);
  map("AcpmuxClientNotifications", "Client to daemon notifications (no response).", "client_notification", params);
  map("AcpmuxNotifications", "Daemon to client notifications.", "notification", params);
  map("AcpmuxServerRequests", "Daemon to client requests the client answers.", "server_request", request);

  lines.push(
    "export type AcpmuxRequestName = keyof AcpmuxRequests;",
    "export type AcpmuxClientNotificationName = keyof AcpmuxClientNotifications;",
    "export type AcpmuxNotificationName = keyof AcpmuxNotifications;",
    "export type AcpmuxServerRequestName = keyof AcpmuxServerRequests;",
    "",
    `export type AcpmuxMethodKind = ${METHOD_KINDS.map((kind) => JSON.stringify(kind)).join(" | ")};`,
    "",
    "/** Every registered method, in registry order. `typed` is false while params and result are both untyped. */",
    "export const ACPMUX_METHODS: ReadonlyArray<{ name: string; kind: AcpmuxMethodKind; acp: boolean; typed: boolean }> = [",
    ...slots.map(
      (slot) =>
        `  { name: ${key(slot.method.name)}, kind: ${JSON.stringify(slot.method.kind)}, acp: ${slot.method.acp}, typed: ${slot.params !== null || slot.result !== null} },`,
    ),
    "];",
    "",
  );
  return lines.join("\n");
}

export function generate(raw: unknown, options: GenerateOptions): GeneratedFiles {
  const ir = parseAcpmuxIr(raw);
  return { "types.ts": generateTypes(ir, options), "methods.ts": generateMethods(ir, options) };
}
