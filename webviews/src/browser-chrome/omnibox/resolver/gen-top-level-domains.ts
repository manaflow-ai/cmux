// Writes top-level-domains.ts from the IANA list the Swift omnibar bundles
// (CmuxNextBrowser/Resources/TopLevelDomains.txt). Run from webviews/:
//   bun src/browser-chrome/omnibox/resolver/gen-top-level-domains.ts && vp fmt src/browser-chrome/omnibox/resolver
import { readFileSync, writeFileSync } from "node:fs";

export const TLD_SOURCE = new URL(
  "../../../../../Packages/macOS/CmuxNext/Sources/CmuxNextBrowser/Resources/TopLevelDomains.txt",
  import.meta.url,
);

/** The source's version line and its labels, lowercased. */
export function parseTopLevelDomains(contents: string): { version: string; labels: string[] } {
  const lines = contents.split(/\r?\n/);
  const version = (lines.find((line) => line.startsWith("#")) ?? "").replace(/^#\s*/, "");
  const labels = lines
    .filter((line) => !line.startsWith("#"))
    .map((line) => line.trim().toLowerCase())
    .filter(Boolean);
  return { version, labels };
}

function render(version: string, labels: readonly string[]): string {
  const chunks: string[] = [];
  let line = "";
  for (const label of labels) {
    if (line && line.length + label.length + 1 > 96) {
      chunks.push(line);
      line = "";
    }
    line = line ? `${line} ${label}` : label;
  }
  if (line) chunks.push(line);
  return `// Generated by gen-top-level-domains.ts from TopLevelDomains.txt; do not edit.
// The IANA root zone's top-level domains (https://data.iana.org/TLD/tlds-alpha-by-domain.txt).

export const TOP_LEVEL_DOMAINS_VERSION = ${JSON.stringify(version)};

const LABELS = [
${chunks.map((chunk) => `  ${JSON.stringify(chunk)},`).join("\n")}
];

const ALL: ReadonlySet<string> = new Set(LABELS.join(" ").split(" "));

/** \`label\` (any case, ASCII or punycode) is a delegated top-level domain. */
export function isTopLevelDomain(label: string): boolean {
  return ALL.has(label.toLowerCase());
}

export function topLevelDomains(): ReadonlySet<string> {
  return ALL;
}
`;
}

if (import.meta.main) {
  const { version, labels } = parseTopLevelDomains(readFileSync(TLD_SOURCE, "utf8"));
  writeFileSync(new URL("./top-level-domains.ts", import.meta.url), render(version, labels));
}
