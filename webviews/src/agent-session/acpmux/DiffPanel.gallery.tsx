const changed = (path: string, before: string | undefined, after: string | undefined): TurnFile => {
  const lines = diffHunks(diffLines(before, after));
  const additions = lines.reduce((count, hunk) => count + hunk.lines.filter((line) => line.type === "add").length, 0);
  const deletions = lines.reduce((count, hunk) => count + hunk.lines.filter((line) => line.type === "del").length, 0);
  return {
    path,
    displayPath: path,
    edits: [{ toolId: `gallery-${path}`, hunks: lines, numbered: true }],
    additions,
    deletions,
    created: before === undefined,
    deleted: after === undefined,
  };
};

