import { afterEach, expect, jest, test } from "bun:test";
import { BridgePageClient, type ReplyHandler } from "../shared/pageClient";
import { CloudStore, CLOUD_RESTART_MIN_MS } from "./store";

// Exercise the real bridge, not a mock's transport spelling. Includes every code emitted by
// pageClient.ts and native PageError/PageProviders, plus forwarded owner errors.
const cases = [
  ["cmux.protocol.closed", "disconnected"],
  ["cmux.protocol.transport", "disconnected"],
  ["cmux.protocol.timeout", "disconnected"],
  ["cmux.protocol.unavailable", "disconnected"],
  ["cmux.op.cancelled", "failed"],
  ["cmux.page.cancelled", "failed"],
  ["cmux.page.not_parked", "failed"],
  ["cmux.page.failed", "failed"],
  ["cmux.protocol.error", "failed"],
  ["cmux.protocol.invalid_result", "failed"],
  ["cmux.protocol.unknown_op", "failed"],
  ["cmux.protocol.invalid_params", "failed"],
  ["cmux.protocol.bad_message", "failed"],
  ["cmux.daemon.failed", "failed"],
  ["cmux.policy.turned_off", "failed"],
  ["cmux.cloud.upstream_error", "failed"],
  ["cmux.cloud.auth_required", "failed"],
  ["cmux.owner.new_error", "failed"],
] as const;

const settle = async () => {
  for (let i = 0; i < 20; i++) await Promise.resolve();
};
afterEach(() => jest.useRealTimers());

for (const [code, connection] of cases) {
  for (const retryable of [undefined, false, true]) {
    test(`auth after a closed link: ${code}, retryable=${retryable}, becomes ${connection}`, async () => {
      jest.useFakeTimers();
      let reads = 0;
      const bridge = new BridgePageClient(
        {
          async postMessage(body) {
            const { id, t } = body as { id: number; t: string };
            // Only auth reads count: the account stream's subscribe (a `sub`) gets no sub id and is dropped.
            if (t !== "call") return { t: "ok", id, value: {} };
            reads += 1;
            if (reads === 1) throw new Error("daemon restarted");
            if (reads === 2) return { t: "err", id, code, message: "auth refused", retryable };
            return { t: "ok", id, value: { signedIn: false } };
          },
        },
        {},
      );
      const store = new CloudStore(bridge);
      const stop = store.subscribe(() => undefined);
      try {
        await settle();
        expect(store.getSnapshot()).toMatchObject({
          connection: "disconnected",
          errorCode: "cmux.protocol.closed",
        });
        jest.advanceTimersByTime(CLOUD_RESTART_MIN_MS);
        await settle();
        expect(reads).toBe(2);
        expect(store.getSnapshot()).toMatchObject({ connection, loading: false, errorCode: code });
        expect(store.getSnapshot().auth).toBeUndefined();
        expect(store.canRetry).toBe(true);
        jest.advanceTimersByTime(CLOUD_RESTART_MIN_MS * 2);
        await settle();
        if (connection === "failed") {
          expect(reads).toBe(2);
          await store.retry();
        }
        expect(reads).toBe(3);
        expect(store.getSnapshot()).toMatchObject({
          connection: "connected",
          loading: false,
          auth: { signedIn: false },
        });
        expect(store.getSnapshot().error).toBeUndefined();
        expect(store.getSnapshot().errorCode).toBeUndefined();
      } finally {
        stop();
      }
    });
  }
}

// These are generated by the client itself, before Cloud can see a host error envelope.
for (const [name, reply, code, connection] of [
  [
    "rejected post",
    async () => {
      throw new Error("closed");
    },
    "cmux.protocol.closed",
    "disconnected",
  ],
  ["malformed reply", async () => null, "cmux.protocol.invalid_result", "failed"],
  ["error without code", async () => ({ t: "err" }), "cmux.protocol.error", "failed"],
] as const) {
  test(`bridge-generated ${name} becomes ${connection}`, async () => {
    jest.useFakeTimers();
    const handler: ReplyHandler = { postMessage: reply };
    const store = new CloudStore(new BridgePageClient(handler, {}));
    const stop = store.subscribe(() => undefined);
    try {
      await settle();
      expect(store.getSnapshot()).toMatchObject({ connection, loading: false, errorCode: code });
    } finally {
      stop();
    }
  });
}
