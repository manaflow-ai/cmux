// Writes the omnibar's top-level domain table (src/browser-chrome/omnibox/resolver/
// top-level-domains.generated.ts) from the IANA list the Swift omnibar bundles
// (CmuxNextBrowser/Resources/TopLevelDomains.txt). Build output, never in git: gen-strings.mjs
// runs it on every run (install, the page and bundle builds, the gallery).
//   node scripts/pages/gen-top-level-domains.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webviews = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const repo = path.dirname(webviews);
export const TLD_SOURCE = path.join(repo, "Packages/macOS/CmuxNext/Sources/CmuxNextBrowser/Resources/TopLevelDomains.txt");
const GENERATED = path.join(webviews, "src/browser-chrome/omnibox/resolver/top-level-domains.generated.ts");

/** The source's version line and its labels, lowercased. */
export function parseTopLevelDomains(contents) {
  const lines = contents.split(/\r?\n/);
  const version = (lines.find((line) => line.startsWith("#")) ?? "").replace(/^#\s*/, "");
  const labels = lines
    .filter((line) => !line.startsWith("#"))
    .map((line) => line.trim().toLowerCase())
    .filter(Boolean);
  return { version, labels };
}

function render({ version, labels }) {
  const chunks = [];
  let line = "";
  for (const label of labels) {
    if (line && line.length + label.length + 1 > 96) {
      chunks.push(line);
      line = "";
    }
    line = line ? `${line} ${label}` : label;
  }
  if (line) chunks.push(line);
  return `// GENERATED by webviews/scripts/pages/gen-top-level-domains.mjs from TopLevelDomains.txt; do not edit.
// The IANA root zone's top-level domains (https://data.iana.org/TLD/tlds-alpha-by-domain.txt).

export const TOP_LEVEL_DOMAINS_VERSION = ${JSON.stringify(version)};

const LABELS = [
${chunks.map((chunk) => `  ${JSON.stringify(chunk)},`).join("\n")}
];

const ALL: ReadonlySet<string> = new Set(LABELS.join(" ").split(" "));

/** \`label\` (any case, ASCII or punycode) is a delegated top-level domain. */
export function isTopLevelDomain(label: string): boolean {
  return ALL.has(label.toLowerCase());
}

export function topLevelDomains(): ReadonlySet<string> {
  return ALL;
}
`;
}

export function writeTopLevelDomains({ check = false, log = console.error } = {}) {
  const next = render(parseTopLevelDomains(fs.readFileSync(TLD_SOURCE, "utf8")));
  const current = fs.existsSync(GENERATED) ? fs.readFileSync(GENERATED, "utf8") : null;
  if (check) {
    if (current === next) return 0;
    log(`${path.relative(repo, GENERATED)} is stale or missing: run node webviews/scripts/pages/gen-top-level-domains.mjs`);
    return 1;
  }
  if (current !== next) fs.writeFileSync(GENERATED, next);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exit(writeTopLevelDomains({ check: process.argv.includes("--check") }));
}
