// The one design scale (spacing, controls, icons, radii, glass, elevation and the colour roles) and the
// Tailwind theme every Tailwind entry imports, from schemas/design-scale/design-scale.json with
// schemas/type-scale and schemas/motion-scale. It writes:
//
// - the design-scale block of src/pages/shared/desktop.css (--ds-*, --elevation-*, --ds-color-*), in git;
// - src/ui/theme.generated.css: Tailwind 4 `@theme inline` naming those variables, so p-3, rounded-md,
//   text-body, bg-hover, shadow-elevation-2 and duration-quick resolve to our tokens;
// - src/ui/designTokens.generated.ts: the same list for the gallery's token sheet.
//
// The last two are build output, ignored by git like the pages' strings tables: every run of
// gen-strings.mjs (install, the webview and bundle builds, the gallery) writes them, and
// test/preload.ts writes them before any test reads them.
//
//   node scripts/pages/gen-design-scale.mjs           # write all three
//   node scripts/pages/gen-design-scale.mjs --check   # exit 1 when desktop.css's block drifted
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const SOURCE = "schemas/design-scale/design-scale.json";
const TYPE_SOURCE = "schemas/type-scale/type-scale.json";
const MOTION_SOURCE = "schemas/motion-scale/motion-scale.json";
export const CSS_FILE = "webviews/src/pages/shared/desktop.css";
export const THEME_FILE = "webviews/src/ui/theme.generated.css";
export const TS_FILE = "webviews/src/ui/designTokens.generated.ts";
const BEGIN = `/* design-scale:begin. GENERATED by webviews/scripts/pages/gen-design-scale.mjs from ${SOURCE}; do not edit. */`;
const END = "/* design-scale:end */";
// The type scale's own aliases (gen-type-scale.py): menu rows and composer controls, reading content.
const TYPE_ALIASES = ["control", "content"];

const read = (file) => JSON.parse(fs.readFileSync(path.join(repo, file), "utf8"));

function assert(condition, message) {
  if (!condition) throw new Error(`gen-design-scale: ${message}`);
}

function load() {
  const data = read(SOURCE);
  for (const step of data.spacing.steps) assert(step.px % 4 === 0, `spacing ${step.name} is off the 4 grid`);
  for (const group of ["controls", "icons", "radii"]) {
    const sizes = data[group].map((entry) => entry.px);
    const sorted = [...new Set(sizes)].sort((a, b) => a - b);
    assert(sizes.join() === sorted.join(), `${group} run small to large, one size each`);
  }
  assert(data.icons.map((icon) => icon.px).join() === "12,14,16,20", "grid.md's icon scale is 12, 14, 16, 20");
  for (const level of data.glass)
    assert(level.tint > 0 && level.tint < 90, `glass ${level.name} is never opaque (surface-roles nearOpaque 0.9)`);
  assert(data.elevation.length === 2, "exactly two shadows");
  for (const color of data.colors)
    assert(color.var.startsWith("--cmux-") && !color.var.includes("#"), `colour ${color.name} names a host variable`);
  return { data, type: read(TYPE_SOURCE), motion: read(MOTION_SOURCE) };
}

const px = (value) => `${value}px`;
const glassVars = (level) => ({
  tint: [`--ds-glass-${level.name}-tint`, `${level.tint}%`],
  blur: [`--ds-glass-${level.name}-${level.blurName ?? "blur"}`, level.blur],
});
const colorValue = (color) =>
  `var(${color.var}, ${color.app ? `var(${color.app}, ${color.fallback})` : color.fallback})`;
const shadow = (entry, mode) => `${entry.geometry} color-mix(in srgb, black ${entry[mode]}%, transparent)`;

function cssBlock(data) {
  const out = [BEGIN, ":root {"];
  for (const step of data.spacing.steps) out.push(`  --ds-space-${step.name}: ${px(step.px)};`);
  for (const size of data.spacing.layout) out.push(`  --ds-space-${size}: ${px(size)}; /* layout gap */`);
  for (const control of data.controls)
    out.push(`  --ds-control-${control.name}: ${px(control.px)}; /* ${control.for} */`);
  for (const icon of data.icons) out.push(`  --ds-icon-${icon.name}: ${px(icon.px)}; /* ${icon.for} */`);
  for (const radius of data.radii) out.push(`  --ds-radius-${radius.name}: ${px(radius.px)}; /* ${radius.for} */`);
  for (const radius of data.namedRadii) {
    const note = radius.for ? ` /* ${radius.for} */` : "";
    out.push(`  --ds-radius-${radius.name}: ${radius.var ?? px(radius.px)};${note}`);
  }
  for (const level of data.glass) {
    const { tint, blur } = glassVars(level);
    out.push(`  /* glass ${level.name}: ${level.for} */`, `  ${tint[0]}: ${tint[1]};`, `  ${blur[0]}: ${blur[1]};`);
  }
  out.push("  --ds-glass-edge: var(--cmux-hairline);");
  for (const entry of data.elevation)
    out.push(`  --elevation-${entry.name}: ${shadow(entry, "light")}; /* ${entry.for} */`);
  for (const color of data.colors) out.push(`  --ds-color-${color.name}: ${colorValue(color)}; /* ${color.for} */`);
  out.push("}");
  const dark = data.elevation.map((entry) => `    --elevation-${entry.name}: ${shadow(entry, "dark")};`);
  out.push("@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', ...dark, "  }", "}");
  out.push(':root[data-theme="dark"] {', ...dark.map((line) => line.slice(2)), "}", END);
  return out.join("\n");
}

function css(current, data) {
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  assert(start >= 0 && end > start, `${CSS_FILE} has no design-scale block`);
  return current.slice(0, start) + cssBlock(data) + current.slice(end + END.length);
}

function theme(data, type, motion) {
  const out = [
    `/* GENERATED by webviews/scripts/pages/gen-design-scale.mjs from ${SOURCE}, ${TYPE_SOURCE} and ${MOTION_SOURCE}; do not edit.`,
    "   The one Tailwind theme: every Tailwind entry imports it before its own @theme, so a surface's",
    "   own names (the agent pane's text-fg, Settings' border-edge) still win where they differ. Each",
    "   value names a token of pages/shared/desktop.css (loaded first everywhere), never a literal, so",
    "   light, dark and the terminal theme reach the utilities through the variables. */",
    "@theme inline {",
    "  /* p-1 is 4px, p-3 12px, gap-6 24px: the grid base, which follows the interface scale. */",
    `  --spacing: ${data.spacing.unit};`,
  ];
  for (const control of data.controls)
    out.push(`  --spacing-control-${control.name}: var(--ds-control-${control.name});`);
  for (const icon of data.icons) out.push(`  --spacing-icon-${icon.name}: var(--ds-icon-${icon.name});`);
  for (const radius of [...data.radii, ...data.namedRadii])
    out.push(`  --radius-${radius.name}: var(--ds-radius-${radius.name});`);
  for (const step of [...type.steps.map((entry) => entry.name), ...TYPE_ALIASES]) {
    out.push(
      `  --text-${step}: var(--text-${step});`,
      `  --text-${step}--line-height: var(--text-${step}--line-height);`,
    );
    if (step !== "content") out.push(`  --text-${step}--letter-spacing: var(--text-${step}--letter-spacing);`);
  }
  for (const weight of type.weights) out.push(`  --font-weight-${weight.name}: var(--weight-${weight.name});`);
  out.push("  --font-ui: var(--font-ui);");
  for (const color of data.colors) out.push(`  --color-${color.name}: var(--ds-color-${color.name});`);
  for (const entry of data.elevation) out.push(`  --shadow-elevation-${entry.name}: var(--elevation-${entry.name});`);
  for (const step of motion.steps) out.push(`  --transition-duration-${step.name}: var(--cmux-motion-${step.name});`);
  out.push("  --ease-standard: var(--cmux-ease-out);", "}");
  return `${out.join("\n")}\n`;
}

function ts(data, type, motion) {
  const rows = (list) => list.map((row) => `  ${JSON.stringify(row)},`).join("\n");
  const sections = [
    [
      "SPACING",
      "Spacing: Tailwind's unit is the grid base, so `p-N` is N x 4 px.",
      [
        ...data.spacing.steps.map((step) => ({ name: step.name, variable: `--ds-space-${step.name}`, px: step.px })),
        ...data.spacing.layout.map((size) => ({ name: String(size), variable: `--ds-space-${size}`, px: size })),
      ],
    ],
    [
      "CONTROLS",
      "Control heights.",
      data.controls.map((c) => ({ name: c.name, variable: `--ds-control-${c.name}`, px: c.px, for: c.for })),
    ],
    [
      "ICONS",
      "The icon scale (grid.md): 12, 14, 16, 20.",
      data.icons.map((i) => ({ name: i.name, variable: `--ds-icon-${i.name}`, px: i.px, for: i.for })),
    ],
    [
      "RADII",
      "Corner radii.",
      [...data.radii, ...data.namedRadii].map((r) => ({
        name: r.name,
        variable: `--ds-radius-${r.name}`,
        px: r.px ?? null,
        for: r.for ?? "",
      })),
    ],
    [
      "GLASS",
      "Glass levels: the surface's tint percentage and the backdrop filter.",
      data.glass.map((level) => {
        const { tint, blur } = glassVars(level);
        return {
          name: level.name,
          tint: tint[0],
          blur: blur[0],
          tintPercent: level.tint,
          filter: level.blur,
          for: level.for,
        };
      }),
    ],
    [
      "ELEVATION",
      "The two shadows.",
      data.elevation.map((e) => ({ name: e.name, variable: `--elevation-${e.name}`, for: e.for })),
    ],
    [
      "COLORS",
      "Colour roles, derived from the active terminal theme by the host.",
      data.colors.map((c) => ({ name: c.name, variable: `--ds-color-${c.name}`, value: colorValue(c), for: c.for })),
    ],
    [
      "TEXT",
      "The type scale (schemas/type-scale).",
      type.steps.map((s) => ({
        name: s.name,
        variable: `--text-${s.name}`,
        px: s.size,
        lineHeight: s.lineHeight,
        for: s.for,
      })),
    ],
    [
      "MOTION",
      "The motion scale (schemas/motion-scale).",
      motion.steps.map((s) => ({ name: s.name, variable: `--cmux-motion-${s.name}`, ms: s.ms, for: s.for })),
    ],
  ];
  const body = sections
    .map(([name, doc, list]) => `/** ${doc} */\nexport const ${name} = [\n${rows(list)}\n] as const;`)
    .join("\n\n");
  return (
    `// GENERATED by webviews/scripts/pages/gen-design-scale.mjs from ${SOURCE},\n// ${TYPE_SOURCE} and ${MOTION_SOURCE}. Do not edit; edit the JSON.\n\n${body}\n\n` +
    '/** The one ease-out every arrival uses (the Tailwind ease). */\nexport const EASE_STANDARD = "var(--cmux-ease-out)";\n'
  );
}

/** Writes the three copies. With `check`, writes the two build outputs only and returns true when
 * desktop.css's block (the copy in git) differs from the schemas. */
export function writeDesignScale({ check = false, log = console.log } = {}) {
  const { data, type, motion } = load();
  const cssPath = path.join(repo, CSS_FILE);
  const current = fs.readFileSync(cssPath, "utf8");
  const wanted = css(current, data);
  let drifted = false;
  if (wanted !== current) {
    if (check) {
      drifted = true;
      log(`design scale drifted from ${SOURCE} in ${CSS_FILE}: run node webviews/scripts/pages/gen-design-scale.mjs`);
    } else {
      fs.writeFileSync(cssPath, wanted);
      log(`wrote ${CSS_FILE}`);
    }
  }
  for (const [file, text] of [
    [THEME_FILE, theme(data, type, motion)],
    [TS_FILE, ts(data, type, motion)],
  ]) {
    const full = path.join(repo, file);
    if (fs.existsSync(full) && fs.readFileSync(full, "utf8") === text) continue;
    fs.writeFileSync(full, text);
  }
  return drifted;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exit(writeDesignScale({ check: process.argv.includes("--check") }) ? 1 : 0);
}
