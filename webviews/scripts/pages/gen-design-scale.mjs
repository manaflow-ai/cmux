// The one design scale (spacing, controls, icons, radii, glass, elevation and the colour roles) and the
// Tailwind theme every Tailwind entry imports, from schemas/design-scale/design-scale.json with
// schemas/type-scale and schemas/motion-scale. It writes:
//
// - the design-scale block of src/pages/shared/desktop.css (--ds-*, --elevation-*, --ds-color-*), in git;
// - src/ui/theme.generated.css: Tailwind 4 `@theme inline` naming those variables, so p-3, rounded-md,
//   text-body, bg-hover, shadow-elevation-2 and duration-quick resolve to our tokens;
// - src/ui/designTokens.generated.ts: the same list for the gallery's token sheet.
//
// The design-scale block also carries tier 2, the roles (schemas/design-roles: --role-*), each field
// an expression over tier 1 written as calc() over the --ds-* variables.
//
// The last two are build output, ignored by git like the pages' strings tables: every run of
// gen-strings.mjs (install, the webview and bundle builds, the gallery) writes them, and
// test/preload.ts writes them before any test reads them.
//
//   node scripts/pages/gen-design-scale.mjs           # write all three
//   node scripts/pages/gen-design-scale.mjs --check   # exit 1 when desktop.css's block drifted
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const SOURCE = "schemas/design-scale/design-scale.json";
const TYPE_SOURCE = "schemas/type-scale/type-scale.json";
const MOTION_SOURCE = "schemas/motion-scale/motion-scale.json";
const ROLES_SOURCE = "schemas/design-roles/design-roles.json";
export const CSS_FILE = "webviews/src/pages/shared/desktop.css";
export const THEME_FILE = "webviews/src/ui/theme.generated.css";
export const TS_FILE = "webviews/src/ui/designTokens.generated.ts";
const BEGIN = `/* design-scale:begin. GENERATED by webviews/scripts/pages/gen-design-scale.mjs from ${SOURCE}; do not edit. */`;
const END = "/* design-scale:end */";
// The type scale's own aliases (gen-type-scale.py): menu rows and composer controls, reading content.
const TYPE_ALIASES = ["control", "content"];

const read = (file) => JSON.parse(fs.readFileSync(path.join(repo, file), "utf8"));

function assert(condition, message) {
  if (!condition) throw new Error(`gen-design-scale: ${message}`);
}

function load() {
  const data = read(SOURCE);
  for (const step of data.spacing.steps) assert(step.px % 4 === 0, `spacing ${step.name} is off the 4 grid`);
  for (const group of ["controls", "icons", "radii"]) {
    const sizes = data[group].map((entry) => entry.px);
    const sorted = [...new Set(sizes)].sort((a, b) => a - b);
    assert(sizes.join() === sorted.join(), `${group} run small to large, one size each`);
  }
  assert(data.icons.map((icon) => icon.px).join() === "12,14,16,20", "grid.md's icon scale is 12, 14, 16, 20");
  for (const level of data.glass) {
    assert(level.tint > 0 && level.tint < 90, `glass ${level.name} is never opaque (surface-roles nearOpaque 0.9)`);
    assert(
      level.darkTint === undefined || (level.darkTint > 0 && level.darkTint <= level.tint),
      `glass ${level.name}'s dark tint is translucent and no denser than its light one (dark glass reads denser)`,
    );
    assert(
      level.artTint === undefined || (level.artTint > 0 && level.artTint < (level.darkTint ?? level.tint)),
      `glass ${level.name}'s artTint is clearer than its tint`,
    );
    assert(
      level.veil === undefined || (level.veil > 0 && level.veil < (level.darkTint ?? level.tint)),
      `glass ${level.name}'s veil on the App's glass is clearer than its own tint`,
    );
    assert(["level", "mode"].includes(level.kind), `glass ${level.name} is a level or a mode`);
    assert(GLASS_FILTER.test(level.blur), `glass ${level.name}'s blur is blur(<px>) saturate(<n>)`);
    if (level.kind === "level")
      assert(
        Number(level.blur.match(GLASS_FILTER)[2]) === data.glassSaturation.value,
        `glass ${level.name} frosts at the one saturation, ${data.glassSaturation.value} (design/glass-system.md)`,
      );
  }
  assert(
    data.glassContent.darkTint <= data.glassContent.tint && data.glassContent.tint < 90,
    "the content surface is near-solid, never opaque, and no denser in dark",
  );
  assert(data.glassUnderlay.value > 0 && data.glassUnderlay.value <= 50, "the see-through underlay stays light");
  {
    // A menu covers the same share of the text under it in light and dark (design/glass-system.md,
    // rule 6): the dark underlay makes up for the menu's clearer dark tint, and no more.
    const menu = data.glass.find((level) => level.name === "menu");
    const cover = (tint, underlay) => tint + ((100 - tint) * underlay) / 100;
    const light = cover(menu.tint, data.glassUnderlay.value);
    const dark = cover(menu.darkTint ?? menu.tint, data.glassUnderlay.darkValue);
    assert(
      data.glassUnderlay.darkValue >= data.glassUnderlay.value && Math.abs(dark - light) < 1 && dark < 90,
      `the menu covers the same share of the text under it in dark (${dark.toFixed(1)}%) as in light (${light.toFixed(1)}%), never opaque`,
    );
  }
  assert(
    data.glassInk.secondary >= 50 &&
      data.glassInk.darkSecondary >= data.glassInk.secondary &&
      data.glassInk.darkSecondary < 100,
    "the secondary ink on glass stays a step under the text, and no fainter in dark (dark glass passes more of a white page)",
  );
  assert(
    data.glassInk.status > 0 &&
      data.glassInk.status <= 100 &&
      data.glassInk.darkStatus >= 40 &&
      data.glassInk.darkStatus <= data.glassInk.status,
    "a status word on glass keeps most of its hue, and no more hue in dark (dark glass passes more of a white page)",
  );
  const levels = data.glass.filter((level) => level.kind === "level").map((level) => level.name);
  assert(
    levels.join() === "chrome,popover,menu,chip",
    "the glass levels are chrome, popover, menu and chip (design/glass.md)",
  );
  const material = data.glassMaterial;
  for (const key of ["neutralLight", "neutralDark", "rimLit", "rimShade"])
    assert(material[key] >= 0 && material[key] <= 1, `glassMaterial.${key} is a gray level from 0 to 1`);
  const transient = data.transientMaterial;
  const menu = data.glass.find((level) => level.name === "menu");
  assert(
    menu.veil === transient.hostVeil * 100 &&
      menu.tint === transient.webTint &&
      (menu.darkTint ?? menu.tint) === transient.webTintDark,
    "menu and transient material stay in sync",
  );
  for (const key of ["darkVeilAlpha", "lightVeilAlpha", "hostVeil"])
    assert(transient[key] > 0 && transient[key] < 0.9, `transientMaterial.${key} stays translucent`);
  assert(transient.webTint > 0 && transient.webTint < 90, "transient web tint stays translucent");
  assert(transient.webSaturation === data.glassSaturation.value, "the transient material frosts at the one saturation");
  // Native parity belongs to check-surface-roles.py. Web-only sparse checkouts
  // generate this scale from schemas without loading platform source files.
  assert(data.elevation.length === 2, "exactly two shadows");
  const surfaces = data.surfaces.levels.map((level) => level.name);
  assert(
    surfaces.join() === "card,inset,hover,control",
    "the surface levels are card, inset, hover and control (design/chat-surfaces.md)",
  );
  for (const level of data.surfaces.levels)
    for (const key of ["fill", "line"])
      if (level[key] !== undefined)
        assert(
          level[key] > 0 && level[key] < 30,
          `surface ${level.name}.${key} is a small share of the ink, never opaque`,
        );
  for (const color of data.colors)
    assert(color.var.startsWith("--cmux-") && !color.var.includes("#"), `colour ${color.name} names a host variable`);
  const type = read(TYPE_SOURCE);
  return { data, type, motion: read(MOTION_SOURCE), roles: loadRoles(data, type) };
}

// Tier 2 (schemas/design-roles): each role's fields, `like` another role's with its own on top
// (null drops one), each an expression over tier 1 resolved twice: to pixels at the default scale,
// for the asserts and the token sheet, and to CSS over the --ds-* variables, so whatever moves a
// tier-1 variable (Settings' page density, the host's button corner) moves the role with it.
const ROLE_FIELDS = ["height", "inset", "minHeight", "radius"];
const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const roleVar = (role, field) => `--role-${role}-${kebab(field)}`;

function loadRoles(data, type) {
  const source = read(ROLES_SOURCE).roles;
  const byName = new Map();
  for (const role of source) {
    assert(!byName.has(role.name), `role ${role.name} is named once`);
    const parent = role.like === undefined ? {} : byName.get(role.like)?.fields;
    assert(parent, `role ${role.name} is like ${role.like}, a role above it`);
    const fields = { ...parent };
    for (const field of ROLE_FIELDS) if (field in role) fields[field] = role[field];
    for (const field of Object.keys(fields)) if (fields[field] === null) delete fields[field];
    byName.set(role.name, { name: role.name, for: role.for, like: role.like, fields });
  }
  const tier1 = (ref) => {
    const [group, name, part] = ref.split(".");
    const found = (list, key = "name") => list.find((entry) => String(entry[key]) === name);
    if (group === "space" && found(data.spacing.steps))
      return { css: `var(--ds-space-${name})`, px: found(data.spacing.steps).px };
    if (group === "control" && found(data.controls))
      return { css: `var(--ds-control-${name})`, px: found(data.controls).px };
    if (group === "radius") {
      const radius = found([...data.radii, ...data.namedRadii]);
      // A radius the host sets (radius.control) resolves to its fallback.
      const px = radius?.px ?? Number(radius?.var?.match(/,\s*([\d.]+)px\)$/)?.[1] ?? Number.NaN);
      if (radius && Number.isFinite(px)) return { css: `var(--ds-radius-${name})`, px };
    }
    if (group === "text" && part === "lineHeight" && found(type.steps))
      return { css: `var(--text-${name}--line-height)`, px: found(type.steps).lineHeight };
    return null;
  };
  const resolved = new Map();
  const resolve = (roleName, field, stack = []) => {
    const key = `${roleName}.${field}`;
    if (resolved.has(key)) return resolved.get(key);
    assert(!stack.includes(key), `role field ${key} refers to itself through ${stack.join(", ")}`);
    const role = byName.get(roleName);
    const text = role?.fields[field];
    assert(typeof text === "string", `role ${roleName} has no ${field}`);
    const ref = (name) => {
      const [head, tail] = name.split(".");
      const owner = head === "self" ? roleName : head;
      if (byName.has(owner) && ROLE_FIELDS.includes(tail) && name.split(".").length === 2) {
        resolve(owner, tail, [...stack, key]);
        return { css: `var(${roleVar(owner, tail)})`, px: resolved.get(`${owner}.${tail}`).px, length: true };
      }
      const value = tier1(name);
      assert(value, `role ${key} names ${name}, which is neither a role field nor a tier-1 step`);
      return { ...value, length: true };
    };
    const value = parseRoleExpression(text, ref, key);
    assert(value.length, `role ${key} is a length`);
    const css = /^(var|min|max|round)\(/.test(value.css) && value.top ? value.css : `calc(${value.css})`;
    resolved.set(key, { css, px: value.px });
    return resolved.get(key);
  };
  const roles = [...byName.values()].map((role) => ({
    ...role,
    values: Object.keys(role.fields)
      .sort((a, b) => ROLE_FIELDS.indexOf(a) - ROLE_FIELDS.indexOf(b))
      .map((field) => ({ field, variable: roleVar(role.name, field), ...resolve(role.name, field) })),
  }));
  for (const role of roles) {
    const value = (field) => role.values.find((entry) => entry.field === field)?.px;
    for (const field of ["radius", "inset"])
      if (value(field) !== undefined)
        assert(Number.isInteger(value(field) / 4), `role ${role.name}'s ${field} is on the 4 grid`);
    if (value("radius") !== undefined && value("minHeight") !== undefined)
      assert(
        value("radius") * 2 < value("minHeight"),
        `role ${role.name} is never a capsule: its corner is under half its shortest height`,
      );
  }
  return roles;
}

// A role expression: numbers, tier-1 and role names, + - * /, parentheses, min(), max() and floor4().
function parseRoleExpression(text, ref, where) {
  const tokens = text.match(/\d+(?:\.\d+)?|[A-Za-z_][\w.]*|[-+*/(),]|\S/g) ?? [];
  let at = 0;
  const peek = () => tokens[at];
  const take = (want) => {
    const token = tokens[at++];
    assert(want === undefined || token === want, `role ${where}: expected ${want} in "${text}"`);
    return token;
  };
  // Each value: its CSS (bare, valid inside calc() or a math function), its pixels, and whether it is
  // a length (a bare number scales one) or a single term (needs no parentheses as an operand).
  const binary = (a, op, b) => {
    if (op === "+" || op === "-") assert(a.length && b.length, `role ${where}: ${op} joins two lengths in "${text}"`);
    if (op === "*") assert(!(a.length && b.length), `role ${where}: * scales a length by a number`);
    if (op === "/") assert(!b.length, `role ${where}: / divides by a number`);
    const wrap = (v) => (v.single ? v.css : `(${v.css})`);
    const px = { "+": a.px + b.px, "-": a.px - b.px, "*": a.px * b.px, "/": a.px / b.px }[op];
    return { css: `${wrap(a)} ${op} ${wrap(b)}`, px, length: a.length || b.length, single: false };
  };
  const factor = () => {
    const token = take();
    if (token === "(") {
      const inner = sum();
      take(")");
      return { ...inner, css: `(${inner.css})`, single: true };
    }
    if (/^\d/.test(token)) return { css: token, px: Number(token), length: false, single: true };
    if (["min", "max", "floor4"].includes(token)) {
      take("(");
      const args = [sum()];
      while (peek() === ",") {
        take(",");
        args.push(sum());
      }
      take(")");
      assert(
        args.every((arg) => arg.length),
        `role ${where}: ${token}() takes lengths`,
      );
      if (token === "floor4") {
        assert(args.length === 1, `role ${where}: floor4() takes one length`);
        return {
          css: `round(down, ${args[0].css}, 4px)`,
          px: Math.floor(args[0].px / 4) * 4,
          length: true,
          single: true,
          top: true,
        };
      }
      const px = Math[token](...args.map((arg) => arg.px));
      return { css: `${token}(${args.map((arg) => arg.css).join(", ")})`, px, length: true, single: true, top: true };
    }
    assert(/^[A-Za-z_]/.test(token ?? ""), `role ${where}: unexpected "${token}" in "${text}"`);
    return { ...ref(token), single: true, top: true };
  };
  const product = () => {
    let value = factor();
    while (peek() === "*" || peek() === "/") value = binary(value, take(), factor());
    return value;
  };
  const sum = () => {
    let value = product();
    while (peek() === "+" || peek() === "-") value = binary(value, take(), product());
    return value;
  };
  const value = sum();
  assert(at === tokens.length, `role ${where}: trailing "${tokens.slice(at).join(" ")}" in "${text}"`);
  return value;
}

const px = (value) => `${value}px`;
// A glass level's backdrop filter: the blur radius and the saturation, nothing else.
const GLASS_FILTER = /^blur\(([\d.]+)px\) saturate\(([\d.]+)\)$/;
const glassVars = (level) => ({
  tint: [`--ds-glass-${level.name}-tint`, `${level.tint}%`],
  blur: [`--ds-glass-${level.name}-${level.blurName ?? "blur"}`, level.blur],
  // The radius alone, for a surface that blurs without the level's saturation (the diff's bars).
  radius: [`--ds-glass-${level.name}-radius`, px(Number(level.blur.match(GLASS_FILTER)[1]))],
  artTint: level.artTint === undefined ? null : [`--ds-glass-${level.name}-art-tint`, `${level.artTint}%`],
  // The theme surface laid on the App's own glass under a surface of this level (host glass, and the
  // native GlassMenu's veil): one number for the page and the App.
  veil: level.veil === undefined ? null : [`--ds-glass-${level.name}-veil`, `${level.veil}%`],
});
// A gray level (0 black, 1 white) as an opaque CSS color, 8 bits a channel.
export const gray = (level) => {
  const channel = Math.round(level * 255);
  return `rgb(${channel} ${channel} ${channel})`;
};
// The neutral glass material's tokens (glassMaterial): the overlay surface roles mix these at their
// own opacities (the surface-roles block of ui/glass/glass.css, scripts/cmux-next/check-surface-roles.py).
// They are opaque grays, named --ds-material-* and not --ds-glass-*: check-glass-never-opaque reads a
// --*glass* token as a glass fill, and these are only ever mixed at an opacity.
const materialVars = (material) => [
  ["--ds-material-neutral-light", gray(material.neutralLight), "the neutral veil's gray on the light side"],
  ["--ds-material-neutral-dark", gray(material.neutralDark), "the neutral veil's gray on the dark side"],
  ["--ds-material-rim-lit", gray(material.rimLit), "the lit rim: a top edge, and a dark side's bottom edge"],
  ["--ds-material-rim-shade", gray(material.rimShade), "the shaded rim: a light side's bottom edge"],
];
// A surface level's fill and line: the page's ink over clear at the level's share (design/chat-surfaces.md).
const ink = (percent) => `color-mix(in srgb, var(--ds-surface-ink) ${percent}%, transparent)`;
export const surfaceVars = (level) =>
  [
    level.fill === undefined ? null : [`--ds-surface-${level.name}`, ink(level.fill)],
    level.line === undefined ? null : [`--ds-surface-${level.name}-line`, ink(level.line)],
  ].filter(Boolean);
const colorValue = (color) =>
  `var(${color.var}, ${color.app ? `var(${color.app}, ${color.fallback})` : color.fallback})`;
const shadow = (entry, mode) => `${entry.geometry} color-mix(in srgb, black ${entry[mode]}%, transparent)`;

function rolesBlock(roles) {
  const out = [`/* roles (tier 2), from ${ROLES_SOURCE}: a component reads these, not --ds-* */`, ":root {"];
  for (const role of roles) {
    out.push(`  /* ${role.name}${role.like ? ` (like ${role.like})` : ""}: ${role.for} */`);
    for (const value of role.values) out.push(`  ${value.variable}: ${value.css}; /* ${value.px}px */`);
  }
  out.push("}");
  return out;
}

function cssBlock(data, roles) {
  const out = [BEGIN, ":root {"];
  for (const step of data.spacing.steps) out.push(`  --ds-space-${step.name}: ${px(step.px)};`);
  for (const size of data.spacing.layout) out.push(`  --ds-space-${size}: ${px(size)}; /* layout gap */`);
  for (const control of data.controls)
    out.push(`  --ds-control-${control.name}: ${px(control.px)}; /* ${control.for} */`);
  for (const icon of data.icons) out.push(`  --ds-icon-${icon.name}: ${px(icon.px)}; /* ${icon.for} */`);
  for (const radius of data.radii) out.push(`  --ds-radius-${radius.name}: ${px(radius.px)}; /* ${radius.for} */`);
  for (const radius of data.namedRadii) {
    const note = radius.for ? ` /* ${radius.for} */` : "";
    out.push(`  --ds-radius-${radius.name}: ${radius.var ?? px(radius.px)};${note}`);
  }
  for (const level of data.glass) {
    const { tint, blur, radius, artTint, veil } = glassVars(level);
    out.push(`  /* glass ${level.name} (${level.kind}): ${level.for} */`, `  ${tint[0]}: ${tint[1]};`);
    if (artTint) out.push(`  ${artTint[0]}: ${artTint[1]};`);
    if (veil) out.push(`  ${veil[0]}: ${veil[1]};`);
    out.push(`  ${blur[0]}: ${blur[1]};`);
    if (level.kind === "level") out.push(`  ${radius[0]}: ${radius[1]};`);
  }
  out.push("  --ds-glass-edge: var(--cmux-hairline);");
  out.push(`  /* glass saturation: ${data.glassSaturation.for} */`);
  out.push(`  --ds-glass-saturation: ${data.glassSaturation.value};`);
  out.push(`  /* glass edge: ${data.glassEdge.for} */`);
  out.push(`  --ds-glass-edge-top: ${data.glassEdge.topLight}%;`);
  out.push(`  /* glass content: ${data.glassContent.for} */`);
  out.push(`  --ds-glass-content-tint: ${data.glassContent.tint}%;`);
  out.push(`  /* glass ink: ${data.glassInk.for} */`);
  out.push(`  --ds-glass-ink-secondary: ${data.glassInk.secondary}%;`);
  out.push(`  --ds-glass-ink-status: ${data.glassInk.status}%;`);
  out.push(`  /* glass underlay: ${data.glassUnderlay.for} */`);
  out.push(`  --ds-glass-underlay: ${data.glassUnderlay.value}%;`);
  out.push(`  /* glass material: ${data.glassMaterial.for} */`);
  for (const [name, value, note] of materialVars(data.glassMaterial)) out.push(`  ${name}: ${value}; /* ${note} */`);
  for (const [key, value] of Object.entries(data.transientMaterial)) {
    if (typeof value !== "number") continue;
    const name = key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
    const unit = key.startsWith("webTint") ? "%" : key === "webBlur" ? "px" : "";
    out.push(`  --ds-transient-${name}: ${value}${unit};`);
  }
  for (const entry of data.elevation)
    out.push(`  --elevation-${entry.name}: ${shadow(entry, "light")}; /* ${entry.for} */`);
  for (const color of data.colors) out.push(`  --ds-color-${color.name}: ${colorValue(color)}; /* ${color.for} */`);
  out.push(
    "  /* content surfaces: the page's ink over clear; a page whose ink is another variable sets --ds-surface-ink */",
  );
  out.push("  --ds-surface-ink: var(--ds-color-fg);");
  for (const level of data.surfaces.levels)
    for (const [name, value] of surfaceVars(level)) out.push(`  ${name}: ${value}; /* ${level.for} */`);
  // A control that rests on a level (a filled button, a row in a card) takes its hover and press as a
  // layer over that level (background-image), never in place of it: in place, the host's hover (ink 4
  // to 5%) is quieter than an inset rest (ink 8%), so the pointer would lighten the control.
  for (const [state, fill] of [
    ["hover", "var(--ds-surface-hover)"],
    ["pressed", "var(--ds-color-pressed)"],
  ])
    out.push(`  --ds-surface-${state}-layer: linear-gradient(${fill}, ${fill}); /* ${state} over a filled rest */`);
  out.push("}");
  // appearance.borders none clears every line; Increase Contrast draws them in the ink itself, as the
  // page's other hairlines (desktop.css prefers-contrast).
  const lines = data.surfaces.levels.filter((level) => level.line !== undefined);
  out.push(
    ':root[data-borders="none"] {',
    ...lines.map((level) => `  --ds-surface-${level.name}-line: transparent;`),
    "}",
  );
  out.push(
    "@media (prefers-contrast: more) {",
    '  :root:not([data-borders="none"]) {',
    ...lines.map((level) => `    --ds-surface-${level.name}-line: var(--ds-surface-ink);`),
    "  }",
    "}",
  );
  // Dark: the same geometry a little darker, and each glass level's own dark tint (dark glass reads
  // denser at the same alpha, so it runs a few points clearer; design/glass-system.md, rule 3).
  const dark = [
    ...data.elevation.map((entry) => `    --elevation-${entry.name}: ${shadow(entry, "dark")};`),
    ...data.glass
      .filter((level) => level.darkTint !== undefined && level.darkTint !== level.tint)
      .map((level) => `    ${glassVars(level).tint[0]}: ${level.darkTint}%;`),
    `    --ds-transient-web-tint: ${data.transientMaterial.webTintDark}%;`,
    `    --ds-glass-edge-top: ${data.glassEdge.topDark}%;`,
    `    --ds-glass-content-tint: ${data.glassContent.darkTint}%;`,
    `    --ds-glass-ink-secondary: ${data.glassInk.darkSecondary}%;`,
    `    --ds-glass-ink-status: ${data.glassInk.darkStatus}%;`,
    `    --ds-glass-underlay: ${data.glassUnderlay.darkValue}%;`,
  ];
  out.push("@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', ...dark, "  }", "}");
  out.push(':root[data-theme="dark"] {', ...dark.map((line) => line.slice(2)), "}");
  // Reduce Transparency (the system's or the host's): no level blurs, so a surface that names a level
  // directly, outside .ui-glass, still turns solid with the rest (its own rule gives it the opaque fill).
  const still = data.glass
    .filter((level) => level.kind === "level")
    .map((level) => `  ${glassVars(level).blur[0]}: none;`);
  out.push(
    "@media (prefers-reduced-transparency: reduce) {",
    "  :root {",
    ...still.map((line) => `  ${line}`),
    "  }",
    "}",
  );
  // The host's Reduce Transparency, and Liquid Glass off (appearance.liquidGlass, data-glass="off").
  out.push(':root:is([data-reduce-transparency], [data-glass="off"]) {', ...still, "}");
  out.push(...rolesBlock(roles), END);
  return out.join("\n");
}

function css(current, data, roles) {
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  assert(start >= 0 && end > start, `${CSS_FILE} has no design-scale block`);
  return current.slice(0, start) + cssBlock(data, roles) + current.slice(end + END.length);
}

function theme(data, type, motion) {
  const out = [
    `/* GENERATED by webviews/scripts/pages/gen-design-scale.mjs from ${SOURCE}, ${TYPE_SOURCE} and ${MOTION_SOURCE}; do not edit.`,
    "   The one Tailwind theme: every Tailwind entry imports it before its own @theme, so a surface's",
    "   own names (the agent pane's text-fg, Settings' border-edge) still win where they differ. Each",
    "   value names a token of pages/shared/desktop.css (loaded first everywhere), never a literal, so",
    "   light, dark and the terminal theme reach the utilities through the variables. */",
    "@theme inline {",
    "  /* p-1 is 4px, p-3 12px, gap-6 24px: the grid base, which follows the interface scale. */",
    `  --spacing: ${data.spacing.unit};`,
  ];
  for (const control of data.controls)
    out.push(`  --spacing-control-${control.name}: var(--ds-control-${control.name});`);
  for (const icon of data.icons) out.push(`  --spacing-icon-${icon.name}: var(--ds-icon-${icon.name});`);
  for (const radius of [...data.radii, ...data.namedRadii])
    out.push(`  --radius-${radius.name}: var(--ds-radius-${radius.name});`);
  for (const step of [...type.steps.map((entry) => entry.name), ...TYPE_ALIASES]) {
    out.push(
      `  --text-${step}: var(--text-${step});`,
      `  --text-${step}--line-height: var(--text-${step}--line-height);`,
    );
    if (step !== "content") out.push(`  --text-${step}--letter-spacing: var(--text-${step}--letter-spacing);`);
  }
  for (const weight of type.weights) out.push(`  --font-weight-${weight.name}: var(--weight-${weight.name});`);
  out.push("  --font-ui: var(--font-ui);");
  for (const color of data.colors) out.push(`  --color-${color.name}: var(--ds-color-${color.name});`);
  for (const entry of data.elevation) out.push(`  --shadow-elevation-${entry.name}: var(--elevation-${entry.name});`);
  for (const level of data.surfaces.levels)
    for (const [name] of surfaceVars(level)) out.push(`  --color-${name.slice("--ds-".length)}: var(${name});`);
  for (const step of motion.steps) out.push(`  --transition-duration-${step.name}: var(--cmux-motion-${step.name});`);
  out.push("  --ease-standard: var(--cmux-ease-out);", "}");
  return `${out.join("\n")}\n`;
}

function ts(data, type, motion, roles) {
  const rows = (list) => list.map((row) => `  ${JSON.stringify(row)},`).join("\n");
  const sections = [
    [
      "SPACING",
      "Spacing: Tailwind's unit is the grid base, so `p-N` is N x 4 px.",
      [
        ...data.spacing.steps.map((step) => ({ name: step.name, variable: `--ds-space-${step.name}`, px: step.px })),
        ...data.spacing.layout.map((size) => ({ name: String(size), variable: `--ds-space-${size}`, px: size })),
      ],
    ],
    [
      "CONTROLS",
      "Control heights.",
      data.controls.map((c) => ({ name: c.name, variable: `--ds-control-${c.name}`, px: c.px, for: c.for })),
    ],
    [
      "ICONS",
      "The icon scale (grid.md): 12, 14, 16, 20.",
      data.icons.map((i) => ({ name: i.name, variable: `--ds-icon-${i.name}`, px: i.px, for: i.for })),
    ],
    [
      "RADII",
      "Corner radii.",
      [...data.radii, ...data.namedRadii].map((r) => ({
        name: r.name,
        variable: `--ds-radius-${r.name}`,
        px: r.px ?? null,
        for: r.for ?? "",
      })),
    ],
    [
      "GLASS",
      "Glass levels: the surface's tint percentage and the backdrop filter.",
      data.glass.map((level) => {
        const { tint, blur } = glassVars(level);
        return {
          name: level.name,
          kind: level.kind,
          tint: tint[0],
          blur: blur[0],
          tintPercent: level.tint,
          filter: level.blur,
          for: level.for,
        };
      }),
    ],
    [
      "ELEVATION",
      "The two shadows.",
      data.elevation.map((e) => ({ name: e.name, variable: `--elevation-${e.name}`, for: e.for })),
    ],
    [
      "SURFACES",
      "Content surface levels: the page's ink over clear (design/chat-surfaces.md).",
      data.surfaces.levels.flatMap((level) =>
        surfaceVars(level).map(([variable, value]) => ({
          name: variable.slice("--ds-surface-".length),
          variable,
          value,
          for: level.for,
        })),
      ),
    ],
    [
      "COLORS",
      "Colour roles, derived from the active terminal theme by the host.",
      data.colors.map((c) => ({ name: c.name, variable: `--ds-color-${c.name}`, value: colorValue(c), for: c.for })),
    ],
    [
      "TEXT",
      "The type scale (schemas/type-scale).",
      type.steps.map((s) => ({
        name: s.name,
        variable: `--text-${s.name}`,
        px: s.size,
        lineHeight: s.lineHeight,
        for: s.for,
      })),
    ],
    [
      "ROLES",
      "Roles (tier 2, schemas/design-roles): each field's variable and its pixels at the default scale.",
      roles.flatMap((role) =>
        role.values.map((value) => ({
          role: role.name,
          field: value.field,
          variable: value.variable,
          px: value.px,
          for: role.for,
        })),
      ),
    ],
    [
      "MOTION",
      "The motion scale (schemas/motion-scale).",
      motion.steps.map((s) => ({ name: s.name, variable: `--cmux-motion-${s.name}`, ms: s.ms, for: s.for })),
    ],
  ];
  const body = sections
    .map(([name, doc, list]) => `/** ${doc} */\nexport const ${name} = [\n${rows(list)}\n] as const;`)
    .join("\n\n");
  return (
    `// GENERATED by webviews/scripts/pages/gen-design-scale.mjs from ${SOURCE},\n// ${TYPE_SOURCE}, ${MOTION_SOURCE} and ${ROLES_SOURCE}. Do not edit; edit the JSON.\n\n${body}\n\n` +
    '/** The one ease-out every arrival uses (the Tailwind ease). */\nexport const EASE_STANDARD = "var(--cmux-ease-out)";\n'
  );
}

/** Writes the three copies. With `check`, writes the two build outputs only and returns true when
 * desktop.css's block (the copy in git) differs from the schemas. */
export function writeDesignScale({ check = false, log = console.log } = {}) {
  const { data, type, motion, roles } = load();
  const cssPath = path.join(repo, CSS_FILE);
  const current = fs.readFileSync(cssPath, "utf8");
  const wanted = css(current, data, roles);
  let drifted = false;
  if (wanted !== current) {
    if (check) {
      drifted = true;
      log(`design scale drifted from ${SOURCE} in ${CSS_FILE}: run node webviews/scripts/pages/gen-design-scale.mjs`);
    } else {
      fs.writeFileSync(cssPath, wanted);
      log(`wrote ${CSS_FILE}`);
    }
  }
  for (const [file, text] of [
    [THEME_FILE, theme(data, type, motion)],
    [TS_FILE, ts(data, type, motion, roles)],
  ]) {
    const full = path.join(repo, file);
    if (fs.existsSync(full) && fs.readFileSync(full, "utf8") === text) continue;
    fs.writeFileSync(full, text);
  }
  return drifted;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exit(writeDesignScale({ check: process.argv.includes("--check") }) ? 1 : 0);
}
