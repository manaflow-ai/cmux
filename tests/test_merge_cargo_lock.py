#!/usr/bin/env python3
"""scripts/merge-cargo-lock.py: Cargo.lock merges package-wise, written the way cargo writes it.

Run: python3 -I tests/test_merge_cargo_lock.py
"""
from __future__ import annotations

import importlib.util
import os
import subprocess
import tempfile
import textwrap
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DRIVER = ROOT / "scripts" / "merge-cargo-lock.py"
spec = importlib.util.spec_from_file_location("merge_cargo_lock", DRIVER)
mcl = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mcl)

HEADER = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n"
REG = "registry+https://github.com/rust-lang/crates.io-index"


def pkg(name, version="0.1.0", deps=(), source=None, checksum=None):
    lines = ["", "[[package]]", f'name = "{name}"', f'version = "{version}"']
    if source:
        lines.append(f'source = "{source}"')
    if checksum:
        lines.append(f'checksum = "{checksum}"')
    if deps:
        lines.append("dependencies = [")
        lines += [f' "{d}",' for d in deps]
        lines.append("]")
    return "\n".join(lines) + "\n"


def lock(*pkgs):
    return HEADER + "".join(pkgs)


SERDE = pkg("serde", "1.0.200", source=REG, checksum="aa")
BASE = lock(pkg("app", deps=["cmux-a", "serde"]), pkg("cmux-a", deps=["serde"]), pkg("cmux-z"), SERDE)


class MergeTest(unittest.TestCase):
    def test_two_new_crates_next_to_each_other_both_stay_in_order(self):
        ours = lock(pkg("app", deps=["cmux-a", "cmux-b", "serde"]), pkg("cmux-a", deps=["serde"]), pkg("cmux-b"),
                    pkg("cmux-z"), SERDE)
        theirs = lock(pkg("app", deps=["cmux-a", "cmux-c", "serde"]), pkg("cmux-a", deps=["serde"]), pkg("cmux-c"),
                      pkg("cmux-z"), SERDE)
        want = lock(pkg("app", deps=["cmux-a", "cmux-b", "cmux-c", "serde"]), pkg("cmux-a", deps=["serde"]),
                    pkg("cmux-b"), pkg("cmux-c"), pkg("cmux-z"), SERDE)
        self.assertEqual(mcl.merge_text(BASE, ours, theirs), want)
        self.assertEqual(mcl.merge_text(BASE, theirs, ours), want)

    def test_a_second_version_qualifies_the_other_sides_new_reference(self):
        serde2 = pkg("serde", "2.0.0", source=REG, checksum="bb")
        # Ours adds serde 2 for cmux-z: every serde reference now names its version.
        ours = lock(pkg("app", deps=["cmux-a", "serde 1.0.200"]), pkg("cmux-a", deps=["serde 1.0.200"]),
                    pkg("cmux-z", deps=["serde 2.0.0"]), SERDE, serde2)
        # Theirs adds cmux-b, which depends on the one serde it knows.
        theirs = lock(pkg("app", deps=["cmux-a", "cmux-b", "serde"]), pkg("cmux-a", deps=["serde"]),
                      pkg("cmux-b", deps=["serde"]), pkg("cmux-z"), SERDE)
        want = lock(pkg("app", deps=["cmux-a", "cmux-b", "serde 1.0.200"]), pkg("cmux-a", deps=["serde 1.0.200"]),
                    pkg("cmux-b", deps=["serde 1.0.200"]), pkg("cmux-z", deps=["serde 2.0.0"]), SERDE, serde2)
        self.assertEqual(mcl.merge_text(BASE, ours, theirs), want)

    def test_a_bump_on_one_side_takes_the_other_sides_new_reference_along(self):
        bumped = pkg("serde", "1.0.201", source=REG, checksum="cc")
        ours = lock(pkg("app", deps=["cmux-a", "serde"]), pkg("cmux-a", deps=["serde"]), pkg("cmux-z"), bumped)
        theirs = lock(pkg("app", deps=["cmux-a", "serde"]), pkg("cmux-a", deps=["serde"]), pkg("cmux-z", deps=["serde"]),
                      SERDE)
        want = lock(pkg("app", deps=["cmux-a", "serde"]), pkg("cmux-a", deps=["serde"]), pkg("cmux-z", deps=["serde"]),
                    bumped)
        self.assertEqual(mcl.merge_text(BASE, ours, theirs), want)

    def test_a_package_nothing_reaches_any_more_is_dropped(self):
        log = pkg("log", "0.4.0", source=REG, checksum="dd")
        base = lock(pkg("app", deps=["cmux-a", "serde"]), pkg("cmux-a", deps=["log", "serde"]), pkg("cmux-z"), log,
                    SERDE)
        # Each side drops one of the two references to log.
        ours = lock(pkg("app", deps=["cmux-a", "serde"]), pkg("cmux-a", deps=["serde"]), pkg("cmux-z", deps=["log"]),
                    log, SERDE)
        theirs = base.replace(pkg("cmux-a", deps=["log", "serde"]), pkg("cmux-a", deps=["serde"]))
        theirs = theirs.replace(log, "")
        got = mcl.merge_text(base, ours, theirs)
        self.assertIn('name = "log"', got)  # ours' new cmux-z -> log keeps it, restored from ours
        ours2 = ours.replace(pkg("cmux-z", deps=["log"]), pkg("cmux-z"))
        self.assertNotIn('name = "log"', mcl.merge_text(base, ours2, theirs))

    def test_one_package_changed_both_ways_is_a_conflict(self):
        ours = BASE.replace('checksum = "aa"', 'checksum = "a1"')
        theirs = BASE.replace('checksum = "aa"', 'checksum = "a2"')
        with self.assertRaises(mcl.Conflict):
            mcl.merge_text(BASE, ours, theirs)

    def test_check_accepts_cargos_own_form_and_refuses_another(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp, "Cargo.lock")
            path.write_text(BASE)
            self.assertEqual(mcl.main(["--check", str(path)]), 0)
            # Packages out of cargo's order.
            path.write_text(lock(pkg("cmux-a", deps=["serde"]), pkg("app", deps=["cmux-a", "serde"]), pkg("cmux-z"),
                                 SERDE))
            self.assertEqual(mcl.main(["--check", str(path)]), 1)

    def test_semver_order_puts_a_prerelease_before_its_release_and_10_after_9(self):
        keys = [("x", v, REG) for v in ("0.10.0", "0.9.0", "1.0.0", "1.0.0-rc.1")]
        self.assertEqual([k[1] for k in sorted(keys, key=mcl.package_sort_key)],
                         ["0.9.0", "0.10.0", "1.0.0-rc.1", "1.0.0"])


ENV = {**os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1"}


class DriverTest(unittest.TestCase):
    def git(self, repo, *args):
        return subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True, check=True, env=ENV).stdout

    def test_git_merges_two_branches_that_each_added_a_crate_with_no_conflict(self):
        with tempfile.TemporaryDirectory() as repo:
            self.git(repo, "init", "-q", "-b", "main")
            self.git(repo, "config", "user.name", "t")
            self.git(repo, "config", "user.email", "t@example.com")
            self.git(repo, "config", "merge.cmux-cargo-lock-v1.driver", f"python3 -I {DRIVER} %O %A %B %P")
            Path(repo, ".gitattributes").write_text("**/Cargo.lock merge=cmux-cargo-lock-v1\n")
            Path(repo, "ws").mkdir()
            Path(repo, "ws/Cargo.lock").write_text(BASE)
            self.git(repo, "add", "-A")
            self.git(repo, "commit", "-qm", "base")
            self.git(repo, "checkout", "-qb", "b")
            Path(repo, "ws/Cargo.lock").write_text(BASE.replace(pkg("cmux-z"), pkg("cmux-b") + pkg("cmux-z")))
            self.git(repo, "commit", "-qam", "b")
            self.git(repo, "checkout", "-q", "main")
            Path(repo, "ws/Cargo.lock").write_text(BASE.replace(pkg("cmux-z"), pkg("cmux-c") + pkg("cmux-z")))
            self.git(repo, "commit", "-qam", "c")
            r = subprocess.run(["git", "-C", repo, "merge", "-q", "--no-edit", "b"], capture_output=True, text=True,
                               env=ENV)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertEqual(Path(repo, "ws/Cargo.lock").read_text(),
                             BASE.replace(pkg("cmux-z"), pkg("cmux-b") + pkg("cmux-c") + pkg("cmux-z")))

    def test_a_real_conflict_leaves_git_conflict_markers(self):
        with tempfile.TemporaryDirectory() as tmp:
            o, a, b = (Path(tmp, n) for n in "oab")
            o.write_text(BASE)
            a.write_text(BASE.replace('checksum = "aa"', 'checksum = "a1"'))
            b.write_text(BASE.replace('checksum = "aa"', 'checksum = "a2"'))
            r = subprocess.run(["python3", "-I", str(DRIVER), str(o), str(a), str(b), "ws/Cargo.lock"],
                               capture_output=True, text=True)
            self.assertEqual(r.returncode, 1)
            self.assertIn("<<<<<<< ours", a.read_text())
            self.assertIn("serde 1.0.200: checksum changed on both sides", r.stderr)


if __name__ == "__main__":
    unittest.main()
