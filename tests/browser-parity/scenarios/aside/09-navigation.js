// Navigation, history, waits, SPA URL changes.
await openTab(`${PRIMARY}/dynamic.html`);
emit("title", await page.title());
await page.locator("#push").click();
emit("pushed-url", page.url().replace(PRIMARY, "PRIMARY"));
await page.locator("#later").click();
await page.waitForSelector("#late");
emit("late", await page.locator("#late").textContent());
await page.locator("#nav").click();
await page.waitForURL(/\/slow/);
await page.waitForLoadState("load");
emit("slow-heading", await page.locator("h1").textContent());
await page.goBack();
emit("back-url", page.url().replace(PRIMARY, "PRIMARY"));
await page.goForward();
emit("forward-url", page.url().replace(PRIMARY, "PRIMARY"));
await page.reload();
emit("reload-title", await page.title());
await page.goto(`${PRIMARY}/aria.html`);
emit("goto-title", await page.title());
