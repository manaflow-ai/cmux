// Tab management, screenshots, clipboard, console logs.
const browser = await agent.browsers.getDefault();
const tab = await browser.tabs.new();
await tab.goto(`${PRIMARY}/dynamic.html`);
emit("title", await tab.title());
emit("url", (await tab.url()).replace(PRIMARY, "PRIMARY"));
const listed = (await browser.tabs.list()).filter((t) => t.url?.startsWith(PRIMARY));
emit("list-keys", Object.keys(listed[0]).sort());
emit("selected-is-tab", (await browser.tabs.selected())?.id === tab.id);
emit("get-same", (await browser.tabs.get(tab.id)).id === tab.id);
const png = await tab.screenshot({});
emit("screenshot", { type: png.constructor.name, magic: String.fromCharCode(...png.slice(1, 4)) });
const both = await tab.ax.get("both", { disableDiffing: true });
emit("both-keys", Object.keys(both).sort());
await tab.playwright.locator("#log").click();
await new Promise((r) => setTimeout(r, 300));
const logs = await tab.dev.logs({ levels: ["log", "warn", "error"] });
emit("logs", logs.map((l) => `${l.level}:${l.message}`).filter((m) => m.includes("parity")).sort());
await tab.clipboard.writeText("clip text");
emit("clipboard", await tab.clipboard.readText());
await tab.goto(`${PRIMARY}/aria.html`);
await tab.back();
emit("back-url", (await tab.url()).replace(PRIMARY, "PRIMARY"));
await tab.forward();
emit("forward-url", (await tab.url()).replace(PRIMARY, "PRIMARY"));
await tab.reload();
emit("reload-title", await tab.title());
await tab.close();
emit("closed", (await browser.tabs.list()).some((t) => t.id === tab.id));
