// Uploads through the file chooser, and downloads.
const fsm = await import("node:fs");
const os = await import("node:os");
const pathm = await import("node:path");
const dir = fsm.mkdtempSync(pathm.join(os.tmpdir(), "parity-"));
fsm.writeFileSync(pathm.join(dir, "a.txt"), "alpha");
fsm.writeFileSync(pathm.join(dir, "b.txt"), "beta");
const browser = await agent.browsers.getDefault();
const tab = await browser.tabs.new();
await tab.goto(`${PRIMARY}/files.html`);
const pw = tab.playwright;
const waitFiles = async (p) => { for (let i = 0; i < 50; i++) { const t = await pw.locator("#files").textContent(); if (t.startsWith(p)) return t; await new Promise((r) => setTimeout(r, 100)); } return pw.locator("#files").textContent(); };
let chooserP = pw.waitForEvent("filechooser");
await pw.locator("#many").click();
let chooser = await chooserP;
emit("multiple", chooser.isMultiple());
await chooser.setFiles([pathm.join(dir, "a.txt"), pathm.join(dir, "b.txt")]);
emit("many", await waitFiles("many:"));
chooserP = pw.waitForEvent("filechooser");
await pw.locator("#picker").click();
chooser = await chooserP;
await chooser.setFiles(pathm.join(dir, "b.txt"));
emit("hidden", await waitFiles("hidden-file:"));
const dlP = pw.waitForEvent("download");
await pw.locator("#dl").click();
const dl = await dlP;
const p = await dl.path();
emit("download-body", fsm.readFileSync(p, "utf8"));
await tab.close();
