// Coordinate input through ax, cua and dom_cua.
const browser = await agent.browsers.getDefault();
const tab = await browser.tabs.new();
await tab.goto(`${PRIMARY}/input.html`);
const pw = tab.playwright;
const box = async (sel) => pw.locator(sel).evaluate((e) => { const r = e.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2, w: r.width, h: r.height, left: r.x, top: r.y }; });
const canvas = await box("#canvas");
await tab.cua.click({ x: canvas.left + canvas.w - 20, y: canvas.top + 20 });
emit("cua-canvas", await pw.locator("#canvas-hit").textContent());
const dbl = await box("#dbl");
await tab.cua.double_click({ x: dbl.x, y: dbl.y });
emit("cua-dbl", await pw.locator("#dbl").textContent());
const ctx = await box("#ctx");
await tab.cua.click({ x: ctx.x, y: ctx.y, button: 3 });
emit("cua-right", await pw.locator("#ctx").textContent());
const keys = await box("#keys");
await tab.cua.click({ x: keys.x, y: keys.y });
await tab.cua.type({ text: "ab" });
await tab.cua.keypress({ keys: ["BACKSPACE"] });
emit("cua-type", await pw.locator("#keys").inputValue());
const drag = await box("#drag");
const drop = await box("#drop");
await tab.cua.drag({ path: [{ x: drag.x, y: drag.y }, { x: drop.x, y: drop.y }] });
emit("cua-drag", await pw.locator("#drop").textContent());
const sc = await box("#scroller");
await tab.cua.scroll({ x: sc.x, y: sc.y, scrollX: 0, scrollY: 200 });
emit("cua-scroll", (await pw.locator("#scroller").evaluate((e) => e.scrollTop)) > 0);
await tab.ax.click([dbl.x, dbl.y], { clickCount: 2 });
emit("ax-point-dbl", await pw.locator("#dbl").textContent());
const dom = await tab.dom_cua.get_visible_dom();
emit("dom-type", typeof dom);
emit("untrusted-events", await pw.evaluate(() => window.__summary().filter((l) => l.includes("UNTRUSTED"))));
await tab.close();
