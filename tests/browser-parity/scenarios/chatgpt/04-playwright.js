// tab.playwright locators, reads, waits and frames.
const browser = await agent.browsers.getDefault();
const tab = await browser.tabs.new();
await tab.goto(`${PRIMARY}/aria.html`);
const pw = tab.playwright;
emit("role-tabs", await pw.getByRole("tab").count());
emit("by-text", await pw.getByText("Panel one").count());
emit("by-label", await pw.getByLabel("Label for").inputValue?.() ?? null);
emit("labelledby", await pw.getByRole("textbox", { name: "Labelled by span" }).count());
emit("nth", await pw.locator("button").nth(1).textContent());
emit("filter", await pw.locator("li").filter({ hasText: "main.swift" }).count());
emit("visible", [await pw.getByText("Hidden details text").isVisible(), await pw.getByText("Heads up").isVisible()]);
emit("eval-all", await pw.locator("th").evaluateAll((els) => els.map((e) => e.textContent)));
emit("all-text", await pw.locator("td").allTextContents());
emit("attr", await pw.locator("[aria-current]").getAttribute("aria-current"));
await tab.goto(`${PRIMARY}/frames.html?peer=${encodeURIComponent(PEER)}`);
await pw.waitForLoadState("load");
await pw.frameLocator("#cross").locator("#inner-btn").click();
emit("cross-frame-click", await pw.frameLocator("#cross").locator("#inner-btn").textContent());
await pw.frameLocator("#same").getByRole("textbox", { name: "Frame field" }).fill("same value");
emit("same-frame-fill", await pw.frameLocator("#same").locator("#inner-input").evaluate((e) => e.value));
emit("dom-snapshot-has-frames", (await pw.domSnapshot()).includes("Inside frame"));
await tab.goto(`${PRIMARY}/dynamic.html`);
await pw.locator("#later").click();
await pw.locator("#late").waitFor({ state: "visible" });
emit("late", await pw.locator("#late").textContent());
await pw.locator("#push").click();
await pw.waitForURL(/step=2/);
emit("pushed-url", (await tab.url()).replace(PRIMARY, "PRIMARY"));
await tab.close();
