#!/usr/bin/env python3
"""Writes the iPhone composer's emoji shortcode table (EmojiShortcodes.swift) from the icon
picker's bundled table, webviews/src/icon-picker/generated/emoji-data.json (Unicode emoji-test.txt
and CLDR annotations, Unicode License v3; emojibase-data GitHub shortcodes, MIT; see LICENSES.md
beside it). Only emoji with a shortcode are kept, with their English name and keywords.

One line per emoji, tab-separated: glyph, shortcodes (shown first, `|`), English name,
English keywords (`|`), the five skin-tone forms (space-separated, or empty).

    python3 cmux-next-ios/scripts/gen-emoji-shortcodes.py          # writes the resource
    python3 cmux-next-ios/scripts/gen-emoji-shortcodes.py --check  # exit 1 when it is stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "webviews/src/icon-picker/generated/emoji-data.json"
OUT = ROOT / "cmux-next-ios/CmuxMobileKit/Sources/CmuxMobileAgentChat/Resources/emoji-shortcodes.tsv"


def render() -> str:
    table = json.loads(SOURCE.read_text(encoding="utf-8"))
    lines = [
        "# Generated by cmux-next-ios/scripts/gen-emoji-shortcodes.py from "
        "webviews/src/icon-picker/generated/emoji-data.json "
        f"(Emoji {table['unicode']['emoji']}, CLDR {table['unicode']['cldr']}: Unicode License v3; "
        f"emojibase GitHub shortcodes {table['unicode'].get('shortcodes', '?')}: MIT). Do not edit."
    ]
    for row in table["rows"]:
        emoji, _group, _version, name, keywords, _name_ja, _keywords_ja, codes = row[:8]
        tones = row[8] if len(row) > 8 else []
        if not codes:
            continue
        fields = [emoji, codes, name, keywords, " ".join(tones or [])]
        assert all("\t" not in f and "\n" not in f for f in fields), row
        lines.append("\t".join(fields))
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run {pathlib.Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.encode())} bytes, {text.count(chr(10)) - 1} emoji)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
