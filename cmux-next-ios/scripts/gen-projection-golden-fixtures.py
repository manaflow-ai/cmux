#!/usr/bin/env python3
"""Writes the iOS projection golden fixtures from the Rust golden run.

The Rust golden tests (cmux-tui/crates/cmux-terminal-projection/tests/golden.rs)
write each case's program bytes to GOLDEN_OUT/vt/NAME.vt and its golden text to
GOLDEN_OUT/NAME.txt. This script turns them into
CmuxMobileKit/Sources/CmuxMobileTerminal/Demo/TerminalProjectionGoldenFixtures.swift,
so the simulator feeds the app the very bytes the golden was made from
(`-CmuxMobileProjectionGolden NAME`, TerminalProjectionGoldenDemo.swift).

    # on the fleet (never on a Mac of Leo's):
    cmux-ci test --artifact OUT -- bash -c 'cd cmux-tui && GOLDEN_UPDATE=1 \
      GOLDEN_OUT="$FAST_CHECKS_OUT" cargo test -p cmux-terminal-projection --test golden'
    python3 cmux-next-ios/scripts/gen-projection-golden-fixtures.py OUT

Each case is cut into stages where the golden takes a snapshot (STAGES below:
the byte string each later stage starts with), so the screenshots show the
same moments the golden text records. A stage marked streamed is fed in small
chunks over a few seconds (live output), the rest in one feed.
"""
import base64
import pathlib
import re
import sys

# name -> [(stage, starts-with bytes or None for the first, streamed)]
STAGES = {
    "headers_claude_code": [("welcome", None, False), ("typed-hello", b"hello", False)],
    "cursor_positions": [
        ("cursor-30-back", None, False),
        ("pending-wrap", b"\x1b[30C\r\n", False),
        ("cup-after-clear", b"\r\n\x1b[2J\x1b[H", False),
    ],
    "alternate_screen_codex_and_back": [
        ("before-codex", None, False),
        ("codex", b"\x1b[?1049h", False),
        ("codex-redraw", b"\x1b[38;6H\x1b[Kfix it", False),
        ("after-exit", b"\x1b[?2004l\x1b[?1l\x1b>\x1b[?1049l", False),
    ],
    "live_streaming_output": [("halfway", None, True), ("finished", "half", True)],
}

HEADER = re.compile(r"^# Mac pane (\d+)x(\d+), phone (\d+)x(\d+)$", re.M)
SAMPLE_NAMES = [(b"leo@cosmic-gray", b"dev@sample-host"), (b"/Users/leo/", b"/Users/dev/")]
assert all(len(real) == len(sample) for real, sample in SAMPLE_NAMES)


def stages_for(name: str, data: bytes):
    plan = STAGES.get(name, [("final", None, False)])
    cuts = []
    for stage, start, streamed in plan:
        if start is None:
            offset = 0
        elif start == "half":
            offset = len(data) // 2
        else:
            offset = data.find(start, cuts[-1][1] if cuts else 0)
            if offset < 0:
                sys.exit(f"{name}: stage {stage}: {start!r} not in the stream")
        cuts.append((stage, offset, streamed))
    out = []
    for i, (stage, offset, streamed) in enumerate(cuts):
        end = cuts[i + 1][1] if i + 1 < len(cuts) else len(data)
        out.append((stage, end, streamed))
    return out


def swift_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = pathlib.Path(sys.argv[1])
    vts = sorted((root / "vt").glob("*.vt"))
    if not vts:
        sys.exit(f"no vt/*.vt under {root}")
    cases = []
    for vt in vts:
        name = vt.stem
        golden = (root / f"{name}.txt").read_text()
        about = golden.splitlines()[0].split(": ", 1)[1] if ": " in golden.splitlines()[0] else ""
        grid = HEADER.search(golden)
        if not grid:
            sys.exit(f"{name}: no '# Mac pane CxR, phone CxR' header")
        mc, mr, pc, pr = (int(g) for g in grid.groups())
        data = vt.read_bytes()
        # Screenshots of these fixtures go into PR media, which refuses personal machine and account
        # names. Swap them for sample ones of the same byte length, so every column stays where the
        # golden put it.
        for real, sample in SAMPLE_NAMES:
            data = data.replace(real, sample)
        stages = ", ".join(
            f".init(name: {swift_string(s)}, end: {end}, streamed: {'true' if streamed else 'false'})"
            for s, end, streamed in stages_for(name, data)
        )
        cases.append(
            f"        .init(name: {swift_string(name)}, about: {swift_string(about)},\n"
            f"              macColumns: {mc}, macRows: {mr}, goldenPhoneColumns: {pc}, goldenPhoneRows: {pr},\n"
            f"              stages: [{stages}],\n"
            f"              base64: {swift_string(base64.b64encode(data).decode())}),"
        )
    dest = pathlib.Path(__file__).resolve().parent.parent / "CmuxMobileKit/Sources/CmuxMobileTerminal/Demo/TerminalProjectionGoldenFixtures.swift"
    dest.write_text(
        "// Generated by cmux-next-ios/scripts/gen-projection-golden-fixtures.py from the\n"
        "// cmux-terminal-projection golden run (tests/golden.rs, GOLDEN_OUT): do not edit.\n"
        "// DEBUG only: never compiled into Production.\n"
        "#if DEBUG\n"
        "extension TerminalProjectionGoldenCase {\n"
        "    static let all: [TerminalProjectionGoldenCase] = [\n"
        + "\n".join(cases)
        + "\n    ]\n}\n#endif\n"
    )
    print(f"wrote {dest} ({len(cases)} cases)")


if __name__ == "__main__":
    main()
