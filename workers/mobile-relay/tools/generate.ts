// Codegen for the mobile relay protocol. Source of truth: src/protocol.ts
// (Effect Schema) and src/ticket.ts. Outputs, all checked in:
//
//   1. web/services/mobileRelay/generated/{protocol,ticket}.ts
//      Verbatim copies (the web app mints tickets; Vercel builds cannot reach
//      files outside web/, the same reason the relay catalog was copied).
//   2. Packages/Shared/CmuxRelayTransport/Sources/CmuxRelayTransport/Generated/
//      RelayProtocolGenerated.swift
//      Swift Codable types emitted from the JSON Schema of every control
//      message, plus the wire constants.
//
// Run `bun tools/generate.ts --write` after editing the protocol;
// `--check` (CI) fails on drift. The emitter is deliberately narrow: flat
// structs of primitives only. It THROWS on anything else, so an unsupported
// schema shape breaks generation instead of silently emitting wrong Swift.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { JSONSchema, Schema } from "effect";
import * as protocol from "../src/protocol";

const repoRoot = join(import.meta.dir, "..", "..", "..");
const workerDir = join(repoRoot, "workers", "mobile-relay");
const webGeneratedDir = join(repoRoot, "web", "services", "mobileRelay", "generated");
const swiftOutputPath = join(
  repoRoot,
  "Packages",
  "Shared",
  "CmuxRelayTransport",
  "Sources",
  "CmuxRelayTransport",
  "Generated",
  "RelayProtocolGenerated.swift",
);

const GENERATED_TS_HEADER = `// GENERATED by workers/mobile-relay/tools/generate.ts — DO NOT EDIT.
// Source of truth: workers/mobile-relay/src. Run \`bun run generate\` there.

`;

interface MessageSpec {
  readonly swiftName: string;
  readonly schema: Schema.Schema.AnyNoContext;
  /** Which decode enum the message belongs to (nil = plain struct). */
  readonly group: "server" | "client" | null;
}

const MESSAGES: readonly MessageSpec[] = [
  { swiftName: "RelayWelcome", schema: protocol.WelcomeMessage, group: "server" },
  { swiftName: "RelayPeerJoined", schema: protocol.PeerJoinedMessage, group: "server" },
  { swiftName: "RelayPeerLeft", schema: protocol.PeerLeftMessage, group: "server" },
  { swiftName: "RelayRefreshAck", schema: protocol.RefreshAckMessage, group: "server" },
  { swiftName: "RelayBye", schema: protocol.ByeMessage, group: "server" },
  { swiftName: "RelayRefresh", schema: protocol.RefreshMessage, group: "client" },
  { swiftName: "RelayCloseSession", schema: protocol.CloseSessionMessage, group: "client" },
  { swiftName: "RelayTicketClaims", schema: protocol.TicketClaims, group: null },
];

/** JSON-Schema property shapes the emitter accepts. */
interface JsonSchemaObject {
  readonly $defs?: Record<string, { type?: string }>;
  readonly type?: string;
  readonly required?: readonly string[];
  readonly properties?: Record<string, JsonSchemaProperty>;
}

interface JsonSchemaProperty {
  readonly $ref?: string;
  readonly type?: string;
  readonly enum?: readonly string[];
}

interface SwiftField {
  readonly name: string;
  readonly swiftType: string;
  /** Set for the `t` discriminator. */
  readonly literal?: string;
}

function resolveType(
  property: JsonSchemaProperty,
  defs: Record<string, { type?: string }>,
  context: string,
): string {
  if (property.$ref) {
    const name = property.$ref.replace("#/$defs/", "");
    const definition = defs[name];
    if (!definition?.type) throw new Error(`${context}: unresolvable $ref ${property.$ref}`);
    return resolveType({ type: definition.type }, defs, context);
  }
  switch (property.type) {
    case "string":
      return "String";
    case "integer":
      return "Int";
    case "number":
      return "Double";
    case "boolean":
      return "Bool";
    default:
      throw new Error(`${context}: unsupported schema type ${JSON.stringify(property)}`);
  }
}

function fieldsFor(spec: MessageSpec): SwiftField[] {
  const raw = JSONSchema.make(spec.schema as Schema.Schema<unknown>) as JsonSchemaObject;
  if (raw.type !== "object" || !raw.properties) {
    throw new Error(`${spec.swiftName}: expected a flat object schema`);
  }
  const required = new Set(raw.required ?? []);
  const defs = raw.$defs ?? {};
  return Object.entries(raw.properties).map(([name, property]) => {
    if (!required.has(name)) {
      throw new Error(`${spec.swiftName}.${name}: optional fields are not supported; add emitter support first`);
    }
    if (property.enum) {
      if (property.enum.length === 1 && name === "t") {
        return { name, swiftType: "String", literal: property.enum[0] };
      }
      const expected = ["host", "client"];
      if (name === "role" && JSON.stringify(property.enum) === JSON.stringify(expected)) {
        return { name, swiftType: "RelayRole" };
      }
      throw new Error(`${spec.swiftName}.${name}: unsupported enum ${JSON.stringify(property.enum)}`);
    }
    return { name, swiftType: resolveType(property, defs, `${spec.swiftName}.${name}`) };
  });
}

function swiftStruct(spec: MessageSpec): string {
  const fields = fieldsFor(spec);
  const discriminator = fields.find((field) => field.literal !== undefined);
  const stored = fields.filter((field) => field.literal === undefined);
  const lines: string[] = [];
  lines.push(`public struct ${spec.swiftName}: Codable, Sendable, Equatable {`);
  if (discriminator) {
    lines.push(`    public static let type = "${discriminator.literal}"`);
    lines.push(`    public var t: String = Self.type`);
  }
  for (const field of stored) {
    lines.push(`    public var ${field.name}: ${field.swiftType}`);
  }
  const params = stored.map((field) => `${field.name}: ${field.swiftType}`).join(", ");
  const assigns = stored.map((field) => `        self.${field.name} = ${field.name}`).join("\n");
  lines.push(`    public init(${params}) {`);
  if (assigns) lines.push(assigns);
  lines.push("    }");
  lines.push("}");
  return lines.join("\n");
}

function swiftServerEnum(): string {
  const server = MESSAGES.filter((spec) => spec.group === "server");
  const cases = server.map((spec) => {
    const caseName = spec.swiftName.replace(/^Relay/, "");
    return { spec, caseName: caseName.charAt(0).toLowerCase() + caseName.slice(1) };
  });
  const lines: string[] = [];
  lines.push("/// Every message the relay can send. Decode with `RelayServerMessage.decode(_:)`;");
  lines.push("/// unknown or malformed input returns nil (a same-version relay never sends it).");
  lines.push("public enum RelayServerMessage: Sendable, Equatable {");
  for (const { spec, caseName } of cases) {
    lines.push(`    case ${caseName}(${spec.swiftName})`);
  }
  lines.push("");
  lines.push("    private struct Probe: Decodable { let t: String }");
  lines.push("");
  lines.push("    public static func decode(_ data: Data) -> RelayServerMessage? {");
  lines.push("        let decoder = JSONDecoder()");
  lines.push("        guard let probe = try? decoder.decode(Probe.self, from: data) else { return nil }");
  lines.push("        switch probe.t {");
  for (const { spec, caseName } of cases) {
    lines.push(`        case ${spec.swiftName}.type:`);
    lines.push(`            return (try? decoder.decode(${spec.swiftName}.self, from: data)).map(RelayServerMessage.${caseName})`);
  }
  lines.push("        default:");
  lines.push("            return nil");
  lines.push("        }");
  lines.push("    }");
  lines.push("}");
  return lines.join("\n");
}

