interface Output {
  readonly path: string;
  readonly content: string;
}

function outputs(): Output[] {
  return [
    {
      path: join(webGeneratedDir, "protocol.ts"),
      content: GENERATED_TS_HEADER + readFileSync(join(workerDir, "src", "protocol.ts"), "utf8"),
    },
    {
      path: join(webGeneratedDir, "ticket.ts"),
      content: GENERATED_TS_HEADER + readFileSync(join(workerDir, "src", "ticket.ts"), "utf8"),
    },
    { path: swiftOutputPath, content: swiftFile() },
  ];
}

function main(): void {
  const mode = process.argv.includes("--check") ? "check" : process.argv.includes("--write") ? "write" : null;
  if (!mode) {
    console.error("usage: bun tools/generate.ts --write|--check");
    process.exit(2);
  }
  let drift = false;
  for (const output of outputs()) {
    if (mode === "write") {
      mkdirSync(dirname(output.path), { recursive: true });
      writeFileSync(output.path, output.content);
      console.log(`wrote ${output.path}`);
      continue;
    }
    let existing: string | null = null;
    try {
      existing = readFileSync(output.path, "utf8");
    } catch {
      existing = null;
    }
    if (existing !== output.content) {
      console.error(`DRIFT: ${output.path} is stale; run \`bun run generate\` in workers/mobile-relay`);
      drift = true;
    }
  }
  if (drift) process.exit(1);
  if (mode === "check") console.log("generated files are current");
}

main();
