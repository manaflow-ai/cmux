#!/usr/bin/env bun
// Writes THIRD_PARTY_NOTICES from the installed packages (every package the web
// bundle may include) with each package's license text. Run after bun install.
// Usage: bun first-party-apps/<app>/notices.ts [--check]
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const dir = new URL(".", import.meta.url).pathname
const nm = join(dir, "node_modules")
const appName = JSON.parse(readFileSync(join(dir, "cmux-app.json"), "utf8")).id as string

const packageDirs = (): string[] => {
  const out: string[] = []
  for (const name of readdirSync(nm).sort()) {
    if (name.startsWith(".")) continue
    const p = join(nm, name)
    if (name.startsWith("@")) for (const sub of readdirSync(p).sort()) out.push(join(p, sub))
    else if (statSync(p).isDirectory()) out.push(p)
  }
  return out.filter((p) => existsSync(join(p, "package.json")))
}

const sections = packageDirs()
  .map((p) => {
    const pkg = JSON.parse(readFileSync(join(p, "package.json"), "utf8")) as { name: string; version: string; license?: string; types?: string }
    if (pkg.name.startsWith("@types/")) return null // type declarations only; not in the bundle
    const file = readdirSync(p).find((f) => /^(licen[sc]e|copying)(\.md|\.txt)?$/i.test(f))
    if (!file) throw new Error(`${pkg.name} has no license file`)
    const extra = readdirSync(p).find((f) => /^thirdpartynotices(\.txt|\.md)?$/i.test(f))
    const body = readFileSync(join(p, file), "utf8").trim()
    const notices = extra ? `\n\n--- ${pkg.name} third-party notices ---\n\n${readFileSync(join(p, extra), "utf8").trim()}` : ""
    return `${pkg.name} ${pkg.version} (${pkg.license ?? "see license"})\n\n${body}${notices}`
  })
  .filter(Boolean)

const text = `Third-party software in the ${appName} web pane bundle (web/).\nGenerated by notices.ts from the installed packages; do not edit.\n\n${sections.join("\n\n" + "=".repeat(78) + "\n\n")}\n`
const target = join(dir, "THIRD_PARTY_NOTICES")
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== text) {
    console.error(`${target} is stale: run bun ${join(dir, "notices.ts")}`)
    process.exit(1)
  }
} else writeFileSync(target, text)
console.log(`THIRD_PARTY_NOTICES: ${sections.length} packages`)
