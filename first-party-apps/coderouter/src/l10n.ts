// Every user-visible string goes through t(key, english). The platform has no
// app localization API yet, so the tables live here (English inline at the
// call site, Japanese below). `{name}` placeholders are filled from `vars`.

let locale: "en" | "ja" = "en"

export function setLocale(value: string | null | undefined) {
  locale = value && value.toLowerCase().startsWith("ja") ? "ja" : "en"
}

export const currentLocale = () => locale

export function t(key: string, english: string, vars?: Record<string, string | number>): string {
  const text = (locale === "ja" ? JA[key] : undefined) ?? english
  return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : text
}

