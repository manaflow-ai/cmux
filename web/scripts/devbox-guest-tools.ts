/**
 * The guest cmux tools the devbox image carries from epoch 2026-09-21-r1
 * (issue #13070): the in-VM `cmux` shim, the pinned Cloud CLI distribution,
 * the browser openers and the resource reporter unit. Until that epoch the
 * driver installed them on every create and re-checked them on every attach,
 * three to four guest execs on a machine that was still booting. They are
 * static per image epoch, like the daemon pin, so:
 *
 *  - the Freestyle bake (build-devbox-freestyle.ts) installs them with the
 *    driver's own generator commands and proves each with the driver's own
 *    readiness gate, so a machine from the snapshot passes ensureGuestCli
 *    and ensureResourceReporter (drivers/freestyle.ts) without an upload;
 *  - the source digest (devbox-image-common.ts, schema 3) covers their
 *    generated bytes (devboxGuestToolsDigestInputs), so a change to any of
 *    them is a re-promotion, never a drift between the image and the driver;
 *  - the container recipe (images/devbox/Dockerfile) COPYs the same bytes
 *    from guest-tools/, rendered here (renderDevboxGuestTools) because a
 *    Dockerfile cannot run the generators and 180 KB of generated shell is
 *    not committed twice.
 */
import { createHash } from "node:crypto";
import { chmodSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { GUEST_BROWSER_FILES, GUEST_BROWSER_VERSION, GUEST_BROWSER_VERSION_PATH } from "../services/vms/guestBrowser";
import { GUEST_CMUX_SHIM, GUEST_CMUX_SHIM_PATH, GUEST_CMUX_SHIM_SHA256 } from "../services/vms/guestCli";
import distribution from "../services/vms/guestCliDistribution.json";
import {
  GUEST_RESOURCE_REPORTER_SCRIPT_PATH,
  GUEST_RESOURCE_REPORTER_UNIT_PATH,
  guestResourceReporterInstallCommand,
  guestResourceReporterScript,
  guestResourceReporterUnit,
} from "../services/vms/guestResourceReporter";

/** The rendered directory, relative to the devbox template dir; gitignored. */
export const DEVBOX_GUEST_TOOLS_DIR = "guest-tools";

/** Where the container recipe reads the Cloud CLI pin from before removing it. */
export const DEVBOX_GUEST_CLI_PIN_PATH = "/tmp/cmux-cloud-cli.json";

export type DevboxGuestToolFile = {
  /** The rendered file's name under guest-tools/. */
  readonly name: string;
  /** The path the driver installs it at (the Dockerfile's COPY destination). */
  readonly target: string;
  readonly mode: number;
  readonly content: string;
};

/** Every generated file the image carries, by the driver's own path and mode. */
export function devboxGuestToolFiles(): readonly DevboxGuestToolFile[] {
  return [
    { name: path.posix.basename(GUEST_CMUX_SHIM_PATH), target: GUEST_CMUX_SHIM_PATH, mode: 0o755, content: GUEST_CMUX_SHIM },
    ...GUEST_BROWSER_FILES.map((file) => ({
      name: path.posix.basename(file.path),
      target: file.path,
      mode: parseInt(file.mode, 8),
      content: file.content,
    })),
    { name: path.posix.basename(GUEST_BROWSER_VERSION_PATH), target: GUEST_BROWSER_VERSION_PATH, mode: 0o644, content: `${GUEST_BROWSER_VERSION}\n` },
    { name: path.posix.basename(GUEST_RESOURCE_REPORTER_SCRIPT_PATH), target: GUEST_RESOURCE_REPORTER_SCRIPT_PATH, mode: 0o644, content: guestResourceReporterScript() },
    { name: path.posix.basename(GUEST_RESOURCE_REPORTER_UNIT_PATH), target: GUEST_RESOURCE_REPORTER_UNIT_PATH, mode: 0o644, content: guestResourceReporterUnit() },
    { name: path.posix.basename(DEVBOX_GUEST_CLI_PIN_PATH), target: DEVBOX_GUEST_CLI_PIN_PATH, mode: 0o644, content: `${JSON.stringify(distribution, null, 2)}\n` },
  ];
}

export type DevboxGuestToolsDigestInputs = {
  /** sha256 of the shim bytes (GUEST_CMUX_SHIM). */
  readonly cmuxShimSha256: string;
  /** The opener set's version stamp: every file, mode and localized string (GUEST_BROWSER_VERSION). */
  readonly browserOpenersVersion: string;
  /** sha256 of the whole reporter installer: script, unit and systemd steps. */
  readonly resourceReporterSha256: string;
  /** The pinned Cloud CLI archive (guestCliDistribution.json). */
  readonly cliDistributionArchiveSha256: string;
};

/** The `guestTools` block of the source digest: what a machine ends up holding, hashed. */
export function devboxGuestToolsDigestInputs(): DevboxGuestToolsDigestInputs {
  return {
    cmuxShimSha256: GUEST_CMUX_SHIM_SHA256,
    browserOpenersVersion: GUEST_BROWSER_VERSION,
    resourceReporterSha256: createHash("sha256").update(guestResourceReporterInstallCommand()).digest("hex"),
    cliDistributionArchiveSha256: distribution.archiveSha256,
  };
}

/**
 * Writes the rendered files into `dir` (created; anything already there is
 * removed first, so a stale render never lingers) and returns their paths.
 */
export function renderDevboxGuestTools(dir: string): string[] {
  mkdirSync(dir, { recursive: true });
  for (const stale of readdirSync(dir)) rmSync(path.join(dir, stale), { recursive: true, force: true });
  const written: string[] = [];
  for (const file of devboxGuestToolFiles()) {
    const target = path.join(dir, file.name);
    writeFileSync(target, file.content, { mode: file.mode });
    chmodSync(target, file.mode);
    written.push(target);
  }
  return written;
}
