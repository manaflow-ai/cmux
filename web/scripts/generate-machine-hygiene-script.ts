// Regenerates services/vms/hygiene/script.generated.ts from the bash source,
// so the server can ship the script through exec without reading files at
// runtime. tests/vm-machine-hygiene-route.test.ts fails when the two drift.
//
//   bun scripts/generate-machine-hygiene-script.ts

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.join(import.meta.dirname, "../services/vms/hygiene");
const source = readFileSync(path.join(dir, "cmux-machine-hygiene"), "utf8");

writeFileSync(
  path.join(dir, "script.generated.ts"),
  [
    "// Generated by scripts/generate-machine-hygiene-script.ts from cmux-machine-hygiene. Do not edit.",
    "",
    `export const MACHINE_HYGIENE_SCRIPT = ${JSON.stringify(source)};`,
    "",
  ].join("\n"),
);
