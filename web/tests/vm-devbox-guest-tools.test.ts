import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import {
  DEVBOX_GUEST_TOOLS_DIR,
  devboxGuestToolFiles,
  devboxGuestToolsDigestInputs,
  renderDevboxGuestTools,
} from "../scripts/devbox-guest-tools";
import { DEVBOX_SOURCE_SCHEMA, devboxSourceDigest, devboxSourceManifest, readDevboxDockerfile } from "../scripts/devbox-image-common";
import { GUEST_BROWSER_FILES, GUEST_BROWSER_VERSION, GUEST_BROWSER_VERSION_PATH, guestBrowserInstallCommand, guestBrowserReadyCommand } from "../services/vms/guestBrowser";
import { GUEST_CMUX_SHIM, GUEST_CMUX_SHIM_PATH, guestCliShimReadyCommand } from "../services/vms/guestCli";
import distribution from "../services/vms/guestCliDistribution.json";
import {
  GUEST_RESOURCE_REPORTER_SCRIPT_PATH,
  GUEST_RESOURCE_REPORTER_UNIT_PATH,
  guestResourceReporterInstallCommand,
  guestResourceReporterReadyCommand,
  guestResourceReporterScript,
  guestResourceReporterUnit,
} from "../services/vms/guestResourceReporter";

// Issue #13070: until devbox epoch 2026-09-21-r1 the driver uploaded the
// in-VM `cmux` shim, downloaded the pinned Cloud CLI distribution, wrote the
// browser openers and installed the resource reporter unit on every create,
// then re-checked all four on every attach: three to four guest execs on a
// machine that was still booting, ahead of the first terminal. The tools are
// static per image epoch, like the daemon pin, so the bake installs them with
// the driver's own generator commands and proves them with the driver's own
// readiness gates, and the source digest covers their generated bytes so a
// change to any of them is a re-promotion, never a silent drift between what
// the image carries and what the driver expects.

const webDir = path.join(import.meta.dirname, "..");
const readWeb = (relative: string) => readFileSync(path.join(webDir, relative), "utf8");
const bake = readWeb("scripts/build-devbox-freestyle.ts");
const verify = readWeb("scripts/verify-devbox-image.ts");
const dockerfile = readDevboxDockerfile();
const sha256 = (text: string) => createHash("sha256").update(text).digest("hex");

describe("baked guest cmux tools (issue #13070)", () => {
  test("the bake installs the four tools with the driver's generators, after the daemon pin and before the agent hooks, and proves each one", () => {
    // The shim is one fs write (the driver's own upload), proven by the
    // driver's sha256 gate; the other three are the driver's install
    // commands, each followed by the driver's readiness check as its own
    // step, so a bake whose tools the driver would re-install fails here.
    expect(bake).toContain("await vm.fs.writeTextFile(GUEST_CMUX_SHIM_PATH, GUEST_CMUX_SHIM, { mode: 0o755 });");
    expect(bake).toContain('await step("guest-cli-shim", `${guestCliShimReadyCommand()} && test -x ${GUEST_CMUX_SHIM_PATH} && sh -n ${GUEST_CMUX_SHIM_PATH} && echo guest-cli-shim-ok`);');
    expect(bake).toContain('await step("guest-cli-distribution", guestCliDistributionCommand());');
    expect(bake).toContain('await step("guest-cli-distribution-verify", `${guestCliDistributionCommand(true)} && test -x /usr/local/bin/cmux && test -x /usr/local/bin/coderouter && test -x /usr/local/bin/cr && test -x /usr/local/libexec/cmux-coderouter && echo guest-cli-distribution-ok`);');
    expect(bake).toContain('await step("guest-browser-openers", guestBrowserInstallCommand());');
    expect(bake).toContain('await step("guest-browser-openers-verify", `${guestBrowserReadyCommand} && ');
    expect(bake).toContain("xdg-mime query default x-scheme-handler/https");
    expect(bake).toContain('await step("guest-resource-reporter", guestResourceReporterInstallCommand());');
    expect(bake).toContain('await step("guest-resource-reporter-verify", `${guestResourceReporterReadyCommand()} && echo guest-resource-reporter-ok`);');
    // Order: the daemon pin (the tools' `cmux --version` is the daemon's),
    // then the tools, then the agent hooks proof; the stamp stays last.
    const pin = bake.indexOf('"cmux-tui-pin"');
    const steps = [
      'await step("guest-cli-shim"',
      'await step("guest-cli-distribution"',
      'await step("guest-cli-distribution-verify"',
      'await step("guest-browser-openers"',
      'await step("guest-browser-openers-verify"',
      'await step("guest-resource-reporter"',
      'await step("guest-resource-reporter-verify"',
    ].map((marker) => bake.indexOf(marker));
    const hooks = bake.indexOf('"agent-hooks"');
    const stamp = bake.indexOf('"image-stamp"');
    expect(pin).toBeGreaterThan(-1);
    expect(steps.every((at) => at > pin)).toBe(true);
    for (let i = 1; i < steps.length; i += 1) expect(steps[i]).toBeGreaterThan(steps[i - 1]);
    expect(hooks).toBeGreaterThan(steps[steps.length - 1]);
    expect(stamp).toBeGreaterThan(hooks);
  });

  test("the driver's readiness gates are the bake's and the verifier's proofs", () => {
    // The exact expression ensureGuestCli runs before it decides to
    // re-install (drivers/freestyle.ts): the same bytes, the same path.
    expect(guestCliShimReadyCommand()).toBe(
      `test "$(sha256sum '${GUEST_CMUX_SHIM_PATH}' 2>/dev/null | cut -d ' ' -f 1)" = '${sha256(GUEST_CMUX_SHIM)}'`,
    );
    expect(GUEST_CMUX_SHIM_PATH).toBe("/usr/local/libexec/cmux-cloud-adapter");
    // The reporter gate: the exact script and unit bytes the installer
    // would otherwise rewrite, and the unit enabled and running.
    const reporter = guestResourceReporterReadyCommand();
    expect(reporter).toContain(`test "$(sha256sum '${GUEST_RESOURCE_REPORTER_SCRIPT_PATH}' 2>/dev/null | cut -d ' ' -f 1)" = '${sha256(guestResourceReporterScript())}'`);
    expect(reporter).toContain(`test "$(sha256sum '${GUEST_RESOURCE_REPORTER_UNIT_PATH}' 2>/dev/null | cut -d ' ' -f 1)" = '${sha256(guestResourceReporterUnit())}'`);
    expect(reporter).toContain("systemctl is-enabled --quiet cmux-resource-stats.service && systemctl is-active --quiet cmux-resource-stats.service");
    expect(GUEST_RESOURCE_REPORTER_SCRIPT_PATH).toBe("/usr/local/lib/cmux/resource-stats.py");
    expect(GUEST_RESOURCE_REPORTER_UNIT_PATH).toBe("/etc/systemd/system/cmux-resource-stats.service");
    // The installer still writes exactly those bytes to exactly those paths.
    const install = guestResourceReporterInstallCommand();
    expect(install).toContain(`install -m 0644 "$cmux_stats_tmp/script" ${GUEST_RESOURCE_REPORTER_SCRIPT_PATH}`);
    expect(install).toContain(`install -m 0644 "$cmux_stats_tmp/unit" ${GUEST_RESOURCE_REPORTER_UNIT_PATH}`);
    expect(guestResourceReporterUnit()).toContain(`ExecStart=/usr/bin/python3 ${GUEST_RESOURCE_REPORTER_SCRIPT_PATH}`);
    // The verifier proves all four on a booted machine and runs the hand
    // check from the startup-latency plan, asserted.
    for (const marker of [
      "guest-cli-shim-baked",
      "guest-cli-distribution-baked",
      "guest-browser-openers-baked",
      "guest-resource-reporter-baked",
      "guest-tools-parity-ok",
      "...GUEST_TOOL_CHECKS,",
      "guestCliShimReadyCommand()",
      "guestCliDistributionCommand(true)",
      "guestBrowserReadyCommand",
      "guestResourceReporterReadyCommand()",
      "cmux --version; command -v coderouter cr; readlink -f /usr/local/bin/xdg-open; xdg-mime query default x-scheme-handler/https; systemctl is-active cmux-resource-stats; cat /etc/cmux/vm-name /etc/cmux/image-stamp",
    ]) {
      expect({ marker, present: verify.includes(marker) }).toEqual({ marker, present: true });
    }
  });

  test("the reporter gate passes only for the installed bytes of an enabled, active unit", () => {
    // The real installer and the real gate against a fixture root with a
    // systemctl that answers from marker files (the pattern of
    // vm-guest-setup-idempotence.test.ts).
    const root = mkdtempSync(path.join(tmpdir(), "cmux-reporter-gate-"));
    try {
      const bin = path.join(root, "bin");
      mkdirSync(bin);
      mkdirSync(path.join(root, "etc/systemd/system"), { recursive: true });
      writeFileSync(path.join(bin, "systemctl"), [
        "#!/bin/sh",
        'case "$1" in',
        '  is-active) test -f "$FIXTURE_ROOT/active" ;;',
        '  is-enabled) test -f "$FIXTURE_ROOT/enabled" ;;',
        '  restart) touch "$FIXTURE_ROOT/active" ;;',
        '  enable) touch "$FIXTURE_ROOT/active" "$FIXTURE_ROOT/enabled" ;;',
        "esac",
        "",
      ].join("\n"), { mode: 0o755 });
      if (spawnSync("which", ["sha256sum"]).status !== 0) {
        writeFileSync(path.join(bin, "sha256sum"), '#!/bin/sh\nexec shasum -a 256 "$@"\n', { mode: 0o755 });
      }
      const confine = (text: string) => text.replaceAll("/usr/local/", `${root}/usr/local/`).replaceAll("/etc/", `${root}/etc/`);
      const run = (command: string) => spawnSync("sh", ["-c", command], {
        encoding: "utf8",
        env: { NODE_ENV: "test", PATH: `${bin}:${process.env.PATH}`, FIXTURE_ROOT: root, HOME: root },
      });
      const install = () => run(confine(guestResourceReporterInstallCommand()));
      // Confining the installer rewrites the paths inside the script and the
      // unit it writes as well, so the gate's digests are rewritten the same
      // way: what is compared is still "the installer's bytes, unchanged".
      const ready = () => run(
        confine(guestResourceReporterReadyCommand())
          .replace(sha256(guestResourceReporterScript()), sha256(confine(guestResourceReporterScript())))
          .replace(sha256(guestResourceReporterUnit()), sha256(confine(guestResourceReporterUnit()))),
      );
      expect(ready().status).not.toBe(0);
      expect(install()).toMatchObject({ status: 0, stderr: "" });
      expect(ready()).toMatchObject({ status: 0, stderr: "" });
      rmSync(path.join(root, "active"));
      expect(ready().status).not.toBe(0);
      expect(install().status).toBe(0);
      expect(ready().status).toBe(0);
      writeFileSync(path.join(root, "usr/local/lib/cmux/resource-stats.py"), "obsolete");
      expect(ready().status).not.toBe(0);
      expect(install().status).toBe(0);
      expect(ready().status).toBe(0);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }, 60_000);

  test("the opener gate holds on a devbox without zsh, exactly where the installer leaves it", () => {
    // Rehearsed 2026-09-21 on the md default (sh-0b6a5ee6…): the image has
    // no zsh, so the gate's `grep /etc/zsh/zshenv` failed on every machine.
    // The installer appends its source line only to rc files that exist, yet
    // the gate demanded the line in /etc/zsh/zshenv: it could never pass,
    // the driver re-installed the openers on every attach and exec, and the
    // bake could not prove them. The gate mirrors the installer: an absent
    // rc file is nothing to do; a present one must carry the line.
    const root = mkdtempSync(path.join(tmpdir(), "cmux-opener-gate-"));
    try {
      const bin = path.join(root, "bin");
      mkdirSync(bin);
      mkdirSync(path.join(root, "etc"), { recursive: true });
      writeFileSync(path.join(root, "etc/bash.bashrc"), "# system bashrc\n");
      const tool = (name: string, script: string) => writeFileSync(path.join(bin, name), `#!/bin/sh\n${script}\n`, { mode: 0o755 });
      tool("getent", "exit 0");
      tool("runuser", 'shift 3; exec "$@"');
      tool("xdg-mime", 'printf "cmux-browser.desktop\\n"');
      if (spawnSync("which", ["sha256sum"]).status !== 0) tool("sha256sum", 'exec shasum -a 256 "$@"');
      const confine = (text: string) => text.replaceAll("/usr/local/", `${root}/usr/local/`).replaceAll("/etc/", `${root}/etc/`);
      const run = (command: string) => spawnSync("sh", ["-c", confine(command)], {
        encoding: "utf8",
        env: { NODE_ENV: "test", PATH: `${bin}:${process.env.PATH}`, HOME: root },
      });
      expect(run(guestBrowserInstallCommand())).toMatchObject({ status: 0, stderr: "" });
      expect(existsSync(path.join(root, "etc/zsh/zshenv"))).toBe(false);
      expect(run(guestBrowserReadyCommand)).toMatchObject({ status: 0, stderr: "" });
      // zsh installed later: its rc file exists without the line, so the
      // gate asks for the install, which appends it, and holds again.
      mkdirSync(path.join(root, "etc/zsh"));
      writeFileSync(path.join(root, "etc/zsh/zshenv"), "# zshenv\n");
      expect(run(guestBrowserReadyCommand).status).not.toBe(0);
      expect(run(guestBrowserInstallCommand()).status).toBe(0);
      expect(readFileSync(path.join(root, "etc/zsh/zshenv"), "utf8")).toContain("cmux-browser.sh");
      expect(run(guestBrowserReadyCommand)).toMatchObject({ status: 0, stderr: "" });
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }, 60_000);

  test("the source digest (schema 3) covers the generated bytes of every tool, so a tool change is a re-promotion", () => {
    expect(DEVBOX_SOURCE_SCHEMA).toBe(3);
    const inputs = devboxGuestToolsDigestInputs();
    expect(Object.keys(inputs).sort()).toEqual(["browserOpenersVersion", "cliDistributionArchiveSha256", "cmuxShimSha256", "resourceReporterSha256"]);
    for (const [key, value] of Object.entries(inputs)) {
      expect({ key, hex: /^[0-9a-f]{64}$/.test(value) }).toEqual({ key, hex: true });
    }
    // Each input is the sha256 of what the guest ends up holding: the shim
    // bytes, the opener set's version stamp (every file, mode and localized
    // string), the whole reporter installer (script, unit, systemd steps),
    // and the pinned Cloud CLI archive.
    expect(inputs.cmuxShimSha256).toBe(sha256(GUEST_CMUX_SHIM));
    expect(inputs.browserOpenersVersion).toBe(GUEST_BROWSER_VERSION);
    expect(GUEST_BROWSER_VERSION).toBe(sha256(JSON.stringify(GUEST_BROWSER_FILES)));
    expect(guestBrowserReadyCommand).toContain(`test "$(cat ${GUEST_BROWSER_VERSION_PATH} 2>/dev/null)" = '${GUEST_BROWSER_VERSION}'`);
    expect(inputs.resourceReporterSha256).toBe(sha256(guestResourceReporterInstallCommand()));
    expect(inputs.cliDistributionArchiveSha256).toBe(distribution.archiveSha256);
    // Schema 3 carries the block for both layer sets; schema 1 and 2 keep
    // their formulas byte for byte (older entries are checked with them).
    for (const layers of ["base", "desktop"] as const) {
      expect(devboxSourceManifest(layers, dockerfile)).toMatchObject({ schema: 3, layers, guestTools: inputs });
      expect(devboxSourceManifest(layers, dockerfile, 2)).not.toHaveProperty("guestTools");
      expect(devboxSourceManifest(layers, dockerfile, 1)).not.toHaveProperty("guestTools");
      expect(devboxSourceDigest(layers, dockerfile, 3)).not.toBe(devboxSourceDigest(layers, dockerfile, 2));
    }
    expect(() => devboxSourceDigest("base", dockerfile, 4)).toThrow(/unknown devbox source schema/);
  });

  test("the container recipe carries the same bytes: rendered guest-tools/ files COPYed to the driver's paths, the Cloud CLI fetched and checked from the rendered pin", () => {
    const files = devboxGuestToolFiles();
    expect(DEVBOX_GUEST_TOOLS_DIR).toBe("guest-tools");
    // Every driver path, once: the shim, the seven opener files and the
    // version stamp, the reporter script and unit, and the CLI pin the RUN
    // below consumes and removes.
    expect(files.map((file) => file.target).sort()).toEqual([
      GUEST_CMUX_SHIM_PATH,
      ...GUEST_BROWSER_FILES.map((file) => file.path),
      GUEST_BROWSER_VERSION_PATH,
      GUEST_RESOURCE_REPORTER_SCRIPT_PATH,
      GUEST_RESOURCE_REPORTER_UNIT_PATH,
      "/tmp/cmux-cloud-cli.json",
    ].sort());
    expect(new Set(files.map((file) => file.name)).size).toBe(files.length);
    for (const file of files) {
      expect({ name: file.name, copied: dockerfile.includes(`COPY ${DEVBOX_GUEST_TOOLS_DIR}/${file.name} ${file.target}\n`) }).toEqual({ name: file.name, copied: true });
      const escaped = file.target.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
      expect({ name: file.name, mode: dockerfile.match(new RegExp(`chmod ${file.mode.toString(8).padStart(4, "0")}[^\\n]*${escaped}`)) !== null })
        .toEqual({ name: file.name, mode: true });
    }
    // The rendered files are what the generators produce, byte for byte.
    const byName = Object.fromEntries(files.map((file) => [file.name, file]));
    expect(byName["cmux-cloud-adapter"].content).toBe(GUEST_CMUX_SHIM);
    for (const opener of GUEST_BROWSER_FILES) {
      expect(byName[path.basename(opener.path)]).toMatchObject({ target: opener.path, content: opener.content, mode: parseInt(opener.mode, 8) });
    }
    expect(byName["browser-opener-version"].content).toBe(`${GUEST_BROWSER_VERSION}\n`);
    expect(byName["resource-stats.py"].content).toBe(guestResourceReporterScript());
    expect(byName["cmux-resource-stats.service"].content).toBe(guestResourceReporterUnit());
    expect(JSON.parse(byName["cmux-cloud-cli.json"].content)).toEqual(distribution);
    // The RUN installs the distribution the way the driver's python
    // installer lays it out (one immutable release dir per archive digest,
    // the three symlinks), verified against the rendered pin, enables the
    // reporter unit by its wants symlink, and wires the openers into the
    // system rc files and the MIME handlers as the install command does.
    for (const fragment of [
      'url="$(jq -r .url /tmp/cmux-cloud-cli.json)" && sha="$(jq -r .archiveSha256 /tmp/cmux-cloud-cli.json)"',
      'release="/usr/local/libexec/cmux-cloud-$sha"',
      'echo "$sha  /tmp/cmux-cloud-cli.tar.gz" | sha256sum -c -',
      "jq -r --arg b \"$b\" '.binaries[$b]' /tmp/cmux-cloud-cli.json",
      'ln -sfn "$release/coderouter" /usr/local/libexec/cmux-coderouter',
      'for n in cmux coderouter cr; do ln -sfn "$release/cmux-cloud-cli" /usr/local/bin/$n; done',
      "rm -f /tmp/cmux-cloud-cli.tar.gz /tmp/cmux-cloud-cli.json",
      "ln -sfn /etc/systemd/system/cmux-resource-stats.service /etc/systemd/system/multi-user.target.wants/cmux-resource-stats.service",
      "grep -Fqx '[ -r /etc/profile.d/cmux-browser.sh ] && . /etc/profile.d/cmux-browser.sh' \"$rc\"",
      "xdg-mime default cmux-browser.desktop x-scheme-handler/$s",
      "echo guest-tools-ok",
    ]) {
      expect({ fragment, present: dockerfile.includes(fragment) }).toEqual({ fragment, present: true });
    }
    // Dockerfile portability (vm-devbox-image.test.ts): nothing above uses
    // printf or a backslash escape inside a RUN.
    const block = dockerfile.slice(dockerfile.indexOf("COPY guest-tools/"), dockerfile.indexOf("echo guest-tools-ok"));
    expect(block).not.toContain("printf");
    expect(block).not.toContain('\\"');
    // The render is not committed (180 KB of shell the generators define);
    // the recipe's README and the render script say so.
    expect(readWeb(".gitignore")).toContain("/services/vms/images/devbox/guest-tools/");
    expect(readWeb("scripts/render-devbox-guest-tools.ts")).toContain("renderDevboxGuestTools(");
    expect((JSON.parse(readWeb("package.json")) as { scripts: Record<string, string> }).scripts["devbox:guest-tools:render"]).toBe("bun scripts/render-devbox-guest-tools.ts");
    expect(readWeb("services/vms/images/devbox/README.md")).toContain("devbox:guest-tools:render");
  });

  test("the render writes exactly the generators' output, with the modes the image needs, and replaces a stale render", () => {
    const dir = mkdtempSync(path.join(tmpdir(), "cmux-guest-tools-"));
    try {
      const out = path.join(dir, "guest-tools");
      mkdirSync(out);
      writeFileSync(path.join(out, "stale"), "from an older render\n");
      const written = renderDevboxGuestTools(out);
      const files = devboxGuestToolFiles();
      expect(written.sort()).toEqual(files.map((file) => path.join(out, file.name)).sort());
      expect(existsSync(path.join(out, "stale"))).toBe(false);
      for (const file of files) {
        const target = path.join(out, file.name);
        expect({ name: file.name, content: readFileSync(target, "utf8") === file.content }).toEqual({ name: file.name, content: true });
        expect({ name: file.name, mode: (statSync(target).mode & 0o777).toString(8) }).toEqual({ name: file.name, mode: file.mode.toString(8) });
      }
      // The shim and the openers are POSIX sh the image can parse.
      for (const name of ["cmux-cloud-adapter", "cmux-open-url", "xdg-open", "cmux-browser.sh"]) {
        expect({ name, status: spawnSync("sh", ["-n", path.join(out, name)]).status }).toEqual({ name, status: 0 });
      }
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
