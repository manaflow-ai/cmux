// Attach-time repair for the model-plane shell contract.
//
// Freestyle machines are persistent and can outlive the devbox image that
// created them.  In particular, an older image may have the agent-config
// hook but not the later Claude/VM-identity exports.  Keep this tiny runtime
// shim separate from the image generator so every attach can repair that
// drift without replacing a user's agent configuration or exposing the route
// token in the command line.

export const GUEST_MODEL_PLANE_RUNTIME_PATH = "/etc/cmux/model-plane-runtime.sh";
export const GUEST_MODEL_PLANE_PROFILE_PATH = "/etc/profile.d/cmux-model-plane.sh";

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * Runtime exports consumed by all login/interactive shells.  The model-plane
 * file is the only place that contains the route token; this script reads it
 * at shell start and never embeds that secret in the installed script.
 */
export function guestModelPlaneRuntimeScript(vmId: string): string {
  const normalizedVmId = vmId.trim();
  if (!normalizedVmId || !/^[A-Za-z0-9._:-]+$/.test(normalizedVmId)) {
    throw new Error(`invalid Freestyle VM id: ${vmId}`);
  }
  const quotedVmId = shellQuote(normalizedVmId);
  return `#!/bin/sh
# Generated by cmux on attach; do not edit.
# A persistent VM can carry an older image's agent-config.sh.  Source the
# durable model-plane file first, then derive the standard Claude names.
set +u
model_plane_file="\${CMUX_MODEL_PLANE_ENV_FILE:-\$HOME/.config/cmux/model-plane.env}"
if [ ! -r "\$model_plane_file" ] && [ -r /root/.config/cmux/model-plane.env ]; then
  model_plane_file=/root/.config/cmux/model-plane.env
fi
if [ -r "\$model_plane_file" ]; then
  # Fill missing values from the managed file without clobbering a caller's
  # explicit provider settings.  cmux-tui can pass only OPENAI_BASE_URL, for
  # example, so preserve every non-empty value across the source operation.
  cmux_explicit_openai_base="\${OPENAI_BASE_URL:-}"
  cmux_explicit_openai_key="\${OPENAI_API_KEY:-}"
  cmux_explicit_coderouter_url="\${CMUX_CODEROUTER_URL:-}"
  cmux_explicit_anthropic_base="\${ANTHROPIC_BASE_URL:-}"
  cmux_explicit_anthropic_auth="\${ANTHROPIC_AUTH_TOKEN:-}"
  cmux_explicit_anthropic_key="\${ANTHROPIC_API_KEY:-}"
  cmux_explicit_vm_id="\${CMUX_VM_ID:-}"
  . "\$model_plane_file" 2>/dev/null || true
  [ -n "\$cmux_explicit_openai_base" ] && OPENAI_BASE_URL="\$cmux_explicit_openai_base"
  [ -n "\$cmux_explicit_openai_key" ] && OPENAI_API_KEY="\$cmux_explicit_openai_key"
  [ -n "\$cmux_explicit_coderouter_url" ] && CMUX_CODEROUTER_URL="\$cmux_explicit_coderouter_url"
  [ -n "\$cmux_explicit_anthropic_base" ] && ANTHROPIC_BASE_URL="\$cmux_explicit_anthropic_base"
  [ -n "\$cmux_explicit_anthropic_auth" ] && ANTHROPIC_AUTH_TOKEN="\$cmux_explicit_anthropic_auth"
  [ -n "\$cmux_explicit_anthropic_key" ] && ANTHROPIC_API_KEY="\$cmux_explicit_anthropic_key"
  [ -n "\$cmux_explicit_vm_id" ] && CMUX_VM_ID="\$cmux_explicit_vm_id"
  unset cmux_explicit_openai_base cmux_explicit_openai_key cmux_explicit_coderouter_url
  unset cmux_explicit_anthropic_base cmux_explicit_anthropic_auth cmux_explicit_anthropic_key cmux_explicit_vm_id
fi
if [ -n "\${OPENAI_BASE_URL:-}" ] && [ -z "\${CMUX_CODEROUTER_URL:-}" ]; then
  CMUX_CODEROUTER_URL="\${OPENAI_BASE_URL%/v1}"
  export CMUX_CODEROUTER_URL
fi
if [ -n "\${OPENAI_API_KEY:-}" ] && [ -n "\${CMUX_CODEROUTER_URL:-}" ]; then
  ANTHROPIC_BASE_URL="\${ANTHROPIC_BASE_URL:-\$CMUX_CODEROUTER_URL}"
  ANTHROPIC_AUTH_TOKEN="\${ANTHROPIC_AUTH_TOKEN:-\$OPENAI_API_KEY}"
  ANTHROPIC_API_KEY="\${ANTHROPIC_API_KEY:-\$OPENAI_API_KEY}"
  export ANTHROPIC_BASE_URL ANTHROPIC_AUTH_TOKEN ANTHROPIC_API_KEY
fi
cmux_default_vm_id=${quotedVmId}
CMUX_VM_ID="\${CMUX_VM_ID:-\$cmux_default_vm_id}"
export CMUX_VM_ID
unset model_plane_file cmux_default_vm_id
`;
}

/**
 * Install the runtime shim and add it to every shell entrypoint used by the
 * devbox and cmux-tui.  All writes are staged and moved atomically; repeated
 * attaches are safe and preserve user-owned agent config files.
 */
export function guestModelPlaneInstallCommand(vmId: string): string {
  const encoded = Buffer.from(guestModelPlaneRuntimeScript(vmId), "utf8").toString("base64");
  const sourceLine = `[ -f ${GUEST_MODEL_PLANE_RUNTIME_PATH} ] && . ${GUEST_MODEL_PLANE_RUNTIME_PATH}`;
  const runtimeDir = GUEST_MODEL_PLANE_RUNTIME_PATH.slice(0, GUEST_MODEL_PLANE_RUNTIME_PATH.lastIndexOf("/"));
  const profileDir = GUEST_MODEL_PLANE_PROFILE_PATH.slice(0, GUEST_MODEL_PLANE_PROFILE_PATH.lastIndexOf("/"));
  return [
    "set -eu",
    `mkdir -p ${runtimeDir} ${profileDir}`,
    `printf '%s' '${encoded}' | base64 -d > ${GUEST_MODEL_PLANE_RUNTIME_PATH}.tmp`,
    `chmod 0644 ${GUEST_MODEL_PLANE_RUNTIME_PATH}.tmp`,
    `mv ${GUEST_MODEL_PLANE_RUNTIME_PATH}.tmp ${GUEST_MODEL_PLANE_RUNTIME_PATH}`,
    `printf '%s\\n' '${sourceLine}' > ${GUEST_MODEL_PLANE_PROFILE_PATH}.tmp`,
    `chmod 0644 ${GUEST_MODEL_PLANE_PROFILE_PATH}.tmp`,
    `mv ${GUEST_MODEL_PLANE_PROFILE_PATH}.tmp ${GUEST_MODEL_PLANE_PROFILE_PATH}`,
    // /etc/cmux/bashrc is the startup path used by cmux-tui's PTY shells;
    // the other hooks cover ordinary login and interactive bash sessions.
    `for hook in /etc/bash.bashrc /root/.bashrc /etc/cmux/bashrc; do if [ -f "$hook" ] && ! grep -Fqx '${sourceLine}' "$hook" 2>/dev/null; then printf '\\n%s\\n' '${sourceLine}' >> "$hook"; fi; done`,
    `test -s ${GUEST_MODEL_PLANE_RUNTIME_PATH}`,
  ].join(" && ");
}
