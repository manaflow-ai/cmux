# Agent sign-in modes: every claude, codex, and opencode launch from a shell
# goes through its launcher (/etc/cmux/<agent>, which picks team or own login
# per launch), whatever PATH order the shell has; the base's login PATH puts
# nvm's bin first, and the bake points nvm's entries at the launchers for
# direct execs. PATH wins when it already leads to the launcher or to a
# cmux-tui agent shim: the shim adds the pane's hook context, then finds the
# launcher further down PATH itself.
cmux_agent_run() {
  cmux_ar_agent=$1
  shift
  cmux_ar_path=$(
    IFS=:
    for cmux_ar_dir in $PATH; do
      if [ -x "${cmux_ar_dir:-.}/$cmux_ar_agent" ] && [ ! -d "${cmux_ar_dir:-.}/$cmux_ar_agent" ]; then
        printf '%s' "${cmux_ar_dir:-.}/$cmux_ar_agent"
        break
      fi
    done
  )
  if [ -n "$cmux_ar_path" ] && { [ "$(readlink -f "$cmux_ar_path" 2>/dev/null)" = "/etc/cmux/$cmux_ar_agent" ] \
    || grep -q "# cmux-tui-$cmux_ar_agent-shim" "$cmux_ar_path" 2>/dev/null; }; then
    command "$cmux_ar_agent" "$@"
  elif [ -x "/etc/cmux/$cmux_ar_agent" ]; then
    "/etc/cmux/$cmux_ar_agent" "$@"
  else
    command "$cmux_ar_agent" "$@"
  fi
}

opencode() { cmux_agent_run opencode "$@"; }

# `cr use` (the sign-in switch) lives in the guest adapter. The pinned Cloud
# CLI facade hands it there only from the release that knows the verb, so a
# shell routes it directly; every other cr/coderouter/cmux command is untouched.
cmux_cr_use() {
  if [ -x /usr/local/libexec/cmux-cloud-adapter ]; then
    /usr/local/libexec/cmux-cloud-adapter coderouter use "$@"
  else
    command cr use "$@"
  fi
}
cr() { if [ "${1-}" = use ]; then shift; cmux_cr_use "$@"; else command cr "$@"; fi; }
coderouter() { if [ "${1-}" = use ]; then shift; cmux_cr_use "$@"; else command coderouter "$@"; fi; }
cmux() {
  case "${1-}:${2-}" in
    cr:use|coderouter:use) shift 2; cmux_cr_use "$@" ;;
    *) command cmux "$@" ;;
  esac
}

claude() { cmux_agent_run claude "$@"; }

# claude folder-trust gate: claude's trust check short-circuits on
# CLAUDE_CODE_SANDBOXED (the escape its own self-hosted runner provisioning
# uses), which describes this machine exactly: a disposable cloud VM the user
# owns. The ~/.claude.json seed above cannot express this for git repos,
# because the trust lookup is exact-path and the paths users clone are
# unknowable at image build. Exported for every shell (this file is sourced
# from /etc/profile.d and the bashrc chain).
export CLAUDE_CODE_SANDBOXED=1

# claude root gate, separate from the trust dialog: claude refuses
# --dangerously-skip-permissions under uid 0 unless IS_SANDBOX=1, its
# documented container escape. cmux-tui sessions and the exec API run as
# root, so without it the seeded `claude --dangerously-skip-permissions`
# launch dies at start. The VM, not the uid, is the isolation boundary here.
export IS_SANDBOX=1

# claude self-update: the npm install auto-updates itself in the background
# on the first interactive launch (2.1.252 -> latest within 20 s, verified
# live on the trust3 bake), reinstalling the package under nvm. That defeats
# the image pin and leaves `claude` briefly unresolvable while npm relinks
# the bin. The binary is image-baked; new versions ship by rebake
# (`bun run devbox:pins:check --write` in web/, then promote).
export DISABLE_AUTOUPDATER=1

# codex folder-trust gate: codex has no sandbox env short-circuit and its
# trust lookup matches config keys EXACTLY against the cwd or its git root,
# no ancestor walk, so the managed defaults (/etc/codex/managed_config.toml,
# baked at image build) can only pre-trust the HOMEs, never a cloned repo.
# Inject the launch directory's trust per invocation instead: -c overrides
# merge as a config layer, so other projects entries survive. For a linked
# worktree codex keys trust by the MAIN checkout root, so trust that too.
# Paths a TOML string cannot carry raw (quote, backslash, unprintable) are
# skipped; codex then prompts, which beats failing its config parse.
codex() {
  local sub main d entries
  # --version/--help need no trust entry, and the launcher answers them
  # without resolving the sign-in mode.
  if [ "$#" -eq 1 ]; then
    case "$1" in --version|-V|--help|-h) cmux_agent_run codex "$@"; return $? ;; esac
  fi
  sub=$(git rev-parse --show-toplevel 2>/dev/null) || sub=$PWD
  main=$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null) || main=""
  case $main in */.git) main=${main%/.git} ;; *) main="" ;; esac
  if [ "$main" = "$sub" ]; then main=""; fi
  entries=""
  for d in "$sub" "$main"; do
    case $d in ''|*[\"\\]*|*[![:print:]]*) continue ;; esac
    entries="${entries:+$entries, }\"$d\" = { trust_level = \"trusted\" }"
  done
  if [ -n "$entries" ]; then set -- -c "projects={ $entries }" "$@"; fi
  cmux_agent_run codex "$@"
}

# usage attribution: cmux-tui exports CMUX_WORKSPACE_ID and CMUX_SURFACE_ID
# into every terminal it opens; the coderouter ledger keys usage by them so
# `cmux coderouter usage` can break spend down per workspace and terminal.
# Claude Code takes extra request headers from ANTHROPIC_CUSTOM_HEADERS (one
# "Name: value" per line); codex reads the same ids through the
# env_http_headers table generated above. A user-set value wins. Outside a
# cmux-tui terminal the variables are unset and no header is sent.
if [ -n "${CMUX_WORKSPACE_ID-}" ] && [ -z "${ANTHROPIC_CUSTOM_HEADERS-}" ]; then
  ANTHROPIC_CUSTOM_HEADERS="x-cmux-workspace-id: $CMUX_WORKSPACE_ID"
  if [ -n "${CMUX_SURFACE_ID-}" ]; then
    ANTHROPIC_CUSTOM_HEADERS="$ANTHROPIC_CUSTOM_HEADERS
x-cmux-surface-id: $CMUX_SURFACE_ID"
  fi
  export ANTHROPIC_CUSTOM_HEADERS
fi

# claude sign-in precedence: Claude Code ranks ANTHROPIC_API_KEY above its own
# /login, so a shell-wide model-plane key would override a user's own Claude
# account and send it to CodeRouter. Keep the pair out of the shell under
# CMUX_CLAUDE_TEAM_*; the claude launcher (/etc/cmux/claude) puts it back only
# in team mode (/etc/cmux/agent-auth.sh, `cr use`). The pair is the model
# plane's when its base URL is the CodeRouter origin; a user-set endpoint or
# key is left exactly as it is.
cmux_claude_set_team_env_aside() {
  if [ -n "${ANTHROPIC_BASE_URL-}" ] && [ "$ANTHROPIC_BASE_URL" = "${CMUX_CODEROUTER_URL-}" ]; then
    CMUX_CLAUDE_TEAM_BASE_URL=$ANTHROPIC_BASE_URL
    CMUX_CLAUDE_TEAM_API_KEY=${ANTHROPIC_API_KEY-}
    export CMUX_CLAUDE_TEAM_BASE_URL CMUX_CLAUDE_TEAM_API_KEY
    unset ANTHROPIC_BASE_URL ANTHROPIC_API_KEY
  fi
}

