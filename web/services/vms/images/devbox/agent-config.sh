# cmux Cloud devbox agent config generator (/etc/cmux/agent-config.sh).
# Parity sources: the chatmux devbox agent-config (byte-identical
# body below the header; vm-devbox-image.test.ts pins it) and chatmux
# infra/sandbox-images/agent-config.sh. Sourced from
# /etc/profile.d/cmux-agents.sh (login/exec shells) and the bashrc chain
# (interactive shells).
#
# Materializes per-harness model-proxy configs from the machine's boot env
# (the model-plane vars listed in cmux_model_plane_vars, delivered at VM
# create; see web/services/coderouter/vmModelPlane.ts). The env carries
# base URLs, a public placeholder API key, and the VM id only: the real
# credential (the coderouter route token) is injected by the provider's TLS
# edge into every request the guest makes to the coderouter host, so no
# secret ever lands on the machine and no config below carries one.
# Idempotent and silent: each harness config is written only when missing,
# so a user who edits or deletes one keeps control.
#
# Create-time envs are not replayed on every provider (resurrect;
# Freestyle has no VM-level create env at all), so shells that see the boot
# env persist it 0600 on disk, and shells that do not re-source the
# persisted copy. The persisted file always mirrors the newest boot env.

# The edge terminates the coderouter session with the platform CA it
# installs at boot. curl, python, bun, and codex trust the system store;
# Node (Claude Code, pi) does not, so point it at the CA when present. A
# user-set NODE_EXTRA_CA_CERTS wins.
if [ -z "${NODE_EXTRA_CA_CERTS-}" ] && [ -f /usr/local/share/ca-certificates/freestyle-tls.crt ]; then
  NODE_EXTRA_CA_CERTS=/usr/local/share/ca-certificates/freestyle-tls.crt
  export NODE_EXTRA_CA_CERTS
fi

# Sets cmux_claude_plane_base/key to Claude's CodeRouter pair: the one this
# shell carries when its base URL is the CodeRouter origin, else the one a
# parent shell set aside (CMUX_CLAUDE_TEAM_*), else empty.
cmux_claude_plane_pair() {
  cmux_claude_plane_base=${CMUX_CLAUDE_TEAM_BASE_URL-}
  cmux_claude_plane_key=${CMUX_CLAUDE_TEAM_API_KEY-}
  if [ -n "${ANTHROPIC_BASE_URL-}" ] && [ "$ANTHROPIC_BASE_URL" = "${CMUX_CODEROUTER_URL-}" ]; then
    cmux_claude_plane_base=$ANTHROPIC_BASE_URL
    cmux_claude_plane_key=${ANTHROPIC_API_KEY-}
  fi
}

cmux_write_agent_configs() {
  # Every model-plane var, persisted generically; OPENAI_BASE_URL is the
  # anchor: its presence means a boot env is present. Claude's pair is the
  # exception: only the CodeRouter pair is persisted (cmux_claude_plane_pair),
  # whether this shell still carries it or a parent set it aside, never a
  # user's own key or endpoint (a one-off `ANTHROPIC_API_KEY=... claude`
  # passes through here via the launcher).
  cmux_model_plane_vars="OPENAI_BASE_URL OPENAI_API_KEY CMUX_CODEROUTER_URL ANTHROPIC_BASE_URL ANTHROPIC_API_KEY CMUX_VM_ID"
  cmux_claude_plane_pair
  if [ -n "${OPENAI_BASE_URL-}" ]; then
    mkdir -p "$HOME/.config/cmux" 2>/dev/null && (
      umask 077
      {
        echo "# generated by cmux from machine boot env; managed, do not edit"
        for cmux_var in $cmux_model_plane_vars; do
          case "$cmux_var" in
            ANTHROPIC_BASE_URL) cmux_val=$cmux_claude_plane_base ;;
            ANTHROPIC_API_KEY) cmux_val=$cmux_claude_plane_key ;;
            *) eval "cmux_val=\${$cmux_var-}" ;;
          esac
          if [ -n "$cmux_val" ]; then
            printf "export %s='%s'\n" "$cmux_var" "$(printf '%s' "$cmux_val" | sed "s/'/'\\\\''/g")"
          fi
        done
      } > "$HOME/.config/cmux/model-plane.env" 2>/dev/null
    ) || true
  elif [ -f "$HOME/.config/cmux/model-plane.env" ]; then
    . "$HOME/.config/cmux/model-plane.env" 2>/dev/null || true
  elif [ -f /etc/cmux/model-plane.env ]; then
    # Baked into the image: the same alias origin for every machine; the
    # machine's TLS edge rule routes it and adds the credential.
    . /etc/cmux/model-plane.env 2>/dev/null || true
  fi
  cmux_claude_plane_pair
  unset cmux_model_plane_vars cmux_var cmux_val

  # codex: a CUSTOM provider, not the built-in openai one. WebSockets are
  # gated per provider by supports_websockets (codex-rs
  # model_provider_info: serde default false; client.rs
  # responses_websocket_enabled checks nothing else), so a custom provider
  # is already HTTP-only. It is pinned false explicitly anyway: the /v1 data
  # plane serves only the plain HTTP Responses API, and an implicit default
  # can move under a codex upgrade. Auth comes from OPENAI_API_KEY at request
  # time (env_key); it is the public placeholder, and the edge adds the real
  # credential, so a rotated token needs no config rewrite.
  #
  # config.toml has a second writer: `cmux-tui agent hook install codex` keeps
  # its hook trust state under [hooks] there (the bake runs it before any
  # shell has seen a boot env). A file that lacks model_provider is one of
  # those: the provider goes in around it, top-level key first (TOML keeps
  # bare keys above the first table header) and the tables last, so the
  # trust state is preserved. A file that already names a provider, or that
  # carries our tables, is left to whoever wrote it.
  # Parse logical TOML keys, including quoted and dotted forms. Invalid user
  # configuration is preserved so a shell startup cannot damage it further.
  if [ -n "${OPENAI_BASE_URL-}" ] && python3 - "$HOME/.codex/config.toml" 2>/dev/null <<'CMUX_TOML_CHECK'
import pathlib, sys, tomllib
config = pathlib.Path(sys.argv[1])
data = tomllib.loads(config.read_text()) if config.exists() else {}
providers = data.get("model_providers", {})
managed = "model_provider" in data or "history" in data or not isinstance(providers, dict) or "cmux" in providers
sys.exit(1 if managed else 0)
CMUX_TOML_CHECK
  then
    mkdir -p "$HOME/.codex" 2>/dev/null && {
      echo "# generated by cmux from machine boot env; delete to manage manually"
      echo "model_provider = \"cmux\""
      echo ""
      if [ -f "$HOME/.codex/config.toml" ]; then
        cat "$HOME/.codex/config.toml"
        echo ""
      fi
      echo "[model_providers.cmux]"
      echo "name = \"cmux\""
      echo "base_url = \"$OPENAI_BASE_URL\""
      echo "env_key = \"OPENAI_API_KEY\""
      echo "wire_api = \"responses\""
      echo "requires_openai_auth = false"
      echo "supports_websockets = false"
      echo ""
      echo "# usage attribution per cmux workspace/terminal; env_http_headers"
      echo "# skips a header whose variable is unset (plain SSH, exec API)"
      echo "[model_providers.cmux.env_http_headers]"
      echo "\"x-cmux-workspace-id\" = \"CMUX_WORKSPACE_ID\""
      echo "\"x-cmux-surface-id\" = \"CMUX_SURFACE_ID\""
      echo ""
      echo "[history]"
      echo "persistence = \"save-all\""
    } > "$HOME/.codex/config.toml.cmux-tmp" 2>/dev/null && mv -f "$HOME/.codex/config.toml.cmux-tmp" "$HOME/.codex/config.toml" 2>/dev/null
  fi

  # pi: override the built-in openai-codex provider, whose
  # openai-codex-responses implementation speaks the exact dialect the /v1
  # plane proxies (it appends /codex/responses to baseUrl, which the plane
  # serves). pi derives a chatgpt-account-id header from its apiKey
  # client-side and refuses a non-JWT, so the apiKey carries the same public
  # placeholder JWT the `cr pi` extension ships. No route-token header is
  # configured: the edge supplies it on every request. baseUrl must be a
  # literal (pi does not env-resolve it), hence this generator.
  if [ -n "${OPENAI_BASE_URL-}" ] && [ ! -e "$HOME/.pi/agent/models.json" ]; then
    mkdir -p "$HOME/.pi/agent" 2>/dev/null && {
      echo '{'
      echo '  "providers": {'
      echo '    "openai-codex": {'
      echo '      "name": "cmux",'
      echo "      \"baseUrl\": \"$OPENAI_BASE_URL\","
      echo '      "apiKey": "e30.eyJodHRwczovL2FwaS5vcGVuYWkuY29tL2F1dGgiOnsiY2hhdGdwdF9hY2NvdW50X2lkIjoiY29kZXJvdXRlciJ9fQ.signature"'
      echo '    }'
      echo '  }'
      echo '}'
    } > "$HOME/.pi/agent/models.json" 2>/dev/null
  fi

  # claude: ANTHROPIC_BASE_URL and the placeholder ANTHROPIC_API_KEY are all
  # Claude Code needs for the model plane; the claude launcher adds them per
  # launch in team mode (cmux_claude_set_team_env_aside). A fresh HOME still
  # blocks an interactive run on three first-run gates before the prompt is
  # usable: the theme/onboarding wizard, the folder-trust dialog, and the
  # --dangerously-skip-permissions confirmation. Seed the flags those gates
  # write. Not env-gated: the gates block regardless of the model plane.
  # The "/" trust entry covers plain directories only; claude's trust lookup
  # is exact-path and stops at a git root, so CLAUDE_CODE_SANDBOXED below is
  # what trusts a cloned repo. bypassPermissionsModeAccepted is the legacy
  # spelling of the bypass acceptance; the documented key,
  # skipDangerousModePermissionPrompt, rides
  # /etc/claude-code/managed-settings.json (written at image build).
  # A fourth gate is the custom-API-key consent ("Detected a custom API key
  # in your environment ... use this API key?", seen live on 2.1.252 and
  # still gated the same way on 2.1.267): claude
  # records answers under customApiKeyResponses as the key's LAST 20
  # characters, so the placeholder key from the env is pre-approved the same
  # way. Derived from the env so a placeholder change cannot desync it.
  if [ ! -e "$HOME/.claude.json" ]; then
    cmux_claude_key_tail=""
    if [ -n "$cmux_claude_plane_key" ]; then
      cmux_claude_key_tail=$(printf '%s' "$cmux_claude_plane_key" | tail -c 20)
    fi
    (
      umask 077
      {
        echo '{'
        echo '  "hasCompletedOnboarding": true,'
        echo '  "bypassPermissionsModeAccepted": true,'
        echo '  "theme": "dark",'
        if [ -n "$cmux_claude_key_tail" ]; then
          printf '  "customApiKeyResponses": { "approved": ["%s"], "rejected": [] },\n' "$cmux_claude_key_tail"
        fi
        echo '  "projects": { "/": { "hasTrustDialogAccepted": true } }'
        echo '}'
      } > "$HOME/.claude.json"
    ) 2>/dev/null
    unset cmux_claude_key_tail
  fi

}

# Optional provider discovery belongs to OpenCode launch, never shell startup.
# Python owns the advisory lock so process exit releases it even after a crash.
# The CodeRouter providers go to a cmux-owned file, not opencode's global
# config: the opencode launcher layers it on (OPENCODE_CONFIG) only in team
# mode, so an own-login launch sees none of them (agent-auth.sh).
cmux_ensure_opencode_config() {
  [ -e "$HOME/.config/cmux/opencode-team.json" ] && return 0
  [ -n "${CMUX_CODEROUTER_URL-}" ] && [ -n "${OPENAI_API_KEY-}" ] || return 0
  python3 - <<'CMUX_OPENCODE_CONFIG'
import fcntl, hashlib, json, os, pathlib, re, subprocess, sys, tempfile, time

config = pathlib.Path.home() / ".config/cmux/opencode-team.json"
origin = os.environ["CMUX_CODEROUTER_URL"].rstrip("/")
key = os.environ["OPENAI_API_KEY"]
state = pathlib.Path.home() / ".cache/cmux"
state.mkdir(parents=True, exist_ok=True, mode=0o700)
scope = hashlib.sha256((origin + "\0" + key).encode()).hexdigest()
failure = state / ("opencode-config-" + scope + ".failed")

def unavailable():
    print("cmux: OpenCode provider configuration is unavailable; retry in one minute.", file=sys.stderr)
    sys.exit(75)

def redact(value):
    if isinstance(value, dict):
        return {k: redact(v) for k, v in value.items()}
    if isinstance(value, list):
        return [redact(v) for v in value]
    if isinstance(value, str):
        return re.sub(r"crt_[A-Za-z0-9._-]+", "{env:OPENAI_API_KEY}", value.replace(key, "{env:OPENAI_API_KEY}"))
    return value

with (state / "opencode-config.lock").open("a") as lock:
    fcntl.flock(lock, fcntl.LOCK_EX)
    # Waiting callers must observe the result of the first request before
    # deciding to retry or launch. An existing file always wins.
    if config.exists() or config.is_symlink():
        sys.exit(0)
    try:
        age = time.time() - float(failure.read_text())
        if 0 <= age < 60:
            unavailable()
    except (FileNotFoundError, ValueError):
        pass
    try:
        result = subprocess.run(
            ["curl", "-sS", "--connect-timeout", "2", "-m", "10", "-w", "\n%{http_code}",
             "-H", "authorization: Bearer " + key,
             origin + "/api/coderouter/opencode/config"],
            capture_output=True, timeout=12, check=True,
        )
        body, _, status = result.stdout.rpartition(b"\n")
        if status == b"403":
            # The team has no OpenCode account: terminal, so say what the
            # server says (add one, or use your own sign-in) instead of
            # asking for a retry that cannot help.
            try:
                message = json.loads(body)["error"]["message"]
            except Exception:
                message = None
            if isinstance(message, str) and message and len(message) < 2000:
                print("cmux: " + "".join(c for c in message if c.isprintable()), file=sys.stderr)
                sys.exit(78)
        if status != b"200":
            raise ValueError("unexpected status")
        document = json.loads(body)
        if not isinstance(document, dict) or not isinstance(document.get("provider"), dict) or not document["provider"]:
            raise ValueError("missing provider catalog")
        document = redact(document)
        config.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        fd, temporary = tempfile.mkstemp(prefix=".cmux-config-", dir=config.parent)
        try:
            with os.fdopen(fd, "w") as output:
                json.dump(document, output)
                output.write("\n")
                output.flush()
                os.fsync(output.fileno())
            try:
                # Atomic write-if-absent, never replace a file written while
                # the request was in flight, including an existing symlink.
                os.link(temporary, config)
            except FileExistsError:
                pass
        finally:
            os.unlink(temporary)
        failure.unlink(missing_ok=True)
    except (OSError, ValueError, subprocess.SubprocessError):
        if config.exists() or config.is_symlink():
            sys.exit(0)
        failure.write_text(str(time.time()))
        unavailable()
CMUX_OPENCODE_CONFIG
}

# Computer use is an MCP server local to the VM, not part of the model-plane
# provider config. Register it in each bundled agent's native config while
# preserving any user-owned entries. A fresh Cloud VM otherwise has the
# driver and desktop but no MCP entry, so agents silently launch without
# computer-use tools. The operation is idempotent and leaves malformed files
# and symlinks untouched rather than replacing user configuration.
cmux_write_cua_mcp_config() {
  local mode="${1-}" driver
  driver=$(command -v cua-driver 2>/dev/null || true)
  [ -x "$driver" ] || return 0
  CMUX_CUA_CONFIG_HOME="$HOME" CMUX_CUA_DRIVER_BIN="$driver" CMUX_CUA_ALLOW_MISSING="$mode" \
    CMUX_CUA_OPENCODE_CONFIG="${OPENCODE_CONFIG-}" python3 - <<'CMUX_CUA_CONFIG'
import json
import os
import pathlib
import stat
import sys
import tempfile

try:
    import tomllib
except ImportError:
    tomllib = None

home = pathlib.Path(os.environ["CMUX_CUA_CONFIG_HOME"])
driver = os.environ["CMUX_CUA_DRIVER_BIN"]
allow_missing = os.environ.get("CMUX_CUA_ALLOW_MISSING") == "allow-missing"
opencode_config = os.environ.get("CMUX_CUA_OPENCODE_CONFIG")


def report_os_error(label):
    print(f"cmux: unable to update {label} computer-use configuration; keeping existing settings.", file=sys.stderr)


def load_json(path, label):
    # Do not follow a user-owned link, including a dangling one.
    try:
        if path.is_symlink():
            return None
        if not path.exists():
            return {}
        value = json.loads(path.read_text())
    except OSError:
        report_os_error(label)
        return None
    except ValueError:
        return None
    return value if isinstance(value, dict) else None


def atomic_write(path, contents, label):
    temporary = None
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        mode = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o600
        fd, temporary = tempfile.mkstemp(prefix=".cmux-cua-", dir=str(path.parent))
        with os.fdopen(fd, "w") as stream:
            stream.write(contents)
            os.fchmod(stream.fileno(), mode)
        os.replace(temporary, path)
        temporary = None
        return True
    except OSError:
        report_os_error(label)
        return False
    finally:
        if temporary is not None and os.path.exists(temporary):
            try:
                os.unlink(temporary)
            except OSError:
                report_os_error(label)


def atomic_json(path, document, label):
    return atomic_write(path, json.dumps(document, indent=2) + "\n", label)


def add_json_server(path, key, name, server, label, create_if_missing=True):
    document = load_json(path, label)
    if document is None or (not path.exists() and not create_if_missing):
        return
    servers = document.get(key)
    if servers is None:
        document[key] = {name: server}
        atomic_json(path, document, label)
    elif isinstance(servers, dict) and name not in servers:
        servers[name] = server
        atomic_json(path, document, label)


