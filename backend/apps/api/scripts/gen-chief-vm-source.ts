// Regenerates src/chief-brain-cc/chief-vm-source.ts from backend/chief-cc/image/chief-vm.mjs (the turn machine's
// `chief-vm`), which the Worker writes into each turn machine at boot (turn.ts), so a new verb ships with the
// Worker instead of waiting for the next snapshot bake. test/chief-vm-source.test.ts fails when the two drift.
//   bun scripts/gen-chief-vm-source.ts
const here = new URL(".", import.meta.url).pathname
const src = await Bun.file(`${here}../../../chief-cc/image/chief-vm.mjs`).text()
await Bun.write(
  `${here}../src/chief-brain-cc/chief-vm-source.ts`,
  `// Generated by scripts/gen-chief-vm-source.ts from backend/chief-cc/image/chief-vm.mjs; do not edit.\nexport const CHIEF_VM_MJS: string = ${JSON.stringify(src)}\n`
)
