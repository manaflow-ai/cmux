// Writes src/chief-brain-cc/chief-vm-source.ts from backend/chief-cc/image/chief-vm.mjs (the turn machine's
// `chief-vm`), which the Worker writes into each turn machine at boot (turn.ts), so a new verb ships with the
// Worker instead of waiting for the next snapshot bake. The output is build output (gitignored, listed in
// scripts/ci/generated-files.json): `bun run typecheck`, the vitest config and wrangler's build command
// (deploy, dev) each write it first. Only when its content changed: it sits in wrangler's watch dir, so a write of the
// same bytes would start another build.
//   bun scripts/gen-chief-vm-source.ts
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const at = (path: string) => fileURLToPath(new URL(path, import.meta.url).href)

export const writeChiefVmSource = (): void => {
  const src = readFileSync(at("../../../chief-cc/image/chief-vm.mjs"), "utf8")
  const out = `// Generated by scripts/gen-chief-vm-source.ts from backend/chief-cc/image/chief-vm.mjs; do not edit.\nexport const CHIEF_VM_MJS: string = ${JSON.stringify(src)}\n`
  const target = at("../src/chief-brain-cc/chief-vm-source.ts")
  if (!existsSync(target) || readFileSync(target, "utf8") !== out) writeFileSync(target, out)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) writeChiefVmSource()
