/**
 * Writes schemas/link-token/keyset-vectors.json (repo root): what the VM daemon does with each
 * GET /v1/cloud/keyset answer (CLOUD-LINK-FOLLOWUPS 1; a9's request 2026-10-05). Each case lists one
 * or more answers in order (status, headers, body) and the expected read; the held keyset changes
 * only on an `ok: true` read. Keys are the FIXED TEST KEYS of the link-token vectors (public halves).
 *
 *   bun scripts/export-keyset-vectors.ts          write
 *   bun scripts/export-keyset-vectors.ts --check  fail when the checked-in file differs
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { parseKeysetAnswer } from "../../../apps/api/src/link-keyset.ts"
import { publicKeyset } from "../../../apps/api/src/link-token.ts"

const vectorsPath = fileURLToPath(new URL("../../../../schemas/link-token/vectors.json", import.meta.url))
const TEST_KEYS = (JSON.parse(readFileSync(vectorsPath, "utf8")) as { test_keys: Record<string, Record<string, string>> }).test_keys
const set = async (kids: Array<string>) => publicKeyset({ active: kids[0]!, keys: Object.fromEntries(kids.map((k) => [k, TEST_KEYS[k]!])), published_at: {} })
const ok = (value: unknown) => ({ ok: true, value })
const H200 = { "content-type": "application/json", "cache-control": "public, max-age=300" }

const both = await set(["test-k1", "test-k2"])
const k2 = await set(["test-k2"])
const k1x = both.keys["test-k1"]!
const answers: Array<{ name: string; note: string; answers: Array<{ status: number; headers: Record<string, string>; body: unknown }> }> = [
  { name: "ok", note: "A 200 with one or two Ed25519 kids replaces the held keyset.", answers: [{ status: 200, headers: H200, body: ok(both) }] },
  {
    name: "unknown_fields",
    note: "Unknown fields at every level are ignored; the read is the same as without them.",
    answers: [{ status: 200, headers: H200, body: { ok: true, extra: 1, value: { ...both, rotation: "soon", keys: { ...both.keys, "test-k1": { ...k1x, ext: true } } } } }]
  },
  {
    name: "three_kids",
    note: "More than 2 kids: refused; keep the held keyset.",
    answers: [{ status: 200, headers: H200, body: ok({ version: both.version, keys: { ...both.keys, "test-k3": { ...k1x, kid: "test-k3" } } }) }]
  },
  { name: "version_change", note: "A second answer with another version replaces the first (rotation removed test-k1).", answers: [{ status: 200, headers: H200, body: ok(both) }, { status: 200, headers: H200, body: ok(k2) }] },
  { name: "rate_limited", note: "429: keep the held keyset; wait retry-after seconds (60 when absent or invalid) before the next refetch.", answers: [{ status: 429, headers: { "content-type": "application/json", "retry-after": "60" }, body: { ok: false, error: { code: "cloud.rate_limited", message: "too many keyset requests; retry in a minute" } } }] },
  { name: "unavailable", note: "503 (no signing keys on the deployment), no-store: keep the held keyset.", answers: [{ status: 503, headers: { "content-type": "application/json", "cache-control": "no-store" }, body: { ok: false, error: { code: "owner.unreachable", message: "link signing keys are not configured on this deployment" } } }] },
  { name: "wrong_alg", note: "A key with alg other than EdDSA: the whole answer is refused; keep the held keyset.", answers: [{ status: 200, headers: H200, body: ok({ version: both.version, keys: { ...both.keys, "test-k1": { ...k1x, alg: "ES256" } } }) }] },
  { name: "wrong_crv", note: "A key with crv other than Ed25519: the whole answer is refused; keep the held keyset.", answers: [{ status: 200, headers: H200, body: ok({ version: both.version, keys: { ...both.keys, "test-k1": { ...k1x, crv: "X25519" } } }) }] },
  { name: "private_part", note: "A key that carries d (a private part) is refused.", answers: [{ status: 200, headers: H200, body: ok({ version: both.version, keys: { "test-k1": { ...k1x, d: TEST_KEYS["test-k1"]!.d } } }) }] }
]
const cases = answers.map((c) => ({ ...c, answers: c.answers.map((a) => ({ ...a, expect: parseKeysetAnswer(a) })) }))

const doc = {
  $comment:
    "GET /v1/cloud/keyset answers and the VM daemon's expected read (CLOUD-LINK-FOLLOWUPS 1). Only an ok:true read replaces the held keyset; keep_held:true means keep it. Body value has the same shape as the bind answer's keyset: {version: 16 hex (first 8 bytes of sha256 over the canonical public keyset), keys: {kid: {kty: OKP, crv: Ed25519, x, kid, alg: EdDSA, use: sig}}}, at most 2 kids. Refetch on an unknown kid (rate-limited on the daemon side) and once a day; a new kid is published at least 24 h before it signs. Generated by backend/packages/protocol/scripts/export-keyset-vectors.ts.",
  version: 1,
  cases
}
const out = fileURLToPath(new URL("../../../../schemas/link-token/keyset-vectors.json", import.meta.url))
const text = `${JSON.stringify(doc, null, 2)}\n`
if (process.argv.includes("--check")) {
  let current = ""
  try {
    current = readFileSync(out, "utf8")
  } catch {}
  if (current !== text) {
    console.error(`keyset vectors out of date: run bun scripts/export-keyset-vectors.ts (${out})`)
    process.exit(1)
  }
  console.log(`keyset vectors ok: ${cases.length} cases`)
} else {
  writeFileSync(out, text)
  console.log(`wrote ${out}: ${cases.length} cases`)
}
